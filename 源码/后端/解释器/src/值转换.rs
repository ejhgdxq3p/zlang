// 职责: `运行时值` ↔ 并发运行时 `拥有值` 双向转换。
//   ⚡双模式⚡ 2026-08-03 统一真相：全部委托 base 分发器（运行时值转拥有值/拥有值转运行时值），
//   消除 VM 自实现与 base 的重复；拥有值::异常 语义统一为 base 版（在当前线程抛出异常）。

use super::虚拟机::虚拟机;
use base::值类型::*;
use base::公共服务::拥有值;

impl 虚拟机 {
    /// 运行时值 → 拥有值（深拷贝至自包含表示，跨线程 Send）
    pub fn 运行时值到拥有值(&self, v: &运行时值) -> 拥有值 {
        base::分发器::运行时值转拥有值(v)
    }

    /// 拥有值 → 运行时值（在运行时全局堆上重建）
    pub fn 拥有值到运行时值(&self, v: &拥有值) -> 运行时值 {
        base::分发器::拥有值转运行时值(v)
    }
}
