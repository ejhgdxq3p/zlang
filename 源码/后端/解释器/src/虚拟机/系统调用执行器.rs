#![allow(non_snake_case)]
#![allow(private_interfaces)]

use base;
use base::值类型::*;

// 文件: 后端/解释器/src/虚拟机/系统调用执行器.rs
// 职责: 虚拟机 的姐妹模块，承载系统调用相关方法
// 统一架构：参数已经是 运行时值，直接调用运行时 API，不再桥接
//
// ⚡双模式⚡ 统计/文本长度/数组长度 等系统函数已统一收归 base（系统调用 分发），
// 此处不再保留重复实现（原 VM 侧副本已被 #![allow(dead_code)] 掩盖，实为死代码）。
// 唯一真相在 base::系统调用，解释/编译双模自动 parity。

impl crate::虚拟机::虚拟机 {
    /// 分发系统函数——参数已是运行时值，直接调用运行时
    pub(crate) fn 分发系统函数寄存器(&mut self, 索引: usize, 参数: &[运行时值]) -> 运行时值 {
        // 统一架构：参数已经是 运行时值，无需转换
        let 调用前待处理 = base::异常运行时::智语言_异常待处理();
        let 结果 = base::系统调用(索引, 参数);
        // 异常传播（仅当本调用新置位 待处理；finally 体进入时 待处理 已被契约保留为 1，不得误触发）
        if 调用前待处理 == 0 && base::异常运行时::智语言_异常待处理() == 1 {
            if let Some(载荷) = base::异常运行时::取当前异常() {
                base::异常运行时::智语言_清除当前异常();
                self.触发异常(&载荷.类型, 载荷.描述);
                return 运行时值::空值();
            }
        }
        结果
    }

}
