// 文件: 前端/src/流水线.rs
// 职责: 前端流水线统一入口 — 词法→语法→语义→降级 一站式处理
//       消除命令文件中 10+ 处重复前端调用，统一诊断输出路径

use crate::诊断收集器::诊断收集器;
use crate::词法分析::词法分析器;
use crate::语法分析::语法分析器;
use crate::语义::语义分析器;
use crate::降级::公共降级;
use crate::底层表示::模块结构::底层表示模块;

/// 前端流水线配置
pub struct 前端流水线配置 {
    pub 文件路径: String,
    pub 源码: String,
    pub 是否入口文件: bool,
    pub 编译模式: bool,
    pub 注册源文件: bool,       // 是否将源码注册到源映射（用于代码上下文显示）
}

impl 前端流水线配置 {
    pub fn 新建(文件路径: &str, 源码: &str) -> Self {
        前端流水线配置 {
            文件路径: 文件路径.to_string(),
            源码: 源码.to_string(),
            是否入口文件: true,
            编译模式: false,
            注册源文件: true,
        }
    }

    pub fn 设置入口文件(mut self, 是入口: bool) -> Self { self.是否入口文件 = 是入口; self }
    pub fn 设置编译模式(mut self, 是编译: bool) -> Self { self.编译模式 = 是编译; self }
    pub fn 设置注册源文件(mut self, 注册: bool) -> Self { self.注册源文件 = 注册; self }
}

/// 前端流水线结果
pub enum 流水线结果 {
    成功(底层表示模块),
    错误,
}

/// 执行完整前端流水线：词法→语法→语义→降级
///
/// 返回 `流水线结果` 而非 `Option`，更清晰表达成功/失败两种状态。
/// 诊断记录在 `诊断` 参数中，供调用方检查/输出。
///
/// # 使用示例
/// ```ignore
/// let mut 诊断 = 诊断收集器::新建();
/// let 配置 = 前端流水线配置::新建("文件.智", &源码);
/// match 执行前端流水线(&配置, &mut 诊断) {
///     流水线结果::成功(模块) => { /* 使用模块 */ }
///     流水线结果::错误 => { /* 诊断已有错误信息 */ }
/// }
/// ```
pub fn 执行前端流水线(配置: &前端流水线配置, 诊断: &mut 诊断收集器) -> 流水线结果 {
    // 可选择注册源文件以支持代码上下文显示
    if 配置.注册源文件 {
        诊断.注册源文件(&配置.文件路径, &配置.源码);
    }

    // ① 词法分析
    let 词条列表 = 词法分析器::新建(&配置.源码, 配置.文件路径.clone(), 诊断).扫描所有词条();
    if 诊断.有错误() {
        return 流水线结果::错误;
    }

    // ② 语法分析
    let mut 程序 = 语法分析器::新建(&词条列表, 诊断).解析程序();
    if 诊断.有错误() {
        return 流水线结果::错误;
    }

    // ③ 语义分析
    let 高层表示模块 = match 语义分析器::新建(诊断)
        .设置入口文件路径(&配置.文件路径)
        .设置是否为入口文件(配置.是否入口文件)
        .设置编译模式(配置.编译模式)
        .分析程序(&mut 程序)
    {
        Ok(m) => m,
        Err(_) => {
            return 流水线结果::错误;
        }
    };

    // ④ 降级为底层表示模块（LIR）
    let 底层表示模块 = 公共降级::降级转换(&高层表示模块);

    流水线结果::成功(底层表示模块)
}

/// 执行前端流水线并输出诊断（便捷函数）
///
/// 成功时返回 `Some(底层表示模块)`，失败时输出诊断并返回 `None`。
/// 保持与原有 `编译并降级` 函数兼容的签名。
pub fn 执行前端流水线_兼容(配置: &前端流水线配置, 诊断: &mut 诊断收集器) -> Option<底层表示模块> {
    match 执行前端流水线(配置, 诊断) {
        流水线结果::成功(模块) => Some(模块),
        流水线结果::错误 => None,
    }
}

/// 输出诊断（结构化模式输出到 stdout，普通/简洁模式输出到 stderr）
///
/// 诊断收集器内置的 简洁模式/颜色模式/结构化模式 决定输出格式。
pub fn 输出诊断(诊断: &诊断收集器) {
    let 是否结构化 = 诊断.结构化模式();
    for 行 in 诊断.输出所有诊断() {
        if 是否结构化 {
            println!("{}", 行);   // stdout（供工具解析）
        } else {
            eprintln!("{}", 行);  // stderr（供开发人员查看）
        }
    }
}

/// 设置诊断收集器的简洁模式和颜色模式（便捷函数）
pub fn 设置诊断模式(诊断: &mut 诊断收集器, 简洁: bool, 颜色: bool) {
    诊断.设置简洁模式(简洁);
    诊断.设置颜色模式(颜色);
}

/// 输出简洁诊断到标准错误（使用测试格式化器，无源码上下文）
pub fn 输出诊断简洁(诊断: &诊断收集器) {
    for 行 in 诊断.输出所有诊断简洁() {
        eprintln!("{}", 行);
    }
}
