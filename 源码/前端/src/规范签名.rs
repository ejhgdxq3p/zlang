pub struct 规范函数 {
    pub 模块: &'static str,
    pub 函数名: &'static str,
    /// 用户可见形参类型序列（含全部形参，无「自身」；默认值长度与其对齐，缺省位空串）。
    pub 形参类型: &'static [&'static str],
    pub 返回: Option<&'static str>,
    /// 可选形参默认值文本（None = 无任何可选形参；长度 == 形参类型.len()，必填位空串）。
    pub 默认值: Option<&'static [&'static str]>,
}

impl 规范函数 {
    /// 规范全名「模块.函数名」
    pub fn 规范名(&self) -> String {
        format!("{}.{}", self.模块, self.函数名)
    }
}

