/// ★F2 全量收严（2026-10-14）：类型是否**确定含空值** ——
///   ① `空值` 本体（`类型信息::空值` / `基本型(空值)`）；
///   ② `任意<…|空值>` 这类**约束范围含空值**的联合（规范 §10319：`.获取` → `任意<乙|空值>`）。
///   ⚠ 裸 `任意`（无约束）**不算**确定含空值 ✓（动态类型，运行时兜底）。
pub fn 确定含空值(类型: &类型信息) -> bool {
    match 类型 {
        类型信息::空值 | 类型信息::基本型(基本类型::空值) => true,
        类型信息::任意类型 { 约束范围, .. } => 约束范围.iter().any(确定含空值),
        _ => false,
    }
}

/// ★F2 全量收严（2026-10-14）：目标类型是否**确定非空**（可拒绝"确定含空值"的源 ✓）。
///   未推断 / 空值 / 任意（含含空值约束者）⇒ 不算"确定非空" ⇒ 放行 ✓（动态/可空通道）。
pub fn 确定非空(类型: &类型信息) -> bool {
    match 类型 {
        类型信息::未推断 | 类型信息::空值 | 类型信息::基本型(基本类型::空值) => false,
        类型信息::任意类型 { .. } => false,
        _ => true,
    }
}

pub fn 检查赋值兼容(目标类型: &类型信息, 源类型: &类型信息) -> bool {
    if 目标类型 == 源类型 {
        return true;
    }
    // 唯一隐式转换：整数 → 小数
    if *目标类型 == 类型信息::小数类型() && *源类型 == 类型信息::整数类型() {
        return true;
    }
    // 匿名/有名任意类型兼容性：统一委托 检查任意类型约束（单一真相，2026-07-28）
    if let 类型信息::任意类型 { 约束范围, .. } = 目标类型 {
        if 约束范围.is_empty() {
            return true; // 无约束的 任意<甲>：接受任何类型（泛型类型变量占位）
        }
        return 检查任意类型约束(目标类型, 源类型);
    }
    // 未推断：跳过静态检查（运行时处理）
    if matches!(目标类型, 类型信息::未推断) || matches!(源类型, 类型信息::未推断) {
        return true;
    }
    false
}

pub fn 可能插入隐式转换(表达式: 高层表示表达式, 期望类型: &类型信息) -> 高层表示表达式 {
    let 源类型 = super::类型推断::从表达式推断(&表达式);
    if 检查赋值兼容(期望类型, &源类型) && 源类型 != *期望类型 {
        高层表示表达式::隐式转换 {
            源表达式: Box::new(表达式),
            目标类型: 期望类型.clone(),
        }
    } else {
        表达式
    }
}

pub fn 算术运算结果类型(左: &类型信息, 右: &类型信息) -> Result<类型信息, String> {
    // 未推断操作数：用另一操作数的具体类型作为结果类型（类型推断从已知操作数推导，
    // 如 未推断 + 整数 = 整数；两操作数均未推断则保持未推断交由运行时处理）
    if matches!(左, 类型信息::未推断) && matches!(右, 类型信息::未推断) {
        return Ok(类型信息::未推断);
    }
    if matches!(左, 类型信息::未推断) {
        return Ok(右.clone());
    }
    if matches!(右, 类型信息::未推断) {
        return Ok(左.clone());
    }
    // ★F2 全量收严（2026-10-14，规范 §2.4.5 铁律「空值不参与任何运算」）：
    //   任一操作数**确定含空值**（`空值` 本体 或 `任意<…|空值>` 联合）⇒ **明确报错** ✓；
    //   裸 `任意`（无约束）仍放行（泛型占位/动态类型，运行时兜底）✓。
    //   缺口实证：`表.获取("乙") + 1` 此前编译通过 ✗（`.获取` 返回 `任意<整数|空值>` ⇒ 落入下方"泛型占位"分支）。
    if 确定含空值(左) || 确定含空值(右) {
        return Err(format!(
            "含空值的表达式不能参与算术运算：操作数类型【{}】和【{}】含空值，请先判空（`如果 … == 空值: …`）后再运算",
            左.类型名称(), 右.类型名称()
        ));
    }
    if matches!(左, 类型信息::任意类型 { .. }) || matches!(右, 类型信息::任意类型 { .. }) {
        return Ok(类型信息::未推断); // 泛型类型变量，运行时处理
    }
    match (左, 右) {
        (类型信息::基本型(基本类型::整数), 类型信息::基本型(基本类型::整数)) => {
            Ok(类型信息::整数类型())
        }
        (类型信息::基本型(基本类型::小数), 类型信息::基本型(基本类型::小数)) => {
            Ok(类型信息::小数类型())
        }
        (类型信息::基本型(基本类型::整数), 类型信息::基本型(基本类型::小数)) => {
            Ok(类型信息::小数类型())
        }
        (类型信息::基本型(基本类型::小数), 类型信息::基本型(基本类型::整数)) => {
            Ok(类型信息::小数类型())
        }
        (类型信息::基本型(基本类型::文本), 类型信息::基本型(基本类型::文本)) => {
            Ok(类型信息::文本类型())
        }
        _ => Err(format!(
            "不支持的操作数类型：{} 和 {}",
            左.类型名称(),
            右.类型名称()
        )),
    }
}

pub fn 检查比较操作数(左: &类型信息, 右: &类型信息) -> Result<(), String> {
    // 任意类型或未推断：跳过静态检查
    if matches!(左, 类型信息::未推断 | 类型信息::任意类型 { .. }) 
        || matches!(右, 类型信息::未推断 | 类型信息::任意类型 { .. }) 
    {
        return Ok(());
    }
    if 左 == 右
        || (*左 == 类型信息::整数类型() && *右 == 类型信息::小数类型())
        || (*左 == 类型信息::小数类型() && *右 == 类型信息::整数类型())
    {
        Ok(())
    } else {
        Err(format!("无法比较 {} 和 {}", 左.类型名称(), 右.类型名称()))
    }
}

pub fn 检查任意类型赋值(目标类型: &类型信息, 源类型: &类型信息) -> bool {
    match 目标类型 {
        类型信息::任意类型 { 约束范围, .. } => {
            约束范围.iter().any(|t| {
                t == 源类型
                    || 匹配函数约束(t, 源类型)
                    || 匹配接口约束(t, 源类型)
                    || 匹配结构体约束(t, 源类型)
                    || 检查任意类型赋值(t, 源类型)
            })
        }
        _ => 目标类型 == 源类型,
    }
}

/// 约束成员为裸容器（映射/数组，元素为空值=任意元素占位，见 类型语法分析.rs 裸容器默认 空值）时，
/// 匹配任意同构具体容器。例如 任意<映射|文本> 的约束成员 映射(空值,空值) 应接受返回的 映射<文本,整数|文本>。
fn 匹配裸容器约束(成员: &类型信息, 源: &类型信息) -> bool {
    // 裸容器占位：元素类型为 空值 或 未推断 均视为「任意元素」
    fn 元素通配(元: &类型信息) -> bool {
        matches!(元, 类型信息::空值) || matches!(元, 类型信息::未推断)
    }
    match (成员, 源) {
        (类型信息::映射(键c, 值c), 类型信息::映射(键s, 值s)) => {
            let 键匹配 = *键c == *键s || 元素通配(键c) || 元素通配(键s);
            let 值匹配 = *值c == *值s || 元素通配(值c) || 元素通配(值s);
            键匹配 && 值匹配
        }
        (类型信息::数组(元素c), 类型信息::数组(元素s)) => {
            *元素c == *元素s || 元素通配(元素c) || 元素通配(元素s)
        }
        _ => false,
    }
}

/// 约束成员为函数类型时，匹配任意函数类型的值。
/// 函数是一等公民，运行时按实际签名分派（间接调用已校验实参数），与裸容器同构匹配一致——
/// 签名不参与静态约束判定。例：任意<函数(整数,整数)整数|空值> 的约束成员 函数(整数,整数)整数
/// 应接受任意函数引用（如裸函数名 加法）。
fn 匹配函数约束(成员: &类型信息, 源: &类型信息) -> bool {
    matches!(
        (成员, 源),
        (类型信息::函数类型(..), 类型信息::函数类型(..))
    )
}

/// 约束成员为结构体类型时，匹配**同名**结构体值。
/// 为什么不能逐字比较：`类型信息::结构体(名, 类型参数)` 的**约束侧参数恒空**
/// （`任意<汽车|空值>` 只写名字，见 类型语法分析.rs），而**实例侧参数携带字段分量**
/// ⇒ 逐字相等判定会把「把该结构体的实例装进 `任意<该结构体|空值>`」这一**规范允许**的用法全量误拒 ✗
/// （实测：`任意<甲|空值> 值甲 = 甲()` 报「不满足任意类型约束」，双模一致）。

/// 取名匹配与「裸容器 / 函数 / 接口」三条同类宽松支同哲学：静态只判**是不是这类**，
/// 具体成员/签名/实现由运行期实际对象决定（规范 §2.3.3「任意类型」包装语义）。
fn 匹配结构体约束(成员: &类型信息, 源: &类型信息) -> bool {
    match (成员, 源) {
        (类型信息::结构体(成员名, _), 类型信息::结构体(源名, _)) => 成员名 == 源名,
        _ => false,
    }
}

/// 约束成员为接口类型时，匹配结构体值。
/// 结构体「适配」某接口的关系在结构体声明处校验；此处与「接口类型变量直接赋值」
/// （`可移动 设备 = 汽车(...)`，无静态兼容校验）既有的宽松语义保持一致。
/// 否则 任意<接口|空值> 将只能存 空值，「接口字段用任意类型包装」即失去意义。
/// 若结构体实际未适配该接口，运行期接口分发会明确报错（可捕获），不会静默错值。
fn 匹配接口约束(成员: &类型信息, 源: &类型信息) -> bool {
    matches!(
        (成员, 源),
        (类型信息::接口型(_), 类型信息::结构体(_, _))
    )
}

/// 任意类型约束严格判定（单一真相，2026-07-28）：
/// 当目标为带约束的任意类型时：
///  - 源是具体类型：须精确落入约束范围（杜绝 小数 被误判落入 整数|文本）；
///  - 源自身是任意类型：源约束 ⊆ 目标约束 时接受（如 任意<整数|文本>→任意<整数|文本>）；
///  - 源无约束(泛型占位)或 未推断：接受（运行时解析，与既有宽松哲学一致）。
/// 对约束范围成员（具体类型）复用 检查赋值兼容（含 整数↔小数 单向宽松、未推断跳过）；
/// 成员为裸容器（映射/数组 元素未推断）时额外匹配任意同构具体容器。
pub fn 检查任意类型约束(目标: &类型信息, 源: &类型信息) -> bool {
    match 目标 {
        类型信息::任意类型 { 约束范围, .. } => {
            if 约束范围.is_empty() {
                return true; // 目标无约束（泛型占位）：接受任何源
            }
            match 源 {
                类型信息::任意类型 { 约束范围: 源约束, .. } => {
                    // 源约束 ⊆ 目标约束 时接受（规范 §2.4.6）；源无约束或源未推断也接受
                    源约束.is_empty()
                        || 源约束.iter().all(|s| 约束范围.iter().any(|t| t == s))
                }
                类型信息::未推断 => true,
                _ => 约束范围.iter().any(|t| {
                    匹配裸容器约束(t, 源)
                        || 匹配函数约束(t, 源)
                        || 匹配接口约束(t, 源)
                        || 匹配结构体约束(t, 源)
                        || 检查任意类型约束(t, 源)
                }),
            }
        }
        _ => 检查赋值兼容(目标, 源),
    }
}

// ── 空值安全 ──

/// 检查空值不能参与类型转换
pub fn 检查空值转换(参数类型: &类型信息) -> Result<(), String> {
    // 未推断/任意类型：类型尚未解析，允许通过（运行时由VM处理）
    if matches!(参数类型, 类型信息::未推断 | 类型信息::任意类型 { .. }) {
        return Ok(());
    }
    if matches!(参数类型, 类型信息::基本型(基本类型::空值)) {
        return Err("空值不能参与类型转换".into());
    }
    Ok(())
}

/// 检查空值不能参与算术/逻辑/比较/遍历运算
pub fn 检查空值运算(左: &类型信息, 右: &类型信息) -> Result<(), String> {
    // ★F2 全量收严**配套**（2026-10-14）：**可空 ↔ 空值** 必须放行 ——
    //   规范 §2.4.5 铁律「空值…**只允许与自身进行 `==` / `===` 判断**」⇒ 判空写法
    //   `如果 表.获取(键) == 空值: …`（左侧静态类型 = `任意<乙|空值>`）**合法** ✓。
    //   此前口径为"两侧都不是空值才放行" ⇒ 该写法被误杀 ✗（实测：`E` 探针报「空值不能参与运算」）。
    //   ⚠ 未收窄"空值 ↔ **确定非空**"的拦截 ✓（如 `空值 == 0` 仍报错 ✓）；本函数亦服务于算术/逻辑路径，
    //     而"可空参与**算术**"由 `算术运算结果类型` 的专条拦截 ✓（二者分工明确）。
    let 可能含空值 = |t: &类型信息| {
        确定含空值(t) || matches!(t, 类型信息::未推断 | 类型信息::任意类型 { .. })
    };
    if 可能含空值(左) && 可能含空值(右) {
        return Ok(());
    }
    // 未推断/任意类型：类型尚未解析，允许通过（运行时由VM处理）
    let 是未推断或者任意 = |t: &类型信息| matches!(t, 类型信息::未推断 | 类型信息::任意类型 { .. });
    if (是未推断或者任意(左) || 是未推断或者任意(右))
        && !matches!(左, 类型信息::基本型(基本类型::空值))
        && !matches!(右, 类型信息::基本型(基本类型::空值))
    {
        return Ok(());
    }
    if matches!(左, 类型信息::基本型(基本类型::空值))
        || matches!(右, 类型信息::基本型(基本类型::空值))
    {
        return Err("空值不能参与运算（算术/逻辑/比较/遍历）".into());
    }
    Ok(())
}

/// 检查空值的**比较**合法性（规范 §2.4.5 铁律：空值**只允许与自身**进行 `==` / `===` 等值判断）。
///
/// 规则（与 `检查空值运算` 的"未推断/任意放行"口径保持一致）：
///   · 两侧都不是空值 ⇒ 放行（本函数只负责"空值参与的比较"）；
///   · 任一侧为 `未推断`/`任意类型` ⇒ 放行（类型未解析，交运行期；避免误伤泛型、容器取值与空值哨兵模式）；
///   · 空值 ↔ **非空值** ⇒ 一律报错（即使是 `==` / `!=`）；
///   · 空值 ↔ 空值 ⇒ 仅放行**等值判断**（`==` `!=` `===` `!==`）；`>` `<` `>=` `<=` **报错**。
/// `非空侧确定非空`：由调用方按**表达式形态 + 静态类型**判定"另一侧静态上确定不可能为空值"
/// （字面量 / 变量引用 / 结构体构造，且类型为基本类型·结构体·枚举）。
/// ⚠ 必须为假的情形（实测语料大量依赖，**放行是刻意的**）：容器缺键/越界得空值（`.获取` 等**调用**）、
///   通道接收、字段默认值、接口变量、`任意`/`未推断` —— 这些静态类型具体但**运行期可能为空值**。
pub fn 检查空值比较(
    是等值判断: bool,
    非空侧确定非空: bool,
    非空侧描述: &str,
    左: &类型信息,
    右: &类型信息,
) -> Result<(), String> {
    let 是空值 = |t: &类型信息| matches!(t, 类型信息::基本型(基本类型::空值));
    let 左空 = 是空值(左);
    let 右空 = 是空值(右);
    if !左空 && !右空 {
        return Ok(());
    }
    let 是未推断或者任意 = |t: &类型信息| matches!(t, 类型信息::未推断 | 类型信息::任意类型 { .. });
    if 是未推断或者任意(左) || 是未推断或者任意(右) {
        return Ok(());
    }
    if 左空 && 右空 {
        if 是等值判断 {
            return Ok(());
        }
        return Err("空值不能参与排序比较（空值只允许与自身进行 `==`/`===` 判断）".into());
    }
    if !非空侧确定非空 {
        // 另一侧可能运行期为 空值（容器缺键/字段默认值/通道/接口…）⇒ 放行，保留判空惯用法 ✓
        return Ok(());
    }
    Err(format!(
        "空值不能与非空值比较（空值只允许与自身进行 `==`/`===` 判断）；另一侧：{}",
        非空侧描述
    ))
}

/// 条件必须是逻辑类型，空值不能直接作为条件
pub fn 检查条件类型(条件类型: &类型信息) -> Result<(), String> {
    if *条件类型 == 类型信息::逻辑类型() || *条件类型 == 类型信息::未推断 {
        Ok(())
    } else if matches!(条件类型, 类型信息::基本型(基本类型::空值)) {
        Err("条件必须是逻辑类型，空值不能直接作为条件".into())
    } else {
        Err(format!("条件必须是逻辑类型，当前类型为【{}】", 条件类型.类型名称()))
    }
}

// ── 容器约束（元素类型 / 映射值类型）──
//
// 2026-10-12（规范 §2.4.2「有约束的数组写作 数组<类型>」）：**让写下的约束真正生效**。
// 覆盖两处：① **写入端**（`.追加/.插入/.设置/索引写` 的待写入值）② **声明端**（有约束容器的**字面量初值**
// 逐元素/逐值）。判定统一走 `检查赋值兼容`（整数→小数 合法、`任意<…>` 约束范围、**未推断放行**——
// 未推断表示"编译器无法确定"（空容器、异构字面量），按既有"运行时处理"口径跳过，避免误报）。

/// 单个元素/值是否满足容器的元素类型约束。
///
/// ⚠ 2026-10-12 实测收敛（避免误伤，见项目记忆「容器约束 4 类误伤」）：仅对**具体标量与容器**强制；
/// 以下情形一律放行：
///   - `未推断`（空容器 / 异构字面量 ⇒ 编译器无法确定）；
///   - `任意`（两侧之一）：无约束泛型占位，按既有口径"运行时处理"；
///   - `空值`（实际值）：容器元素/值置空的既有惯用法（基线用例依赖）；
///   - **结构体 / 接口（声明侧）**：结构体需按名比较（泛型实参可能不同）、接口需结构体适配表、
///     泛型类型参数在 `类型信息` 里呈结构体形态 ⇒ 静态强制误报风险高（实测误伤 6 个基线用例），
///     改由运行期（值语义 / 适配检查）兜底。
fn 元素值兼容(声明类型: &类型信息, 实际类型: &类型信息) -> bool {
    if matches!(声明类型, 类型信息::未推断 | 类型信息::任意类型 { .. })
        || matches!(
            实际类型,
            类型信息::未推断
                | 类型信息::任意类型 { .. }
                | 类型信息::空值
                | 类型信息::基本型(基本类型::空值)
        )
        || matches!(
            声明类型,
            类型信息::空值 | 类型信息::基本型(基本类型::空值)
        )
    {
        return true;
    }
    if matches!(声明类型, 类型信息::结构体(..) | 类型信息::接口型(_)) {
        return true;
    }
    检查赋值兼容(声明类型, 实际类型)
}

/// **写入端**容器约束：容器静态类型 + 待写入值的类型。
pub fn 检查容器写入约束(容器: &类型信息, 待写类型: &类型信息) -> Result<(), String> {
    match 容器 {
        类型信息::数组(元素类型) => {
            if 元素值兼容(元素类型, 待写类型) {
                Ok(())
            } else {
                Err(format!(
                    "数组元素类型不匹配：声明的元素类型为【{}】，实际写入【{}】",
                    元素类型.类型名称(),
                    待写类型.类型名称()
                ))
            }
        }
        类型信息::映射(_, 值类型) => {
            if 元素值兼容(值类型, 待写类型) {
                Ok(())
            } else {
                Err(format!(
                    "映射值类型不匹配：声明的值类型为【{}】，实际写入【{}】",
                    值类型.类型名称(),
                    待写类型.类型名称()
                ))
            }
        }
        _ => Ok(()),
    }
}

/// **声明端**容器约束：有约束容器的初值为**字面量**时，逐元素/逐值核对。
pub fn 检查容器字面量约束(声明类型: &类型信息, 初值: &高层表示表达式) -> Result<(), String> {
    if let 高层表示表达式::字面值(字面值::数组(元素列表, _), _) = 初值 {
        if let 类型信息::数组(元素类型) = 声明类型 {
            for 元素 in 元素列表 {
                let 实际 = super::类型推断::从表达式推断(元素);
                if !元素值兼容(元素类型, &实际) {
                    return Err(format!(
                        "数组元素类型不匹配：声明的元素类型为【{}】，字面量元素为【{}】",
                        元素类型.类型名称(),
                        实际.类型名称()
                    ));
                }
            }
        }
    }
    if let 高层表示表达式::字面值(字面值::映射(对列表), _) = 初值 {
        if let 类型信息::映射(_, 值类型) = 声明类型 {
            for (_, 值表达式) in 对列表 {
                let 实际 = super::类型推断::从表达式推断(值表达式);
                if !元素值兼容(值类型, &实际) {
                    return Err(format!(
                        "映射值类型不匹配：声明的值类型为【{}】，字面量值为【{}】",
                        值类型.类型名称(),
                        实际.类型名称()
                    ));
                }
            }
        }
    }
    Ok(())
}

// ── 映射键类型限制 ──

/// 映射键可编码性检查（规范 §2.4.2「键白名单」）。
///
/// 判据：键必须是「可稳定编码为标量序列」的类型，即**相等 ⟹ 同一个键**能够成立。
///   ✅ 允许：整数、小数、文本、逻辑、空值、枚举
///   ❌ 禁止：数组、映射（规范 §2.4.2 明文）；接口、函数（无内容相等 / 无法编码）
///   ⏳ 运行期判定：`任意` 类型键（约束范围内的动态值）、未推断
///
/// 结构体：规范允许「所有字段都可作键**且未自定义 `等于`**」的结构体作键（§2.6.8 允许结构体重载
///   `等于` 自定义值相等语义，实测生效 ⇒ 自定义相等者无法编码成键，等价于 Python「定义 `__eq__`
///   而未定义 `__hash__` ⇒ 不可哈希 ⇒ 不能作 dict 键」）。该递归判定需符号表上下文，见后续
///   `检查结构体可作键`；在此之前结构体键一律拒绝（与其运行时行为一致，不再静默塌陷）。
pub fn 检查映射键类型(键类型: &类型信息) -> Result<(), String> {
    match 键类型 {
        类型信息::数组(_) => Err("数组不能作为映射的键（键必须是可比较的标量、枚举或结构体）".into()),
        类型信息::映射(_, _) => Err("映射不能作为映射的键（键必须是可比较的标量、枚举或结构体）".into()),
        类型信息::接口型(名) => Err(format!("接口【{}】不能作为映射的键", 名)),
        类型信息::函数类型(_, _) => Err("函数不能作为映射的键".into()),
        // ⚠ 结构体键：**不在此静态拒绝** ——
        //   ① 泛型类型参数在类型信息里就是「结构体(名, 实参)」形态，静态拒绝会误伤 `任意<键型>` 泛型声明；
        //   ② 规范允许「所有字段都可作键且未自定义 等于」的结构体作键（递归判定需符号表上下文）。
        //   故结构体键在此**放行**，由运行期 `值转键` 按实际值判定（当前阶段结构体键未支持 ⇒ 运行期抛
        //   「键类型无效」，不做静默塌陷；结构体键的完整支持见后续批次）。
        _ => Ok(()),
    }
}

/// 映射键**使用点**总检查：白名单 + （有约束映射的）键类型符合性。
///
/// - `声明键类型`：接收者/容器静态类型里的键类型（`未推断` / `任意类型`（无约束） ⇒ 跳过符合性，交运行期）
/// - `实参键类型`：实际键表达式的静态类型（`任意类型` / `未推断` / `推断错误` ⇒ 跳过符合性，交运行期）
///
/// 2026-10-12（规范 §2.4.2）：把「键可编码性」静态闸门从**映射字面量**扩展到
/// `.插入/.删除/.是否包含/.获取`、索引读写、声明层（变量 / 模块级 / 结构体字段）。
pub fn 检查映射键使用(_声明键类型: &类型信息, 实参键类型: &类型信息) -> Result<(), String> {
    // ⚠ 2026-10-12：此处**只做键白名单**（可编码性）。
    //   「实参键类型是否属于声明的键类型 K」这一**符合性**检查暂不在此强制：
    //   既有基线用例有意用「合法但非声明键类型」的键做边界探测（如 `映射<文本,整数>.是否包含(1)`
    //   验证缺键语义 ⇒ 期望返回假）。若要强制符合性，需与「容器元素/值类型约束生效」同批评估
    //   （同一族「约束未强制」问题，见项目记忆）。
    检查映射键类型(实参键类型)
}

/// **递归**检查类型内**所有**映射的键类型是否合法（声明层专用）。
///
/// 覆盖：`映射<K,V>`（查 K，并递归 K/V）、`数组<元素>`、结构体泛型实参、函数类型的参数与返回值、
/// `任意<T|...>` 的约束范围。声明层没有「实参」，所以要查的是**声明的键类型本身**（而非某个实参类型）。
/// 类型结构是有限树（结构体自引用字段已被拒绝）⇒ 递归必然终止。
pub fn 检查类型内映射键(类型: &类型信息) -> Result<(), String> {
    match 类型 {
        类型信息::映射(键类型, 值类型) => {
            检查映射键类型(键类型)?;
            检查类型内映射键(键类型)?;
            检查类型内映射键(值类型)
        }
        类型信息::数组(元素类型) => 检查类型内映射键(元素类型),
        类型信息::结构体(_, 类型实参) => {
            for 实参 in 类型实参 {
                检查类型内映射键(实参)?;
            }
            Ok(())
        }
        类型信息::函数类型(参数类型, 返回类型) => {
            for 参数 in 参数类型 {
                检查类型内映射键(参数)?;
            }
            检查类型内映射键(返回类型)
        }
        类型信息::任意类型 { 约束范围, .. } => {
            for 约束 in 约束范围 {
                检查类型内映射键(约束)?;
            }
            Ok(())
        }
        _ => Ok(()),
    }
}

// ── 接口类型兼容性（2.4.4：结构体→接口自动适配）──

/// 检查源类型是否可以赋值给目标类型（含接口适配 2.4.4）
/// 当目标是接口类型时，检查源结构体是否适配了该接口
pub fn 检查赋值兼容含接口(
    目标类型: &类型信息,
    源类型: &类型信息,
    结构体适配表: &std::collections::HashMap<String, Vec<String>>,
) -> bool {
    if 检查赋值兼容(目标类型, 源类型) {
        return true;
    }
    // 接口类型兼容：目标是接口型，源是结构体
    if let 类型信息::结构体(结构体名, _) = 源类型 {
        if let 类型信息::接口型(接口名) = 目标类型 {
            if let Some(适配列表) = 结构体适配表.get(结构体名) {
                return 适配列表.contains(接口名);
            }
        }
    }
    false
}

