use super::高层表示节点::高层表示运算符;
use crate::语法分析::运算符 as 语法运算符;

/// 可重载运算符对应的方法名（规范 2.6.7 运算符重载表格）
/// 二元（加/减/乘/除/整除/取余/幂/等于/大于/小于/大于等于/小于等于/不等于/异或/位与/位或/左移/右移）为 1 参数；
/// 一元（取负、位非）为 0 参数；比较返回逻辑。
/// 复合赋值运算符（+=-…>>=）对应「XX赋值」方法，由 语法运算符到复合赋值方法名 映射，不在此表。
pub const 可重载映射: &[(&str, 高层表示运算符)] = &[
    ("加法", 高层表示运算符::加),
    ("减法", 高层表示运算符::减),
    ("乘法", 高层表示运算符::乘),
    ("除法", 高层表示运算符::除),
    ("整除", 高层表示运算符::整除),
    ("取余", 高层表示运算符::取余),
    ("幂", 高层表示运算符::幂),
    ("取负", 高层表示运算符::位非),  // 一元运算符（枚举无 取负 变体，复用 位非 占位；分发与校验均按方法名处理）
    ("等于", 高层表示运算符::等于),
    ("大于", 高层表示运算符::大于),
    ("小于", 高层表示运算符::小于),
    ("大于等于", 高层表示运算符::大于等于),
    ("小于等于", 高层表示运算符::小于等于),
    ("不等于", 高层表示运算符::不等于),
    ("异或", 高层表示运算符::异或),
    ("位与", 高层表示运算符::位与),
    ("位或", 高层表示运算符::位或),
    ("位非", 高层表示运算符::位非),  // 一元运算符（~甲）
    ("左移", 高层表示运算符::左移),
    ("右移", 高层表示运算符::右移),
];

/// 语法运算符 → 复合赋值方法名（规范 2.6.7 复合赋值运算符表）。
/// 语句分析在结构体复合赋值时调用；基本类型复合赋值仍走展开。
pub fn 语法运算符到复合赋值方法名(运算符: &语法运算符) -> Option<&'static str> {
    match 运算符 {
        语法运算符::加 => Some("加法赋值"),
        语法运算符::减 => Some("减法赋值"),
        语法运算符::乘 => Some("乘法赋值"),
        语法运算符::除 => Some("除法赋值"),
        语法运算符::取余 => Some("取余赋值"),
        语法运算符::整除 => Some("整除赋值"),
        语法运算符::幂 => Some("幂赋值"),
        语法运算符::位与 => Some("位与赋值"),
        语法运算符::位或 => Some("位或赋值"),
        语法运算符::异或 => Some("异或赋值"),
        语法运算符::左移 => Some("左移赋值"),
        语法运算符::右移 => Some("右移赋值"),
        _ => None,
    }
}

/// 检查方法名是否为合法的运算符重载方法名
pub fn 是否为重载方法(方法名: &str) -> bool {
    可重载映射.iter().any(|(名, _)| *名 == 方法名) || 语法运算符到复合赋值方法名_反查(方法名)
}

/// 反查：方法名是否是「XX赋值」复合赋值方法
fn 语法运算符到复合赋值方法名_反查(方法名: &str) -> bool {
    matches!(方法名, "加法赋值" | "减法赋值" | "乘法赋值" | "除法赋值" | "取余赋值" | "整除赋值"
        | "幂赋值" | "位与赋值" | "位或赋值" | "异或赋值" | "左移赋值" | "右移赋值")
}

/// 检查运算符是否支持重载
pub fn 是否支持重载(运算符: &高层表示运算符) -> bool {
    可重载映射.iter().any(|(_, op)| op == 运算符)
}

/// 获取重载方法名对应的运算符
pub fn 方法名到运算符(方法名: &str) -> Option<高层表示运算符> {
    可重载映射.iter().find(|(名, _)| *名 == 方法名).map(|(_, op)| op.clone())
}

/// 运算符 → 方法名（单一真相源，供表达式分析分发调用）
pub fn 运算符到方法名(运算符: &高层表示运算符) -> Option<&'static str> {
    可重载映射.iter().find(|(_, op)| op == 运算符).map(|(名, _)| *名)
}

/// 语法运算符 → 重载方法名（二元可重载运算符的单一分发真相源）。
/// 表达式分析在分发结构体运算符重载时调用本函数，方法名统一来自 `可重载映射`，
/// 杜绝与硬编码字面量漂移。非二元可重载运算符（如一元 取负）返回 None。
pub fn 语法运算符到重载方法名(运算符: &语法运算符) -> Option<&'static str> {
    let 高层 = match 运算符 {
        语法运算符::加 => 高层表示运算符::加,
        语法运算符::减 => 高层表示运算符::减,
        语法运算符::乘 => 高层表示运算符::乘,
        语法运算符::除 => 高层表示运算符::除,
        语法运算符::整除 => 高层表示运算符::整除,
        语法运算符::取余 => 高层表示运算符::取余,
        语法运算符::幂 => 高层表示运算符::幂,
        语法运算符::等于等于 => 高层表示运算符::等于,
        语法运算符::不等于 => 高层表示运算符::不等于,
        语法运算符::大于 => 高层表示运算符::大于,
        语法运算符::小于 => 高层表示运算符::小于,
        语法运算符::大于等于 => 高层表示运算符::大于等于,
        语法运算符::小于等于 => 高层表示运算符::小于等于,
        语法运算符::异或 => 高层表示运算符::异或,
        语法运算符::位与 => 高层表示运算符::位与,
        语法运算符::位或 => 高层表示运算符::位或,
        语法运算符::左移 => 高层表示运算符::左移,
        语法运算符::右移 => 高层表示运算符::右移,
        _ => return None,
    };
    运算符到方法名(&高层)
}

/// ★F16（2026-10-13）**分派期**签名门禁（规范 §2.6.7 规则 3/7）。
///
/// 规范原文：「若方法名匹配运算符但**参数数量不符**，它只是一个普通公开方法
/// （可通过 `.` 显式调用），**不参与运算符分派**。」
///
/// 实证缺口：`乘法()`（0 参）仍被 `*` 分派（`甲 * 乙` ⇒ 调用 0 参方法）✗。
/// 判据：一元（`取负`/`位非`）须 **0 参**；二元与复合赋值（`XX赋值`）须 **1 参**。
pub fn 方法签名可参与分派(方法名: &str, 参数数量: usize) -> bool {
    if 语法运算符到复合赋值方法名_反查(方法名) {
        return 参数数量 == 1;
    }
    if matches!(方法名, "取负" | "位非") {
        return 参数数量 == 0;
    }
    if !是否为重载方法(方法名) {
        return false;
    }
    参数数量 == 1
}

/// 验证运算符重载方法签名（规范 2.6.7 约束规则）
/// - 二元运算符：1个参数（另一个操作数）
/// - 一元运算符（取负/位非）：0个参数
/// - 比较运算符：必须返回逻辑类型
/// - 复合赋值运算符（XX赋值）：1个参数（另一个操作数）
/// - 规则7：参数数量与运算符要求不符时，仅视为普通公开方法（可通过 `.` 显式调用），不报错。
/// - 第一参数类型必须与定义结构体一致（外部调用者验证）
pub fn 验证重载方法签名(方法名: &str, 参数数量: usize, 返回类型: &super::类型信息::类型信息) -> Result<(), String> {
    // 是否复合赋值方法（XX赋值）
    if 语法运算符到复合赋值方法名_反查(方法名) {
        if 参数数量 != 1 {
            // 规则7：参数数量不符 → 普通方法，不参与运算符重载
            return Ok(());
        }
        return Ok(());
    }
    // 检查是否可重载
    if !是否为重载方法(方法名) {
        return Ok(()); // 非重载方法，不检查
    }
    // 一元运算符（取负、位非）：无参数
    if matches!(方法名, "取负" | "位非") {
        if 参数数量 != 0 {
            // 规则7：参数数量不符 → 普通方法
            return Ok(());
        }
        return Ok(());
    }
    // 二元运算符：1个参数
    if 参数数量 != 1 {
        // 规则7：参数数量不符 → 普通方法
        return Ok(());
    }
    // 比较运算符必须返回逻辑
    if matches!(方法名, "等于" | "大于" | "小于" | "大于等于" | "小于等于" | "不等于") {
        if !matches!(返回类型, super::类型信息::类型信息::基本型(super::类型信息::基本类型::逻辑)) {
            return Err(format!("比较运算符【{}】的重载方法必须返回逻辑类型", 方法名));
        }
    }
    Ok(())
}
