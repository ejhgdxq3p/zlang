//! 函数/方法级「类型参数」命名空间上下文（规范 §2.4.7）。
//!
//! 规范原文（§2.4.7 函数/方法级 + 类型参数段）：
//!   - 「函数/方法内部的**参数、局部变量、局部常量、类型参数**共享一个命名空间」；
//!   - 「类型参数遵循以下规则：**同一函数签名内不可重复**，且**不能与参数名、局部变量名同名**」。
//!
//! 设计选择（为什么不用"把类型参数登记成符号"）：
//!   符号表里的 `符号种类::类型参数` 目前只用于**内置类型名**（整数/小数…）。若把用户类型参数
//!   （`任意<甲>` 的 `甲`）也登记成符号，会改变**表达式解析**的既有行为（`甲` 一旦出现在表达式里
//!   会被当成"符号名"而报错，而不是"未定义标识符/隐式局部声明"），波及面远超本规则，风险不可控。
//!   ⇒ 采用**只读上下文**：进入函数/方法体时把该签名的类型参数名集合压入 thread_local，
//!     在「形参注册、局部变量/常量声明、遍历循环变量」处以**名字比对**实现，行为零扩散。
//!
//! 双模一致性：本模块**只在前端语义分析阶段**工作（命中即 `Err` 拒绝编译/解释），
//!   解释模式与编译模式共用同一前端 ⇒ 规则天然一致，**零后端改动**。

use std::cell::RefCell;

use crate::公共数据结构::源码位置;
use crate::语法分析::{形参, 类型表达式};

thread_local! {
    /// 当前正在分析的函数/方法的类型参数名（未去重；退出时由 [`类型参数作用域`] 还原）。
    static 当前类型参数: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
}

/// RAII 作用域守卫：`进入` 设置集合，`Drop` 还原进入前的集合（支持 λ 嵌套 / 方法体内再分析 λ）。
pub(crate) struct 类型参数作用域(Vec<String>);

impl 类型参数作用域 {
    /// 以 `集合` 作为当前类型参数上下文；返回值必须绑定到局部变量（`let _守卫 = ...`），
    /// 否则会立即 Drop ⇒ 上下文失效。
    pub(crate) fn 进入(集合: Vec<String>) -> Self {
        let 旧 = 当前类型参数.with(|c| std::mem::replace(&mut *c.borrow_mut(), 集合));
        Self(旧)
    }
}

impl Drop for 类型参数作用域 {
    fn drop(&mut self) {
        let 旧 = std::mem::take(&mut self.0);
        当前类型参数.with(|c| *c.borrow_mut() = 旧);
    }
}

/// 递归收集类型标注中的**有名任意类型**名（即类型参数），含容器/函数类型内部。
///
/// ⚠ **不去重**：重名本身就是待检项（"同一签名内不可重复"）——去重会静默放过重名。
pub(crate) fn 收集类型参数名(类型: &类型表达式, 输出: &mut Vec<String>) {
    match 类型 {
        类型表达式::任意类型 { 标记名称, 约束范围 } => {
            if let Some(名) = 标记名称 {
                输出.push(名.clone());
            }
            for 约束 in 约束范围 {
                收集类型参数名(约束, 输出);
            }
        }
        类型表达式::数组(元素) => 收集类型参数名(元素, 输出),
        类型表达式::映射(键, 值) => {
            收集类型参数名(键, 输出);
            收集类型参数名(值, 输出);
        }
        类型表达式::泛型 { 类型参数, .. } => {
            for t in 类型参数 {
                收集类型参数名(t, 输出);
            }
        }
        类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
            for t in 参数类型列表 {
                收集类型参数名(t, 输出);
            }
            收集类型参数名(返回类型, 输出);
        }
        _ => {}
    }
}

/// 同 [`收集类型参数名`]，额外记录「该次出现是否**带约束**」与**所在形参位置**（用于判「引入 vs 引用」）。
fn 收集带约束(类型: &类型表达式, 位置: &源码位置, 输出: &mut Vec<(String, bool, 源码位置)>) {
    match 类型 {
        类型表达式::任意类型 { 标记名称, 约束范围 } => {
            if let Some(名) = 标记名称 {
                输出.push((名.clone(), !约束范围.is_empty(), 位置.clone()));
            }
            for 约束 in 约束范围 {
                收集带约束(约束, 位置, 输出);
            }
        }
        类型表达式::数组(元素) => 收集带约束(元素, 位置, 输出),
        类型表达式::映射(键, 值) => {
            收集带约束(键, 位置, 输出);
            收集带约束(值, 位置, 输出);
        }
        类型表达式::泛型 { 类型参数, .. } => {
            for t in 类型参数 {
                收集带约束(t, 位置, 输出);
            }
        }
        类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
            for t in 参数类型列表 {
                收集带约束(t, 位置, 输出);
            }
            收集带约束(返回类型, 位置, 输出);
        }
        _ => {}
    }
}

/// 当前函数/方法是否为类型参数名（供局部声明处比对）。
pub(crate) fn 是类型参数名(名称: &str) -> bool {
    当前类型参数.with(|c| c.borrow().iter().any(|n| n == 名称))
}

/// 局部声明（变量/常量/遍历变量）落点：与类型参数同名即拒绝。
///
/// 返回 `Err(说明)` 由调用方用 `self.报错(...)` 落到具体位置（与项目内其它前置校验同款）。
pub(crate) fn 检查局部名(名称: &str) -> Result<(), String> {
    if 是类型参数名(名称) {
        return Err(format!(
            "【{}】是类型参数名，不能与函数/方法内部的局部变量/局部常量同名（参数、局部变量、局部常量、类型参数共享一个命名空间）",
            名称
        ));
    }
    Ok(())
}

/// 签名级校验 + 建立上下文：收集类型参数 → ① 重复 ❌ ② 与形参同名 ❌ → 返回守卫。
///
/// `签名描述` 仅用于错误文案（如 `函数【处理】` / `方法【车.移动】`）。
pub(crate) fn 建立(
    签名描述: &str,
    形参列表: &[形参],
    返回类型: &Option<类型表达式>,
) -> Result<类型参数作用域, (String, 源码位置)> {
    // ⚠ 只从**参数类型标注**收集：返回类型里的 `任意<甲>` 是对已声明类型参数的**引用**，
    //   不是又一次声明（`处理(任意<甲> 值) 任意<甲>` 是标准泛型签名，不得判重 ✗ 实测踩过）。
    //
    // 「重复声明」判据（★规范内部两处条文的**交集**，2026-10-17 定）：
    //   §2.4.7 明令「同一函数签名内不可重复」，❌ 示例 = `处理(任意<甲> a, 任意<甲> b)`（两处都是**裸引入**）；
    //   §5.1 官方签名表却写 `数学.最大值(任意<甲:整数|小数> 第一个, 任意<甲> 第二个)`（**带约束引入 + 裸引用**）。
    //   两者只在「**首次带约束、其后裸**」这一形态上相容 ⇒ 判据：
    //     名字**首次出现**＝引入（可裸、可带约束）；
    //     之后的同名出现**必须是裸引用**（且首次必须是带约束引入），否则即「重复声明」❌。
    //   这样：§2.4.7 的裸+裸示例 ❌ 报错、§5.1 的约束+裸签名 ✓ 放行。
    let mut 出现序列: Vec<(String, bool, 源码位置)> = Vec::new();
    for 形参 in 形参列表 {
        if let Some(类型标注) = &形参.类型标注 {
            收集带约束(类型标注, &形参.位置, &mut 出现序列);
        }
    }
    let _ = 返回类型; // 保留形参以维持调用点稳定（不参与收集）

    // ① 同一签名内不可重复（见上判据）
    {
        let mut 首次: std::collections::HashMap<String, bool> = std::collections::HashMap::new();
        for (名, 带约束, 位置) in &出现序列 {
            match 首次.get(名) {
                None => {
                    首次.insert(名.clone(), *带约束);
                }
                Some(&首次带约束) => {
                    if !(首次带约束 && !带约束) {
                        return Err((
                            format!(
                                "{}的类型参数【{}】重复声明（同一函数签名内类型参数不可重复；同名第二次出现只能作为无约束引用，且首次须带约束）",
                                签名描述, 名
                            ),
                            位置.clone(),
                        ));
                    }
                }
            }
        }
    }
    let 名称列表: Vec<String> = 出现序列.iter().map(|(n, _, _)| n.clone()).collect();

    // ② 不能与参数名同名
    for 类型参数名 in &名称列表 {
        for 形参 in 形参列表 {
            if &形参.名称 == 类型参数名 {
                return Err((
                    format!(
                        "{}的类型参数【{}】与参数【{}】同名（类型参数不能与参数名、局部变量名同名）",
                        签名描述, 类型参数名, 形参.名称
                    ),
                    形参.位置.clone(),
                ));
            }
        }
    }

    Ok(类型参数作用域::进入(名称列表))
}
