#[derive(Debug, Clone, PartialEq)]
pub enum 类型信息 {
    基本型(基本类型),
    数组(Box<类型信息>),
    映射(Box<类型信息>, Box<类型信息>),
    结构体(String, Vec<类型信息>),
    枚举(String),
    接口型(String),           // 接口类型变量（2.4.3）
    任意类型 {
        约束范围: Vec<类型信息>,
        变量索引: usize,       // 类型变量表中的索引
    },
    函数类型(Vec<类型信息>, Box<类型信息>),
    空值,
    未推断,
    推断错误,
}

#[derive(Debug, Clone, PartialEq)]
pub enum 基本类型 { 整数, 小数, 文本, 逻辑, 空值 }

impl 类型信息 {
    pub fn 整数类型() -> Self { 类型信息::基本型(基本类型::整数) }
    pub fn 小数类型() -> Self { 类型信息::基本型(基本类型::小数) }
    pub fn 文本类型() -> Self { 类型信息::基本型(基本类型::文本) }
    pub fn 逻辑类型() -> Self { 类型信息::基本型(基本类型::逻辑) }
    pub fn 空值类型() -> Self { 类型信息::基本型(基本类型::空值) }

    /// 是否是有类型参数的泛型结构体（形参列表非空）
    pub fn 是否为泛型结构体(&self) -> bool {
        matches!(self, 类型信息::结构体(_, 参数列表) if !参数列表.is_empty())
    }

    /// 获取泛型结构体的类型参数数量
    /// 数组（1个）、映射（2个）、泛型结构体（形参列表长度）
    pub fn 泛型参数数量(&self) -> usize {
        match self {
            类型信息::结构体(_, 参数列表) => 参数列表.len(),
            类型信息::数组(_) => 1,
            类型信息::映射(_, _) => 2,
            _ => 0,
        }
    }

    pub fn 类型名称(&self) -> String {
        match self {
            类型信息::基本型(基本类型::整数) => "整数".into(),
            类型信息::基本型(基本类型::小数) => "小数".into(),
            类型信息::基本型(基本类型::文本) => "文本".into(),
            类型信息::基本型(基本类型::逻辑) => "逻辑".into(),
            类型信息::基本型(基本类型::空值) => "空值".into(),
            类型信息::数组(_) => "数组".into(),
            类型信息::映射(_, _) => "映射".into(),
            类型信息::结构体(名, _) => 名.clone(),
            类型信息::枚举(名) => 名.clone(),
            类型信息::接口型(名) => format!("接口【{}】", 名),
            类型信息::任意类型 { 约束范围, .. } => {
                let 类型名列表: Vec<String> = 约束范围.iter().map(|t| t.类型名称()).collect();
                if 类型名列表.is_empty() {
                    "任意".into()
                } else {
                    format!("任意<{}>", 类型名列表.join("|"))
                }
            },
            类型信息::函数类型(_, _) => "函数".into(),
            类型信息::空值 => "空值".into(),
            类型信息::未推断 => "未推断".into(),
            类型信息::推断错误 => "推断错误".into(),
        }
    }
}