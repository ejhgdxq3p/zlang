// 文件: 前端/src/语义/类型推断.rs
// 职责: 类型推断逻辑，根据字面值和表达式推断类型

use super::高层表示节点::{字面值, 高层表示表达式};
use super::类型信息::类型信息;

pub fn 从字面值推断(字面值: &字面值) -> 类型信息 {
    match 字面值 {
        字面值::整数(_) => 类型信息::整数类型(),
        字面值::小数(_) => 类型信息::小数类型(),
        字面值::文本(_) => 类型信息::文本类型(),
        字面值::逻辑(_) => 类型信息::逻辑类型(),
        字面值::空值 => 类型信息::空值类型(),
        字面值::数组(元素列表, 元素类型) => {
            if 元素列表.is_empty() {
                类型信息::数组(Box::new(类型信息::未推断))
            } else if let Some(t) = 元素类型 {
                // 优先使用显式元素类型标注（类型化数组字面量）
                类型信息::数组(Box::new(*t.clone()))
            } else {
                // ★ 2026-10-19 修复（核心库全面测试发现，与 F30 映射同源）：
                //   原实现**只取首元素**推断元素类型 ✗ —— `[3, 1.5, 2]` ⇒ `数组<整数>`，
                //   而运行时元素保留真实标签（1.5 仍是小数），于是：
                //     · `混[2] == 1.5` ⇒ **恒假**（静态按整数语义比较 ✗，实测复现）
                //     · `.排序()` 修复前亦因静态/运行时错位而观测异常
                //   ⇒ 改为**全元素求统一类型**（与映射 F30 修法完全同源）：
                //     全部相同 ⇒ 用该类型；出现不同 ⇒ `未推断`（取回值按**运行时实际类型**分派）。
                //   同构字面量（绝大多数用例）行为不变 ✓；异构字面量从"首元素类型 + 静默错判"
                //   变为"未知类型 + 运行时正确" ✓。
                let 类型列表: Vec<类型信息> = 元素列表.iter().map(从表达式推断).collect();
                let 首类型 = 类型列表[0].clone();
                if 类型列表.iter().all(|t| *t == 首类型) {
                    类型信息::数组(Box::new(首类型))
                } else {
                    类型信息::数组(Box::new(类型信息::未推断))
                }
            }
        }
        字面值::映射(对列表) => {
            // ★ 2026-10-02（**F30 修复**）：原实现**只取首对**推断键/值类型 ✗。
            //   **缺陷**（真实、双模一致、**静默错值** ✗）：字面量**异构**时（如 `{"甲": {…}, "丙": [1, 2, 3]}`），
            //     映射的**值类型被推成首对的类型**（此处 = 映射 ✗）⇒ 之后取回的**数组**值被按
            //     「映射」做**静态方法分派** ⇒ `.长度()` 读到映射的槽位 ⇒ **0** ✗（`是否包含` 恒假 ✗、
            //     `查找索引` 恒 0 ✗），而 `类型()`=数组 ✓、`索引`/`取末尾`/`转文本` 全对 ✓
            //     ⇒ 即"**数据本体完好、仅长度类查询读错**" ✓。
            //   **判据**（实测钉死）：把键顺序调换成"数组在前"即恢复正常 ✓、标量在首也正常 ✓
            //     ⇒ 确系"首对决定 ✗"；同构字面量（全数组）始终正常 ✓。
            //   **修法**：**全对求统一类型** —— 全部相同 ⇒ 用该类型 ✓；出现不同 ⇒ **未推断**（未知 ✓）
            //     ⇒ 取回值走**运行时按实际类型分派** ✓（与 `类型文本转类型` 对 `"数组"`/`"映射"`
            //       一律落 `未推断` 元素的既有约定同源 ✓）。
            //   ⚠ 键类型同理统一（异构键亦不应按首键分派 ✗）；空映射保持双向未推断 ✓。
            if 对列表.is_empty() {
                return 类型信息::映射(Box::new(类型信息::未推断), Box::new(类型信息::未推断));
            }
            let 键列表: Vec<类型信息> = 对列表.iter().map(|(k, _)| 从表达式推断(k)).collect();
            let 值列表: Vec<类型信息> = 对列表.iter().map(|(_, v)| 从表达式推断(v)).collect();
            let 统一 = |列表: &Vec<类型信息>| -> 类型信息 {
                let 首 = 列表[0].clone();
                if 列表.iter().all(|t| *t == 首) { 首 } else { 类型信息::未推断 }
            };
            let 键类型 = 统一(&键列表);
            let 值类型 = 统一(&值列表);
            类型信息::映射(Box::new(键类型), Box::new(值类型))
        }
    }
}

pub fn 从表达式推断(表达式: &高层表示表达式) -> 类型信息 {
    match 表达式 {
        高层表示表达式::字面值(值, _) => 从字面值推断(值),
        高层表示表达式::变量引用 { 类型, .. } => 类型.clone(),
        高层表示表达式::二元运算 { 类型, .. } => 类型.clone(),
        高层表示表达式::调用 { 类型, .. } => 类型.clone(),
        高层表示表达式::间接调用 { 类型, .. } => 类型.clone(),
        高层表示表达式::方法调用 { 类型, .. } => 类型.clone(),
        高层表示表达式::字段访问 { 类型, .. } => 类型.clone(),
        高层表示表达式::枚举成员访问 { 类型, .. } => 类型.clone(),
        高层表示表达式::成员访问 { 类型, .. } => 类型.clone(),
        高层表示表达式::隐式转换 { 目标类型, .. } => 目标类型.clone(),
        高层表示表达式::函数引用 { 类型, .. } => 类型.clone(),
        高层表示表达式::创建结构体 { 结构体名, 实参列表, .. } => {
            // 从实参推断类型参数（用于泛型结构体如 栈(整数)）
            let 类型参数: Vec<类型信息> = 实参列表.iter()
                .map(|e| 从表达式推断(e))
                .collect();
            if 类型参数.is_empty() {
                类型信息::结构体(结构体名.clone(), vec![])
            } else {
                类型信息::结构体(结构体名.clone(), 类型参数)
            }
        }
        高层表示表达式::匿名函数(函数) => {
            // 从闭包的形参列表推断参数类型，从返回类型标注推断函数类型
            let 返回类型 = 函数.返回类型.clone().unwrap_or(类型信息::未推断);
            let 参数类型: Vec<类型信息> = 函数.形参列表.iter()
                .map(|(_, t)| t.clone())
                .collect();
            类型信息::函数类型(参数类型, Box::new(返回类型))
        }
    }
}