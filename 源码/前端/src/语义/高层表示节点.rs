#[derive(Debug, Clone)]
pub enum 高层表示语句 {
    变量声明 {
        名称: String,
        初始值: 高层表示表达式,
        类型: 类型信息,
        是否可变: bool,
        /// ★§2.4.7 收口（2026-09-19）：**是否模块级声明**。
        /// 背景：降级层原先**只看名字**是否在 `全局变量名列表` 中，就把变量声明写进全局存储 ——
        /// 这在新语义下是错的：函数内 `X = 值`（X 与模块级变量同名）已被语义层判为**隐式声明局部**，
        /// 但降级层仍按名字写全局槽 ⇒ 模块级被误改（实测：冒烟 `改局部()` 后 `本模块.模块值` 变成 20）。
        /// ⇒ 由语义层显式标注本字段，降级层据此区分（`true` 才写全局槽）。
        /// 置 `true` 的唯一位置：`公共降级.rs` 注入「顶层初始化语句」时（那才是模块级声明）。
        是否模块级: bool,
    },
    赋值 {
        目标: 高层表示表达式,
        值: 高层表示表达式,
    },
    表达式语句(高层表示表达式),
    条件语句 {
        分支列表: Vec<(高层表示表达式, Vec<高层表示语句>)>,
        否则分支: Option<Vec<高层表示语句>>,
    },
    循环语句 {
        条件: 高层表示表达式,
        循环体: Vec<高层表示语句>,
        步进: Option<Box<高层表示语句>>,
    },
    跳出语句(源码位置),
    继续语句(源码位置),
    返回语句(Option<高层表示表达式>),
    异常控制 {
        危险块: Vec<高层表示语句>,
        异常块: Vec<高层表示语句>,
        始终块: Vec<高层表示语句>,
        存在异常块: bool,
    },
    抛出语句(Option<Box<高层表示表达式>>, 源码位置),
    代码块(Vec<高层表示语句>),
    /// 🆕 **语句序列**：纯多语句容器，**不引入块作用域**（顺序执行、不改变可见性）。
    /// 专门用于语义层**反糖打包**（例：`循环 计数 = 1..N` ⇒ `语句序列[变量声明{计数}, 循环语句{…}]`；
    /// `遍历` ⇒ `语句序列[索引/键/值声明…, 循环语句]`）。
    /// 依据（实测铁证）：反糖用 `代码块` 打包 ⇒ 降级层按"块作用域"在块退出时清除块内声明 ⇒
    /// 循环变量在用户视角的同一作用域内被清掉 ⇒ 外部引用取到 `函数#-65536`（最小复现 `二分_循环变量最小复现.智`）。
    /// 与 `代码块` 的唯一区别：**是否引入作用域**。`代码块` = 用户书写的内层块（块内声明到块结束失效、遮蔽可恢复）。
    语句序列(Vec<高层表示语句>),
}

