/// FFI: 外部块中声明的函数（无函数体，通过动态库/静态链接调用）
#[derive(Debug, Clone)]
pub struct 高层表示外部函数 {
    pub 名称: String,
    pub 链接名: String,            // C 符号名
    pub 形参列表: Vec<(String, 类型信息)>,
    pub 返回类型: Option<类型信息>,
    pub 语言: String,              // "C" 等
    pub 库标识: String,            // 🆕 FFI: 库标识
    pub 输出位图: Vec<bool>,        // 🆕 FFI: 每形参是否为输出参数
    /// 🆕 P3: 每形参的精确 C 类型码（0=缺省；跨层契约见 外部调用注册::精确类型码到C类型）
    pub 形参C类型: Vec<u8>,
    /// 🆕 P3: 返回类型的精确 C 类型码（0=缺省）
    pub 返回C类型: u8,
    /// 🆕 回调：每个函数指针形参对应的 trampoline 形状码（0-4，255=动态）
    pub 函数指针形状: Vec<u8>,
    /// 🆕 FFI（§6.5.2 第5项）：是否外部全局变量（true=C 全局变量，shim 走 `static` 读取而非 `fn` 调用）
    pub 是否全局变量: bool,
    /// 🆕 2026-08-29 FFI 数组：每形参的数组元素外部类型码（非数组形参=0；数组形参=元素精确码，
    /// 宿主据此把智语言数组序列化为 C ABI 紧凑缓冲传给 shim）
    pub 形参数组元素C类型: Vec<u8>,
    /// 🆕 2026-08-29 FFI 数组：数组形参的紧邻长度参数索引（经典 `T*, len` 模式；
    /// 无紧邻长度参数 = usize::MAX）。宿主据此校验「长度 ≤ 数组实际长度」并限定序列化/回写范围。
    pub 形参数组长度索引: Vec<usize>,
}

/// FFI: 外部块中声明的结构体（C 兼容布局）
#[derive(Debug, Clone)]
pub struct 高层表示外部结构体 {
    pub 名称: String,
    pub 字段列表: Vec<(String, 类型信息)>,
    pub 链接名: String,            // C 结构体名称
    /// 🆕 2026-09-25 **字段 FFI 精确码通道**（规范 §6.5.6）：按声明顺序扁平编码，
    /// 自描述、可变长：
    ///   · 标量外部类型      ⇒ `[精确码]`
    ///   · 数组字段 `数组<X>` ⇒ `[布局码_外部数组字段(22)][元素精确码]`（规范数组映射表：C 指针 `X*`）
    ///   · 嵌套结构体字段     ⇒ `[21][名字字节长度 u8][名字 UTF-8 字节…]`
    ///   · 其它/未知          ⇒ `[0]`（交由既有「大专」通道回退）
    /// 【为何必须存在】`类型信息`/`底层表示类型` 只保留**大类**（结构体→指针、无符号位宽整数→整数64），
    /// 若布局仅由大类推导 ⇒ 嵌套结构体字段退化为不透明指针、数组元素位宽丢失 ⇒ 跨边界编组错。
    pub 字段精确码: Vec<u8>,
}