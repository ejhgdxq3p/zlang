                        // ⚠ 2026-09-26 修复（规范 §2.7.4 L8098「命名别名后**原来的名字不可使用**」）：
                        //   带 `别名` 的导入改以**别名**作注册前缀 ⇒ 成员符号注册为 `别名.成员`，
