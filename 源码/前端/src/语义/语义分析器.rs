                            let 之前结构体 = self.当前结构体.replace(结构体.名称.clone());
                            // ★F19 修复（2026-10-14）：初始化方法**登记返回类型 = 空值** —— 使下方注释早已声明、
                            //   但**从未实施**的规则「初始化不能带返回值」（规范明文）由返回处一致性校验真正生效 ✓。
                            let 之前初始化返回类型 = self.当前函数返回类型.replace(类型信息::空值);
                            // ★§2.3.5（修复 2026-10-12，探针 Z4）：**初始化体顶层与构造参数同属一个命名空间**
                            //   ⇒ `初始化(): 整数 宽 = 2`（与构造参数 宽 同名）必须报「重复声明」，
                            //   此前因多开一层「代码块」作用域被静默接受（局部遮蔽构造参数）。
                            let 体 = self.分析代码块_内部(&初始化定义.函数体)?;
                            // 【A2 已彻底移除（2026-09-21 · COW 退役）】此前在此**隐式追加「返回 自身」**，
                            //   目的是把 COW 分离产生的新句柄带回构造处持久化。
