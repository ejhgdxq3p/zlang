                    //     A3 已知限制（跨库同名全局变量冲突），另行处理。
                    let mut 排序后模块: Vec<(&String, &_)> = 模块映射.iter().collect();
                    排序后模块.sort_by(|甲, 乙| 甲.0.cmp(乙.0));
