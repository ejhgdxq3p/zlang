    /// 检查类型是否为泛型结构体，若是则注册类型绑定表（写入真实类型参数）
    pub(crate) fn 注册泛型实例(&mut self, 变量名: &str, 类型: &类型信息) {
        match 类型 {
            类型信息::结构体(结构体名, 实参列表) if !实参列表.is_empty() => {
                // 有显式类型参数时直接写入（如 任务<整数> → [整数]）
                self.类型绑定表.注册或重置实例(变量名, 实参列表);
            }
            类型信息::结构体(结构体名, _) => {
                // 无显式类型参数：从结构体环境推断参数数量并占位
                if let Some(定义) = self.结构体环境.get(结构体名) {
                    let 类型参数数 = 定义.形参列表.iter()
                        .filter(|p| p.类型标注.as_ref().map_or(false, |t| matches!(t, 类型表达式::任意类型 { .. })))
                        .count();
                    if 类型参数数 > 0 {
                        self.类型绑定表.注册或重置实例占位(变量名, 类型参数数);
                    }
                }
            }
            _ => {}
        }
    }

    /// 从表达式中提取简单变量名（用于类型绑定查找）
    pub(crate) fn 提取变量名(&self, 表达式: &高层表示表达式) -> Option<String> {
        match 表达式 {
            高层表示表达式::变量引用 { 名称, .. } => Some(名称.clone()),
            // 🆕 支持 `对象.方法()` 形式（如 结果.等待结果() 提取 "结果"），
            // 此前只认 变量引用，导致 `结果.等待结果()` 的 对象名 提取为 None，
            // 泛型实例绑定表查不到 结果 的类型参数（任务<甲> 的 甲），方法返回类型无法回填。
            高层表示表达式::成员访问 { 对象, .. } => self.提取变量名(对象),
            _ => None,
        }
    }

    /// ★★ 单一真相：类型的**自然零值**表达式（规范 §2.3.4「默认值规则」，规范第 1645-1696 行）★★
    ///
    /// 规范铁律（规范第 1649 行原文）：
    ///   **「所有变量声明都是『声明 + 初始化』。有自然零值的类型可以省略初始化，
    ///     没有自然零值的类型必须初始化。」**
    ///
    /// 因此本函数做的是**声明脱糖（desugar）**——把 `类型 名称`（省略初始化）展开为
    /// `类型 名称 = <自然零值字面量>`，而不是"运行期兜底补一个值"。
    ///
    /// | 类别 | 类型 | 自然零值 | 可否省略初始化 |
    /// | :--- | :--- | :--- | :--- |
    /// | 基本类型(5) | 整数 / 小数 / 文本 / 逻辑 / 空值 | `0` / `0.0` / `""` / `假` / `空值` | ✅ 可省略 |
    /// | **容器类型(2)** | **数组 / 映射** | **`[]` / `{}`** | **✅ 可省略** |
    /// | 自定义类型(5) | 任意 / 函数 / 结构体 / 接口 / 枚举 | 无 | ❌ 必须初始化 |
    ///
    /// 返回：`Err` 表示该类型**没有自然零值**，必须显式初始化。调用方必须**报错并中断**；
    ///       **严禁**用「补空值」之类的方式兜底——那会让违反规范的代码静默通过，
    ///       且这种错误是**双模一致地错**（解释与编译同错），双模门禁永远查不出来。
    pub(crate) fn 获取类型默认值(&mut self, 类型: &类型信息, 位置: &源码位置) -> Result<高层表示表达式, ()> {
        match 类型 {
            类型信息::基本型(基本类型::整数) =>
                Ok(高层表示表达式::字面值(字面值::整数(0), 类型信息::整数类型())),
            类型信息::基本型(基本类型::小数) =>
                Ok(高层表示表达式::字面值(字面值::小数(0.0), 类型信息::小数类型())),
            类型信息::基本型(基本类型::文本) =>
                Ok(高层表示表达式::字面值(字面值::文本(String::new()), 类型信息::文本类型())),
            类型信息::基本型(基本类型::逻辑) =>
                Ok(高层表示表达式::字面值(字面值::逻辑(false), 类型信息::逻辑类型())),
            类型信息::空值 | 类型信息::基本型(基本类型::空值) =>
                Ok(高层表示表达式::字面值(字面值::空值, 类型信息::空值类型())),
            // ★★ 2026-09-20 缺口修复（真实现缺陷；规范要求 vs 实现不符）★★
            //   规范依据（三处，互为印证）：
            //     ① 规范第 1295 行：「**容器类型**（数组、映射）：**有默认值 `[]`/`{}`**，
            //        隐式声明必须赋值，显式声明可省略初始化。」
            //     ② 规范「声明写法总表」第 1523-1526 行：数组(有约束/无约束)、映射(有约束/无约束)
            //        一律「✅ 可省略 | 默认值 `[]` / `{}`」。
            //     ③ 规范「字段类型支持总表」第 1580-1583 行：容器字段同样「可省略（默认 `[]` / `{}`）」。
            //
            //   而旧实现把 数组/映射 与 结构体/枚举/函数/接口 **归入同一 `Err` 分支**（「必须显式赋值初始化」）：
            //     ① 变量声明路径（语句分析.rs:227 局部 / 语义分析器.rs:1214 顶层）会**直接报错**，
            //        把规范明确允许的 `数组<整数> 数字` 判为非法；
            //     ② 结构体字段路径（表达式分析.rs:913）落到 `Err(_) => 补空值` 兜底 ⇒
            //        字段默认值变成**「空值」而不是 `[]`/`{}`** ⇒ 运行期 `.长度()`/`.插入()` 必错，
            //        且解释与编译**同错**（双模一致地错 ⇒ 双模门禁查不出）。
            //     实证：`测试/2项目类测试/结构体测试项目/源码/总_深层嵌套第三轮类型系统.智`
            //       第 30-32 行 `结构体 库房:` 的 `映射 分区` / `数组 流水`（字段省略初始化），
            //       第 63-65 行**被迫手工构造** `映射 空分区 = {}` / `数组 空流水 = []` 再传入
            //       （`库房 甲库 = 库房(空分区, 空流水)`）才能工作 —— 这正是"规范要的默认值没实现"的现场证据。
            //
            //   ⇒ 修法：返回**空容器字面量表达式**（即把 `数组<整数> 甲` 脱糖为 `数组<整数> 甲 = []`）。
            //
            //   ⚠ 为什么必须是「字面量表达式」而不是"共享的空容器常量"（关键设计约束）：
            //     · 每个声明点各自求值 ⇒ 每次**新建独立容器**，`数组 甲` 与 `数组 乙` 不共享；
            //       结构体变量字段也因此"各实例取值可不同"（规范第 3477 行）。
            //     · 降级层对数组/映射字面量有配套处理：复合类型深拷贝（语句转换.rs:440）、
            //       复合字面量就地释放（语句转换.rs:323-329、441-442）、待释放局部登记
            //       （语句转换.rs:402-407）⇒ 走**真实字面量路径**才能自动获得正确的
            //       引用计数语义，避免泄漏/二次释放，也避免多变量共享同一容器。
            //     · 与用户手写 `= []` **完全同一条 LIR 指令序列** ⇒ 两后端零改动、天然双模一致。
            类型信息::数组(元素类型) => Ok(高层表示表达式::字面值(
                字面值::数组(Vec::new(), Some(Box::new((**元素类型).clone()))),
                类型.clone(),
            )),
            类型信息::映射(_, _) => Ok(高层表示表达式::字面值(
                字面值::映射(Vec::new()),
                类型.clone(),
            )),
            // 自定义类型(5)：无自然零值 ⇒ 一律报错，必须显式初始化（调用方严禁兜底）。
            //   任意类型（含约束含空值者）同样必须显式初始化（规范第 1672、1687 行；
            //   ⚠ 2026-09-04 已删除原「约束含空值→默认空值」豁免，与规范冲突）。
            类型信息::任意类型 { .. } => {
                self.报错(
                    &format!("类型【{}】没有默认值，必须显式初始化", 类型.类型名称()),
                    位置,
                );
                Err(())
            }
            类型信息::函数类型(_, _) => {
                // 规范 §2.3.2「函数」条款（第 3098-3104 行原文）：
                //   「函数类型支持显式和隐式两种声明，但**必须直接赋值**。
                //     显式声明必须写完整的函数类型签名（参数类型 + 返回类型）。
                //     简写 `函数 操作 = 加法` 禁止，因为类型不明确。」
                //   「❌ 禁止：先声明后赋值」「❌ 禁止：赋空值（类型不匹配）」。
                // ⇒ 给**专用措辞**（而非通用"必须显式赋值初始化"），让用户一眼看懂该怎么改。
                self.报错(
                    &format!(
                        "函数类型【{}】必须直接赋值初始化（禁止先声明后赋值）：请写成 `{} 名称 = 函数名`",
                        类型.类型名称(),
                        类型.类型名称()
                    ),
                    位置,
                );
                Err(())
            }
            类型信息::结构体(_, _)
            | 类型信息::接口型(_) | 类型信息::枚举(_) => {
                self.报错(
                    &format!("类型【{}】必须显式赋值初始化", 类型.类型名称()),
                    位置,
                );
                Err(())
            }
            // 未推断 / 推断错误：**不得**补空值（类型擦除.rs:20-26 记载过「未推断 曾擦除为 空值
            //   致双模分歧」的历史事故，此处保持同一原则）。
            类型信息::未推断 | 类型信息::推断错误 => {
                self.报错(
                    &format!("类型【{}】必须显式赋值初始化", 类型.类型名称()),
                    位置,
                );
                Err(())
            }
        }
    }

    /// 检查是否为常量声明（用于常量不可修改检测）
    pub(crate) fn 是常量符号(&self, 名称: &str) -> bool {
        self.符号表.查找符号(名称)
            .map(|s| !s.是否可变 && matches!(s.符号种类, 符号种类::变量{..}))
            .unwrap_or(false)
    }

    /// 🆕 收集当前作用域中所有「可变符号」名称（变量/参数，是否可变=true），供常量初值编译期检查
    pub(crate) fn 收集可变符号名(&self) -> std::collections::HashSet<String> {
        let mut 集合 = std::collections::HashSet::new();
        for 作用域 in &self.符号表.作用域栈 {
            for (名, 符号) in &作用域.符号映射 {
                if 符号.是否可变 && matches!(符号.符号种类, 符号种类::变量 { .. }) {
                    集合.insert(名.clone());
                }
            }
        }
        集合
    }

    /// 🆕 校验常量初值是否为编译期常量：不得引用运行时变量/参数/自身/字段，不得含函数调用。
    /// 返回 Err(原因) 表示非法；Ok(()) 表示合法（字面量/其他常量/纯运算组合）。
    pub(crate) fn 校验常量初值(&self, 表达式: &表达式, 禁止名: &std::collections::HashSet<String>) -> Result<(), String> {
        match 表达式 {
            表达式::字面值(_) => Ok(()),
            表达式::标识符(名, _) => {
                if 禁止名.contains(名) {
                    Err(format!("不能包含运行时变量【{}】", 名))
                } else {
                    Ok(())
                }
            }
            表达式::二元运算(左, _, 右, _) => {
                self.校验常量初值(左, 禁止名).and_then(|_| self.校验常量初值(右, 禁止名))
            }
            表达式::一元运算(_, 操作数) => self.校验常量初值(操作数, 禁止名),
            表达式::调用 { .. } => Err("不能包含函数调用".to_string()),
            表达式::类型标注表达式 { 表达式: e, .. } => self.校验常量初值(e, 禁止名),
            表达式::成员访问 { 对象, .. } => self.校验常量初值(对象, 禁止名),
            表达式::索引访问 { 对象, 索引, .. } => {
                self.校验常量初值(对象, 禁止名).and_then(|_| self.校验常量初值(索引, 禁止名))
            }
            表达式::类型转换 { 源表达式, .. } => self.校验常量初值(源表达式, 禁止名),
            // ⚠ 保持禁止（2026-09-19 复核规范后**确认正确**，勿放宽）：
            //   规范第 1263-1270 行原文：「智语言的『常量』是**编译期常量**」并给出
            //     `常量 类型 = "普通用户"` ✅（字面量/编译期确定） vs `常量 编号 = 姓名 + "-001"` ❌（运行时变量）。
            //   匿名函数字面量是**运行时值**（闭包需捕获环境）⇒ 不得作常量初值。
            //   规范第 2703 行「常量…类型可以是…匿名函数」指的是**类型标注**可为函数类型
            //     （此时初值应写编译期已知的**具名函数名**，如 `常量 加倍 = 某具名函数`），并非允许匿名函数字面量。
            //   ⇒ `47 匿名函数.智` 用 `常量 加倍 = 函数(...)…结束` 属**用例违反规范**，已改用例而非改实现。
            表达式::匿名函数(_) => Err("不能包含匿名函数".to_string()),
        }
    }

