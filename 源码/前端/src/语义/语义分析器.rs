    /// 在导入列表中定位「加载器的模块键」对应的导入声明（相对导入以 `解析后键` 匹配）。
    /// 统一两处注册点的匹配口径（此前一处含 `模块路径.join("/")`、另一处不含）。
    fn 找对应导入<'i>(
        导入列表: &'i [crate::语法分析::导入声明],
        模块名: &str,
    ) -> Option<&'i crate::语法分析::导入声明> {
        导入列表.iter().find(|i| Self::导入声明匹配(i, 模块名))
    }

    /// 导入声明 ↔「加载器模块键」对应判定（**单一匹配口径**，供 `找对应导入` 与注册循环共用）。
    ///
    /// 三种键形态都必须命中（历史原因，缺一不可）：
    ///   · `模块路径.join("/")`：用户书写形式（`图形界面/基础部件`）；
    ///   · `模块路径.join(".")`：加载器**绝对导入**模块键（`图形界面.基础部件`，见 模块加载器::递归加载模块）；
    ///   · `解析后键`：**相对导入**模块键（规范化绝对路径，见 模块加载器::解析相对导入）。
    pub(crate) fn 导入声明匹配(i: &crate::语法分析::导入声明, 模块名: &str) -> bool {
        i.模块路径.join("/") == 模块名
            || i.模块路径.join(".") == 模块名
            || i.解析后键.as_deref() == Some(模块名)
    }

    /// F5（2026-09-28）：判定「标准库模块前缀**未导入**」并给出可执行的报错描述。
    ///
    /// **为什么需要**：`类型推导::预注册内置模块符号` 已按导入列表注册符号（规范 §5），
    ///   未导入时符号查不到 ⇒ 调用/常量访问会**静默落到方法分派** ⇒ 报出与事实无关的
    ///   「类型没有方法」✗（实测口径误导）。本助手把该情形改写为精确诊断。
    ///
    /// **判定链（全部满足才报）**：
    ///   ① 首段是标准库模块名（`标准库元数据::按模块分组` 单一真相）；
    ///   ② 该首段**不在**本文件已导入的标准库访问名里；
    ///   ③ 首段**不是**用户可用符号（避免用户变量/模块恰与标准库同名时误报）。
    ///
    /// **文案分两种**：该模块已以**别名**导入 ⇒ 按 §2.7.3 L8098「命名别名后原来的名字不可使用」提示；
    ///   否则 ⇒ 提示补 `导入 X`。
    pub(crate) fn 标准库未导入报错描述(&self, 完整名: &str) -> Option<String> {
        let 首段 = 完整名.split('.').next()?;
        if 首段.is_empty() {
            return None;
        }
        let 是标准库模块 = crate::标准库元数据::按模块分组()
            .iter()
            .any(|(m, _)| *m == 首段);
        if !是标准库模块 {
            return None;
        }
        let 全表 = crate::降级::类型转换::本文件标准库访问名
            .get_or_init(|| std::sync::Mutex::new(HashMap::new()));
        let 全表 = 全表.lock().unwrap();
        // 该首段是否在**任何**文件里被当作标准库模块导入过 —— 用于区分「标准库虚拟变量」与
        // 「用户自己的同名符号」（后者必须在标准库判定之前让路，否则会误报）
        let 是标准库符号 = 全表.values().any(|m| m.contains_key(首段));
        if !是标准库符号 && self.符号表.查找符号(首段).is_some() {
            return None; // 用户同名符号（局部变量 / 用户模块）⇒ 交给常规解析
        }
        // 本文件的键：被导入模块用其**访问前缀**（= `当前模块`），入口文件用固定键
        let 文件键 = match &self.当前模块 {
            Some(名) => 名.clone(),
            None => crate::降级::类型转换::入口文件键.to_string(),
        };
        let 本文件 = 全表.get(&文件键);
        if let Some((规范名, 是否展开)) = 本文件.and_then(|m| m.get(首段).cloned()) {
            // 本文件已以「首段」为访问名导入 ⇒ 正常。唯一例外：**展开导入后仍用模块前缀**。
            // 依据 §2.7.3 L8082「展开只留裸名，子命名空间不能使用」、
            //      §2.7.2 L7952「展开后只剩裸名，模块名和别名均失效」。
            if 是否展开 && 规范名 == 首段 {
                return Some(format!(
                    "模块【{}】以展开方式导入，展开后模块名不再可用：请直接用展开后的裸名成员（如 `成员名(...)`），子命名空间不能用。",
                    首段
                ));
            }
            return None;
        }
        // 本文件是否以**别名**导入了该模块？若是，则用户是在用「原名字」（§2.7.3 明令不可用）
        if let Some(别名) = 本文件.and_then(|m| {
            m.iter()
                .find(|(_, (规范名, _))| 规范名.as_str() == 首段)
                .map(|(别名, _)| 别名.clone())
        }) {
            return Some(format!(
                "标准库模块【{}】已以别名【{}】导入，别名导入后原模块名不可使用：请改用【{}】访问，或去掉别名。",
                首段, 别名, 别名
            ));
        }
        Some(format!(
            "标准库模块【{}】使用前必须先导入（要先导入才能用 `模块名.成员`）：请在文件顶层添加 `导入 {}`。",
            首段, 首段
        ))
    }

    /// F5 收口（2026-09-28）：计算**某个文件**可用的标准库访问名集合。
    ///
    /// **规则（文件级）**：
    ///   · 该文件**自己** `导入 X` / `导入 X 别名 Y` / `导入 X 展开` 的标准库模块 ⇒ 可见（访问名 = 别名/模块名）；
    ///   · 该文件导入的**聚合模块**（`聚合导入 …`，规范 §2.9）所聚合的目标模块，其导入的标准库模块
    ///     ⇒ 亦可见（聚合重导出语义；递归覆盖多级聚合，按目标键去重防环）。
    ///   · 其它文件的标准库导入**不可见** —— 这正是「程序级并集注册」与「严格文件级校验」的分工：
    ///     符号由并集注册（保证降级期可解析），可见性由本表按**当前文件**判定 ✓。
    fn 计算标准库可见集(
        导入列表: &[crate::语法分析::导入声明],
        模块映射: &std::collections::HashMap<String, crate::模块加载器::模块数据>,
    ) -> std::collections::HashMap<String, (String, bool)> {
        let mut 可见: std::collections::HashMap<String, (String, bool)> = std::collections::HashMap::new();
        let mut 待处理: Vec<crate::语法分析::导入声明> = 导入列表.to_vec();
        let mut 已处理聚合: std::collections::HashSet<String> = std::collections::HashSet::new();
        while let Some(导入) = 待处理.pop() {
            if 导入.是否聚合 {
                let 目标键 = if 导入.是否相对 {
                    导入.解析后键.clone().unwrap_or_else(|| 导入.模块路径.join("."))
                } else {
                    导入.模块路径.join(".")
                };
                if 已处理聚合.insert(目标键.clone()) {
                    if let Some(数据) = 模块映射.get(&目标键) {
                        for 子 in 数据.导入列表.iter() {
                            待处理.push(子.clone());
                        }
                    }
                }
                continue;
            }
            let 键 = 导入.模块路径.join(".");
            if crate::标准库元数据::按模块分组().iter().any(|(m, _)| *m == 键) {
                let 访问名 = 导入.别名.clone().unwrap_or_else(|| 键.clone());
                可见.insert(访问名, (键, 导入.是否展开));
            }
        }
        可见
    }

    /// 导入模块的**访问前缀**（成员符号注册为 `前缀.成员名` 时使用的前缀）。
    ///
    /// **规范依据（§2.7.2 L7943-7953）**：
    ///   · L7943「代码中**不支持嵌套引用，只保留『模块名.成员』这一种访问方式**」；
    ///   · L7947「导入路径 `/` ✅ 保留，**只用于定位文件**」；
    ///   · L7948「访问路径 `.`（多级）❌ **禁止**，如 `数学.几何.圆形.计算面积()`」；
    ///   · L7949「**短名访问** ✅ 保留，如 `圆形.计算面积()`」。
    ///   ⇒ 路径只用于**定位文件**；访问一律用**末段短名**（或 `别名`、或 `展开` 后的裸名）。
    ///
    /// **为何必须有它（2026-09-26 实测）**：此前直接以 `模块路径.join(".")` 作前缀 ⇒
    ///   `导入 子/库` 会注册出 `子.库.成员` 键，于是：
    ///     · `子.库.成员()` **畅通**（规范❌禁止的多级点路径）；
    ///     · `库.成员()` **未定义标识符**（规范✅要求的短名缺失）。
    ///   ——与规范**恰好相反**。由「规范一致性门禁」R46/R47 正负配对实测抓出
    ///   （两引擎共用同一前端 ⇒ 双模同错，双模门禁查不出）。
    ///
    /// **例外（必须保留）**：聚合导入不套用末段规则——
    ///   L7951「**聚合模块内的别名** ✅ 允许，`数学.几何.计算面积()` 中的 `几何` 是聚合模块
    ///   **内部别名**，不是路径层级」⇒ 聚合重导出的对外名本身可含点（如 `成员库.矩形`），
    ///   其点来自**别名**而非导入路径，不能按路径规则收窄。
    /// 模块键 → **末段短名**（规范 §2.7.2「访问一律用末段短名」口径）。
    ///
    /// ★2026-10-17（项目外聚合下结构体方法不可用）：**项目外**的模块键是**文件系统绝对路径**
    ///   （`\\?\D:\…\计算工具.智`），而项目内是逻辑名（`聚合校验.基础库`）。
    ///   此前直接用 `模块名.rsplit('.').next()` 取末段：
    ///     · 逻辑名 `聚合校验.基础库` ⇒ `基础库` ✓
    ///     · 绝对路径 `…\计算工具.智` ⇒ **`智`** ✗（把 `.智` 后缀当成了点分隔）
    ///   ⇒ `结构体环境` 登记成 `智.工具盒`，而对外名是 `计算工具.工具盒`
    ///   ⇒ 实测报「类型没有方法【翻倍】」（字段因短名回退侥幸可用）。
    ///   ⚠ 顺序不可颠倒：先剥 `.智` → 再按**路径分隔符**取末段 → 最后按**点**取逻辑末段。
    fn 模块末段名(模块名: &str) -> &str {
        let 去后缀 = 模块名.strip_suffix(".智").unwrap_or(模块名);
        let 路径末段 = 去后缀
            .rsplit(|ch: char| ch == '/' || ch == '\\')
            .next()
            .unwrap_or(去后缀);
        路径末段.rsplit('.').next().unwrap_or(路径末段)
    }

    fn 外部模块访问前缀(
        导入: Option<&crate::语法分析::导入声明>,
        模块名: &str,
    ) -> String {
        let 导入 = match 导入 {
            Some(i) => i,
            None => return 模块名.to_string(),
        };
        // ① 别名优先（规范 §2.7.4：命名别名后原模块名不可用；R13 已落地）
        if let Some(别名) = &导入.别名 {
            return 别名.clone();
        }
        // ② 聚合导入保持原键（其点来自内部别名，非路径层级，见上）
        if 导入.是否聚合 {
            return 模块名.to_string();
        }
        // ③ 路径导入：访问名 = 末段短名（§2.7.2 L7948/L7949）
        let 段: Vec<String> = 导入
            .模块路径
            .iter()
            .skip_while(|s| *s == "." || *s == "..")
            .cloned()
            .collect();
        match 段.last() {
            Some(末段) if !末段.is_empty() => 末段.clone(),
            _ => 模块名.to_string(),
        }
    }

    // ════════════════════════════════════════════════════════════
    //  §2.4.7 导入名占用模块命名空间（2026-10-18 补齐）
    // ════════════════════════════════════════════════════════════

    /// 校验「导入名 / 导入别名」是否与**本文件顶层标识符**同名（规范 §2.4.7）。
    ///
    /// **规范依据**（§2.4.7 命名空间总览）：
    ///   · L5663/L5750：「函数名、变量名、常量名、结构体名、枚举名、接口名、
    ///     **普通导入模块名、导入别名**，全部占用同一命名空间，互不可重名」；
    ///   · L6223：「导入别名与模块内顶层标识符同名 ❌」。
    ///
    /// **判据 = 集合交叉**（与声明顺序无关）：
    ///   对每个「非展开、非聚合」的导入取**访问名**（别名优先，否则路径末段，
    ///   与 `外部模块访问前缀` **同一真相**），若该访问名与本文件某个顶层标识符同名 ⇒ 报错。
    ///
    /// **为什么必须顺序无关**：语法同时允许「先导入后声明」与「先声明后导入」；
    ///   缺少本校验时两种顺序都**静默接受** ⇒ 同一名字在符号表里有两个含义
    ///   （变量 `数学` 与 模块成员 `数学.绝对值` 并存）⇒ 违反「禁静默」铁律。
    ///   实测证据（2026-10-18）：`导入 数学` + `数学 = 10` 双模 rc=0。
    ///
    /// **豁免**（每条都有规范出处）：
    ///   · `展开` 导入：展开后只留裸名，模块名/别名均失效（§2.7.3 L8082）⇒ 不占访问名；
    ///   · `聚合导入`：其对外名可含点（来自聚合内部别名，非路径层级，§2.7.2 L8007），
    ///     命名冲突另由 §2.9 专用检查承担；
    ///   · `启动程序`：入口函数不构成可访问成员、不占命名空间（§6229）。
    pub(crate) fn 校验导入名占用命名空间(
        &mut self,
        导入列表: &[crate::语法分析::导入声明],
        顶层列表: &[crate::语法分析::顶层定义],
    ) -> Result<(), ()> {
        // 顶层标识符 → (种类中文名, 位置)。同名只可能来自「重复声明」检查已拦下的形态，
        // 这里取首个即可（避免重复报错时位置抖动）。
        let mut 顶层名: HashMap<String, (String, 源码位置)> = HashMap::new();
        for 定义 in 顶层列表 {
            if let Some((类别, 名)) = 定义.元数据() {
                if 名 == "启动程序" { continue; }
                顶层名.entry(名).or_insert((format!("{:?}", 类别), 定义.位置().clone()));
            }
        }
        if 顶层名.is_empty() {
            return Ok(());
        }
        for 导入 in 导入列表 {
            if 导入.是否展开 || 导入.是否聚合 {
                continue;
            }
            let 路径串 = 导入.模块路径.join("/");
            if 路径串.is_empty() || 路径串 == "自身" {
                continue;
            }
            let 访问名 = Self::外部模块访问前缀(Some(导入), &路径串);
            if let Some((种类, 定义位置)) = 顶层名.get(&访问名) {
                let 描述 = format!(
                    "导入名【{}】与当前模块的顶层{}【{}】同名（导入名会占用模块的命名空间，不能与顶层成员重名）",
                    访问名, 种类, 访问名
                );
                let 帮助 = format!("请改用「导入 {} 别名 其他名」，或重命名该{}", 路径串, 种类);
                self.报错_也见于(
                    &描述,
                    &导入.位置,
                    vec![定义位置.clone()],
                    None,
                    Some(&帮助),
                );
                return Err(());
            }
        }
        Ok(())
    }

    // ════════════════════════════════════════════════════════════
    //  🆕 P3: FFI 精确类型解析（外部块语境专用）
    //  外部块中函数形参/返回类型可使用 FFI 精确类型名（单整数/短整数/长小数/指针 等），
    //  编译器把「精确 C 类型码」随 FFI 元数据传到底层，shim 按声明位宽编组；
    //  精确码跨层契约与 基础功能 外部调用注册.rs::精确类型码到C类型 严格对齐。
    //  ═══ 2026-08-29 命名体系改版定稿（规范 §6.5）═══
    //  位宽前缀：单(8)/微(16)/短(32)/长(64)/平台(随ABI)/位宽(恒等于指针宽)；
    //  无符号前置（`无符号微整数`，与 C unsigned / Rust u 惯例一致）；
    //  字符仅保留 `字符`(c_char)；`指针` 回归（码13，独立类型，不管理生命周期）；
    //  `整数`/`小数` 在外部块已废弃，报错引导改用 `长整数`/`长小数`。
    //  ════════════════════════════════════════════════════════════

    /// FFI 精确类型名 → (类型信息, 精确码)；返回 None 表示非 FFI 精确名（走常规类型解析）。
    /// ★单源★ 名称→(核心类型文本, 精确码) 的真相在 `名称身份::FFI标量类型表`
    /// （取代原手写 20 分支 match；此处仅做「核心类型文本 → 类型信息」桥接）。
    fn FFI精确类型码(名: &str) -> Option<(类型信息, u8)> {
        let (类型文本, 码) = crate::名称身份::FFI标量类型(名)?;
        let 类型 = match 类型文本 {
            "逻辑" => 类型信息::逻辑类型(),
            "文本" => 类型信息::文本类型(),
            "空值" => 类型信息::空值类型(),
            "整数" => 类型信息::整数类型(),
            "小数" => 类型信息::小数类型(),
            _ => return None,
        };
        Some((类型, 码))
    }

    /// 🆕 2026-09-04 FFI 隔离补全：外部结构体字段类型 FFI 专属解析。
    /// 外部块声明层与本语言类型隔离——FFI 精确类型名（长整数/短小数/指针 等）在此经
    /// FFI精确类型码 识别为等价核心类型；普通代码的 解析类型标注 已不再认识 FFI 名
    /// （类型推导.rs:148-156 兜底映射已移除），`短小数` 等回归数学内建结构体语义。
    /// 与 解析外部函数形参(180)/解析外部函数返回类型 同源，杜绝第三套 FFI 名表。
    fn 解析外部结构体字段类型(&mut self, 标注: &类型表达式, 位置: &源码位置) -> 类型信息 {
        // 🆕 2026-09-25 数组字段（规范 §6.5.6 ③，A 指针口径）：本层无需特判。
        //   标注 `数组<标量外部类型>` 经下方 外部字段标注改写（FFI 精确名→核心名）后走
        //   解析类型标注 ⇒ `类型信息::数组(元素)`；降级层由 **外部结构体字段专属转换**
        //   （降级/公共降级.rs::外部结构体字段类型）保留 `底层表示类型::数组(元素索引)`，
        //   再由 模块到FFI结构体布局 写出布局码 `[22][元素码]`，供 shim/宿主按元素宽度编组。
        if let 类型表达式::基本类型(名称) = 标注 {
            // `整数`/`小数` 是调用层核心类型，外部块声明层禁用（引导用 FFI 精确名）
            if 名称 == "整数" || 名称 == "小数" {
                self.外部声明类型有误 = true;
                self.报错(
                    &format!(
                        "外部结构体字段 `{}` 是调用层核心类型，声明层只支持外部类型，改用 `长整数`/`长小数`。",
                        名称
                    ),
                    位置,
                );
            }
            if let Some((类型, _码)) = Self::FFI精确类型码(名称.as_str()) {
                return 类型;
            }
            self.检查外部声明类型名(名称, "结构体字段", 位置);
        }
        // 数组<FFI元素>/映射/任意/非 FFI 名：改写标注中 FFI 精确名→等价核心名后常规解析
        let 改写后 = self.外部字段标注改写(标注);
        self.解析类型标注(&Some(改写后)).unwrap_or(类型信息::未推断)
    }

    /// 🆕 2026-09-25 外部结构体字段的**扁平 FFI 精确码**（自描述可变长；规范 §6.5.6）。
    /// 编码见 高层表示外部结构体::字段精确码：
    ///   标量 ⇒ `[码]`；数组 ⇒ `[22][元素码]`；嵌套结构体 ⇒ `[21][名字长 u8][名字字节…]`；其它 ⇒ `[0]`。
    fn 外部字段扁平精确码(标注: &类型表达式) -> Vec<u8> {
        match 标注 {
            类型表达式::基本类型(名称) => {
                if let Some((_, 码)) = Self::FFI精确类型码(名称.as_str()) {
                    return vec![码];
                }
                if 名称 == "整数" || 名称 == "小数" {
                    return vec![0]; // 调用层核心类型（别处已报错）；此处不叠加语义
                }
                // 非 FFI 名 ⇒ 外部结构体（嵌套结构体字段）：[21][名字长][名字字节]
                let 字节 = 名称.as_bytes();
                let 长度 = 字节.len().min(255);
                let mut 结果 = vec![21u8, 长度 as u8];
                结果.extend_from_slice(&字节[..长度]);
                结果
            }
            类型表达式::数组(元素) => {
                let 元素码 = match 元素.as_ref() {
                    类型表达式::基本类型(名) => {
                        Self::FFI精确类型码(名.as_str()).map(|(_, 码)| 码).unwrap_or(0)
                    }
                    _ => 0,
                };
                vec![crate::降级::公共降级::布局码_外部数组字段, 元素码]
            }
            _ => vec![0],
        }
    }

    /// 把类型标注中出现的 FFI 精确类型名改写为等价核心类型名
    /// （供 结构体环境 延迟解析、模块加载器 跨模块等消费方使用）。
    /// 例：基本类型("长整数")→基本类型("整数")；数组(短小数)→数组(小数)。
    fn 外部字段标注改写(&self, 标注: &类型表达式) -> 类型表达式 {
        match 标注 {
            类型表达式::基本类型(名称) => {
                if let Some((类型, _码)) = Self::FFI精确类型码(名称.as_str()) {
                    if let Some(核心名) = Self::类型信息到核心类型名(&类型) {
                        return 类型表达式::基本类型(核心名);
                    }
                }
                标注.clone()
            }
            类型表达式::数组(元素) => {
                类型表达式::数组(Box::new(self.外部字段标注改写(元素)))
            }
            类型表达式::映射(键, 值) => 类型表达式::映射(
                Box::new(self.外部字段标注改写(键)),
                Box::new(self.外部字段标注改写(值)),
            ),
            _ => 标注.clone(),
        }
    }

    /// 类型信息 → 智语言核心类型名（仅基本型；供 FFI 精确名改写，FFI精确类型码 全部返回在此覆盖）
    fn 类型信息到核心类型名(t: &类型信息) -> Option<String> {
        match t {
            类型信息::基本型(基本类型::整数) => Some("整数".into()),
            类型信息::基本型(基本类型::小数) => Some("小数".into()),
            类型信息::基本型(基本类型::文本) => Some("文本".into()),
            类型信息::基本型(基本类型::逻辑) => Some("逻辑".into()),
            类型信息::基本型(基本类型::空值) => Some("空值".into()),
            _ => None,
        }
    }

    /// 🆕 2026-09-25 **有效输出位图**（单一真相）：**数组形参强制非输出** ✓
    ///
    /// **为什么必须强制（实测机理取证，非猜测）**：FFI 数组形参走**独立编组通道** ——
    ///   宿主 `处理外部调用` 把数组**无条件**序列化为 C ABI 紧凑缓冲，并把地址放进参数槽
    ///   （`外部调用注册.rs`：`数组回写.push((数组句柄, 缓冲, 元素码, 长度))` **只要元素码≠0 就登记**）
    ///   ⇒ 调用后**必然回写**数组 ⇒ **数组默认就是 In/Out**（与 `输出位图` 无关）✓
    ///
    /// **若保留输出位会怎样（真 bug，故原实现以报错挡住）**：
    ///   shim 见 `输出位` ⇒ 走「本地临时变量 + 指针」路径（`let mut out{i}: T = 默认; &mut out{i} as *mut T`）
    ///   ⇒ C 侧拿到的是**单个临时变量的地址**，而非数组缓冲 ✗ ⇒ 写入越界/丢失 ✗
    ///   （且 `输出位图` 还参与**返回槽数**：`输出参数数 + 1` ⇒ 数组会被误算成一个输出槽 ✗）
    ///
    /// **正解**：对数组形参**清除输出位**（不是拒绝！）—— 用户写 `输出 数组<长整数>` 时，
    ///   数组通道本就回写，语义**恰好满足用户意图** ✓；清除后 shim 与返回槽数自动一致 ✓
    ///
    /// ⚠ 全部引用点必须走本函数（预扫注册 / 高层表示 / 表达式分析注册），否则又会出现
    ///   「调用校验用一套位图、shim 用另一套」的跨层漂移 ✗（历史上此类漂移代价极高）
    fn 有效输出位图(形参列表: &[形参], 输出位图: &[bool]) -> Vec<bool> {
        let mut 位图 = 输出位图.to_vec();
        for (i, p) in 形参列表.iter().enumerate() {
            if matches!(p.类型标注, Some(类型表达式::数组(_))) {
                if let Some(位) = 位图.get_mut(i) {
                    *位 = false;
                }
            }
        }
        位图
    }

    /// 外部块里写的类型名既不是外部类型、也不是已声明的结构体/接口/枚举时报错。
    /// 通用的 解析类型标注 会把查不到的名字当成「尚未解析的自定义类型」占位放行；外部块里这样的
    /// 名字会按不透明指针传给 C，写错一个字（`长整数` 写成 `长整型`）结果就是错的且没有提示。
    fn 检查外部声明类型名(&mut self, 名称: &str, 位置描述: &str, 位置: &源码位置) {
        if matches!(名称, "数组" | "映射") || self.查找命名类型(名称).is_some() {
            return;
        }
        self.外部声明类型有误 = true;
        self.报错(
            &format!(
                "外部块{}的类型 `{}` 未定义：它既不是外部类型，也不是已声明的结构体。{}",
                位置描述, 名称, 外部类型清单
            ),
            位置,
        );
    }

    /// 解析外部函数形参：返回 (类型信息, 精确C类型码, 函数指针形状码, 数组元素C类型码)
    /// 形状码 0-4 与 shim 预生成的 5 种 trampoline 对齐；非函数指针形参形状恒 255（无意义）。
    /// 数组元素C类型码：非数组形参=0；数组形参=元素外部类型精确码（宿主据此序列化 C 紧凑缓冲）。
    fn 解析外部函数形参(&mut self, 形参: &形参) -> (类型信息, u8, u8, u8) {
        match &形参.类型标注 {
            Some(类型表达式::基本类型(名称)) => {
                // 【2026-08-29 规范 §6.5】外部块声明层只支持外部类型；`整数`/`小数` 是调用层核心类型，禁止在声明层使用
                if 名称 == "整数" || 名称 == "小数" {
                    self.外部声明类型有误 = true;
                    self.报错(
                        &format!(
                            "外部块声明层只支持外部类型：`{}` 是调用层核心类型，此处改用 `长整数`/`长小数`。\
                             {}",
                            名称, 外部类型清单
                        ),
                        &形参.位置,
                    );
                    let 类型 = if 名称 == "整数" { 类型信息::整数类型() } else { 类型信息::小数类型() };
                    return (类型, 0, 255, 0);
                }
                if let Some((类型, 码)) = Self::FFI精确类型码(名称.as_str()) {
                    return (类型, 码, 255, 0);
                }
                // 非 FFI 精确名：结构体名/数组/映射等走常规解析
                self.检查外部声明类型名(名称, &format!("形参【{}】", 形参.名称), &形参.位置);
                (self.解析形参类型(形参), 0, 255, 0)
            }
            // 🆕 FFI 数组参数：`数组<短整数> 数据` → 元素外部类型码（宿主序列化为 C 紧凑缓冲，shim 按元素码还原指针）
            Some(类型表达式::数组(元素类型)) => {
                let (元素码, 旧元素名) = match 元素类型.as_ref() {
                    类型表达式::基本类型(元素名) if 元素名 == "整数" || 元素名 == "小数" => {
                        self.外部声明类型有误 = true;
                        (0, Some(元素名.clone()))
                    }
                    类型表达式::基本类型(元素名) => {
                        (Self::FFI精确类型码(元素名).map(|(_, 码)| 码).unwrap_or(0), None)
                    }
                    _ => (0, None),
                };
                if let Some(名) = 旧元素名 {
                    self.报错(
                        &format!("外部块声明层只支持外部类型：`数组<{}>` 的元素 `{}` 是调用层核心类型，改用 `数组<长整数>`/`数组<长小数>`。", 名, 名),
                        &形参.位置,
                    );
                } else if !matches!(元素码, 1..=10 | 14..=18) {
                    self.报错(
                        "FFI 数组参数必须指定元素外部类型（如 `数组<短整数>`、`数组<无符号单整数>`、`数组<长小数>`），\
                         元素须为整数/浮点/字符类外部类型。",
                        &形参.位置,
                    );
                }
                // 调用层类型 = 数组<整数>（元素 ABI 由 元素码 决定；宿主序列化/回写）
                (类型信息::数组(Box::new(类型信息::整数类型())), 0, 255, 元素码)
            }
            // 🆕 P3: 函数指针类型 `函数指针(...) 返回类型` → 码 20（函数指针），形状由签名映射
            Some(类型表达式::函数类型 { 参数类型列表, 返回类型 }) => {
                let 类型 = self.解析类型标注(&形参.类型标注).unwrap_or(类型信息::未推断);
                let 形状 = Self::函数类型到形状(参数类型列表, 返回类型);
                // 【G6】回调形状降级编译期诊断：签名不在 5 种预生成 trampoline 覆盖范围内时，
                // 旧实现静默取 255 回退为 `fn()` 不透明句柄——C 侧一旦按声明签名调用该回调，
                // 实参/返回值全部错位（UB，运行期表现为随机崩溃）。此处改为编译期明确报错，
                // 而非把问题推到运行时。
                if 形状 == 255 {
                    self.报错(
                        &format!(
                            "回调形参【{}】的签名暂不受支持：当前 FFI 仅预生成 3 种回调跳板——\
                             `函数指针(长整数) 空值`、`函数指针() 长整数`、`函数指针(长整数) 长整数`。\
                             （外部地址/不透明句柄统一用 `指针` 类型声明，编译器在 shim 层按 ABI 与 void* 等价传递；\
                             回调的 void* 形参也写作 `指针`。）\
                             请改用受支持的签名，或把额外参数打包为 指针/长整数 传递。",
                            形参.名称
                        ),
                        &形参.位置,
                    );
                }
                (类型, 20, 形状, 0)
            }
            _ => (self.解析形参类型(形参), 0, 255, 0),
        }
    }

    /// 把 `函数指针(参数类型列表) 返回类型` 映射到 trampoline 形状码（与 外部调用注册::注册ffi回调
    /// 经 转换签名形状 调度的 5 种 trampoline 严格对应）：
    /// 0=void fn(i64) / 1=i64 fn() / 2=i64 fn(i64) / 3=i64 fn(i64,*void*) / 4=void fn(*void*)，
    /// 无匹配签名为 255（动态，回退 fn()，仅作不透明句柄）。
    fn 函数类型到形状(参数: &[类型表达式], 返回: &类型表达式) -> u8 {
        let 返回空 = matches!(返回, 类型表达式::基本类型(名) if 名 == "空值");
        // 指针类：`指针`（void* 外部类型）或 `文本`（const char*，均按指针 ABI 传递）
        let 指针类 = |t: &类型表达式| -> bool {
            matches!(t, 类型表达式::基本类型(名) if 名 == "指针" || 名 == "文本")
        };
        match 参数.len() {
            0 => if 返回空 { 255 } else { 1 },
            1 => {
                if 指针类(&参数[0]) {
                    if 返回空 { 4 } else { 255 }
                } else if 返回空 {
                    0
                } else {
                    2
                }
            }
            2 => {
                if !返回空 && !指针类(&参数[0]) && 指针类(&参数[1]) {
                    3
                } else {
                    255
                }
            }
            _ => 255,
        }
    }

