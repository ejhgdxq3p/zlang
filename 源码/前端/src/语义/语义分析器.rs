                        //   带 `别名` 的导入优先按别名匹配（R13 已落地：别名后原名不可用）。
                        // 🆕 2026-09-27 修复（**传递依赖的访问名**）：此前只在**主程序导入列表**里匹配 ⇒
                        //   由子模块间接引入的模块（如 `界面.智` 里的 `导入 图形界面/基础部件`）匹配不到，
