                    //     · 编译模式 8 次 = **4×`库甲` / 4×`库乙`** ✗ = 掷硬币（同一 exe 语义不可复现）
                    //   解法与 `降级/公共降级.rs` 中同类修复**完全一致**（那里按名排序修复「外部函数索引错位」，
