    /// 预注册内置模块符号：把**本文件已导入**的标准库模块成员注入符号表。
    ///
    /// **规范依据**：
    ///   · §5 L10536「标准库是智语言官方提供的功能模块集合，**需要先导入再使用**」
    ///     （数学/文件/网络/时间/系统/工具/并发；§5.4 L12542、§5.6 L12706 均明写「导入方式为 `导入 X`」）；
