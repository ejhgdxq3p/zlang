/// 精确小数方法签名表（规范 §5.1.11）：(方法名, 形参类型名列表, 返回类型名)。
///
/// 为何提取为模块级函数：本表是结构体方法签名的**语义层真相**，
/// 而 标准库元数据.rs（数学内建 / 数学内建带默认）持有「名→索引 + 可选形参/默认值」的**元数据真相**。
/// 二者分居两处且表达力不对等（本表无法表达默认值），历史上因此漂移——
/// 默认填充对结构体方法结构性失效（形参数量为 0 → 填充循环永不进入）。
/// 提取后由 标准库真源校验 断言两侧形参数量一致，把「统一」固化为自动化约束而非一次性修复。
///
/// 约定：本表形参**不含自身**；元数据侧（数学内建带默认）形参[0] 为「自身」，故比较时元数据侧须 -1。
pub fn 精确小数方法签名表() -> Vec<(&'static str, Vec<&'static str>, &'static str)> {
    // 单源收口（2026-08-31）：从 标准库注册表 派生精确小数方法签名，消除手写第二源。
    // 注册表条目含「自身」首位，此处取去自身后的用户可见参数类型列表。
    use crate::标准库元数据::{标准库注册表, 标准库种类};
    标准库注册表
        .iter()
        .filter(|e| matches!(e.种类, 标准库种类::数学内建方法) && e.函数名.starts_with("精确小数."))
        .map(|e| {
            let 方法短名 = &e.函数名["精确小数.".len()..];
            let 用户参数: Vec<&'static str> = e.形参
                .iter()
                .skip_while(|(名, _)| *名 == "自身")
                .map(|(_, 类型)| *类型)
                .collect();
            let 返回 = e.返回.unwrap_or("精确小数");
            (方法短名, 用户参数, 返回)
        })
        .collect()
}

