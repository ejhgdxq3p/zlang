use super::类型信息::类型信息;
use crate::公共数据结构::源码位置;
use std::collections::HashMap;
use crate::公共数据结构 as 公共数据;

#[derive(Debug, Clone)]
pub struct 符号表 {
    pub 作用域栈: Vec<作用域>,
    /// 函数名 → 带默认值的形参数量（仅用户函数填充；内置/外部函数不填 → 视为 0）。
    /// 供 表达式分析 在普通函数调用时计算「最少所需实参数 = 形参数 − 默认值形参数」，
    /// 实现与解释器一致的参数数量校验（修复 编译模式少参致 lowering 崩溃）。
    pub 函数默认值数量: HashMap<String, usize>,
    /// 🆕 2026-09-27 **模块上下文**（供裸名回退解析）：主程序 = None；被导入模块 = Some(模块名)。
    ///
    /// **为什么需要**：被导入模块的顶层定义会**合并进主程序**再分析（`用户模块定义列表` →
    ///   `全部定义` 循环），而模块**自身内部**按规范**直接写名字**（裸名）引用本模块成员。
    ///   ② 收口（非展开导入不再注册裸名）后，这些**模块内部裸名引用**随之失效
    ///   （实测：`公开求和` 内裸调 `内部求和` ⇒ 未定义；`适配 可计算` ⇒ 未找到接口）。
    ///   ⚠ §2.7.2 L7952「展开后只剩裸名」约束的是**导入方**的访问名，**不**影响模块**自身**的内部引用。
    ///   ⇒ 裸名未命中且 `当前模块 = Some(M)` 时回退查「`M.名`」（导入时以限定键注册）。
    ///   **主程序 当前模块 = None** ⇒ 该回退**完全不生效**（导入方仍必须写 `模块名.成员`）✓
    /// 由 `语义分析器` 在设置 `self.当前模块` 的**两处**同步（全部定义循环 / 主程序复位）。
    pub 当前模块: Option<String>,
}

#[derive(Debug, Clone)]
pub struct 作用域 {
    pub 符号映射: HashMap<String, 符号>,
    pub 作用域类型: 作用域类型,
}

#[derive(Debug, Clone, PartialEq)]
pub enum 作用域类型 {
    全局,
    函数,
    代码块,
    结构体,
}

#[derive(Debug, Clone)]
pub struct 符号 {
    pub 名称: String,
    pub 符号种类: 符号种类,
    pub 是否公开: bool,
    pub 是否可变: bool,
    pub 定义位置: 源码位置,
    /// 所属模块：主程序顶层符号 = None；被导入模块的顶层符号 = Some(模块名)。
    /// 用于模块级私有可见性判定（私有符号仅其所属模块可访问）。
    pub 所属模块: Option<String>,
}

#[derive(Debug, Clone)]
pub enum 符号种类 {
    变量 { 类型: 类型信息 },
    /// 函数/方法：名称唯一（规范 §2.4 不支持函数和方法重载）
    函数 { 签名: 函数签名, 是否公开: bool },
    结构体 { 字段列表: Vec<字段符号>, 方法列表: Vec<函数符号> },
    接口 { 方法声明列表: Vec<方法声明> },
    枚举 { 枚举成员列表: Vec<枚举成员信息> },
    类型参数 { 约束列表: Vec<类型信息> },
}

/// 函数签名（名称唯一，不重载）
#[derive(Debug, Clone)]
pub struct 函数签名 {
    pub 形参类型: Vec<类型信息>,
    pub 形参名称: Vec<String>,  // 用于命名参数重排
    pub 返回类型: Option<类型信息>,
}

#[derive(Debug, Clone)]
pub struct 字段符号 {
    pub 名称: String,
    pub 类型: 类型信息,
    pub 是否公开: bool,
    pub 是否可变: bool,
}

#[derive(Debug, Clone)]
pub struct 函数符号 {
    pub 名称: String,
    pub 形参类型: Vec<类型信息>,
    pub 返回类型: Option<类型信息>,
    pub 是否公开: bool,
}

#[derive(Debug, Clone)]
pub struct 方法声明 {
    pub 名称: String,
    pub 形参类型: Vec<类型信息>,
    pub 返回类型: Option<类型信息>,
}

#[derive(Debug, Clone)]
pub struct 枚举成员信息 {
    pub 名称: String,
    pub 数据参数类型: Vec<类型信息>,
}

impl 符号表 {
    pub fn 新建() -> Self {
        let mut 符号表 = 符号表 { 作用域栈: Vec::new(), 函数默认值数量: HashMap::new(), 当前模块: None };
        符号表.进入作用域(作用域类型::全局);
        符号表
    }

    pub fn 进入作用域(&mut self, 作用域类型: 作用域类型) {
        self.作用域栈.push(作用域 { 符号映射: HashMap::new(), 作用域类型 });
    }

    pub fn 离开作用域(&mut self) {
        self.作用域栈.pop();
    }

    pub fn 声明符号(&mut self, 符号: 符号) -> Result<(), String> {
        let 当前作用域 = self.作用域栈.last_mut().unwrap();
        // 名称唯一（规范 §2.4：智语言不支持函数和方法重载）
        if 当前作用域.符号映射.contains_key(&符号.名称) {
            return Err(format!("重复声明【{}】：作用域内名称必须唯一", 符号.名称));
        }
        当前作用域.符号映射.insert(符号.名称.clone(), 符号);
        Ok(())
    }

    /// 声明符号，失败时返回（错误消息, 已有符号位置）
    /// 用于需要展示"也见于"关联位置链的错误场景
    pub fn 声明符号_调试(&mut self, 符号: 符号) -> Result<(), (String, 源码位置)> {
        let 当前作用域 = self.作用域栈.last_mut().unwrap();
        if let Some(已有符号) = 当前作用域.符号映射.get(&符号.名称) {
            return Err((format!("重复声明【{}】：作用域内名称必须唯一", 符号.名称), 已有符号.定义位置.clone()));
        }
        当前作用域.符号映射.insert(符号.名称.clone(), 符号);
        Ok(())
    }

    /// ⚠ 曾于 2026-09-17 加入 `当前作用域已声明()` 并用于"自动声明"判定，**已撤销**：
    /// 规范 §1384 明确函数内部的名字**共享一个命名空间**（从内向外查找即正确判据），
    /// §1411 仅要求"同一作用域内不能重复声明"。收窄为"仅当前块"会让内层隐式赋值变成新声明，
    /// 实测致循环步进 `计数 += 1` 失效 ⇒ **无限循环吃满内存**。勿再复活此思路。
    pub fn 查找符号(&self, 名称: &str) -> Option<&符号> {
        for 作用域 in self.作用域栈.iter().rev() {
            if let Some(符号) = 作用域.符号映射.get(名称) {
                return Some(符号);
            }
        }

        // 🆕 2026-09-27 **模块上下文回退**：被导入模块自身定义内的**裸名**引用本模块符号。
        //   裸名未命中且 `当前模块 = Some(M)` ⇒ 再查「M.名」（导入时以限定键注册）。
        //   仅在被导入模块的合并分析期生效（主程序 当前模块 = None ⇒ 零影响、导入方仍须写前缀）。
        self.查找模块限定符号(名称)
    }

    /// 🆕 2026-09-27 模块上下文回退查（供 `查找符号` / `查找符号_带层级` 共用）。
    fn 查找模块限定符号(&self, 名称: &str) -> Option<&符号> {
        let 模 = self.当前模块.as_ref()?;
        let 限定 = format!("{}.{}", 模, 名称);
        for 作用域 in self.作用域栈.iter().rev() {
            if let Some(符号) = 作用域.符号映射.get(&限定) {
                return Some(符号);
            }
        }
        None
    }

    /// 🆕 阶段 6a（2026-09-23）**查找符号并返回其「作用域下标」**（**0 = 全局/模块级作用域**）。
    ///
    /// 为什么需要：规范 §2.4.7 的判定「命中的**是不是模块级**变量/常量」**不能只看名字在表里**
    ///   —— 函数内同名局部会**遮蔽**模块级名字（规范允许），此时裸名表示局部 ⇒ 必须放行。
    ///   历史做法是另存一张 `模块级变量定义位置: 名称 → 源码位置` 并与命中符号的 `定义位置`
    ///   **比对位置**：能工作，但属**规则与数据结构不匹配**的债务（位置是启发式，且在
    ///   "遮蔽 + 隐式声明"组合处天然脆弱 —— 曾出过「循环步进被当新声明 ⇒ 无限循环」事故，
    ///   见 2026-09-17 实测）。
    ///   现改为**结构判据**：命中符号的**作用域下标 == 0**（全局作用域）⟺ 命中就是模块级符号 ✓
    ///   ⇒ O(1)、**与源码位置无关**，且遮蔽语义天然正确（局部永远在更深的作用域）✓
    /// ★F3（2026-10-14）：**模块级（全局作用域，下标 0）专用查找** —— 不受同名局部遮蔽影响 ✓。
    ///
    /// 与 `查找符号`/`查找符号_带层级` 的区别：后两者返回**最内层**命中 ⇒ 名字被局部变量遮蔽时**拿不到**
    /// 模块级符号 ✗。规范 5875 要求「局部变量与模块级函数同名时，可用 `本模块.` 前缀**显式访问被遮蔽的
    /// 模块成员**」⇒ 必须有一个"只看全局作用域"的查找 ✓。
    ///
    /// 顺序：① 模块限定键 `当前模块.名`（导入模块以此登记）② 全局作用域的裸名（本模块顶层 / 主程序）。
    pub fn 查找模块级(&self, 名称: &str) -> Option<&符号> {
        let 全局 = self.作用域栈.first()?;
        if let Some(模) = self.当前模块.as_ref() {
            if let Some(符号) = 全局.符号映射.get(&format!("{}.{}", 模, 名称)) {
                return Some(符号);
            }
        }
        全局.符号映射.get(名称)
    }

    pub fn 查找符号_带层级(&self, 名称: &str) -> Option<(&符号, usize)> {
        for (离顶深度, 作用域) in self.作用域栈.iter().rev().enumerate() {
            if let Some(符号) = 作用域.符号映射.get(名称) {
                // 离顶深度 → **栈下标**（0 = 全局作用域），供调用方做"是否模块级"的结构判定
                let 栈下标 = self.作用域栈.len() - 1 - 离顶深度;
                return Some((符号, 栈下标));
            }
        }
        // 🆕 2026-09-27 模块上下文回退（同 `查找符号`）：命中「M.名」，作用域下标仍为 0（全局）
        let 模 = self.当前模块.as_ref()?;
        let 限定 = format!("{}.{}", 模, 名称);
        for (离顶深度, 作用域) in self.作用域栈.iter().rev().enumerate() {
            if let Some(符号) = 作用域.符号映射.get(&限定) {
                let 栈下标 = self.作用域栈.len() - 1 - 离顶深度;
                return Some((符号, 栈下标));
            }
        }
        None
    }

    /// 将已声明的同名符号标记为公开（供 导出: 裸名 语法复用此前定义的函数/变量）
    /// 返回是否找到并标记成功
    pub fn 标记符号公开(&mut self, 名称: &str) -> bool {
        for 作用域 in self.作用域栈.iter_mut().rev() {
            if let Some(符号) = 作用域.符号映射.get_mut(名称) {
                符号.是否公开 = true;
                return true;
            }
        }
        false
    }

    /// 更新符号的类型信息（第二遍语义分析可能有更精确的类型推断）
    /// 查找与给定名称最相似的中文标识符（编辑距离 ≤ 2）。
    /// 用于 `是否是指` 拼写建议。
    pub fn 查找最相似标识符(&self, 名称: &str) -> Option<(String, 源码位置)> {
        let 候选: Vec<(String, 源码位置)> = self.作用域栈.iter()
            .rev()
            .flat_map(|作用域| 作用域.符号映射.iter())
            .map(|(名, 符号)| (名.clone(), 符号.定义位置.clone()))
            .collect();
        公共数据::查找最相似标识符(名称, &候选)
    }

    pub fn 更新符号类型(&mut self, 名称: &str, 新类型: 类型信息) -> Result<(), String> {
        for 作用域 in self.作用域栈.iter_mut().rev() {
            if let Some(符号) = 作用域.符号映射.get_mut(名称) {
                if let 符号种类::变量 { ref mut 类型 } = &mut 符号.符号种类 {
                    *类型 = 新类型;
                    return Ok(());
                }
                // 非变量类型（函数/结构体等）不更新
                return Ok(());
            }
        }
        Err(format!("未找到符号【{}】", 名称))
    }

    /// 更新函数符号的返回类型（用于函数体推断后更新）。
    /// 名称唯一，仅回填该唯一签名的返回类型；
    /// 仅当尚未显式标注返回类型时才覆盖，避免冲掉手写标注。
    pub fn 更新函数返回类型(&mut self, 名称: &str, 新返回类型: 类型信息) -> Result<(), String> {
        for 作用域 in self.作用域栈.iter_mut().rev() {
            if let Some(符号) = 作用域.符号映射.get_mut(名称) {
                if let 符号种类::函数 { ref mut 签名, .. } = &mut 符号.符号种类 {
                    if 签名.返回类型.is_none() {
                        签名.返回类型 = Some(新返回类型.clone());
                    }
                }
                return Ok(());
            }
        }
        Err(format!("未找到符号【{}】", 名称))
    }

    pub fn 声明内置类型(&mut self) {
        let 基本类型名 = ["整数", "小数", "文本", "逻辑", "空值"];
        for 名称 in &基本类型名 {
            self.声明符号(符号 {
                名称: 名称.to_string(),
                符号种类: 符号种类::类型参数 { 约束列表: vec![] },
                是否公开: true,
                是否可变: false,
                定义位置: 源码位置::新("内置".into(), 0, 0),
                所属模块: None,
            }).ok();
        }
    }

    /// 🆕 注册类型收窄变量：在当前作用域插入一个同名变量（遮蔽外部），不检查重复声明。
    /// 用于 `如果 x != 空值:` 分支内的类型收窄。
    pub fn 声明收窄变量(&mut self, 名称: &str, 收窄类型: 类型信息, 位置: &源码位置) {
        if let Some(当前作用域) = self.作用域栈.last_mut() {
            当前作用域.符号映射.insert(名称.to_string(), 符号 {
                名称: 名称.to_string(),
                符号种类: 符号种类::变量 { 类型: 收窄类型 },
                是否公开: false,
                是否可变: false,
                定义位置: 位置.clone(),
                所属模块: None,
            });
        }
    }
}