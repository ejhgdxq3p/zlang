// 职责: 编译期常量表达式求值

use super::高层表示节点::{字面值, 高层表示表达式, 高层表示运算符};

#[derive(Debug, Clone)]
pub enum 求值结果 {
    成功(字面值),
    无法求值,
}

pub fn 编译期求值(表达式: &高层表示表达式) -> 求值结果 {
    match 表达式 {
        高层表示表达式::字面值(值, _) => 求值结果::成功(值.clone()),
        高层表示表达式::二元运算 {
            左侧,
            运算符,
            右侧,
            ..
        } => {
            let 左结果 = 编译期求值(左侧);
            let 右结果 = 编译期求值(右侧);
            match (左结果, 右结果) {
                (求值结果::成功(左值), 求值结果::成功(右值)) => {
                    求值二元运算(左值, 运算符, 右值)
                }
                _ => 求值结果::无法求值,
            }
        }
        高层表示表达式::隐式转换 { 源表达式, .. } => 编译期求值(源表达式),
        _ => 求值结果::无法求值,
    }
}

fn 求值二元运算(左: 字面值, 运算符: &高层表示运算符, 右: 字面值) -> 求值结果 {
    match (左, 右) {
        (字面值::整数(甲), 字面值::整数(乙)) => {
            let 结果 = match 运算符 {
                高层表示运算符::加 => 甲 + 乙,
                高层表示运算符::减 => 甲 - 乙,
                高层表示运算符::乘 => 甲 * 乙,
                高层表示运算符::除 if 乙 != 0 => return 求值结果::成功(字面值::小数(甲 as f64 / 乙 as f64)),
                高层表示运算符::整除 if 乙 != 0 => { let (x, y) = (甲, 乙); let mut q = x / y; let r = x % y; if r != 0 && ((r < 0) != (y < 0)) { q -= 1; } return 求值结果::成功(字面值::整数(q)); },
                高层表示运算符::取余 if 乙 != 0 => {
                    // 数学取余（欧几里得非负余数），与运行时 堆_取余 完全一致：
                    // r = x % y; if r < 0 { r + |y| }。wrapping 序列防 i64::MIN % -1 溢出 panic（数学余数为 0）。
                    let r = 甲.wrapping_rem(乙);
                    return 求值结果::成功(字面值::整数(if r < 0 { r.wrapping_add(乙.wrapping_abs()) } else { r }));
                }
                高层表示运算符::幂 => {
                    // ⚡守恒对齐（2026-09-02）：负整指数 / 整数幂溢出 不折叠——与运行时域规则一致，
                    // 交给运行时 base（抛「整数幂负指数」/「整数幂溢出」），避免负字面 as u32 回绕或静默折叠。
                    if 乙 < 0 { return 求值结果::无法求值; }
                    match 甲.checked_pow(乙 as u32) {
                        Some(v) => v,
                        None => return 求值结果::无法求值,
                    }
                }
                高层表示运算符::等于 => return 求值结果::成功(字面值::逻辑(甲 == 乙)),
                高层表示运算符::不等于 => return 求值结果::成功(字面值::逻辑(甲 != 乙)),
                高层表示运算符::大于 => return 求值结果::成功(字面值::逻辑(甲 > 乙)),
                高层表示运算符::小于 => return 求值结果::成功(字面值::逻辑(甲 < 乙)),
                高层表示运算符::大于等于 => return 求值结果::成功(字面值::逻辑(甲 >= 乙)),
                高层表示运算符::小于等于 => return 求值结果::成功(字面值::逻辑(甲 <= 乙)),
                _ => return 求值结果::无法求值,
            };
            求值结果::成功(字面值::整数(结果))
        }
        (字面值::小数(甲), 字面值::小数(乙)) => {
            let 结果 = match 运算符 {
                高层表示运算符::加 => 甲 + 乙,
                高层表示运算符::减 => 甲 - 乙,
                高层表示运算符::乘 => 甲 * 乙,
                高层表示运算符::除 if 乙 != 0.0 => 甲 / 乙,
                高层表示运算符::等于 => return 求值结果::成功(字面值::逻辑(甲 == 乙)),
                高层表示运算符::不等于 => return 求值结果::成功(字面值::逻辑(甲 != 乙)),
                高层表示运算符::大于 => return 求值结果::成功(字面值::逻辑(甲 > 乙)),
                高层表示运算符::小于 => return 求值结果::成功(字面值::逻辑(甲 < 乙)),
                _ => return 求值结果::无法求值,
            };
            求值结果::成功(字面值::小数(结果))
        }
        (字面值::文本(甲), 字面值::文本(乙)) if matches!(运算符, 高层表示运算符::加) => {
            求值结果::成功(字面值::文本(甲 + &乙))
        }
        _ => 求值结果::无法求值,
    }
}