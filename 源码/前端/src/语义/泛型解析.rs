use super::语义分析器;
use super::符号表::{符号, 符号种类, 函数签名, 作用域类型};
use super::类型信息::{类型信息};
use super::高层表示节点::*;
use super::类型推断;
use super::类型检查;
use crate::公共数据结构::源码位置;
use crate::语法分析::{函数定义, 类型表达式, 表达式 as 语法表达式, 参数传递方式, 调用实参};
use std::collections::HashMap;

impl<'a> 语义分析器<'a> {
    /// 对任意类型函数调用进行单态化：根据实参类型生成具体版本的函数
    pub(crate) fn 单态化任意类型调用(
        &mut self,
        函数名: &str,
        实参列表: &[调用实参],
        位置: &源码位置,
    ) -> Result<高层表示表达式, ()> {
        // 获取原始任意类型函数定义（克隆以释放不可变借用）
        let 原始定义 = self.任意类型函数定义.get(函数名).cloned().ok_or(())?;

        // 命名参数重排：将含名称的实参按 形参名称列表 排序；无命名参数时保持原顺序
        let 形参名称列表: Vec<String> = 原始定义.形参列表.iter().map(|p| p.名称.clone()).collect();
        let 形参数量 = 形参名称列表.len();
        let 有序实参值: Vec<语法表达式> = if 实参列表.iter().any(|a| a.名称.is_some()) {
            let mut 已排序: Vec<Option<语法表达式>> = vec![None; 形参数量];
            let mut 下一位置 = 0usize;
            for 实参 in 实参列表 {
                if let Some(参数名) = &实参.名称 {
                    match 形参名称列表.iter().position(|n| n == 参数名) {
                        Some(位置索引) => { 已排序[位置索引] = Some(实参.值.clone()); }
                        None => {
                            self.报错(&format!("函数【{}】没有名为【{}】的形参", 函数名, 参数名), 位置);
                            return Err(());
                        }
                    }
                } else {
                    while 下一位置 < 形参数量 && 已排序[下一位置].is_some() { 下一位置 += 1; }
                    if 下一位置 < 形参数量 {
                        已排序[下一位置] = Some(实参.值.clone());
                        下一位置 += 1;
                    } else {
                        self.报错(&format!("函数【{}】的实参数量超出形参数量", 函数名), 位置);
                        return Err(());
                    }
                }
            }
            已排序.into_iter().filter_map(|x| x).collect()
        } else {
            实参列表.iter().map(|a| a.值.clone()).collect()
        };

        // 先分析所有实参
        let mut 高层表示实参 = Vec::new();
        for 实参 in &有序实参值 {
            高层表示实参.push(self.分析表达式(实参)?);
        }

        // 类型参数映射基于已重排的实参继续推断（下方沿用 原始定义）

        // 收集各类型标记的声明约束（首个非空约束），供提取时的"数值提升守护"判定
        let mut 声明约束: HashMap<String, Vec<类型表达式>> = HashMap::new();
        for 形参 in &原始定义.形参列表 {
            if let Some(标注) = &形参.类型标注 {
                self.收集声明约束(标注, &mut 声明约束);
            }
        }

        // 从实参推断类型参数映射
        let mut 类型参数映射: HashMap<String, 类型信息> = HashMap::new();
        for (i, 实参) in 高层表示实参.iter().enumerate() {
            if i < 原始定义.形参列表.len() {
                let 形参 = &原始定义.形参列表[i];
                let 实参类型 = 类型推断::从表达式推断(实参);
                if let Some(类型标注) = &形参.类型标注 {
                    self.提取类型参数映射(类型标注, &实参类型, &mut 类型参数映射, &声明约束)?;
                }
            }
        }
        // 🆕 实参隐式提升（2026-09-02，与普通函数调用路径 表达式分析.rs 的"整数实参→小数形参"
        // 转换完全同源；规范 §2.4.3 绑定提升规则）：单态化形参（经映射替换）为 小数 而实参为 整数 时，
        // 包裹 整数→小数 隐式转换。否则 取较大值(3, 2.5) 会把整数 3 直接传入小数形参/经小数返回槽
        // 返回整标签 → 位模式错乱（生成单态化函数体以替换后类型重分析，天然一致，无需额外修补）。
        for (i, 形参) in 原始定义.形参列表.iter().enumerate() {
            if i < 高层表示实参.len() {
                if let Some(类型标注) = &形参.类型标注 {
                    let 形参类型 = self.替换类型参数(类型标注, &类型参数映射);
                    if 形参类型 == 类型信息::小数类型()
                        && 类型推断::从表达式推断(&高层表示实参[i]) == 类型信息::整数类型()
                    {
                        高层表示实参[i] = 高层表示表达式::隐式转换 {
                            源表达式: Box::new(高层表示实参[i].clone()),
                            目标类型: 类型信息::小数类型(),
                        };
                    }
                }
            }
        }

        // 生成单态化版本的函数名
        let 类型参数描述: Vec<String> = 类型参数映射
            .iter()
            .map(|(k, v)| format!("{}_{}", k, v.类型名称()))
            .collect();
        let 单态化名称 = format!("{}__单态化__{}", 函数名, 类型参数描述.join("_"));

        // 计算替换后的返回类型（G4：从原始返回类型 + 类型参数映射得出精确类型）
        let 替换后返回类型 = 原始定义.返回类型.as_ref()
            .map(|rt| self.替换类型参数(rt, &类型参数映射))
            .unwrap_or(类型信息::未推断);

        // 检查缓存
        if self.单态化缓存.contains_key(&单态化名称) {
            return Ok(高层表示表达式::调用 {
                    位置: 源码位置::默认(),
                函数名: 单态化名称,
                实参列表: 高层表示实参,
                类型: 替换后返回类型,
            });
        }

        // 生成单态化函数体
        let 单态化函数 = self.生成单态化函数(&原始定义, &类型参数映射, &单态化名称)?;
        self.单态化缓存.insert(单态化名称.clone(), 单态化函数);

        // 注册单态化函数符号
        let mut 单态化形参类型 = Vec::new();
        for 形参 in &原始定义.形参列表 {
            let 具体类型 = if let Some(类型标注) = &形参.类型标注 {
                self.替换类型参数(类型标注, &类型参数映射)
            } else {
                // 从默认值推断
                if let Some(默认值) = &形参.默认值 {
                    let 高层表示默认值 = self.分析表达式(默认值)
                        .unwrap_or(高层表示表达式::字面值(字面值::空值, 类型信息::空值类型()));
                    类型推断::从表达式推断(&高层表示默认值)
                } else {
                    类型信息::未推断
                }
            };
            单态化形参类型.push(具体类型);
        }
        self.符号表.声明符号(符号 {
            名称: 单态化名称.clone(),
            符号种类: 符号种类::函数 {
                签名: 函数签名 {
                    形参类型: 单态化形参类型,
                    形参名称: 原始定义.形参列表.iter().map(|p| p.名称.clone()).collect(),
                    返回类型: Some(替换后返回类型.clone()),
                },
                是否公开: true,
            },
            是否公开: true,
            是否可变: false,
            定义位置: 位置.clone(),
                        所属模块: None,
            }).ok();

        Ok(高层表示表达式::调用 {
                    位置: 源码位置::默认(),
            函数名: 单态化名称,
            实参列表: 高层表示实参,
            类型: 替换后返回类型,
        })
    }

    /// 从类型表达式中提取任意类型参数到具体类型的映射（G7：含冲突检测+约束校验）。
    /// 约束表 = 各类型标记的声明约束（首个非空约束），供"数值提升守护"判定 小数 是否被约束允许
    /// （守护须基于声明处约束，而非当前遇到的引用节点约束——引用型 任意<甲> 约束为空会误放行）。
    fn 提取类型参数映射(
        &mut self,
        类型标注: &类型表达式,
        实参类型: &类型信息,
        映射: &mut HashMap<String, 类型信息>,
        约束表: &HashMap<String, Vec<类型表达式>>,
    ) -> Result<(), ()> {
        match 类型标注 {
            类型表达式::基本类型(_) => {}
            类型表达式::数组(元素类型) => {
                if let 类型信息::数组(实参元素) = 实参类型 {
                    self.提取类型参数映射(元素类型, 实参元素, 映射, 约束表)?;
                }
            }
            类型表达式::映射(键类型, 值类型) => {
                if let 类型信息::映射(实参键, 实参值) = 实参类型 {
                    self.提取类型参数映射(键类型, 实参键, 映射, 约束表)?;
                    self.提取类型参数映射(值类型, 实参值, 映射, 约束表)?;
                }
            }
            类型表达式::任意类型 { 标记名称, 约束范围 } => {
                if let Some(参数名) = 标记名称 {
                    // G7-冲突检测：同一占位已绑定不同类型→报错
                    if let Some(已绑定) = 映射.get(参数名) {
                        if !类型检查::检查赋值兼容(已绑定, 实参类型) {
                            // 🆕 数值甲族提升（2026-09-02，规范 §2.4.3 绑定提升规则；与库族 数值甲统一返回类型、
                            // 运算符幂 同一语义单源）：同名甲先后绑定 整数/小数（如 取较大值(1, 2.5)）→
                            // 统一提升为小数（顺序无关，Python/Julia 数值提升）。
                            // 守护：基于类型标记的声明约束（约束表），而非当前节点约束范围——
                            // 冲突可能发生在引用型节点（任意<甲> 约束为空会误放行），真实约束在声明处。
                            // 仅当声明约束为空 或 含基本类型"小数" 才允许提升；否则维持「类型守恒冲突」报错
                            // （如 任意<甲: 整数> 被 2.5 偷渡成小数）。
                            let 甲允许小数 = match 约束表.get(参数名) {
                                None => true,
                                Some(声明约束) => 声明约束.is_empty()
                                    || 声明约束.iter().any(|c| matches!(c, 类型表达式::基本类型(n) if n.as_str() == "小数")),
                            };
                            let 可提升为小数 = 甲允许小数
                                && ((*已绑定 == 类型信息::整数类型() && *实参类型 == 类型信息::小数类型())
                                    || (*已绑定 == 类型信息::小数类型() && *实参类型 == 类型信息::整数类型()));
                            if 可提升为小数 {
                                映射.insert(参数名.clone(), 类型信息::小数类型());
                            } else {
                                let 位置 = 源码位置::新("".into(), 0, 0);
                                self.报错(&format!(
                                    "类型守恒冲突：类型参数【{}】已绑定为【{}】，不能同时为【{}】",
                                    参数名, 已绑定.类型名称(), 实参类型.类型名称()
                                ), &位置);
                                return Err(()); // 类型守恒冲突须中断单态化（否则报错被吞，程序继续执行）
                            }
                        }
                    } else {
                        // G7-约束校验：有约束时检查实参是否在约束集合中
                        if !约束范围.is_empty() {
                            let 约束解析: Vec<类型信息> = 约束范围.iter()
                                .filter_map(|c| self.解析类型标注(&Some(c.clone())))
                                .collect();
                            if !约束解析.is_empty() {
                                let 约束目标 = 类型信息::任意类型 { 约束范围: 约束解析, 变量索引: usize::MAX };
                                // G4：使用单一真相 检查任意类型约束（严格成员判定），
                                // 避免 检查赋值兼容 的整数↔小数数值宽松把 小数 误判为落入 整数|文本。
                                if !类型检查::检查任意类型约束(&约束目标, 实参类型) {
                                    let 位置 = 源码位置::新("".into(), 0, 0);
                                    self.报错(&format!(
                                        "类型约束冲突：类型【{}】不在【{}】的约束范围内",
                                        实参类型.类型名称(), 参数名
                                    ), &位置);
                                    return Err(());
                                }
                            }
                        }
                        映射.insert(参数名.clone(), 实参类型.clone());
                    }
                } else if !约束范围.is_empty() {
                    // 🆕 2026-09-04 匿名任意联合约束校验（与有名分支 G7 同源）：实参须落入约束范围。
                    // 此前匿名任意（如 任意<整数|小数> 形参）无此校验——取数("abc") 文本实参静默通过，
                    // 约束形同虚设且文本混入后续按整数槽使用产生位模式错乱。
                    // 用 类型检查::检查任意类型约束 单源：源为任意(自由/约束⊆目标)或 未推断 → 放行
                    // （运行时按标签分派，不误伤动态实参如 工具.解析数据 结果）；源为具体类型 → 精确
                    // 落入约束范围（含 整数↔小数 单向宽松、裸容器同构匹配）。
                    let 约束解析: Vec<类型信息> = 约束范围.iter()
                        .filter_map(|c| self.解析类型标注(&Some(c.clone())))
                        .collect();
                    if !约束解析.is_empty() {
                        let 约束目标 = 类型信息::任意类型 { 约束范围: 约束解析.clone(), 变量索引: usize::MAX };
                        if !类型检查::检查任意类型约束(&约束目标, 实参类型) {
                            let 位置 = 源码位置::新("".into(), 0, 0);
                            let 约束文本 = 约束解析.iter().map(|t| t.类型名称()).collect::<Vec<_>>().join("|");
                            self.报错(&format!(
                                "类型约束冲突：类型【{}】不在【任意<{}>】的约束范围内",
                                实参类型.类型名称(), 约束文本
                            ), &位置);
                            return Err(()); // 约束冲突须中断单态化（否则报错被吞，程序继续执行）
                        }
                    }
                }
            }
            类型表达式::泛型 { 类型参数, .. } => {
                if let 类型信息::结构体(_, 实参参数) = 实参类型 {
                    for (形参, 实参) in 类型参数.iter().zip(实参参数.iter()) {
                        self.提取类型参数映射(形参, 实参, 映射, 约束表)?;
                    }
                }
            }
            类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
                if let 类型信息::函数类型(实参参数列表, 实参返回) = 实参类型 {
                    for (形参标注, 实参) in 参数类型列表.iter().zip(实参参数列表.iter()) {
                        self.提取类型参数映射(形参标注, 实参, 映射, 约束表)?;
                    }
                    self.提取类型参数映射(返回类型, 实参返回, 映射, 约束表)?;
                }
            }
        }
        Ok(())
    }

    /// 用具体类型替换类型表达式中的任意类型参数
    fn 替换类型参数(
        &self,
        类型表达式: &类型表达式,
        映射: &HashMap<String, 类型信息>,
    ) -> 类型信息 {
        match 类型表达式 {
            类型表达式::基本类型(名称) => match 名称.as_str() {
                "整数" => 类型信息::整数类型(),
                "小数" => 类型信息::小数类型(),
                "文本" => 类型信息::文本类型(),
                "逻辑" => 类型信息::逻辑类型(),
                "空值" => 类型信息::空值类型(),
                _ => 类型信息::未推断,
            },
            类型表达式::数组(元素类型) => {
                类型信息::数组(Box::new(self.替换类型参数(元素类型, 映射)))
            }
            类型表达式::映射(键类型, 值类型) => {
                类型信息::映射(
                    Box::new(self.替换类型参数(键类型, 映射)),
                    Box::new(self.替换类型参数(值类型, 映射)),
                )
            }
            类型表达式::任意类型 { 标记名称, 约束范围 } => {
                if let Some(参数名) = 标记名称 {
                    映射.get(参数名).cloned().unwrap_or(类型信息::未推断)
                } else {
                    // 匿名联合：递归替换约束成员，保留联合语义
                    let 替换后约束: Vec<类型信息> = 约束范围.iter()
                        .map(|c| self.替换类型参数(c, 映射))
                        .collect();
                    类型信息::任意类型 { 约束范围: 替换后约束, 变量索引: usize::MAX }
                }
            }
            类型表达式::泛型 { 名称, 类型参数 } => {
                let 替换后参数: Vec<类型信息> = 类型参数.iter()
                    .map(|p| self.替换类型参数(p, 映射))
                    .collect();
                类型信息::结构体(名称.clone(), 替换后参数)
            }
            类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
                let 替换后参数: Vec<类型信息> = 参数类型列表.iter()
                    .map(|p| self.替换类型参数(p, 映射))
                    .collect();
                类型信息::函数类型(替换后参数, Box::new(self.替换类型参数(返回类型, 映射)))
            }
        }
    }

    /// 生成单态化函数体：用具体类型替换所有任意类型参数
    fn 生成单态化函数(
        &mut self,
        原始定义: &函数定义,
        类型参数映射: &HashMap<String, 类型信息>,
        新名称: &str,
    ) -> Result<高层表示函数, ()> {
        // 创建新的形参列表（使用具体类型）
        let mut 新形参列表 = Vec::new();
        for 形参 in &原始定义.形参列表 {
            let 具体类型 = if let Some(类型标注) = &形参.类型标注 {
                self.替换类型参数(类型标注, 类型参数映射)
            } else {
                类型信息::未推断
            };
            新形参列表.push((形参.名称.clone(), 具体类型));
        }

        // 分析原始函数体（使用已有的分析逻辑）
        self.符号表.进入作用域(作用域类型::函数);
        for (名称, 类型) in &新形参列表 {
            self.符号表.声明符号(符号 {
                名称: 名称.clone(),
                符号种类: 符号种类::变量 { 类型: 类型.clone() },
                是否公开: false,
                是否可变: false,
                定义位置: 原始定义.位置.clone(),
                            所属模块: None,
            }).ok();
        }
        // ★§2.3.5（修复 2026-10-12，用例 228 同口径）：泛型实例化的函数体顶层同样与形参
        //   同用一个命名空间 ⇒ 用 `分析代码块_内部`（作用域由本处管理＝上面 push 的「函数」作用域）。
        let 函数体 = self.分析代码块_内部(&原始定义.函数体)?;
        self.符号表.离开作用域();

        Ok(高层表示函数 {
            名称: 新名称.to_string(),
            形参列表: 新形参列表.clone(),
            形参默认值: vec![None; 新形参列表.len()],
            形参传递方式: vec![参数传递方式::传值; 新形参列表.len()],
            返回类型: 原始定义.返回类型.as_ref()
                .map(|rt| Some(self.替换类型参数(rt, 类型参数映射)))
                .unwrap_or_else(|| self.解析类型标注(&原始定义.返回类型)),
            函数体,
            依赖自身: false,
        })
    }

    /// 递归收集类型标注中 类型标记 → 首个非空约束（数值提升守护用，2026-09-02）。
    /// 引用型 任意<甲>（约束为空）不覆盖已记录的声明约束。
    fn 收集声明约束(&self, 标注: &类型表达式, 表: &mut HashMap<String, Vec<类型表达式>>) {
        match 标注 {
            类型表达式::任意类型 { 标记名称, 约束范围 } => {
                if let Some(名) = 标记名称 {
                    if !约束范围.is_empty() {
                        表.entry(名.clone()).or_insert_with(|| 约束范围.clone());
                    }
                }
            }
            类型表达式::数组(元素) => self.收集声明约束(元素, 表),
            类型表达式::映射(键类型, 值类型) => {
                self.收集声明约束(键类型, 表);
                self.收集声明约束(值类型, 表);
            }
            类型表达式::泛型 { 类型参数, .. } => {
                for p in 类型参数 { self.收集声明约束(p, 表); }
            }
            类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
                for p in 参数类型列表 { self.收集声明约束(p, 表); }
                self.收集声明约束(返回类型, 表);
            }
            _ => {}
        }
    }
}
