// 文件: 前端/src/标准库真源校验.rs
// 职责: ★标准库真源自洽门禁★ —— 防「声明层双源」漂移复发。
//
// 三层校验：
//   ① 元数据自洽：规范全名唯一（抓重复注册死条目）、索引 < 用户函数索引基址（用户函数从 用户函数索引基址 起）。
//   ② 元数据形参/默认值 == 语义层方法表：防「签名第二源」漂移（可选形参静默失效）。
//   ③ 门面 == 元数据：对每个 标准库/<模块>.智 解析，断言
//        - 函数定义集 == 元数据按模块分组集（防漏生成 / 防多生成）；
//        - 函数体调用全为 canonical 「模块.函数」形式（防裸名 / 防接错线）；
//        - 调用目标 函数名 必在元数据该模块定义集中（防接错线）。
//   门面被两模式跳过，故本门禁作用在共享层，双模式自动 parity、零后端改动。
//
// 注：元数据 ↔ base(Rust) 的真实覆盖由 标准库元数据.rs::自检_索引一致 在运行期 fail-fast 保证
//     （同一 标准库索引::X 常量在元数据表与 base match 臂共用，编译期固化为单源）。

use crate::标准库元数据::{标准库注册表, 按模块分组};
use std::fs;
use std::path::Path;

/// 运行全部校验。返回 Ok(()) 或 Err(合并的错误清单)。
pub fn 校验(可选目录: Option<&str>) -> Result<(), String> {
    let mut 错误 = Vec::new();

    错误.extend(校验元数据自洽());
    错误.extend(校验形参与默认值一致());
    错误.extend(校验门面等于元数据(可选目录));
    错误.extend(校验规范签名一致());

    if 错误.is_empty() {
        Ok(())
    } else {
        Err(错误.join("\n"))
    }
}

/// ④ 规范签名 == 元数据（双向对账）—— 规范为准：不一致一律视为「实现偏离规范」。
/// 机制：`规范签名.rs` 是从《智语言编程规范》§5 转录的可执行权威表（人工维护）；
///      对「已覆盖模块」，要求元数据与权威表双向一致，漂移即报红。
/// 当前覆盖模块：系统(§5.5)、时间(§5.4)；其余模块转录分批补入后自动纳入（覆盖集由表派生）。
fn 校验规范签名一致() -> Vec<String> {
    let mut 错误 = Vec::new();
    use crate::标准库元数据::{标准库注册表, 标准库种类};
    use crate::规范签名::规范签名表;

    let 覆盖模块: std::collections::HashSet<&str> =
        规范签名表.iter().map(|s| s.模块).collect();

    // ── 正向：规范表每条 须在元数据命中且签名一致 ──
    for 规 in 规范签名表.iter() {
        let 命中 = 标准库注册表.iter().find(|e| e.模块 == 规.模块 && e.函数名 == 规.函数名);
        let e = match 命中 {
            Some(x) => x,
            None => {
                错误.push(format!(
                    "[规范→元数据] {} 规范声明但元数据未登记（实现缺失或拼写漂移）",
                    规.规范名()
                ));
                continue;
            }
        };
        // 元数据形参含「自身」的（数学内建/句柄方法），比对时去自身
        let 注册类型: Vec<&str> = e.形参
            .iter()
            .filter(|(名, _)| *名 != "自身")
            .map(|(_, t)| *t)
            .collect();
        let 去空格 = |s: &str| s.chars().filter(|c| !c.is_whitespace()).collect::<String>();
        if 注册类型.len() != 规.形参类型.len() {
            错误.push(format!(
                "[规范→元数据] {}.{} 形参数 规范={} vs 元数据={}",
                规.模块, 规.函数名, 规.形参类型.len(), 注册类型.len()
            ));
        } else {
            for i in 0..规.形参类型.len() {
                if 去空格(&注册类型[i]) != 去空格(&规.形参类型[i]) {
                    错误.push(format!(
                        "[规范→元数据] {}.{} 第{}形参类型 规范『{}』 vs 元数据『{}』",
                        规.模块, 规.函数名, i + 1, 规.形参类型[i], 注册类型[i]
                    ));
                }
            }
        }
        // 返回类型
        match (规.返回, e.返回) {
            (None, None) => {}
            (None, Some(实际)) => 错误.push(format!(
                "[规范→元数据] {}.{} 规范无返回值，但元数据返回『{}』",
                规.模块, 规.函数名, 实际
            )),
            (Some(期望), None) => 错误.push(format!(
                "[规范→元数据] {}.{} 规范返回『{}』，但元数据无返回值",
                规.模块, 规.函数名, 期望
            )),
            (Some(期望), Some(实际)) => {
                if 去空格(期望) != 去空格(实际) {
                    错误.push(format!(
                        "[规范→元数据] {}.{} 返回类型 规范『{}』 vs 元数据『{}』",
                        规.模块, 规.函数名, 期望, 实际
                    ));
                }
            }
        }
    }

    // ── 反向：已覆盖模块内，元数据「公开函数/结构体方法/句柄方法」集 ⊆ 规范表集 ──
    for &模块 in &覆盖模块 {
        let 规范名集: std::collections::HashSet<&str> = 规范签名表
            .iter()
            .filter(|s| s.模块 == 模块)
            .map(|s| s.函数名)
            .collect();
        for e in 标准库注册表.iter() {
            if e.模块 != 模块 {
                continue;
            }
            // 反向仅覆盖「模块公开函数」：数学内建方法/句柄方法是类型方法，签名一致性
            // 由真源校验②（语义层方法签名表=注册表派生）+ 数学内建方法转录批次（§5.1.11~15）单独承担。
            if e.种类 == 标准库种类::模块公开函数 && !规范名集.contains(e.函数名) {
                错误.push(format!(
                    "[元数据→规范] {}.{} 元数据登记但规范签名表缺此函数（实现超前规范，或转录遗漏）",
                    模块, e.函数名
                ));
            }
        }
    }
    错误
}

/// ① 元数据自洽性
fn 校验元数据自洽() -> Vec<String> {
    let mut 错误 = Vec::new();
    let mut 已见: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
    for 条 in 标准库注册表.iter() {
        let 全名 = 条.规范全名();
        // 规范全名唯一（同一全名多次登记 = 重复注册死条目，与「重载已取消」冲突）
        if let Some(&已) = 已见.get(&全名) {
            if 已 != 条.索引 {
                错误.push(format!(
                    "[元数据] 规范全名 {} 索引不一致：{} 与 {}（疑似重复注册）",
                    全名, 已, 条.索引
                ));
            } else {
                错误.push(format!(
                    "[元数据] 规范全名 {} 重复登记（索引相同 {}），属重复死条目，应删冗余",
                    全名, 条.索引
                ));
            }
        } else {
            已见.insert(全名.clone(), 条.索引);
        }
        // 索引 < 用户函数索引基址（用户函数从 用户函数索引基址 起；专用 opcode 型 usize::MAX 跳过）
        if 条.索引 != usize::MAX && 条.索引 >= crate::底层表示::模块结构::用户函数索引基址 {
            错误.push(format!(
                "[元数据] 索引 {} ({}) 越界：系统函数索引必须低于 用户函数索引基址",
                条.索引, 全名
            ));
        }
    }
    错误
}

/// ③ 元数据形参/默认值 与 语义层方法表 一致性 —— 防「签名第二源」漂移
///
/// 背景：结构体方法签名分居两处且表达力不对等——
///   · 元数据侧：标准库元数据.rs（数学内建 / 数学内建带默认）持有 形参[0]=自身 + 可选默认值；
///   · 语义侧：语义::类型推导::精确小数方法签名表 持有 形参类型（不含自身，且无法表达默认值）。
/// 二者漂移时的表现极其隐蔽：**可选形参静默失效**（形参数量为 0 时降级填充循环永不进入），
/// 不报错、只是结果错误。故在此以自动化断言固化一致性——把「统一」从一次性修复升级为长期约束。
fn 校验形参与默认值一致() -> Vec<String> {
    let mut 错误 = Vec::new();
    let 语义形参数: std::collections::HashMap<&'static str, usize> =
        crate::语义::类型推导::精确小数方法签名表()
            .into_iter()
            .map(|(名, 形参, _)| (名, 形参.len()))
            .collect();

    for 条 in 标准库注册表.iter() {
        // ① 默认值列表按索引与形参对齐，长度不等即整体错位（静默取错/取空）
        if let Some(默认列表) = 条.默认值 {
            if 默认列表.len() != 条.形参.len() {
                错误.push(format!(
                    "[元数据] {} 默认值长度({}) 与形参长度({}) 不一致——默认值按索引对齐，错位将静默失效",
                    条.规范全名(),
                    默认列表.len(),
                    条.形参.len()
                ));
            }
        }

        // ②/③ 仅结构体方法（数学内建方法）需要「含自身」约定与语义表交叉校验
        if !(matches!(条.种类, crate::标准库元数据::标准库种类::数学内建方法)
            && !条.形参.is_empty())
        {
            continue;
        }
        // ② 形参[0] 必须是「自身」：降级默认填充按「形参数量含自身」处理（-1 for self、+1 skip self）
        if 条.形参[0].0 != "自身" {
            错误.push(format!(
                "[元数据] {} 形参[0] 应为「自身」，实为「{}」——降级按「含自身」计数，首位非自身将导致默认填充错位",
                条.规范全名(),
                条.形参[0].0
            ));
        }
        // ③ 仅精确小数方法需与语义层方法表交叉校验（单源收口后语义表=注册表派生，恒一致）；
        //    其它数值类型数学方法（短小数/无符号整数/字节/无限整数）签名真相已收口进元数据，
        //    语义层方法表目前仅覆盖精确小数，故不再要求它们出现在该表（避免误报无对应方法）。
        if 条.函数名.starts_with("精确小数.") {
            let 方法短名 = 条.函数名.rsplit('.').next().unwrap_or(条.函数名);
            match 语义形参数.get(方法短名) {
                Some(&语义数) => {
                    let 元数据数 = 条.形参.len() - 1; // 去自身
                    if 元数据数 != 语义数 {
                        错误.push(format!(
                            "[元数据] {} 形参数({} 已去自身) 与语义层方法表({}) 不一致——签名第二源漂移",
                            条.规范全名(),
                            元数据数,
                            语义数
                        ));
                    }
                }
                None => 错误.push(format!(
                    "[元数据] {} 在语义层方法表中无对应方法——签名第二源漂移",
                    条.规范全名()
                )),
            }
        }
    }
    错误
}

/// ③ 门面 == 元数据
fn 校验门面等于元数据(可选目录: Option<&str>) -> Vec<String> {
    let 目录 = match 可选目录 {
        Some(d) => d.to_string(),
        // ⚠ 2026-11-16 发布安全：不用 `env!("CARGO_MANIFEST_DIR")`（会把仓库绝对路径固化进
        //   发布二进制），改为运行时推导（见 标准库门面生成::默认输出目录）。
        None => crate::标准库门面生成::默认输出目录(),
    };
    let mut 错误 = Vec::new();

    for (模块, 条目) in 按模块分组() {
        let 元数据定义集: std::collections::HashSet<String> =
            条目.iter().map(|e| e.函数名.to_string()).collect();
        // 期望的 canonical 调用集合「模块.函数名」——函数名可含点（结构体方法如 数学.精确小数.加法）
        let 期望调用: std::collections::HashSet<String> = 条目
            .iter()
            .map(|e| format!("{}.{}", e.模块, e.函数名))
            .collect();

        let 路径 = Path::new(&目录).join(format!("{}.智", 模块));
        let 内容 = match fs::read_to_string(&路径) {
            Ok(c) => c,
            Err(e) => {
                错误.push(format!("[门面] 无法读取 {}: {}", 路径.display(), e));
                continue;
            }
        };

        let (定义集, 调用集) = 解析门面(&内容);
        let 定义集: std::collections::HashSet<String> = 定义集.into_iter().collect();

        // 定义集 == 元数据定义集
        for 缺 in 元数据定义集.difference(&定义集) {
            错误.push(format!("[门面] {}.智 缺失函数定义：{}", 模块, 缺));
        }
        for 多 in 定义集.difference(&元数据定义集) {
            错误.push(format!("[门面] {}.智 多余函数定义（元数据无此条目）：{}", 模块, 多));
        }

        // 函数体调用校验：必须与期望 canonical 调用集完全一致
        let 构造名集合 = crate::标准库元数据::构造内部名集合();
        for 调用 in 调用集 {
            if !调用.contains('.') {
                // 初始化函数体的 canonical 构造调用（如 数学精确小数创建）为元数据内部名，放行
                if 构造名集合.contains(调用.as_str()) {
                    continue;
                }
                错误.push(format!("[门面] {}.智 函数体含裸名调用「{}」——应改为 canonical 模块.函数", 模块, 调用));
                continue;
            }
            if 期望调用.contains(&调用) {
                continue;
            }
            // 未命中：区分「跨模块」与「本模块内接错线」两类，给出可读诊断
            if 调用.starts_with(&format!("{}.", 模块)) {
                错误.push(format!(
                    "[门面] {}.智 函数体接错线：{} 不在本模块标准库条目中",
                    模块, 调用
                ));
            } else {
                错误.push(format!(
                    "[门面] {}.智 函数体调用跨模块「{}」——应为本模块 {}",
                    模块, 调用, 模块
                ));
            }
        }
    }
    错误
}

/// 轻量解析门面：提取函数定义名集合 与 函数体调用（模块.函数）集合。
/// 解析约定（与本生成器输出严格一致）：
///   - 结构体壳子：`结构体 X(形参):` 进入结构体上下文（形参忽略，不计为定义）；
///   - `初始化():` 不计入定义集（构造由 内部名 canonical 调用断言）；
///   - 定义行：含 '(' 且以 ':' 结尾 → 取 '(' 前为定义名；结构体内补回 `X.` 前缀；
///   - 调用行：含 '(' 且不以其结尾 ':'，取含 '(' 且含 '.' 的 token 的 '(' 前部分（模块.函数）；
///   - `结束`：缩进 0 → 闭合结构体；缩进 >0 → 闭合结构体内的方法（保留前缀）。
fn 解析门面(内容: &str) -> (Vec<String>, Vec<String>) {
    let mut 定义 = Vec::new();
    let mut 调用 = Vec::new();
    let mut 结构体前缀: Option<String> = None;
    for 行 in 内容.lines() {
        let 缩进 = 行.len() - 行.trim_start().len();
        let t = 行.trim();
        if t.is_empty() || t.starts_with("//") {
            continue;
        }
        if let Some(剩余) = t.strip_prefix("结构体 ") {
            if 剩余.contains('(') && 剩余.ends_with(':') {
                let 类型名 = 剩余[..剩余.find('(').unwrap()].trim().to_string();
                结构体前缀 = Some(类型名);
            }
            continue;
        }
        if t == "初始化():" {
            continue;
        }
        if t == "结束" {
            if 缩进 == 0 {
                结构体前缀 = None;
            }
            continue;
        }
        if let Some(左) = t.find('(') {
            if t.ends_with(':') {
                let 名 = t[..左].trim();
                if !名.is_empty() {
                    // 结构体块内的定义名 = 类型.短名（补回元数据函数名）
                    let 完整名 = match &结构体前缀 {
                        Some(类型) => format!("{}.{}", 类型, 名),
                        None => 名.to_string(),
                    };
                    定义.push(完整名);
                }
            } else if let Some(p) = t.split_whitespace().find_map(|tok| tok.find('(').map(|i| (tok, i))) {
                let 全 = &p.0[..p.1];
                if 全.contains('.') {
                    调用.push(全.to_string());
                }
            }
        }
    }
    (定义, 调用)
}
