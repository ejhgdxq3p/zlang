// 文件: 前端/src/名称身份.rs
// 职责: ★四类受限名称的统一身份层★ —— 关键字 / 保留关键字 / 上下文关键字 / 预定义标识符。
//       规范依据：《智语言编程规范》§2.2.3 关键字与预定义标识符。
//
// 设计原则（2026-09-14 定稿）：
//   ① 单一真相：预定义标识符派生自 标准库元数据 的「全局函数」种类，不另建平行表；
//      新增/改名全局函数只改元数据一处，本层与全部消费点自动同步。
//   ② 分层落地（不可动摇）：
//        关键字 / 保留关键字  → 词法层 token 化（任何位置禁用，靠词法一次拦住）
//        上下文关键字          → 词法层**绝不** token 化，由语法层按语境识别
//        预定义标识符          → 词法层**绝不** token 化，由语义层在声明点校验
//   ③ ⚡双模式⚡ 本模块纯前端、纯静态，**禁止读取任何编译模式状态** →
//      解释模式与编译模式走同一判定，天然 parity，无需任何后端改动。
//   ④ 命名空间模型（限制的技术根因）：
//        预定义标识符占用「全局函数空间」→ 与模块级函数名冲突，禁用；
//        变量会遮蔽同名函数（表达式分析先查符号表）→ 与模块级/局部变量名冲突，禁用；
//        成员（字段/方法）走「实例.成员」独立寻址 → 不冲突，规范允许。

use std::collections::HashSet;

// ═══════════════════════════════════════════════════════════════════════════
// 一、预定义标识符（§2.2.3，共 8 个）
// ═══════════════════════════════════════════════════════════════════════════

/// §2.2.3 预定义标识符集合（8 个）。
/// 单一真相：标准库元数据 中「种类 = 全局函数」的条目名。
/// 当前成员：输出 / 输入 / 错误输出 / 类型 / 异常错误 / 转整数 / 转小数 / 转文本。
pub fn 预定义标识符集合() -> &'static HashSet<&'static str> {
    crate::标准库元数据::全局函数名集合()
}

/// 是否为预定义标识符。
pub fn 是预定义标识符(名: &str) -> bool {
    预定义标识符集合().contains(名)
}

// ═══════════════════════════════════════════════════════════════════════════
// 二、编译器内部名（非规范「预定义标识符」，用户不可裸调）
// ═══════════════════════════════════════════════════════════════════════════

/// 内部名：编译器合成，用户不可裸调（[]/{} 字面量构造走专用路径）。
const 内部名集合: &[&str] = &["创建数组", "创建映射"];

/// 是否为编译器内部名。
pub fn 是内部名(名: &str) -> bool {
    内部名集合.contains(&名)
}

/// 是否为内置转换器（预定义标识符 ∪ 内部名）：
/// 其调用参数校验策略与普通函数不同（可变参数 / 自行处理类型），须跳过常规校验。
pub fn 是内置转换器(名: &str) -> bool {
    是预定义标识符(名) || 是内部名(名)
}

// ═══════════════════════════════════════════════════════════════════════════
// 三、类型转换函数子集（空值转换检查适用）
// ═══════════════════════════════════════════════════════════════════════════

/// 类型转换函数 {转整数, 转小数, 转文本}：其文本/整数/小数实参需作空值转换检查。
/// 契约：本集合 ⊆ 预定义标识符集合（由契约单测断言）。
const 类型转换函数集合: &[&str] = &["转整数", "转小数", "转文本"];

/// 是否为类型转换函数。
pub fn 是类型转换函数(名: &str) -> bool {
    类型转换函数集合.contains(&名)
}

// ═══════════════════════════════════════════════════════════════════════════
// 四、声明点校验（§2.2.3「规则」表）
// ═══════════════════════════════════════════════════════════════════════════

/// 声明语境（§2.2.3 规则表的行维度）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 声明语境 {
    /// 模块级：变量 / 常量 / 函数 / 结构体 / 枚举 / 接口
    模块级,
    /// 函数局部：局部变量 / 局部常量 / 参数
    函数局部,
    /// 导入别名
    导入别名,
    /// 结构体成员：字段 / 方法（规范允许与预定义标识符同名）
    成员,
}

impl 声明语境 {
    fn 说明(&self) -> &'static str {
        match self {
            声明语境::模块级 => "模块级",
            声明语境::函数局部 => "函数局部",
            声明语境::导入别名 => "导入别名",
            声明语境::成员 => "成员",
        }
    }
}

/// 校验受限名称能否用于指定声明语境。
///
/// 规则（§2.2.3）：
///   - 预定义标识符：模块级 / 函数局部 / 导入别名 ❌；结构体成员 ✅
///   - 关键字 / 保留关键字：由词法层 token 化天然拦截（不经本函数）
///
/// 技术根因（命名空间模型）：
///   预定义标识符占用「全局函数空间」，而变量会遮蔽同名函数（表达式分析先查符号表）
///   → 模块级函数名、变量名、局部变量名冲突，必须禁用；
///   成员走「实例.成员」独立寻址，不冲突，故规范允许。
///
/// 返回 Err(诊断消息)：消息含名称、语境、种类与替代建议。
/// ⚡双模式⚡ 纯静态判定，不读取任何编译模式状态。
/// 是否为关键字 / 保留关键字名（词法保留类）—— 派生自 `词法分析::关键字名集合`。
/// 注：真关键字已在词法层 token 化，正常不会以标识符形式到达声明点；
///     本判定用于兜住「关键字经语法层转为标识符」的既有路径（如 `自身`）。
pub fn 是关键字名(名: &str) -> bool {
    crate::词法分析::关键字名集合().contains(名)
}

pub fn 校验声明名称(名称: &str, 语境: 声明语境, 种类: &str) -> Result<(), String> {
    // 关键字 / 保留关键字 / 类型名：任何位置（含结构体成员级）都不得作标识符（§2.2.3:579-581）
    if 是关键字名(名称) {
        return Err(format!(
            "【{}】是关键字，任何位置（含结构体成员级）都不能用作{}；请改用其它中文名词。",
            名称, 种类
        ));
    }
    if 语境 == 声明语境::成员 {
        return Ok(());
    }
    if 是预定义标识符(名称) {
        return Err(format!(
            "【{}】是预定义标识符，不能用作{}{}（与内置函数冲突：变量会遮蔽同名内置函数、函数名占用同一命名空间）；\
             结构体成员（字段/方法）可以同名，请改用其他名称或改为成员。",
            名称,
            语境.说明(),
            种类
        ));
    }
    Ok(())
}

// ═══════════════════════════════════════════════════════════════════════════
// 五、外部块上下文类型名（§2.2.3，共 17 个）—— FFI 精确类型统一真相
// ═══════════════════════════════════════════════════════════════════════════

/// FFI 标量类型表：规范名 → (核心类型文本, C 精确码)。
///
/// 精确码契约：与 `基础功能/src/外部调用注册.rs::精确类型码到C类型` 严格对齐。
///
/// ★单一真相★：取代此前 **3 份重复表**（曾内容漂移——`模块加载器` 多出 `有符号字符`/`无符号字符`）：
///   1. `语义分析器::FFI精确类型码`（类型 + 精确码）
///   2. `模块加载器::FFI名到核心类型`（仅类型）
///   3. `类型语法分析::是函数指针关键字`（函数指针判定）
///
/// 前 3 项是智语言内置类型（外部块内亦可书写，精确码 0 表示 shim 用默认位宽）；
/// 其后的 16 项即规范 §2.2.3「外部块上下文」的标量类型（第 17 项 `函数指针` 见 [`函数指针名表`]）。
pub const FFI标量类型表: &[(&str, &str, u8)] = &[
    // 智语言内置类型（缺省码 0）
    ("逻辑", "逻辑", 0),
    ("文本", "文本", 0),
    ("空值", "空值", 0),
    // 有符号整数（码 1..4、14、17）
    ("单整数", "整数", 1),
    ("微整数", "整数", 2),
    ("短整数", "整数", 3),
    ("长整数", "整数", 4),
    ("平台整数", "整数", 14),
    ("位宽整数", "整数", 17),
    // 无符号整数（无符号前置；码 5..8、15、16）
    ("无符号单整数", "整数", 5),
    ("无符号微整数", "整数", 6),
    ("无符号短整数", "整数", 7),
    ("无符号长整数", "整数", 8),
    ("无符号平台整数", "整数", 15),
    ("无符号位宽整数", "整数", 16),
    // 浮点（码 9=f32、10=f64）
    ("短小数", "小数", 9),
    ("长小数", "小数", 10),
    // 字符（码 18）/ 指针（码 13）
    ("字符", "整数", 18),
    ("指针", "整数", 13),
    // 历史别名（规范 §2.2.3 未列；保留以兼容既有外部块声明，码同 字符）
    ("有符号字符", "整数", 18),
    ("无符号字符", "整数", 18),
];

/// 函数指针类型构造器名（规范第 17 个外部块上下文类型名；含历史别名 `外部函数`）。
pub const 函数指针名表: &[&str] = &["函数指针", "外部函数"];

/// 查 FFI 标量类型 → (核心类型文本, C 精确码)。None = 非 FFI 标量名。
pub fn FFI标量类型(名: &str) -> Option<(&'static str, u8)> {
    FFI标量类型表
        .iter()
        .find(|(n, _, _)| *n == 名)
        .map(|(_, 类型, 码)| (*类型, *码))
}

/// 是否为函数指针类型构造器名（`函数指针` / 历史别名 `外部函数`）。
pub fn 是函数指针名(名: &str) -> bool {
    函数指针名表.contains(&名)
}

/// 是否为外部块上下文类型名（§2.2.3：16 个标量 + `函数指针` = 17 个；另含 2 个历史别名）。
pub fn 是外部块类型名(名: &str) -> bool {
    FFI标量类型(名).is_some() || 是函数指针名(名)
}

// ═══════════════════════════════════════════════════════════════════════════
// 六、契约单测（守护「单一真相 + 分层契约」，防止再次漂移）
// ═══════════════════════════════════════════════════════════════════════════

#[cfg(test)]
mod 测试 {
    use super::*;

    /// §2.2.3 规定预定义标识符共 8 个。
    #[test]
    fn 预定义标识符恰为八个() {
        assert_eq!(
            预定义标识符集合().len(),
            8,
            "§2.2.3 预定义标识符应为 8 个，实际 {:?}",
            预定义标识符集合()
        );
    }

    /// 类型转换函数必须是预定义标识符的子集（防止两表漂移）。
    #[test]
    fn 类型转换函数是预定义标识符子集() {
        for 名 in 类型转换函数集合 {
            assert!(是预定义标识符(名), "【{}】应为预定义标识符", 名);
        }
    }

    /// 内部名不是预定义标识符，但属于内置转换器。
    #[test]
    fn 内部名归属正确() {
        for 名 in 内部名集合 {
            assert!(!是预定义标识符(名), "【{}】不应是预定义标识符", 名);
            assert!(是内置转换器(名), "【{}】应属内置转换器", 名);
        }
    }

    /// 改名后的新名必须是预定义标识符（回归守护：旧名 整数/小数/文本 已废弃）。
    #[test]
    fn 改名后新名生效旧名失效() {
        for 名 in ["转整数", "转小数", "转文本"] {
            assert!(是预定义标识符(名), "【{}】应为预定义标识符", 名);
        }
        for 旧名 in ["整数", "小数", "文本"] {
            assert!(!是预定义标识符(旧名), "旧名【{}】不应再是预定义标识符", 旧名);
        }
    }

    /// §2.2.3 外部块上下文类型名（17 个）必须全部覆盖（防止三份 FFI 表再次漂移）。
    #[test]
    fn 外部块类型名覆盖规范十七个() {
        let 规范十七 = [
            "单整数", "微整数", "短整数", "长整数", "平台整数", "位宽整数",
            "无符号单整数", "无符号微整数", "无符号短整数", "无符号长整数",
            "无符号平台整数", "无符号位宽整数",
            "短小数", "长小数", "字符", "指针", "函数指针",
        ];
        assert_eq!(规范十七.len(), 17, "§2.2.3 外部块上下文类型名应为 17 个");
        for 名 in 规范十七 {
            assert!(是外部块类型名(名), "外部块上下文类型名【{}】缺失", 名);
        }
    }

    /// FFI 精确码不得重复（不同名可同码仅限历史别名，故按「名→码」唯一性校验）。
    #[test]
    fn FFI标量类型表无重名() {
        let mut 已见 = HashSet::new();
        for (名, _, _) in FFI标量类型表 {
            assert!(已见.insert(*名), "FFI 标量类型表出现重名【{}】", 名);
        }
    }
}
