    /// 扫描文档注释内容：当前位置已在 `//**` 之后，扫描到 `**/` 或连续的 `//**` 文档注释块结束，
    /// 按行清洗后合并返回文本（支持规范 §3.1 的多行文档注释：每行 `//**`，无需 `**/` 收尾）。
    fn 扫描文档注释内容(&mut self) -> String {
        let mut 内容 = String::new();
        let mut 当前行 = String::new();
        while self.当前字符.is_some() {
            let ch = self.当前字符.unwrap();
            if ch == '\r' { self.消耗(); continue; }
            if ch == '\n' {
                内容.push_str(&self.清洗文档行(&当前行));
                内容.push('\n');
                当前行.clear();
                self.消耗();
                // 文档注释跨行时必须同步行号：否则其后所有词条的行号都会比真实源码少
                // （少的行数 = 文档注释占用的行数），导致诊断指向错误的行。
                self.行号 += 1;
                self.列号 = 1;
                // 检查下一行是否仍以 //** 开头（连续的文档注释块，合并为一处）
                while let Some(c) = self.当前字符 {
                    if c == ' ' || c == '\t' { self.消耗(); } else { break; }
                }
                if self.当前字符 == Some('/') && self.查看下一个() == Some('/') && self.查看后续(2) == Some('*') {
                    self.消耗(); self.消耗(); self.消耗(); self.消耗(); // 消耗续行的 //**
                    continue;
                }
                // 下一行不以 //** 开头：多行文档注释块结束（规范 §3.1：每行 //** 无需 **/ 收尾，
                // 遇到非 //** 行即终止）。终止扫描，当前位置停在非 //** 行首，由主循环继续词法分析。
                break;
            }
            if ch == '*' && self.查看下一个() == Some('*') && self.查看后续(2) == Some('/') {
                self.消耗(); self.消耗(); self.消耗(); // 消耗 **/
                内容.push_str(&self.清洗文档行(&当前行));
                break;
            }
            当前行.push(ch);
            self.消耗();
        }
        内容
    }
