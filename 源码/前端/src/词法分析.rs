#[derive(Debug, Clone, PartialEq)]
pub enum 词条类型 {
    整数(i64), 小数(f64), 文本字面量(String), 真, 假, 空值,
    /// ★2026-10-12（规范 §2.4.1 整数范围下界 = -9223372036854775808）：**待定负整数**词条。
    ///
    /// 数字串恰为 `2^63`（= i64::MAX + 1 = 9223372036854775808）时产出本词条 —— 它**本身不是**
    /// 合法整数常量，**只有紧邻一元 `-` 作其操作数**时才折叠为 `i64::MIN`（对齐 Java JLS 3.10.1
    /// 「最小负字面量特例」；Rust/Go 的字面量推断亦等价支持）。其它任何位置出现 ⇒ 语法层报
    /// 「整数常量超出 64 位有符号整数范围」。
    ///
    /// **为何在词法保留、在语法收口**：词法器是**无状态**的（不向前/向后看字符），
    /// 若要在词法层吞掉负号就变成上下文相关词法 ⇒ 违反项目既定原则（同「不加引号的远程 URL」被否的理由）。
    /// 故：词法只负责「把 2^63 识别出来并打上待定标记」，语义收口放在语法层一元 `-` 分支。
    待定负整数(u64),
    标识符(String),
    /// §2.2.3 类型名类关键字：整数 / 小数 / 文本 / 逻辑
    /// 词法分析阶段即识别为关键字词条 → 任何位置（含结构体成员级）都不可用作标识符。
    /// 注：`空值` 已有独立词条；`数组`/`映射` 是内建类型构造器（规范未列为关键字），仍为标识符。
    类型关键字(String),
    外部标识符(String), // 外部/导出块内的 C 符号名（如 sqlite3、open、math_add），无引号，含 ASCII 字母
    如果, 否则如果, 否则, 结束, 循环, 遍历, 跳出, 继续, 返回,
    结构体, 枚举, 任意, 接口, 适配,
    常量, 函数, 私有, 导入, 聚合导入, 展开,
    // 🔒 保留字：公开 / 变量
    //   规则① 命名禁止：禁止用户用作标识符名（词法层 扫描标识符或关键字 优先整词查表命中，永不生成 标识符 token）
    //   规则② 语法禁止：语法层任何位置不消费这两个 token，出现即报清晰错误（见 语句语法分析.rs / 语法分析器.rs / 类型语法分析.rs）
    //   二者已从语言语法中移除其声明/修饰语义，仅作保留字存在。
    //   ✅ 重新启用：词法层已就绪（token 已生成），将来若启用语法功能，
    //      仅在语法层对应 match 加回 `Some(词条类型::变量)=>` / `Some(词条类型::公开)=>` 分支即可，无需改词法层。
    变量, 公开,
    自身, 捕获, 异常, 始终, 抛出, 传值, 传引用,
    /// ★§2.4.7 关键字「本模块」：模块级变量/常量的**唯一**访问前缀（`本模块.变量名`）。
    /// 规范：函数/方法/结构体内部访问模块级**变量、常量**必须写 `本模块.X`，裸名只表示局部
    /// （裸名访问模块级变量/常量 = 编译错误）；模块级函数/结构体/枚举/接口仍可用裸名。
    /// 实现同 `自身`：词法 token 化 → 语法层转标识符 `"本模块"` → 语义层把 `本模块.X`
    /// 归一为「当前模块顶层符号 X」（降级层零改动：按名字命中原有全局变量/函数路径）。
    本模块,
    外部, 导出, 别名,

    且, 或, 非, 属于, 不属于,
    加, 减, 乘, 除, 整除, 取余, 幂,
    大于, 小于, 等于等于, 不等于, 大于等于, 小于等于, 实例相等, 实例不等,
    赋值, 加赋值, 减赋值, 乘赋值, 除赋值, 整除赋值, 取余赋值, 幂赋值,
    位与赋值, 位或赋值, 异或赋值, 左移赋值, 右移赋值,
    位与, 位或, 位非, 异或, 左移, 右移,
    左括号, 右括号, 左方括号, 右方括号, 左大括号, 右大括号, 逗号, 分号, 冒号, 点,
    换行, 文件结束,
    文档注释内容(String), // 文档注释 //** ... **/ 的内容（按行清洗后的文本）
}

