/// 派生：全部「真关键字/保留字」名称集合（§2.2.3）。
/// 供语法层判定「该名字不可作标识符」（取代 语句语法分析.rs 手写关键字数组，防多源漂移）。
/// 排除伪关键字（词法层即 标识符 token，如 整数/小数/文本/逻辑/函数指针）——
/// 它们在受限语境外可自由使用，不属于「任何位置禁用」。
pub fn 关键字名集合() -> &'static std::collections::HashSet<&'static str> {
    static 缓存: std::sync::OnceLock<std::collections::HashSet<&'static str>> = std::sync::OnceLock::new();
    缓存.get_or_init(|| {
        关键字映射表()
            .into_iter()
            .filter(|(_, 词条)| !matches!(词条, 词条类型::标识符(_)))
            .map(|(名, _)| 名)
            .collect()
    })
}

