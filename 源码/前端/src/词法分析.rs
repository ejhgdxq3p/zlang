    /// 是否为「词法保留类」词条（关键字 + 保留关键字 + 类型关键字）。
    /// 这类词条在任何位置（含结构体成员级）都不可用作标识符 —— 规范 §2.2.3:579-581。
    /// 供语法层在「名字位置」判定并给出明确诊断。
