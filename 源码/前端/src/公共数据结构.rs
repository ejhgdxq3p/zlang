// 智语言简洁格式化器 — 无源码上下文（供 --简洁 使用）
//
//   第3行1列 | 错误: 语法错误: 【如果】关键字后缺失判断条件
//   帮助: 如果语句必须以条件表达式开头，后跟冒号。
// ============================================================

/// 智语言简洁格式化器 — 无源码上下文，仅输出两行简版格式。
/// 用于 `--简洁` 命令行选项或需要紧凑输出的场景。
pub struct 智语言简洁格式化器 {
    pub 启用颜色: bool,
}

impl 智语言简洁格式化器 {
    pub fn 新建() -> Self {
        智语言简洁格式化器 { 启用颜色: false }
    }

    pub fn 新建_颜色() -> Self {
        智语言简洁格式化器 { 启用颜色: true }
    }
}

impl 格式化器 for 智语言简洁格式化器 {
    fn 格式化(&self, 诊断: &诊断信息, _源映射: &源文件映射) -> String {
        let (红, 黄, 绿, 重置) = if self.启用颜色 {
            (颜色_红, 颜色_黄, 颜色_绿, 颜色_重置)
        } else {
            ("", "", "", "")
        };

        let 级别文本 = 诊断.级别文本();
        let 类型文本 = 诊断.类型文本();
        let 级别色 = match 诊断.级别 { 诊断级别::错误 => 红, 诊断级别::警告 => 黄 };

        let mut 结果 = format!("第{}行{}列 | {}{}{}: {}: 【{}】{}",
            诊断.位置.行号, 诊断.位置.列号,
            级别色, 级别文本, 重置, 类型文本, 诊断.描述, 重置);

        // 也见于简版
        for 关联位置 in &诊断.也见于 {
            结果.push_str(&format!("\n也见于: {}", 关联位置.位置));
        }

        // 是否是指简版
        if let Some(建议) = &诊断.是否是指 {
            结果.push_str(&format!("\n是否是指: 【{}】（在{}）?", 建议.候选, 建议.位置));
        }

        if let Some(帮助) = &诊断.帮助信息 {
            结果.push_str(&format!("\n{}帮助: {}{}", 绿, 帮助, 重置));
        }
        if 诊断.是否内部错误() {
            结果.push_str(&format!("\n{}请向官方反馈此问题，以便我们改进智语言。{}", 红, 重置));
        }

        结果
    }
}

// ============================================================
// JSON 格式化器 — 供编辑器/LSP使用
// ============================================================

pub struct JSON格式化器;

impl 格式化器 for JSON格式化器 {
    fn 格式化(&self, 诊断: &诊断信息, 源映射: &源文件映射) -> String {
        let 文件 = 转义_json(&诊断.位置.文件路径);
        let 描述 = 转义_json(&诊断.描述);
        let 级别 = 诊断.级别文本();
        let 类型 = 诊断.类型文本();

        // 源码行
        let 源码行字段 = 源映射.获取行(&诊断.位置.文件路径, 诊断.位置.行号)
            .map(|s| format!(",\"源码行\":\"{}\"", 转义_json(s)))
            .unwrap_or_default();

        // 主位置标记说明
        let 标记说明字段 = match &诊断.标记说明 {
            Some(m) => format!(",\"标记说明\":\"{}\"", 转义_json(m)),
            None => String::new(),
        };

        // 也见于（最多3个）
        let 也见于_json: Vec<String> = 诊断.也见于.iter().take(3).map(|p| {
            let 标记 = match &p.标记说明 {
                Some(m) => format!(",\"标记说明\":\"{}\"", 转义_json(m)),
                None => String::new(),
            };
            format!("{{\"文件\":\"{}\",\"行\":{},\"列\":{}{}}}",
                转义_json(&p.位置.文件路径), p.位置.行号, p.位置.列号, 标记)
        }).collect();
        let 也见于 = if 也见于_json.is_empty() {
            String::from("\"也见于\":null")
        } else {
            format!("\"也见于\":[{}]", 也见于_json.join(","))
        };

        // 是否是指
        let 是否是指 = match &诊断.是否是指 {
            Some(建议) => {
                let 标记 = match &建议.标记说明 {
                    Some(m) => format!(",\"标记说明\":\"{}\"", 转义_json(m)),
                    None => String::new(),
                };
                format!(
                    "\"是否是指\":{{\"候选\":\"{}\",\"文件\":\"{}\",\"行\":{},\"列\":{}{}}}",
                    转义_json(&建议.候选), 转义_json(&建议.位置.文件路径),
                    建议.位置.行号, 建议.位置.列号, 标记)
            }
            None => String::from("\"是否是指\":null"),
        };

        // 帮助
        let 帮助字段 = match &诊断.帮助信息 {
            Some(h) => format!("\"帮助\":\"{}\"", 转义_json(h)),
            None => String::from("\"帮助\":null"),
        };

        format!(
            "{{\"级别\":\"{级别}\",\"类型\":\"{类型}\",\"描述\":\"{描述}\",\
             \"位置\":{{\"文件\":\"{文件}\",\"行\":{行},\"列\":{列}}}{标记说明},\
             {帮助},{内部错误},{也见于},{是否是指}{源码行}}}",
            级别=级别, 类型=类型, 描述=描述,
            文件=文件, 行=诊断.位置.行号, 列=诊断.位置.列号,
            标记说明=标记说明字段,
            帮助=帮助字段, 内部错误=format!("\"内部错误\":{}", 诊断.是否内部错误()),
            也见于=也见于, 是否是指=是否是指, 源码行=源码行字段)
    }
}

/// JSON 字符串转义
fn 转义_json(s: &str) -> String {
    s.replace('\\', "\\\\")
     .replace('"', "\\\"")
     .replace('\n', "\\n")
     .replace('\r', "\\r")
     .replace('\t', "\\t")
}

// ============================================================
// 测试格式化器 — 简洁输出（仅基础信息，用于测试断定）
// ============================================================

pub struct 测试格式化器;

impl 格式化器 for 测试格式化器 {
    fn 格式化(&self, 诊断: &诊断信息, _源映射: &源文件映射) -> String {
        format!(
            "第{}行{}列 | {}: {}: 【{}】{}",
            诊断.位置.行号, 诊断.位置.列号,
            诊断.级别文本(), 诊断.类型文本(), 诊断.描述,
            if let Some(帮助) = &诊断.帮助信息 {
                format!("\n帮助: {}", 帮助)
            } else {
                String::new()
            }
        )
    }
}

