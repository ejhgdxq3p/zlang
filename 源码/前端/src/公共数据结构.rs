#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 源码位置 {
    pub 文件路径: String,
    pub 行号: usize,
    pub 列号: usize,
}

impl 源码位置 {
    pub fn 新(文件路径: String, 行号: usize, 列号: usize) -> Self {
        源码位置 { 文件路径, 行号, 列号 }
    }

    /// 空位置（无源码位置信息时使用，异常位置将回退为空字符串）
    pub fn 默认() -> Self {
        源码位置 { 文件路径: String::new(), 行号: 0, 列号: 0 }
    }
}

impl fmt::Display for 源码位置 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "第{}行{}列", self.行号, self.列号)
    }
}

