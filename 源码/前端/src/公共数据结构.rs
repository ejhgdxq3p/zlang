/// 计算两个字符串之间的 Levenshtein 编辑距离。
/// 距离越小表示两个字符串越相似。
pub fn 编辑距离(甲: &str, 乙: &str) -> usize {
    let 甲c: Vec<char> = 甲.chars().collect();
    let 乙c: Vec<char> = 乙.chars().collect();
    let 甲长度 = 甲c.len();
    let 乙长度 = 乙c.len();
    let mut 矩阵 = vec![vec![0usize; 乙长度 + 1]; 甲长度 + 1];
    for i in 0..=甲长度 { 矩阵[i][0] = i; }
    for j in 0..=乙长度 { 矩阵[0][j] = j; }
    for i in 0..甲长度 {
        for j in 0..乙长度 {
            let 代价 = if 甲c[i] == 乙c[j] { 0 } else { 1 };
            矩阵[i + 1][j + 1] = std::cmp::min(
                std::cmp::min(矩阵[i][j + 1] + 1, 矩阵[i + 1][j] + 1),
                矩阵[i][j] + 代价,
            );
        }
    }
    矩阵[甲长度][乙长度]
}

/// 在候选列表中查找与目标最相似的标识符（编辑距离 ≤ 2）。
/// 仅搜索中文标识符，不搜索英文标识符和关键字。
pub fn 查找最相似标识符(名称: &str, 候选: &[(String, 源码位置)]) -> Option<(String, 源码位置)> {
    候选.iter()
        .map(|(n, p)| (n, p, 编辑距离(名称, n)))
        .filter(|(_, _, d)| *d <= 2)
        .min_by_key(|(_, _, d)| *d)
        .map(|(n, p, _)| (n.clone(), p.clone()))
}

