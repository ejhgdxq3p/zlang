/// 红色 — 错误码和错误级别
pub const 颜色_红: &str = "\x1b[31m";
/// 黄色 — 警告级别和波浪线标记
pub const 颜色_黄: &str = "\x1b[33m";
/// 青色 — 行号和对齐线
pub const 颜色_青: &str = "\x1b[36m";
/// 绿色 — 帮助信息
pub const 颜色_绿: &str = "\x1b[32m";
/// 紫色 — 也见于关联位置
pub const 颜色_紫: &str = "\x1b[35m";
/// 灰色 — 次要信息
pub const 颜色_灰: &str = "\x1b[2m";
/// 重置所有颜色属性
pub const 颜色_重置: &str = "\x1b[0m";

/// 带颜色参数的四元组 (红, 黄, 青, 绿, 紫, 灰, 重置)
pub fn 取颜色元组(启用: bool) -> (&'static str, &'static str, &'static str, &'static str, &'static str, &'static str, &'static str) {
    if 启用 {
        (颜色_红, 颜色_黄, 颜色_青, 颜色_绿, 颜色_紫, 颜色_灰, 颜色_重置)
    } else {
        ("", "", "", "", "", "", "")
    }
}

