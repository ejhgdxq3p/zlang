// ============================================================
// 诊断排序键
// ============================================================

/// 诊断排序键：错误优先于警告，同行号按列号排序
pub fn 诊断排序键(诊断: &诊断信息) -> (u8, usize, usize) {
    let 级别序 = match 诊断.级别 {
        诊断级别::错误 => 0,
        诊断级别::警告 => 1,
    };
    (级别序, 诊断.位置.行号, 诊断.位置.列号)
}

// ============================================================
// 行级别截断
// ============================================================

/// 对诊断列表进行行级别截断：同文件同行的错误/警告各最多保留 N 条
pub fn 应用行截断(诊断列表: &mut Vec<诊断信息>, 每行最大数: usize) -> usize {
    let mut 截断计数 = 0;
    let mut 行计数: HashMap<String, usize> = HashMap::new();

    let 原列表 = std::mem::take(诊断列表);
    for 诊断 in &原列表 {
        let 键 = format!("{}:{}:{}", 诊断.位置.文件路径, 诊断.位置.行号, 诊断.级别文本());
        *行计数.entry(键).or_insert(0) += 1;
    }

    let mut 当前行计数: HashMap<String, usize> = HashMap::new();
    for 诊断 in 原列表 {
        let 键 = format!("{}:{}:{}", 诊断.位置.文件路径, 诊断.位置.行号, 诊断.级别文本());
        let 当前 = 当前行计数.entry(键).or_insert(0);
        *当前 += 1;
        if *当前 <= 每行最大数 {
            诊断列表.push(诊断);
        } else {
            截断计数 += 1;
        }
    }

    截断计数
}
