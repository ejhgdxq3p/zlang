// 智语言中文格式化器 — 完整中文调试输出（默认格式）
//
//   第3行1列 | 错误: 语法错误: 【如果】关键字后缺失判断条件
//   3 │ 如果
//     │ ～～ 此处应为判断条件
//     │
//   也见于: 第1行15列
//   1 │ 变量 年龄: 整数 = 25
//     │  ～～ 声明的标识符
//     │
//   帮助: 如果语句必须以条件表达式开头，后跟冒号。
// ============================================================

/// 智语言中文终端格式化器 — 默认输出格式，包含：
/// - 源码行显示 + 波浪线位置标记
/// - 也见于关联位置链
/// - ANSI 颜色（启用时）
pub struct 智语言格式化器 {
    pub 启用颜色: bool,
}

impl 智语言格式化器 {
    pub fn 新建() -> Self {
        智语言格式化器 { 启用颜色: false }
    }

    pub fn 新建_颜色() -> Self {
        智语言格式化器 { 启用颜色: true }
    }
}

impl 格式化器 for 智语言格式化器 {
    fn 格式化(&self, 诊断: &诊断信息, 源映射: &源文件映射) -> String {
        let (红, 黄, 青, 绿, 紫, _灰, 重置) = 取颜色元组(self.启用颜色);

        let 级别文本 = 诊断.级别文本();
        let 类型文本 = 诊断.类型文本();
        let 行号 = 诊断.位置.行号;
        let 列号 = 诊断.位置.列号;

        // 第一行：第N行N列 | 级别: 类型: 【描述】
        let 级别色 = match 诊断.级别 { 诊断级别::错误 => 红, 诊断级别::警告 => 黄 };
        let mut 结果 = format!("第{}行{}列 | {}{}{}: {}: 【{}】",
            行号, 列号, 级别色, 级别文本, 重置, 类型文本, 诊断.描述);

        // 第二段：源码行 + 位置标记
        let 源码行 = 源映射.获取行(&诊断.位置.文件路径, 行号);
        if let Some(行内容) = 源码行 {
            let 行号标签 = format!("{:>4}", 行号);
            结果.push_str(&format!("\n{}{} │{}{}", 青, 行号标签, 重置, 行内容));
            // 波浪线标记：在源码行下方标记问题列
            let 行chars: Vec<char> = 行内容.chars().collect();
            let 行char长度 = 行chars.len();
            if 列号 <= 行char长度 && 列号 > 0 {
                let 缩进列 = 列号.saturating_sub(1);
                let 问题长度 = 行chars[缩进列..].iter()
                    .take_while(|&&c| !c.is_whitespace() && c != ',' && c != ';' && c != ')' && c != ']').count();
                let 波浪线长度 = std::cmp::max(问题长度, 1).min(行char长度 - 列号 + 1);
                let 波浪线 = "～".repeat(波浪线长度);
                let 说明 = 诊断.标记说明.as_deref().unwrap_or("");
                if !说明.is_empty() {
                    结果.push_str(&format!("\n{}{}{}{} {}{}", 黄, "  │ ", " ".repeat(缩进列), 波浪线, 说明, 重置));
                } else {
                    结果.push_str(&format!("\n{}{}{}{}{}", 黄, "  │ ", " ".repeat(缩进列), 波浪线, 重置));
                }
            }
            结果.push_str(&format!("\n{}  │{}", 青, 重置));
        }

        // 第三段：也见于关联位置链（最多显示 3 个）
        let 也见于总数 = 诊断.也见于.len();
        let 显示数 = 也见于总数.min(3);
        for i in 0..显示数 {
            let 也见于项 = &诊断.也见于[i];
            结果.push_str(&format!("\n{}也见于: {}{}", 紫, &也见于项.位置, 重置));
            // 前导空标记行
            结果.push_str(&format!("\n{}  │{}", 青, 重置));
            if let Some(行内容) = 源映射.获取行(&也见于项.位置.文件路径, 也见于项.位置.行号) {
                let 行号标签 = format!("{:>4}", 也见于项.位置.行号);
                结果.push_str(&format!("\n{}{} │{}{}", 青, 行号标签, 重置, 行内容));
                // 波浪线标记行
                let 行chars: Vec<char> = 行内容.chars().collect();
                let 行char长度 = 行chars.len();
                let 列号 = 也见于项.位置.列号;
                if 列号 <= 行char长度 && 列号 > 0 {
                    let 缩进列 = 列号.saturating_sub(1);
                    let 问题长度 = 行chars[缩进列..].iter()
                        .take_while(|&&c| !c.is_whitespace() && c != ',' && c != ';' && c != ')' && c != ']').count();
                    let 波浪线长度 = std::cmp::max(问题长度, 1).min(行char长度 - 列号 + 1);
                    let 波浪线 = "～".repeat(波浪线长度);
                    let 说明 = 也见于项.标记说明.as_deref().unwrap_or("");
                    if !说明.is_empty() {
                        结果.push_str(&format!("\n{}  │ {}{} {}{}", 黄, " ".repeat(缩进列), 波浪线, 说明, 重置));
                    } else {
                        结果.push_str(&format!("\n{}  │ {}{}{}", 黄, " ".repeat(缩进列), 波浪线, 重置));
                    }
                }
            }
            结果.push_str(&format!("\n{}  │{}", 青, 重置));
        }
        if 也见于总数 > 3 {
            结果.push_str(&format!("\n{}也见于：以及其他 {} 处{}", 紫, 也见于总数 - 3, 重置));
        }

        // 是否是指拼写建议
        if let Some(建议) = &诊断.是否是指 {
            结果.push_str(&format!("\n{}是否是指: 【{}】（在{}）?{}", 紫, 建议.候选, 建议.位置, 重置));
            // 前导空标记行
            结果.push_str(&format!("\n{}  │{}", 青, 重置));
            if let Some(行内容) = 源映射.获取行(&建议.位置.文件路径, 建议.位置.行号) {
                let 行号标签 = format!("{:>4}", 建议.位置.行号);
                结果.push_str(&format!("\n{}{} │{}{}", 青, 行号标签, 重置, 行内容));
                // 波浪线标记行
                let 行chars: Vec<char> = 行内容.chars().collect();
                let 行char长度 = 行chars.len();
                let 列号 = 建议.位置.列号;
                if 列号 <= 行char长度 && 列号 > 0 {
                    let 缩进列 = 列号.saturating_sub(1);
                    let 问题长度 = 行chars[缩进列..].iter()
                        .take_while(|&&c| !c.is_whitespace() && c != ',' && c != ';' && c != ')' && c != ']').count();
                    let 波浪线长度 = std::cmp::max(问题长度, 1).min(行char长度 - 列号 + 1);
                    let 波浪线 = "～".repeat(波浪线长度);
                    let 说明 = 建议.标记说明.as_deref().unwrap_or("");
                    if !说明.is_empty() {
                        结果.push_str(&format!("\n{}  │ {}{} {}{}", 黄, " ".repeat(缩进列), 波浪线, 说明, 重置));
                    } else {
                        结果.push_str(&format!("\n{}  │ {}{}{}", 黄, " ".repeat(缩进列), 波浪线, 重置));
                    }
                }
            }
            结果.push_str(&format!("\n{}  │{}", 青, 重置));
        }

        // 帮助信息
        if let Some(帮助) = &诊断.帮助信息 {
            结果.push_str(&format!("\n{}帮助: {}{}", 绿, 帮助, 重置));
        }

        // 内部错误附加反馈提示
        if 诊断.是否内部错误() {
            结果.push_str(&format!("\n{}请向官方反馈此问题，以便我们改进智语言。{}", 红, 重置));
        }

        结果
    }
}

