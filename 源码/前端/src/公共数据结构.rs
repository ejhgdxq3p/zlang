#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 诊断级别 { 错误, 警告 }

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 错误类型 {
    语法错误, 语义错误, 类型错误, 参数错误,
    运行时错误, 资源错误, 网络错误, 并发错误,
    内部错误, 代码建议,
}


#[derive(Debug, Clone)]
pub struct 诊断信息 {
    pub 级别: 诊断级别,
    pub 错误类型: 错误类型,
    pub 描述: String,
    pub 位置: 源码位置,
    pub 也见于: Vec<也见于项>,
    pub 是否是指: Option<拼写建议项>,
    pub 帮助信息: Option<String>,
    pub 标记说明: Option<String>,
}

impl 诊断信息 {
    pub fn 新(级别: 诊断级别, 错误类型: 错误类型, 描述: String, 位置: 源码位置, 帮助信息: Option<String>) -> Self {
        诊断信息 { 级别, 错误类型, 描述, 位置, 也见于: Vec::new(), 是否是指: None, 帮助信息, 标记说明: None }
    }

    /// 设置主位置波浪线说明文字
    pub fn 设置标记说明(mut self, 说明: &str) -> Self {
        self.标记说明 = Some(说明.to_string());
        self
    }

    /// 设置拼写建议（是否是指）
    pub fn 设置是否是指(mut self, 候选: &str, 位置: 源码位置, 标记说明: Option<&str>) -> Self {
        self.是否是指 = Some(拼写建议项 {
            候选: 候选.to_string(),
            位置,
            标记说明: 标记说明.map(|s| s.to_string()),
        });
        self
    }

    /// 添加关联位置（也见于）
    pub fn 添加也见于(mut self, 位置: 源码位置, 标记说明: Option<&str>) -> Self {
        self.也见于.push(也见于项 {
            位置,
            标记说明: 标记说明.map(|s| s.to_string()),
        });
        self
    }

    pub fn 是否内部错误(&self) -> bool {
        matches!(self.错误类型, 错误类型::内部错误)
    }

    /// 获取行号（便捷方法）
    pub fn 获取行号(&self) -> usize { self.位置.行号 }

    /// 获取列号（便捷方法）
    pub fn 获取列号(&self) -> usize { self.位置.列号 }

    /// 获取所属文件路径
    pub fn 获取文件路径(&self) -> &str { &self.位置.文件路径 }

    /// 获取严重程度字符串
    pub fn 级别文本(&self) -> &str {
        match self.级别 { 诊断级别::错误 => "错误", 诊断级别::警告 => "警告" }
    }

    /// 获取错误类型字符串
    pub fn 类型文本(&self) -> &str {
        match self.错误类型 {
            错误类型::语法错误 => "语法错误",
            错误类型::语义错误 => "语义错误",
            错误类型::类型错误 => "类型错误",
            错误类型::参数错误 => "参数错误",
            错误类型::运行时错误 => "运行时错误",
            错误类型::资源错误 => "资源错误",
            错误类型::网络错误 => "网络错误",
            错误类型::并发错误 => "并发错误",
            错误类型::内部错误 => "内部错误",
            错误类型::代码建议 => "代码建议",
        }
    }


}

