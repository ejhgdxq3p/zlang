/// 格式化器 trait — 定义诊断输出的接口。
pub trait 格式化器 {
    /// 格式化单个诊断信息为字符串
    fn 格式化(&self, 诊断: &诊断信息, 源映射: &源文件映射) -> String;

    /// 格式化一组诊断信息
    fn 格式化全部(&self, 诊断列表: &[诊断信息], 源映射: &源文件映射) -> Vec<String> {
        诊断列表.iter().map(|d| self.格式化(d, 源映射)).collect()
    }
}

