// 源文件映射 — 管理源代码行缓存（类似 Rust 的 SourceMap）
// ============================================================

/// 源文件映射，将文件路径映射到其源代码行缓存。
#[derive(Debug, Clone)]
pub struct 源文件映射 {
    行缓存: HashMap<String, Vec<String>>,
}

impl 源文件映射 {
    pub fn 新建() -> Self {
        源文件映射 { 行缓存: HashMap::new() }
    }

    /// 注册源文件并缓存其行内容
    pub fn 注册文件(&mut self, 文件路径: &str, 源码: &str) {
        let 行列表: Vec<String> = 源码.lines().map(|l| l.to_string()).collect();
        self.行缓存.insert(文件路径.to_string(), 行列表);
    }

    /// 获取指定文件的行数
    pub fn 行数(&self, 文件路径: &str) -> usize {
        self.行缓存.get(文件路径).map(|行| 行.len()).unwrap_or(0)
    }

    /// 获取指定行的内容（1-based）
    pub fn 获取行(&self, 文件路径: &str, 行号: usize) -> Option<&str> {
        self.行缓存
            .get(文件路径)
            .and_then(|行| {
                if 行号 >= 1 && 行号 <= 行.len() {
                    Some(行[行号 - 1].as_str())
                } else {
                    None
                }
            })
    }

    /// 获取指定位置附近的代码上下文
    pub fn 获取上下文(&self, 位置: &源码位置, 上下文行数: usize) -> Vec<(usize, String, bool)> {
        let 文件路径 = &位置.文件路径;
        let 行号 = 位置.行号;
        let 行列表 = match self.行缓存.get(文件路径) {
            Some(行) => 行,
            None => return Vec::new(),
        };

        let 起始行 = if 行号 > 上下文行数 { 行号 - 上下文行数 } else { 1 };
        let 结束行 = std::cmp::min(行号 + 上下文行数, 行列表.len());

        let mut 结果 = Vec::new();
        for i in 起始行..=结束行 {
            if i >= 1 && i <= 行列表.len() {
                let 是目标行 = i == 行号;
                结果.push((i, 行列表[i - 1].clone(), 是目标行));
            }
        }
        结果
    }

    /// 清除所有缓存
    pub fn 清除(&mut self) {
        self.行缓存.clear();
    }
}

