pub fn 转换函数(f: &高层表示函数, 常量池: &mut Vec<常量值>, 结构体布局: &HashMap<String, Vec<(String, 底层表示类型)>>, 函数索引映射: &mut HashMap<String, usize>, 结构体类型索引: &HashMap<String, usize>, 全局变量名列表: &[String], 函数签名详情: &HashMap<String, (usize, Vec<Option<高层表示表达式>>, Vec<参数传递方式>, Vec<类型信息>)>, 匿名函数收集: &mut Vec<(usize, 底层表示函数)>, 闭包捕获: Option<&Vec<(String, 底层表示类型)>>) -> 底层表示函数 {
    let mut 局部表 = vec![底层表示类型::整数64];
    let mut 变量映射 = HashMap::new();
    let mut 形参局部索引 = Vec::new();
    if let Some(捕获列表) = 闭包捕获 {
        // 闭包模式：捕获变量前置(索引1..)，闭包自身形参紧随其后；全局变量不进局部表
        // 捕获变量与闭包自身形参都必须登记进 形参局部索引，
        // 否则编译模式据此生成的 cranelift 函数签名会缺少捕获参数，导致派发调用实参数不匹配。
        for (名, 型) in 捕获列表 {
            let 索引 = 局部表.len();
            变量映射.insert(名.clone(), 索引);
            局部表.push(型.clone());
            形参局部索引.push(索引);
        }
        for (_i, (名, 型)) in f.形参列表.iter().enumerate() { let 索引 = 局部表.len(); 变量映射.insert(名.clone(), 索引); 局部表.push(转换类型(型)); 形参局部索引.push(索引); }
    } else {
        // 普通模式：全局变量不进局部变量表，统一走 VM 独立 全局变量表（降级层用 全局变量(gi+1) 操作数）。
        // 局部表仅保留索引0预留位，其后紧跟形参，使形参0对齐 VM 调用约定（参数从槽1起），
        // 否则每个全局占位槽位会把形参索引整体后移，导致调用传参错位、形参读为空值。
        for (_i, (名, 型)) in f.形参列表.iter().enumerate() { let 索引 = 局部表.len(); 变量映射.insert(名.clone(), 索引); 局部表.push(转换类型(型)); 形参局部索引.push(索引); }
    }
    当前函数引用局部.with(|s| s.borrow_mut().clear());
    当前函数引用名映射.with(|m| m.borrow_mut().clear());
    // 🆕 引用计数闭环：重置「待释放栈槽」与「已移出名称」登记（per-function，避免跨函数污染）。
    当前函数待释放局部.with(|s| s.borrow_mut().clear());
    当前函数已移出名称.with(|s| s.borrow_mut().clear());
    // 🆕 2026-10-13（**#13 收窄版**）：记录本函数**声明返回类型**（供返回侧"仅文本去重"判定）
    当前函数返回类型.with(|s| *s.borrow_mut() = f.返回类型.clone());
    当前函数映射读局部.with(|s| s.borrow_mut().clear());
    // 🔁 2026-09-24（**`返回 <值传递形参>` 过度释放修复**）：登记本函数的**值传递形参名**
    //   （供 `语句转换.rs::返回语句` 在裸名返回处**为调用方 +1**；依据与取证实测见该集合的注释 ✓）
    //   ⚠ 与 `形参传递方式` **平行**取；缺项按 `传值` 处理（保守：宁可多计一份，绝不漏计 ⇒ 悬垂）✓
    当前函数值传递形参名.with(|s| {
        let mut s = s.borrow_mut();
        s.clear();
        for (i, (名, _)) in f.形参列表.iter().enumerate() {
            let 方式 = f.形参传递方式.get(i).cloned().unwrap_or(参数传递方式::传值);
            if 方式 == 参数传递方式::传值 {
                s.insert(名.clone());
            }
        }
    });
    // 🆕 阶段 6b（2026-09-23）：重置**槽元数据表**（per-function）+ 登记形参/捕获槽。
    //   定位 = **只读记录**（不参与任何判定）⇒ 对产品行为零影响 ✓ 转储开关 = `智语言_转储槽元数据`
    当前函数槽元数据.with(|s| s.borrow_mut().clear());
    for (i, 槽) in 形参局部索引.iter().enumerate() {
        if let Some((名, 型)) = f.形参列表.get(i) {
            登记槽元数据(名, *槽, 槽声明层级::形参或捕获, format!("{:?}", 转换类型(型)), false);
        }
    }
    // 🆕 引用计数启用闸门：每函数重置；并以「匿名函数收集」增量判定本函数是否含闭包（捕获会共享句柄）。
    当前函数含嵌套控制流.with(|f| *f.borrow_mut() = false);
    当前函数含接口用法.with(|f| *f.borrow_mut() = false);

    // 🔁 2026-09-22③（**闸门②细化：签名含接口型不再整函数禁用释放**）：
    //   原闸门（形参或返回类型含接口型 ⇒ 本函数整体不发射释放）的历史依据是
    //   "释放源局部会误回收仍被接口/接口数组元素持有的实例"（实测 `14接口功能全面验证` /
    //   `15值传递引用传递全面验证` 的"接口数组元素·原实例不受影响"因此失败）。
    //   该依据现已被**按槽排除**完整覆盖（见 `语句转换.rs` 登记处的 `含接口对象`）：
    //     · 接口**变量槽**、以及"内含接口标签的对象槽"（`数组<接口>` / 结构体含接口成员 / `任意<接口>`）
    //       一律**不登记** ⇒ 不参与释放 ⇒ 不存在"级联 −1 到共享实例"的路径 ✓；
    //     · **形参**从不登记 ⇒ 释放形参引用本就不可能 ✓；
    //     · 返回值走"裸变量 move 移出 / 投影为调用方计数一份" ⇒ 调用方句柄不因本帧释放而悬垂 ✓。
    //   ⇒ 收益：接口是常见用法，原闸门使**近乎整程序零释放**（`111` 存活 56/56）；细化后函数内
    //     纯值语义复合槽照常回收。（`当前函数含接口用法` 仍保留为可观测标志，但其置位点仅剩调试用途。）
    let 匿名函数收集基线 = 匿名函数收集.len();
    // ── 「始终」出口完备化：闭包降级保存并清空「始终状态」──
    // 闭包体内的 返回/跳出/继续 只属于闭包自身，绝不能穿越【外层函数】的始终链；
    // 同时避免闭包降级污染外层函数的退出槽。
    let 保留始终状态 = if 闭包捕获.is_some() {
        Some((
            当前函数退出槽.with(|s| s.borrow().clone()),
            始终层栈.with(|s| s.borrow().clone()),
        ))
    } else {
        None
    };
    始终层栈.with(|s| s.borrow_mut().clear());
    当前函数退出槽.with(|s| { *s.borrow_mut() = None; });
    for (i, 形参) in f.形参列表.iter().enumerate() {
        let 是引用 = f.形参传递方式.get(i) == Some(&参数传递方式::传引用);
        if 是引用 {
            if let Some(&idx) = 变量映射.get(&形参.0) {
                当前函数引用局部.with(|s| { s.borrow_mut().insert(idx); });
                当前函数引用名映射.with(|m| { m.borrow_mut().insert(形参.0.clone(), idx); });
            }
        }
    }
    let mut 块列表 = vec![];
    let mut 块编号 = 0;
    let mut 当前块 = 基本块 { 异常目标: crate::底层表示::模块结构::异常目标::无, 标识符: 块编号, 指令列表: vec![], 终止指令: 终止指令::返回(None) };
    块编号 += 1;
    // 「始终」出口完备化：预留函数级落点块标识（带值返回 / 裸返回的最终落点）。
    // 实体块在函数末尾按「是否真的产生过非局部退出」产出（避免不可达块）。
    let 统一返回块标识 = 块编号; 块编号 += 1;
    let 统一裸返回块标识 = 块编号; 块编号 += 1;
    当前函数退出槽.with(|s| {
        *s.borrow_mut() = Some(退出槽位 {
            返回暂存槽: usize::MAX,
            统一返回块: 统一返回块标识,
            统一裸返回块: 统一裸返回块标识,
            下一站点编号: 1,
            用过退出: false,
            闭包前层数: 0,
        });
    });
    for 语句 in &f.函数体 { 转换语句(语句, &mut 当前块, &mut 块列表, &mut 块编号, &mut 局部表, &mut 变量映射, 常量池, 结构体布局, 函数索引映射, 结构体类型索引, 函数签名详情, 全局变量名列表, 匿名函数收集, usize::MAX); }
    // ⚡双模式⚡ 原「函数末尾自动发射 清理 调用」已删除（2026-09-16：`清理` 生命周期方法整体移除）。
    if !matches!(当前块.终止指令, 终止指令::返回(_) | 终止指令::无条件跳转(_) | 终止指令::条件跳转{..} | 终止指令::切换{..} | 终止指令::抛出异常(_)) {
        当前块.终止指令 = 终止指令::返回(None);
    }
    // 「始终」出口完备化：产出函数级落点块 —— 非局部退出跑完整条始终链后在此执行真正的退出动作。
    // 仅当本函数真的产生过非局部退出时才产出，避免不可达块。
    let 末退出槽 = 当前函数退出槽.with(|s| s.borrow().clone());
    if let Some(槽) = 末退出槽 {
        if 槽.用过退出 {
            if 槽.返回暂存槽 != usize::MAX {
                块列表.push(基本块 { 异常目标: crate::底层表示::模块结构::异常目标::无, 标识符: 槽.统一返回块, 指令列表: vec![], 终止指令: 终止指令::返回(Some(操作数::局部变量(槽.返回暂存槽))) });
            }
            块列表.push(基本块 { 异常目标: crate::底层表示::模块结构::异常目标::无, 标识符: 槽.统一裸返回块, 指令列表: vec![], 终止指令: 终止指令::返回(None) });
        }
    }
    块列表.push(当前块);
    块列表.sort_by_key(|b| if b.标识符 == 0 { 0 } else { b.标识符 as usize });
    // 闭包函数：形参列表须把捕获变量前置，与 形参局部索引 / 编译模式 cranelift 签名保持一致；
    // 普通函数：仅自身形参。两者都决定「函数参数数量」，编译签名与解释器参数数量据此生成。
    let 形参列表: Vec<(String, 底层表示类型)> = if let Some(捕获列表) = 闭包捕获 {
        let mut 表 = Vec::with_capacity(捕获列表.len() + f.形参列表.len());
        for (名, 型) in 捕获列表 {
            表.push((名.clone(), 型.clone()));
        }
        for (名, 型) in &f.形参列表 {
            表.push((名.clone(), 转换类型(型)));
        }
        表
    } else {
        f.形参列表.iter().map(|(n, t)| (n.clone(), 转换类型(t))).collect()
    };
    // ⚡双模式⚡ 闭包/值返回修复：返回类型 未推断/推断错误 表示"运行时返回某值但静态类型未知"，
    // 必须按非空返回处理（强制 sret 指针）。否则编译模式函数声明无 sret，而 间接调用/调用 处理器
    // 对非空返回总是/应按 sret 传参，造成 参数数不匹配 + 返回值被丢弃
    // （如 乘积=甲*乙，甲/乙 未推断 → 算术运算结果类型=未推断 → 函数返回未推断）。
    let 返回类型 = match &f.返回类型 {
        Some(类型信息::未推断) | Some(类型信息::推断错误) => 底层表示类型::整数64, // 占位非void，仅触发 sret
        Some(t) => 转换类型(t),
        None => {
            // 🔧 方法返回类型推断：未标注返回类型的函数，从其 返回(Some(v)) 指令的操作数推断具体返回类型。
            // 解释模式会忽略声明的 void 直接返回栈顶值，但编译模式（Cranelift）按 void 声明会丢弃返回值，
            // 导致「方法返回类型推断」在编译模式下返回空值。此处统一在共享前端推断，双模式自动一致。
            let mut 推断 = 底层表示类型::空值;
            for 块 in &块列表 {
                if let 终止指令::返回(Some(值)) = &块.终止指令 {
                    let t = match 值 {
                        操作数::局部变量(i) => 局部表.get(*i).cloned().unwrap_or(底层表示类型::空值),
                        操作数::立即整数(_) => 底层表示类型::整数64,
                        操作数::立即小数(_) => 底层表示类型::小数64,
                        操作数::立即逻辑(_) => 底层表示类型::逻辑,
                        _ => 底层表示类型::空值,
                    };
                    match t {
                        底层表示类型::空值 => {}
                        _ => { 推断 = t; break; }
                    }
                }
            }
            推断
        }
    };
    // 🆕 引用计数闭环（−1 侧）：为每个「以 返回 终止」的基本块补发 `释放引用` 序列
    //    （追加在其指令列表末尾 = 终止指令之前）⇒ 覆盖**全部返回点**：显式 `返回` 语句、
    //    隐式函数末尾（合成 返回(None)）、fall-through 补发、以及**函数级落点块**
    //    （= 始终链跑完之后的真实出口，因此「始终」路径也在其后释放 ⇒ 不会先释放再被始终使用）。
    //    ⚠ 异常路径（抛出 / 传播 / 跨帧退帧）本批不发射 ⇒ 保守泄漏，绝不误回收（留待异常落点批次）。
    //    ⚠ 已 `返回 <名称>` 移出的槽由 发射释放引用 内部跳过（move 语义）。
    // ⛔ 【已停用 · 2026-09-17】引用计数 −1 发射仍**不 sound**：即使加上"单基本块 + 无接口 + 无闭包"
    //    三重闸门，`双模差分对账`（精准测试案例目录）仍出现 **1 条新增分歧**（差异 9 → 10）
    //    ⇒ "值语义 ⇒ 无别名" 至少还有一处未覆盖的共享路径。**在把该路径定位并补上 +1/逃逸判定之前，
    //    绝不启用释放发射**（宁可继续泄漏，绝不误回收）。
    //    下一步定位手段：逐个运行差异用例 + `堆统计()` 观察存活槽位，找出被提前回收的对象来自哪条路径。
    // ⛔ 【已停用 · 2026-09-17 定位进展】闸门版（单基本块 + 无条件保守返回判定 + 无接口 + 无闭包）
    //    在双模对账中仍出现 1 条新增分歧，且**门禁明细指向编译模式**：
    //      用例 `55 资源方法与保留名.智`：解释 rc=0 ('2','0')（2 个通过）/ 编译 rc=0 ('0','0')（0 个通过）
    //      ⇒ 本轮结论：**发释放指令这一侧，编译模式产物静默无输出**（疑似编译侧对 `释放引用`
    //        指令（带结果临时槽、经 `_ =>` 兜底委托 堆操作单表）的执行/约定有缺陷，或释放时机引发了
    //        编译产物的访存异常），而非插桩的静态判定问题。
    //    ⇒ 下一步（务必照此顺序）：① 用 `构建运行 --重新编译` 单跑该用例并捕获 stderr/退出码，
    //       确认是"编译期失败"还是"运行期崩溃"；② 检查 `翻译执行器.rs` 对 释放引用/增加引用 的
    //       `_ =>` 兜底路径是否正确传递「结果临时槽」；③ 修好后**把闸门表达式放回**再验证。
    //    恢复方式：把下面的 `false` 换成注释中的闸门表达式即可。
    // ⛔ 【已停用 · 2026-09-17 确证为**编译侧真实缺陷**】启用后实测：
    //    `测试 --编译模式 "55 资源方法与保留名.智"` ⇒ rc=0 且输出仅 `通过：0 失败：0`
    //    （**编译产物无任何程序输出** ⇒ 疑似运行期崩溃且 stdout 未 flush）；
    //    同一用例解释模式输出 `通过：2 失败：0`（正常）。⇒ 差异**不是门禁口径**，而是
    //    **编译侧执行 `释放引用` 指令时出错**（该指令带结果临时槽、经 翻译执行器.rs 的 `_ =>`
    //    兜底委托 `操作数执行器.rs::堆操作索引查询` → 单表 → base 堆操作 C ABI）。
    //    ⇒ 下一步：① 查 `翻译执行器.rs` 的 `_ =>` 兜底对「一元 + 结果临时槽」指令是否漏了栈位/
    //       参数约定；② 用 `--重新编译` 单跑该用例并捕获 stderr/退出码确认崩溃点；
    //       ③ 修好后把下面的 `false` 换回闸门表达式并复验。
    let 可释放 = 块列表.len() == 1
        && !当前函数含嵌套控制流.with(|f| *f.borrow())
        && !当前函数含接口用法.with(|f| *f.borrow())
        && 匿名函数收集.len() == 匿名函数收集基线;
    // 🔁 2026-09-22②（**闸门粒度细化：清单闸门与逐槽闸门解耦**）：
    //   · 逐槽释放（上方 `可释放`，仅用于 `帧级释放启用()==false` 的旧路径）保持**三闸门全查** ⇒ 零行为变化；
    //   · 「拥有型槽索引」清单改由 `清单可用` 决定 —— 本批**放开闸门①（嵌套控制流）**。
    //
    //   闸门① 为何对**清单**可以放开（分析 + 四条论据）：
    //     ① 闸门①的本意：分支/循环内声明的槽"在某些**返回路径**上未赋值 ⇒ 释放会碰到残留句柄"——
    //        那是**多点释放**（每个 `返回` 处各发一遍）才有的风险；
    //     ② 弹帧批量释放是**单点释放**（只在帧消亡处按清单逐槽 −1，两引擎同为此一处）⇒ 不存在"路径差异"；
    //     ③ 未赋值槽在帧内是**空值**（标签 0）⇒ `堆_释放引用`/`批量释放槽清单` 自动跳过 ✓；
    //     ④ 循环内**重复声明**同一槽的旧值由 `覆盖释放`（S2）先行 −1 ⇒ 帧消亡时槽内恰有 1 份自持引用 ✓；
    //        且 `返回 <名称>` 已移出的槽被排除、**投影返回**已由调用方计数一份（见 `语句转换.rs` 返回语句）✓。
    //   ⇒ 仍**整体禁用**的两条（计数未全覆盖，放了会误回收）：闸门②接口（引用语义共享同一实例）、
    //      "本函数创建闭包"（捕获句柄未 +1）。
    //   实测背景：含循环的函数此前一律"零释放"（`112内存循环创建与槽覆盖` 存活 30/30 = 全部存活）。
    let 无新闭包 = 匿名函数收集.len() == 匿名函数收集基线;
    let 闸门二通过 = !当前函数含接口用法.with(|f| *f.borrow());
    let 清单可用 = 无新闭包 && 闸门二通过;
    if 可释放 {
        if let Some(末尾块) = 块列表.iter_mut().rev().find(|b| matches!(b.终止指令, 终止指令::返回(_))) {
            发射释放引用(末尾块, &mut 局部表);
        }
    }
    let _ = (当前函数含接口用法, 当前函数含嵌套控制流, 匿名函数收集基线, 发射释放引用);
    // ★UFC 释放侧元数据★：把「拥有型槽」清单固化为**函数元数据**（两引擎共用；见 模块结构.rs 字段注释）。
    //   来源 = 前端登记的 `当前函数待释放局部`（值语义复合局部 / 接口标签局部 / 深拷贝临时槽…）
    //   排除 `返回 <名称>` 已整体移出的槽（move 语义：所有权交给调用方）。
    //   ⚠ 本批**只登记、不使用**（逐槽释放仍由闸门控制）⇒ 零行为变化；④ 切换为帧弹出批量释放时启用。
    //   🔁 2026-09-22（**帧级释放安全边界**）：清单**不得绕过闸门** —— 闸门未通过的函数置空，
    //     否则弹帧批量释放会在"整体不释放"的函数上照清单 −1 ⇒ 误回收风险。
    //   🔁 2026-09-22②（**闸门粒度细化**）：清单闸门由 `可释放`（三闸门全查）收窄为 `清单可用`
    //     （仅 = 闸门②接口 + 本函数未创建闭包）⇒ **放开闸门①（嵌套控制流）**，理由见上方 `清单可用` 注释。
    //     实测背景：含循环的函数此前一律"零释放"（`112内存循环创建与槽覆盖` 存活 30/30 = 全部存活）。
    let 拥有型槽索引: Vec<usize> = if 清单可用 {
        let 已移出 = 当前函数已移出名称.with(|s| s.borrow().clone());
        当前函数待释放局部.with(|s| {
            s.borrow()
                .iter()
                .filter(|(名称, _)| !已移出.contains(名称))
                .map(|(_, 索引)| *索引)
                .collect::<Vec<usize>>()
        })
    } else {
        Vec::new()
    };
    // 🆕 阶段 6b（2026-09-23）：**槽元数据自检 + 可选转储**（只读；不影响任何判定）。
    //   价值：① 把两条**结构不变量**从静默变红灯 —— 清单项越界 / 清单项重复（重复 ⇒ 弹帧双份 −1）；
    //        ② 转储后可按名字读清单（`智语言_转储槽元数据`）⇒ 降级后"名字消失"不再妨碍排障。
    校验并转储槽元数据(&f.名称, 局部表.len(), &拥有型槽索引);
    let 结果函数 = 底层表示函数 { 名称: f.名称.clone(), 形参列表, 形参局部索引, 返回类型, 基本块列表: 块列表, 局部变量表: 局部表, 拥有型槽索引 };
    // 清理当前函数的 by-ref 登记，避免污染后续函数
    当前函数引用局部.with(|s| s.borrow_mut().clear());
    当前函数引用名映射.with(|m| m.borrow_mut().clear());
    // 「始终」出口完备化：闭包恢复外层始终状态；顶层函数清空（避免污染后续函数）。
    if let Some((槽备份, 层备份)) = 保留始终状态 {
        当前函数退出槽.with(|s| { *s.borrow_mut() = 槽备份; });
        始终层栈.with(|s| { *s.borrow_mut() = 层备份; });
    } else {
        当前函数退出槽.with(|s| { *s.borrow_mut() = None; });
        始终层栈.with(|s| s.borrow_mut().clear());
    }
    结果函数
}
