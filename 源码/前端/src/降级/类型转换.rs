pub const 入口文件键: &str = "<入口>";

pub fn 转换类型(t: &类型信息) -> 底层表示类型 {
    match t {
        类型信息::基本型(b) => match b {
            crate::语义::类型信息::基本类型::整数 => 底层表示类型::整数64,
            crate::语义::类型信息::基本类型::小数 => 底层表示类型::小数64,
            crate::语义::类型信息::基本类型::文本 => 底层表示类型::文本,
            crate::语义::类型信息::基本类型::逻辑 => 底层表示类型::逻辑,
            crate::语义::类型信息::基本类型::空值 => 底层表示类型::空值,
        },
        类型信息::数组(_) => {
            // 数组运行时用指针表示
            底层表示类型::指针
        }
        类型信息::映射(_, _) => {
            底层表示类型::指针 // 映射运行时用指针表示
        }
        类型信息::结构体(_, _) => {
            底层表示类型::指针 // 结构体运行时用指针表示
        }
        // 数据枚举：运行时为 堆数组(句柄)，与数组/结构体/映射一致
        类型信息::枚举(_) => {
            底层表示类型::指针
        }
        类型信息::接口型(_) => {
            底层表示类型::指针 // 接口运行时用指针表示
        }
        类型信息::任意类型 { .. } => {
            底层表示类型::指针 // 任意类型运行时用指针表示
        }
        类型信息::函数类型(_, _) => 底层表示类型::函数指针,
        类型信息::空值 => 底层表示类型::空值,
        // 2026-08-15：未推断 = 「编译期类型未知」，必须与 空值 = 「确定无值」严格区分。
        // 旧实现把 未推断 擦除为 空值，编译器据此把动态值槽当无载荷空值槽处理，
        // 载荷（句柄/整数）在返回值与赋值转换中被丢弃 → 编译模式报「空值不能参与类型转换」，
        // 解释模式按运行时标签正常取值 → 双模分歧。现与 任意类型 一致擦除为 指针（动态值槽）。
        // 来源场景：深层容器索引结果、裸容器元素方法返回、通用容器方法（容器获取）、泛型擦除。
        类型信息::未推断 => 底层表示类型::指针,
        // 推断错误 是语义分析失败哨兵值，保持 空值（不应进入代码生成）。
        类型信息::推断错误 => 底层表示类型::空值,
    }
}
/// 将高层表达式转为常量值（仅支持简单字面值）
pub(crate) fn 高层表达式转常量(表达式: &高层表示表达式) -> 常量值 {
    match 表达式 {
        高层表示表达式::字面值(字面值, _) => match 字面值 {
            高层表示字面值::整数(v) => 常量值::整数(*v),
            高层表示字面值::小数(v) => 常量值::小数(*v),
            高层表示字面值::文本(v) => 常量值::文本(v.clone()),
            高层表示字面值::逻辑(v) => 常量值::逻辑(*v),
            高层表示字面值::空值 => 常量值::空值,
            高层表示字面值::数组(_, _) => 常量值::空值,  // 复杂类型暂用空值
            高层表示字面值::映射(_) => 常量值::空值,  // 复杂类型暂用空值
        },
        _ => 常量值::空值,
    }
}
/// 解析函数索引：优先查内置函数，再查用户自定义函数表
pub(crate) fn 解析函数索引(名: &str, 函数索引映射: &HashMap<String, usize>) -> usize {
    // B3：展开导入——裸名先查别名表映射到全名（2.7.3）。
    // 🆕 迭代式别名归一：沿映射链循环解析（最多 32 跳），遇自引用/环/超限立即停止，
    //    彻底杜绝别名键成环导致的无限递归死循环（旧递归实现遇 辅.X → 辅助模块.X → 辅.X 环即卡死）。
    let mut 当前名 = 名.to_string();
    for _ in 0..32 {
        let 表 = 展开别名映射.get_or_init(|| Mutex::new(HashMap::new())).lock().unwrap();
        match 表.get(&当前名).cloned() {
            Some(全名) if 全名 != 当前名 => 当前名 = 全名,
            _ => break, // 无映射 / 自引用 → 停止归一
        }
    }
    let 名 = &当前名;
    // 内置函数ID范围: 0-199(核心+标准库), 200+为用户自定义函数
    // 🆕 用户/外部函数优先于内置：外部块声明的函数（及用户自定义函数）可遮蔽同名内置，
    // 否则如 平方根 会错误命中内置索引 45，导致外部调用无法路由到 FFI 注册表。
    let 结果 = 函数索引映射.get(名).copied()
        // 🆕 单源 canonical 直查（2026-08-30）：标准库函数 模块.函数 → 索引，取代 strip/suffix 猜测
        .or_else(|| 标准库索引映射.get().and_then(|m| m.get(名).copied()))
        .or_else(|| crate::标准库元数据::取标准库索引映射().get(名).copied())
        // 🗑️ 2026-08-30 移除「去点号 / 取后缀」两段裸名猜测兜底：二者依赖已删除的裸名别名（内置索引无裸名条目，恒为 None，属死代码）；
        //   其设计意图（模块.函数 → 后缀裸名查全局）正是单源方案要消灭的多源漂移。规范名解析已完全由 canonical 直查（标准库索引映射）承担，
        //   删除后若 canonical 漏覆盖会直接暴露（返回 MAX），应补全预注册表而非以猜测兜底。
        // 🗑️ 2026-08-01 移除「已知前缀猜测」兜底：别名导入已在 表达式分析 调用点归一为 原模块.函数，
        // 无需靠硬编码前缀列表「猜」模块；该猜测是串模块隐患（标准库若有两函数同后缀会猜错模块）。
        .unwrap_or(usize::MAX); // 未定义函数返回最大值，VM端会检测并静默返回空值
    结果
}
