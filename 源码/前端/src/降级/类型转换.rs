/// F5（2026-09-28）：**本文件已导入的标准库模块访问名 → (规范模块名, 是否展开)**（每次分析重置）。
///
/// 用途：标准库模块（数学/文件/网络/时间/系统/工具/并发/内存）在前端**按导入列表注册符号**
/// （见 类型推导::预注册内置模块符号）；当用户代码用到**未导入**的标准库模块前缀时，
