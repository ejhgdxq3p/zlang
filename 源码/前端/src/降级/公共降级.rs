/// 🆕 FFI: 底层表示类型 → 外部调用类型标签（整数1/小数2/逻辑3/外部文本6/堆类型4/其他0）
/// 堆类型（数组/映射/结构体）统一以 标签_外部值 扁平缓冲跨 C ABI 传递，运行时按 标签_句柄
/// 还原为堆对象；此处返回非 0（标签_句柄=4）以令导入侧（处理外部调用）分配返回槽并返回值。
pub fn 类型转外部标签(类型: &底层表示类型) -> u8 {
    match 类型 {
        底层表示类型::整数64 => 1,
        底层表示类型::小数64 => 2,
        底层表示类型::逻辑 => 3,
        // ★FFI 文本参数/返回值：标签 5 = C 字符串（const char*）。
        // 2026-08-05 学生点名系统发现：此前标成 6（函数指针），导致 shim 把文本参数
        // 声明为 Option<extern "C" fn()>、运行时把指针当函数指针 transmute，zc_open 等
        // 真实C库的文本参数调用必崩。对齐 外部调用注册::标签到C类型（5 => 字符串）。
        底层表示类型::文本 => 5,
        底层表示类型::数组(..) => 4,
        底层表示类型::映射(..) => 4,
        底层表示类型::结构体(_) => 4,
        // 指针：底层表示中数组/映射/结构体等堆对象句柄统一以 指针 表示，
        // FFI 跨边界一律按 标签_句柄 编组（深拷贝平面缓冲），故返回标签为 4。
        底层表示类型::指针 => 4,
        // 🆕 P3: 函数指针（外部块内 `外部函数(...)` 类型）→ 标签 6（与 标签到C类型 对齐）
        底层表示类型::函数指针 => 6,
        _ => 0,
    }
}

/// 🆕 P3: 外部函数形参/返回类型 → 底层表示类型（精确 C 类型码驱动大类）。
/// 类型信息 无「指针/函数指针」变体（未推断→空值）；外部块经 生成关联 携带精确码
/// （13=void*/20=函数指针）时由精确码驱动底层大类，保证 类型转外部标签 正确（指针→4）。
/// 【2026-08-09 规范变更】开发者侧不再写 指针（智语言无此类型，外部地址统一用 整数），
/// 故 码 13 仅由 生成关联 从 .h 推导写入 形参C类型/返回C类型 携带。
/// 其余（含精确整数/小数位宽，码 1..=19 除 13）走常规 转换类型，位宽由 形参C类型 承载。
fn 转换外部函数类型(t: &类型信息, 码: u8) -> 底层表示类型 {
    match 码 {
        13 => 底层表示类型::指针,      // 指针（FFI 语境内置标识符）
        20 => 底层表示类型::函数指针,  // 函数指针
        21 => 底层表示类型::指针,      // 外部结构体按不透明指针
        _ => 转换类型(t),
    }
}

