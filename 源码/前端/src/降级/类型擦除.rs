use crate::语义::类型信息::{类型信息, 基本类型};
use crate::底层表示::类型定义::底层表示类型;

pub fn 擦除类型(高层表示类型: &类型信息) -> 底层表示类型 {
    match 高层表示类型 {
        类型信息::基本型(基本类型::整数) => 底层表示类型::整数64,
        类型信息::基本型(基本类型::小数) => 底层表示类型::小数64,
        类型信息::基本型(基本类型::文本) => 底层表示类型::文本,
        类型信息::基本型(基本类型::逻辑) => 底层表示类型::逻辑,
        类型信息::基本型(基本类型::空值) => 底层表示类型::空值,
        类型信息::数组(_) => 底层表示类型::指针,
        类型信息::映射(_, _) => 底层表示类型::指针,
        类型信息::结构体(_, _) => 底层表示类型::指针,
        // 数据枚举：运行时为 堆数组(句柄)，与数组/结构体/映射一致
        类型信息::枚举(_) => 底层表示类型::指针,
        类型信息::任意类型 { .. } => 底层表示类型::指针,
        类型信息::函数类型(_, _) => 底层表示类型::函数指针,
        类型信息::空值 => 底层表示类型::空值,
        类型信息::接口型(_) => 底层表示类型::指针,
        // 2026-08-15：未推断 = 「编译期类型未知」，必须与 空值 = 「确定无值」区分。
        // 旧实现把 未推断 擦除为 空值，使编译器把动态值槽当作无载荷的空值槽处理，
        // 值（句柄/整数载荷）在返回值与赋值转换中被丢弃 → 编译模式报「空值不能参与类型转换」，
        // 而解释模式按运行时标签正常取值 → 双模分歧。
        // 现与 任意类型 一致擦除为 指针（动态值槽，载荷+标签完整保留，运行时按标签解释）。
        // 来源场景：深层容器索引结果、裸容器元素方法返回、通用容器方法（容器获取）、泛型擦除。
        类型信息::未推断 => 底层表示类型::指针,
        // 推断错误 是语义分析失败的哨兵值，保持 空值（不应进入代码生成）。
        类型信息::推断错误 => 底层表示类型::空值,
    }
}