// ============================================================
//  索引空间契约单测（仿 操作数执行器.rs 双向对称契约范式）
//  守卫「跨 crate 索引基址单一真相」不被回归：
//  ① 用户函数索引基址 必须高于所有系统函数号（当前最大已知 = 标准库索引::数学_字节_小于等于 = 300），
//     否则系统空间与用户空间重叠 → 此前 300→400 漏改即此类。
//  ② 用户结构体类型索引基址 必须 = 无限整数类型索引 + 1（16），否则与内建类型撞车。
//  ③ 标准库索引（常量层）不得侵入用户函数空间（运行期全面校验见 标准库元数据::自检_索引一致）。
// ============================================================
#[cfg(test)]
mod 索引空间契约测试 {
    use super::用户函数索引基址;
    use base::值类型::{用户结构体类型索引基址, 无限整数类型索引};
    use base::标准库索引;

    /// 用户函数索引基址必须高于所有系统/内建函数号，否则系统空间与用户空间重叠。
    #[test]
    fn 用户函数索引基址高于系统函数空间() {
        // 已知最大系统函数号（base 标准库索引表）必须 < 用户函数索引基址。
        assert!(
            用户函数索引基址 > 标准库索引::数学_字节_小于等于,
            "用户函数索引基址({}) 必须高于系统函数号 {}",
            用户函数索引基址, 标准库索引::数学_字节_小于等于
        );
        // 基址须为单一真相契约值；若调整须同步全仓引用（本测试即守卫）。
        assert_eq!(用户函数索引基址, 400, "用户函数索引基址契约值；若调整须同步全仓引用");
    }

    /// 用户结构体类型索引基址必须紧随内建结构体之后（无限整数类型索引+1），
    /// 否则会与内建类型撞车（历史 bug：基址 11 与精确小数撞车，致 类型(用户结构体) 错返「精确小数」）。
    #[test]
    fn 用户结构体类型索引基址紧随内建() {
        assert_eq!(用户结构体类型索引基址, 无限整数类型索引 + 1);
        assert_eq!(用户结构体类型索引基址, 16, "用户结构体基址契约值；若调整须同步 公共降级.rs 特判");
    }

    /// 标准库索引（常量层）不得侵入用户函数空间（运行期注册表全面校验见 自检_索引一致）。
    #[test]
    fn 标准库索引不侵入用户空间() {
        let 已知系统索引 = [
            标准库索引::数学_字节_小于等于, // 当前最大已知系统函数号
        ];
        for &idx in 已知系统索引.iter() {
            assert!(idx < 用户函数索引基址, "标准库索引 {} 侵入用户函数空间", idx);
        }
    }
}