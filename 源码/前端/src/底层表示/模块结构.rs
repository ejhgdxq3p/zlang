#[derive(Debug, Clone)]
pub struct 底层表示函数 {
    pub 名称: String,
    pub 形参列表: Vec<(String, 底层表示类型)>,
    /// 每个形参在 局部变量表 中的实际索引（前端按下标顺序推入：保留位→全局变量→形参→临时变量）。
    /// 编译模式据此正确初始化参数变量，避免把形参误映射到表末尾的临时槽（D5 参数初始化 bug）。
    pub 形参局部索引: Vec<usize>,
    pub 返回类型: 底层表示类型,
    pub 基本块列表: Vec<基本块>,
    pub 局部变量表: Vec<底层表示类型>,
    /// ★统一帧契约（UFC）**释放侧**元数据★（2026-09-22）：本函数的「**拥有型槽**」局部索引清单。
    ///
    /// 语义：该槽**持有一份 +1 引用**（创建转移 / 值语义深拷贝 / 接口标签 +1 / 存储类 +1），
    ///   故帧退出时应对其执行 −1（`堆_释放引用` 语义）。
    ///   **借用型槽不得入内**（例：`文本 s = 列表[1]` —— 非复合类型不深拷贝 ⇒ 槽内是容器元素的句柄，
    ///   释放它 = 误回收容器仍持有的对象；2026-09 实测曾致 3 例失败 + 对账 9→13）。
    ///
    /// 用途（两引擎**取同一份**，见《内存管理技术方案》§5.1 同源红线 / §9.2）：
    ///   · 解释模式：VM 弹帧时按本清单把 `局部变量表` 对应槽交由 base `批量释放槽清单`；
    ///   · 编译模式：`弹出影子帧` 时按本清单把**影子块**对应槽交由同一函数。
    ///   ⇒ 比"在若干出口点逐槽发射 `操作码::释放引用`"**更完备**：返回（值/无值）、异常提前返回、
    ///     `始终` 链落点块、嵌套控制流各出口**全都被帧弹出统一覆盖**，无遗漏出口。
    ///
    /// 备注：当前前端仍按闸门①② 条件发射逐槽释放（保守）；本字段为 ④ 批量释放的**唯一真相来源**，
    ///   切换时须同时停止逐槽发射（否则重复 −1）。
    pub 拥有型槽索引: Vec<usize>,
}

/// 🆕 方案B（异常模型前移）S1：基本块触发异常时的静态派发目标（前端单源）。
/// 危险区→捕获(异常处理块)、异常区→收尾(始终块)、始终/传播/续延区及外层→外层目标/无。
/// 后端（解释器/编译器）在「在途异常」时按当前块查此目标跳转——替代历史双运行时状态机。
/// S1 阶段仅填充不消费（旧 设置异常处理/弹出异常处理 opcode 双轨保留）；S2/S3 后端接入。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 异常目标 {
    /// 本函数内无 handler：退帧（VM）/ 异常返回块早返回（编译）。
    无,
    /// 跳到 异常处理块（catch，或无 catch 层的 stub）——其入口自行复位重抛标志（吞/传播）。
    捕获(usize),
    /// 跳到 始终块 —— 后端必须先置 全局变量(0)=1（本层异常经 finally 外传）再清在途标志（保载荷）。
    收尾(usize),
}

