// ⚡双模式⚡ 单一真相表：可抛性（编译模式异常检查注入的判定）
//
//   与 `操作码到堆操作` 同位置的第二张单一真相表。编译模式在「每条可抛指令后」
//   注入异常检查（读 base 双信号 → 跳 catch / 异常返回块），使异常被 try...捕获
//   捕获并沿调用链上抛。此前该判定靠「各 arm 手插 + 编译堆操作 内部注入」的纪律，
//   新增可抛 opcode 漏插即复发 X1/X2A（编译模式特有异常泄漏）。现收口为单表：
//   前端登记一次，编译器主循环依此自动注入，杜绝手插遗漏。
//
//   ⚠️ 覆盖规则：
//     - 一切经 `操作码到堆操作` 映射（即调 base 堆操作常量）的 opcode 均可抛
//       （含 加法/减法/乘法/除法/整除/取余/幂/字段加载/数组加载/通道发送 等越界与空值异常）；
//     - 调用族（CALL 0-99 系统调用 / 用户函数 / 外部调用）不走堆操作表，显式补；
//     - 任务等待族 / 抛出 / 传播异常 不走堆操作表，显式补；
//     - 查询/复位/置位重抛标志、加载、存储、跳转、条件跳转、返回 等控制/信号操纵
//       opcode 不可抛（注入会误读刚置的标志 → 误跳），刻意排除。
pub fn 操作码可抛(码: &操作码) -> bool {
    操作码到堆操作(码).is_some()
        || matches!(
            码,
            操作码::调用
                | 操作码::间接调用
                | 操作码::外部调用
                | 操作码::任务等待
                | 操作码::批量等待
                | 操作码::批量等待超时
                | 操作码::抛出
                | 操作码::传播异常
        )
}

