// 文件: 前端/src/格式化器.rs
// 职责: 智语言代码格式化器（3.3 编码格式规范）
// - 缩进4空格，禁止Tab
// - 控制流关键字后换行
// - 每行最大120字符
// - 运算符两侧空格
// - 逗号后空格、冒号后空格
// - 括号内侧无空格
// - 逻辑段空行分隔
// - 命名规范检查（全中文、变量名词、函数动宾、结构体名词、逻辑"是否"开头）

use crate::公共数据结构::{源码位置, 诊断信息, 诊断级别, 错误类型};
use crate::诊断收集器::诊断收集器;
use crate::词法分析::{词法分析器, 词条, 词条类型};

pub struct 格式化器<'a> {
    诊断: &'a mut 诊断收集器,
}

impl<'a> 格式化器<'a> {
    pub fn 新建(诊断: &'a mut 诊断收集器) -> Self {
        格式化器 { 诊断 }
    }

    /// 格式化源码（3.3），返回格式化后的源码
    pub fn 格式化(&mut self, 源码: &str, 文件路径: &str) -> Result<String, ()> {
        let mut 词法器 = 词法分析器::新建(源码, 文件路径.to_string(), self.诊断);
        let 词条列表 = 词法器.扫描所有词条();
        let 初始词条列表: Vec<_> = 词条列表.iter()
            .filter(|t| !matches!(t.类型, 词条类型::文件结束 | 词条类型::换行))
            .collect();

        let mut 输出 = String::new();
        let mut 缩进级别: usize = 0;
        let mut 当前行长度: usize = 0;
        let mut 需要换行 = true;
        let mut 上一个词条类型: Option<&词条类型> = None;

        for (i, 词条) in 初始词条列表.iter().enumerate() {
            let 需要空格_前 = self.需要前导空格(词条, 上一个词条类型);
            let 需要空格_后 = self.需要后置空格(词条);

            // 处理缩进变化的词条
            match &词条.类型 {
                词条类型::结束 => { if 缩进级别 > 0 { 缩进级别 -= 1; } }
                词条类型::冒号 => { 缩进级别 += 1; }
                _ => {}
            }

            if 需要换行 {
                if !输出.is_empty() && !输出.ends_with('\n') {
                    输出.push('\n');
                }
                // 添加缩进
                for _ in 0..缩进级别 * 4 {
                    输出.push(' ');
                }
                当前行长度 = 缩进级别 * 4;
                需要换行 = false;
            }

            if 需要空格_前 && !输出.ends_with(' ') && 当前行长度 > 0 && !输出.ends_with('\n') {
                // 检查120字符行宽
                if 当前行长度 + 1 > 120 {
                    输出.push('\n');
                    for _ in 0..缩进级别 * 4 { 输出.push(' '); }
                    当前行长度 = 缩进级别 * 4;
                }
                输出.push(' ');
                当前行长度 += 1;
            }

            let 词条文本 = self.词条格式化文本(词条);
            if 当前行长度 + 词条文本.len() > 120 {
                输出.push('\n');
                for _ in 0..(缩进级别 + 1) * 4 { 输出.push(' '); }
                当前行长度 = (缩进级别 + 1) * 4;
            }
            输出.push_str(&词条文本);
            当前行长度 += 词条文本.len();

            if 需要空格_后 {
                输出.push(' ');
                当前行长度 += 1;
            }

            // 控制流关键字后换行（3.3.2）
            let 是控制流 = matches!(&词条.类型,
                词条类型::如果 | 词条类型::否则如果 | 词条类型::否则 | 词条类型::循环
                | 词条类型::捕获 | 词条类型::异常
            );
            if 是控制流 {
                // 检查下一词条是否是冒号
                if let Some(下) = 初始词条列表.get(i + 1) {
                    if matches!(&下.类型, 词条类型::冒号) {
                        // 冒号后应换行
                    }
                }
            }

            // 冒号后换行（3.3.2）
            if matches!(&词条.类型, 词条类型::冒号) {
                if let Some(下) = 初始词条列表.get(i + 1) {
                    if !matches!(&下.类型, 词条类型::结束) {
                        需要换行 = true;
                    }
                }
            }

            // 检查命名规范（3.2）
            if let 词条类型::标识符(名称) = &词条.类型 {
                self.检查命名规范(名称, &词条.位置);
            } else if let 词条类型::外部标识符(_) = &词条.类型 {
                // C 符号名（如 sqlite3、open）豁免中文命名规范检查
            }

            上一个词条类型 = Some(&词条.类型);
        }

        // 确保文件以换行结尾
        if !输出.ends_with('\n') {
            输出.push('\n');
        }

        Ok(输出)
    }

    fn 词条格式化文本(&self, 词条: &词条) -> String {
        match &词条.类型 {
            词条类型::整数(v) => v.to_string(),
            // 待定负整数（2^63）：源码原样输出即可（仅在 `-` 后合法，格式化时不应改写用户代码）
            词条类型::待定负整数(v) => v.to_string(),
            词条类型::小数(v) => v.to_string(),
            词条类型::文本字面量(v) => format!("\"{}\"", v),
            词条类型::真 => "真".to_string(),
            词条类型::假 => "假".to_string(),
            词条类型::空值 => "空值".to_string(),
            词条类型::标识符(v) => v.clone(),
            词条类型::类型关键字(v) => v.clone(), // §2.2.3 类型名类关键字（整数/小数/文本/逻辑）
            词条类型::外部标识符(v) => v.clone(),
            词条类型::如果 => "如果".to_string(),
            词条类型::否则如果 => "否则如果".to_string(),
            词条类型::否则 => "否则".to_string(),
            词条类型::结束 => "结束".to_string(),
            词条类型::循环 => "循环".to_string(),
            词条类型::遍历 => "遍历".to_string(),
            词条类型::跳出 => "跳出".to_string(),
            词条类型::继续 => "继续".to_string(),
            词条类型::返回 => "返回".to_string(),
            词条类型::结构体 => "结构体".to_string(),
            词条类型::枚举 => "枚举".to_string(),
            词条类型::任意 => "任意".to_string(),
            词条类型::接口 => "接口".to_string(),
            词条类型::适配 => "适配".to_string(),
            词条类型::常量 => "常量".to_string(),
            词条类型::函数 => "函数".to_string(),
            词条类型::私有 => "私有".to_string(),
            词条类型::导入 => "导入".to_string(),
            词条类型::展开 => "展开".to_string(),
            词条类型::自身 => "自身".to_string(),
            词条类型::本模块 => "本模块".to_string(),
            词条类型::捕获 => "捕获".to_string(),
            词条类型::异常 => "异常".to_string(),
            词条类型::传值 => "传值".to_string(),
            词条类型::传引用 => "传引用".to_string(),
            词条类型::且 => "且".to_string(),
            词条类型::或 => "或".to_string(),
            词条类型::非 => "非".to_string(),
            词条类型::属于 => "属于".to_string(),
            词条类型::不属于 => "不属于".to_string(),
            词条类型::加 => "+".to_string(),
            词条类型::减 => "-".to_string(),
            词条类型::乘 => "*".to_string(),
            词条类型::除 => "/".to_string(),
            词条类型::整除 => "%%".to_string(),
            词条类型::取余 => "%".to_string(),
            词条类型::幂 => "^".to_string(),
            词条类型::大于 => ">".to_string(),
            词条类型::小于 => "<".to_string(),
            词条类型::等于等于 => "==".to_string(),
            词条类型::不等于 => "!=".to_string(),
            词条类型::大于等于 => ">=".to_string(),
            词条类型::小于等于 => "<=".to_string(),
            词条类型::实例相等 => "===".to_string(),
            词条类型::实例不等 => "!==".to_string(),
            词条类型::赋值 => "=".to_string(),
            词条类型::加赋值 => "+=".to_string(),
            词条类型::减赋值 => "-=".to_string(),
            词条类型::乘赋值 => "*=".to_string(),
            词条类型::除赋值 => "/=".to_string(),
            词条类型::取余赋值 => "%=".to_string(),
            词条类型::整除赋值 => "%%=".to_string(),
            词条类型::幂赋值 => "^=".to_string(),
            词条类型::位与 => "&".to_string(),
            词条类型::位或 => "|".to_string(),
            词条类型::位非 => "~".to_string(),
            词条类型::异或 => "~|".to_string(),
            词条类型::左移 => "<<".to_string(),
            词条类型::右移 => ">>".to_string(),
            词条类型::位与赋值 => "&=".to_string(),
            词条类型::位或赋值 => "|=".to_string(),
            词条类型::异或赋值 => "~|=".to_string(),
            词条类型::左移赋值 => "<<=".to_string(),
            词条类型::右移赋值 => ">>=".to_string(),
            词条类型::左括号 => "(".to_string(),
            词条类型::右括号 => ")".to_string(),
            词条类型::左方括号 => "[".to_string(),
            词条类型::右方括号 => "]".to_string(),
            词条类型::左大括号 => "{".to_string(),
            词条类型::右大括号 => "}".to_string(),
            词条类型::逗号 => ",".to_string(),
            词条类型::分号 => ";".to_string(),
            词条类型::冒号 => ":".to_string(),
            词条类型::点 => ".".to_string(),
            _ => String::new(),
        }
    }

    /// 词条前是否需要空格（3.3.4）
    fn 需要前导空格(&self, 词条: &词条, 上一个: Option<&词条类型>) -> bool {
        match &词条.类型 {
            // 这些符号前不需要空格
            词条类型::逗号 | 词条类型::分号 | 词条类型::冒号 | 词条类型::右括号
            | 词条类型::右方括号 | 词条类型::右大括号 | 词条类型::点 => false,
            // 左括号前需要空格（除函数名后面）
            词条类型::左括号 => {
                match 上一个 {
                    Some(词条类型::标识符(_)) | Some(词条类型::属于) | Some(词条类型::不属于)
                    | Some(词条类型::且) | Some(词条类型::或) | Some(词条类型::非) => false,
                    _ => false,
                }
            }
            // 二元运算符两侧需要空格（3.3.4）
            词条类型::加 | 词条类型::减 | 词条类型::乘 | 词条类型::除 | 词条类型::整除
            | 词条类型::取余 | 词条类型::幂 | 词条类型::赋值 | 词条类型::加赋值
            | 词条类型::减赋值 | 词条类型::乘赋值 | 词条类型::除赋值 | 词条类型::取余赋值
            | 词条类型::幂赋值 | 词条类型::等于等于 | 词条类型::不等于 | 词条类型::大于
            | 词条类型::小于 | 词条类型::大于等于 | 词条类型::小于等于 | 词条类型::实例相等
            | 词条类型::实例不等 | 词条类型::且 | 词条类型::或 | 词条类型::属于 | 词条类型::不属于
            | 词条类型::位与 | 词条类型::位或 | 词条类型::异或 | 词条类型::左移 | 词条类型::右移
            | 词条类型::位与赋值 | 词条类型::位或赋值 | 词条类型::异或赋值 | 词条类型::左移赋值
            | 词条类型::右移赋值 => true,
            // 关键字前一般需要空格
            _ => {
                match 上一个 {
                    Some(词条类型::左括号) | Some(词条类型::左方括号) | Some(词条类型::左大括号)
                    | Some(词条类型::点) | Some(词条类型::减) | Some(词条类型::非) => false,
                    None => false,
                    _ => true,
                }
            }
        }
    }

    /// 词条后是否需要空格（逗号后空格、冒号后空格）（3.3.4）
    fn 需要后置空格(&self, 词条: &词条) -> bool {
        match &词条.类型 {
            词条类型::逗号 | 词条类型::冒号 => true,
            _ => false,
        }
    }

    /// 检查命名规范（3.2）
    fn 检查命名规范(&mut self, 名称: &str, 位置: &源码位置) {
        let 含非中文 = 名称.chars().any(|c| c.is_ascii_alphabetic());
        if 含非中文 && !self.是内建标识符(名称) {
            self.诊断.报告(诊断信息 {
                级别: 诊断级别::警告,
                错误类型: 错误类型::代码建议,
                描述: format!("标识符【{}】不符合全中文命名规范", 名称),
                位置: 位置.clone(),
                帮助信息: Some("智语言采用全中文化命名，建议使用中文词语命名变量、函数、结构体".to_string()),
                也见于: Vec::new(),
                是否是指: None,
                标记说明: None,
                });
        }
    }

    fn 是内建标识符(&self, 名称: &str) -> bool {
        matches!(名称, "自身" | "true" | "false" | "null" | "NaN" | "Inf")
    }
}
