// 文件: 前端/src/模块加载器.rs
// 职责: 模块加载器 — 递归加载导入的 .智 文件，提取公开符号并命名空间化
// 解决问题: 从硬编码符号表改为真正读取和编译源文件

use crate::语法分析::{程序, 顶层定义, 导入声明, 结构体成员, 类型表达式, 外部块的项, 导出块的项};
use crate::标准库元数据::标准库种类;
use crate::语义::符号表::{符号, 符号种类, 字段符号, 函数签名, 枚举成员信息, 方法声明, 函数符号};
use crate::语义::类型信息::{类型信息, 基本类型};
use crate::公共数据结构::源码位置;
use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::fs;

/// 模块加载器：负责加载 .智 文件并提取符号
pub struct 模块加载器 {
    pub 已加载缓存: HashMap<String, 模块数据>,
    pub 加载路径列表: Vec<PathBuf>,
    /// 依赖解析方案（规范 §2.7.5 **三层分派**的第三方库层真相源）。
    /// `None` = 单文件模式（无 `项目.配置`/`项目依赖.配置`）⇒ 只有标准库层与项目内层。
    pub 解析方案: Option<pm::依赖解析::模块解析方案>,
}

#[derive(Debug, Clone)]
pub struct 模块数据 {
    pub 文件路径: String,
    pub 模块名: String,
    /// 该模块是否含「启动程序」（即启动模块）——打包规范 §2.9：启动模块严禁被导入
    pub 是启动模块: bool,
    pub 顶层定义列表: Vec<顶层定义>,
    pub 导入列表: Vec<导入声明>,
}

impl 模块加载器 {
    pub fn 新建(加载路径列表: Vec<PathBuf>) -> Self {
        模块加载器 { 已加载缓存: HashMap::new(), 加载路径列表, 解析方案: None }
    }

    /// 带依赖解析方案构造：启用规范 §2.7.5 **三层分派**（第三方库 `导入 库名/模块路径`）。
    pub fn 新建_带方案(方案: pm::依赖解析::模块解析方案, 加载路径列表: Vec<PathBuf>) -> Self {
        模块加载器 { 已加载缓存: HashMap::new(), 加载路径列表, 解析方案: Some(方案) }
    }

    pub fn 默认加载路径(编译模式: bool) -> Vec<PathBuf> {
        let 起始 = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
        if let Some(项目根) = pm::依赖解析::检测项目根(&起始) {
            if let Ok(方案) = pm::依赖解析::构建模块解析方案(&项目根, 编译模式) {
                return 方案.搜索路径列表();
            }
        }
        let mut 路径列表 = Vec::new();
        路径列表.push(pm::目录::标准库根(编译模式));
        路径列表.push(起始);
        路径列表.push(PathBuf::from("库"));
        路径列表
    }

    pub fn 加载依赖模块(&mut self, 导入列表: &mut [导入声明], 当前目录: Option<&Path>, 词法分析器: &mut dyn FnMut(&str, &Path) -> Result<程序, String>, 加载中栈: &mut HashSet<String>) -> Result<HashMap<String, 模块数据>, String> {
        // ── 规范 §2.7.5 三层分派：先算本文件的「项目内候选根」（层内有序，**不跨层撞库**）──
        let 项目内候选根 = self.项目内候选根(当前目录);
        // 🆕 2026-09-25 **单源化**：内置模块名集合**从 标准库元数据 单一真相派生**
        //   （与 语义分析器::分析程序 构造「内置模块名集合」的口径**完全一致**），
        //   取代此前的硬编码列表 `["数学","文件","时间","系统","工具","网络","并发"]`。
        //   【为何要改】两处口径并存即会漂移：新增标准库模块时，语义层从元数据自动生效，
        //   而此处仍按文件加载该内置模块 ⇒ 报「无法找到模块」（同一名字在两处判定相反）。
        //   提到导入循环之外只构造一次，避免逐次导入重复构建集合。
        let 内置模块名集合: std::collections::HashSet<&str> =
            crate::标准库元数据::按模块分组().into_iter().map(|(名, _)| 名).collect();
        for 导入 in 导入列表.iter_mut() {
            // ── 相对层（`导入 ./模块`、`../模块`）：基于当前文件所在目录解析 ──
            if 导入.是否相对 {
                let 基准目录 = 当前目录.ok_or_else(|| "相对导入缺少基准目录（导入语句所在文件目录）".to_string())?;
                let 相对模块名 = self.解析相对导入(基准目录, &导入.模块路径)?;
                // 回填解析后键，供语义层匹配相对模块
                导入.解析后键 = Some(相对模块名.clone());
                self.递归加载模块(&相对模块名, &项目内候选根, 词法分析器, 加载中栈)?;
                continue;
            }
            if 导入.模块路径.is_empty() { continue; }
            // 核心库（8 个全局函数 + 文本/数组/映射/异常错误内置方法）**无需导入**（规范 §4.1）；
            // 标准库模块**单独成段**（`导入 数学`）时符号由 标准库元数据 预注册，无需文件。
            // 标准库层的内嵌路径（`导入 数学/几何/圆形`）仍走文件加载 —— 标准库根在候选根中（层内，不由库根撞）。
            if 导入.模块路径.len() == 1 {
                let 单段 = 导入.模块路径[0].as_str();
                if 单段 == "自身" || 内置模块名集合.contains(单段) { continue; }
            }
            // 模块键 = `模块路径.join(".")`（语义层 `导入声明匹配` 的三种键形态之一，保持既有口径）
            let 模块键 = 导入.模块路径.join(".");
            self.递归加载模块(&模块键, &项目内候选根, 词法分析器, 加载中栈)?;
        }
        Ok(self.已加载缓存.clone())
    }

    /// 项目内层候选根（规范 §2.7.5）：**作用域 `源码/` 根 → 当前文件目录 → 项目级固定根**。
    /// 层内有序回退；**不含**其他依赖库的源码根（库模块必须经库名前缀，见 `依赖解析::定位模块`）。
    fn 项目内候选根(&self, 当前目录: Option<&Path>) -> Vec<PathBuf> {
        let mut 列表: Vec<PathBuf> = Vec::new();
        let mut 已见: HashSet<PathBuf> = HashSet::new();
        // 顺序：当前文件目录（保留既有「相邻/同级导入」便利，避开行为变化）→ 作用域 `源码/` 根
        //（规范 §2.7.5 的基准：库文件 = 本库源码根；项目文件 = 项目源码根）→ 项目级固定根
        if let Some(目录) = 当前目录 {
            Self::压入候选根(&mut 列表, &mut 已见, 目录);
            if let Some(作用域根) = self.作用域源码根(目录) {
                Self::压入候选根(&mut 列表, &mut 已见, &作用域根);
            }
        }
        for 根 in &self.加载路径列表 {
            Self::压入候选根(&mut 列表, &mut 已见, 根);
        }
        列表
    }

    /// 候选根入列（去重 + 规范化；与 `pm::依赖解析::加入路径` 同口径）
    fn 压入候选根(列表: &mut Vec<PathBuf>, 已见: &mut HashSet<PathBuf>, 路径: &Path) {
        if !路径.exists() { return; }
        let 规范 = 路径.canonicalize().unwrap_or_else(|_| 路径.to_path_buf());
        if 已见.insert(规范.clone()) {
            列表.push(规范);
        }
    }

    /// 本文件所属的「项目内解析作用域」= `源码/` 根：库文件 ⇒ **本库**源码根；项目文件 ⇒ 项目源码根。
    /// ⇒ 库是**独立解析作用域**：库内模块互导写库内路径即可（无需库名前缀），库可改名、可作传递依赖复用。
    fn 作用域源码根(&self, 目录: &Path) -> Option<PathBuf> {
        let 方案 = self.解析方案.as_ref()?;
        if let Some(库根) = 方案.库归属(目录) {
            return Some(库根.clone());
        }
        if 目录.starts_with(&方案.项目源码根) || 方案.项目源码根.starts_with(目录) {
            return Some(方案.项目源码根.clone());
        }
        None
    }

    /// 规范 §2.7.5 三层分派的**定位**：标准库层/项目内层走候选根；第三方库层定向到该库源码根。
    fn 解析文件路径(&self, 模块名: &str, 项目内候选根: &[PathBuf]) -> Result<PathBuf, String> {
        if let Some(方案) = self.解析方案.as_ref() {
            let 分段: Vec<String> = 模块名.split('.').map(|s| s.to_string()).collect();
            return Ok(方案.定位模块(&分段, 项目内候选根)?.文件);
        }
        // 单文件模式（无依赖声明）：层内候选根查找（与既有口径一致）
        let 文件子路径 = 模块名.replace('.', &std::path::MAIN_SEPARATOR.to_string());
        for 根 in 项目内候选根 {
            let 候选 = 根.join(format!("{}.智", 文件子路径));
            if 候选.exists() {
                return Ok(候选);
            }
        }
        Err(format!("无法找到模块【{}】", 模块名))
    }

    /// 将相对导入的路径段（首段为 "." 或 ".."）基于基准目录解析为规范化绝对路径字符串。
    /// 该绝对路径同时作为模块标识（缓存键）与命名空间键，避免不同目录下同名模块串缓存。
    fn 解析相对导入(&self, 基准目录: &Path, 路径段: &[String]) -> Result<String, String> {
        // 基准目录可能传入相对路径，先规范化成绝对路径，避免 canonicalize 相对路径失败
        let 基准绝对 = fs::canonicalize(基准目录)
            .map(|p| p.to_string_lossy().to_string())
            .ok()
            .and_then(|s| Some(PathBuf::from(s)))
            .unwrap_or_else(|| 基准目录.to_path_buf());
        let mut 目标 = 基准绝对;
        for 段 in 路径段 {
            if 段 == "." {
                // 当前目录，无操作
                continue;
            } else if 段 == ".." {
                目标 = 目标.parent().ok_or_else(|| format!("相对导入路径上溯超出根目录：{}", 基准目录.display()))?.to_path_buf();
            } else {
                目标 = 目标.join(段);
            }
        }
        // 模块文件名 = 最后一段 + ".智" 后缀（避免把 .智 当作路径子目录）
        目标 = 目标.with_extension("智");
        fs::canonicalize(&目标).map(|p| p.to_string_lossy().to_string()).ok().ok_or_else(|| format!("无法找到相对模块【{}】 基准【{}】 目标【{}】", 路径段.join("/"), 基准目录.display(), 目标.display()))
    }

    fn 递归加载模块(&mut self, 模块名: &str, 项目内候选根: &[PathBuf], 词法分析器: &mut dyn FnMut(&str, &Path) -> Result<程序, String>, 加载中栈: &mut HashSet<String>) -> Result<(), String> {
        use std::cell::Cell;
        thread_local!(static DEPTH_RLM: Cell<u32> = Cell::new(0));
        struct Guard;
        impl Drop for Guard { fn drop(&mut self) { DEPTH_RLM.with(|c| c.set(c.get().saturating_sub(1))); } }
        let d = DEPTH_RLM.with(|c| { let v = c.get() + 1; c.set(v); v });
        if d > 500 {
            panic!("DEPTH_LIMIT 递归加载模块 d={} name={}", d, 模块名);
        }
        let _guard = Guard;
        if self.已加载缓存.contains_key(模块名) { return Ok(()); }
        // 循环依赖检测（规范 §2.9：环形聚合按 2.7.4 循环导入检测处理）：
        // 模块仍在当前加载链上 → 环，直接报错，避免无限递归到 DEPTH_LIMIT panic。
        if 加载中栈.contains(模块名) {
            return Err(format!("循环依赖：模块【{}】被自身依赖链回指（环形聚合/循环导入）", 模块名));
        }
        加载中栈.insert(模块名.to_string());
        // ── 相对导入：模块名已是规范化绝对路径，直接读取 ──
        if 模块名.ends_with(".智") {
            let 候选 = Path::new(模块名);
            if !候选.exists() {
                return Err(format!("无法找到相对模块【{}】", 模块名));
            }
            let 文件路径 = 候选.to_path_buf();
            let 源码 = fs::read_to_string(&文件路径).map_err(|e| format!("读取模块【{}】失败: {}", 模块名, e))?;
            let mut 程序 = 词法分析器(&源码, &文件路径)?;
            let _依赖模块 = self.加载依赖模块(&mut 程序.导入列表, 文件路径.parent(), 词法分析器, 加载中栈)?;
            let 模块键 = fs::canonicalize(&文件路径).map(|p| p.to_string_lossy().to_string()).unwrap_or_else(|_| 文件路径.to_string_lossy().to_string());
            self.已加载缓存.insert(模块键.clone(), 模块数据 { 文件路径: 文件路径.to_string_lossy().to_string(), 模块名: 模块键.clone(), 是启动模块: 程序.入口.is_some(), 顶层定义列表: 程序.顶层定义列表, 导入列表: 程序.导入列表 });
            加载中栈.remove(&模块键);
            加载中栈.remove(模块名);
            return Ok(());
        }
        // ── 规范 §2.7.5 三层分派：标准库层 / 项目内层走候选根；第三方库层定向到该库源码根 ──
        let 文件路径 = self.解析文件路径(模块名, 项目内候选根)?;
        let 源码 = fs::read_to_string(&文件路径).map_err(|e| format!("读取模块【{}】失败: {}", 模块名, e))?;
        let mut 程序 = 词法分析器(&源码, &文件路径)?;
        let _依赖模块 = self.加载依赖模块(&mut 程序.导入列表, 文件路径.parent(), 词法分析器, 加载中栈)?;
        self.已加载缓存.insert(模块名.to_string(), 模块数据 { 文件路径: 文件路径.to_string_lossy().to_string(), 模块名: 模块名.to_string(), 是启动模块: 程序.入口.is_some(), 顶层定义列表: 程序.顶层定义列表, 导入列表: 程序.导入列表 });
        加载中栈.remove(模块名);
        Ok(())
    }

    /// 聚合重导出：按 展开 / 别名 / 默认 三种形态计算对外名（规范 §2.9）
    /// 单一真相：加载器（递归提取）与语义层（冲突检查）共用，禁止各自再写一份。
    pub(crate) fn 聚合对外名(聚合: &导入声明, 目标末段: &str, 内部名: &str) -> String {
        if 聚合.是否展开 {
            内部名.to_string()
        } else if let Some(别名) = &聚合.别名 {
            format!("{}.{}", 别名, 内部名)
        } else {
            format!("{}.{}", 目标末段, 内部名)
        }
    }

    /// 环形聚合检测：命中环时返回环上的模块键，无环返回 None。
    /// 规范 §2.9：环形聚合按 2.7.4 循环导入检测处理（报错，而非静默去重）。
    pub(crate) fn 检测环形聚合(
        模块映射: &HashMap<String, 模块数据>,
        当前: &str,
        路径栈: &mut HashSet<String>,
    ) -> Option<String> {
        if !路径栈.insert(当前.to_string()) {
            return Some(当前.to_string());
        }
        if let Some(数据) = 模块映射.get(当前) {
            for 聚合 in 数据.导入列表.iter().filter(|i| i.是否聚合) {
                let 目标键 = if 聚合.是否相对 {
                    聚合.解析后键.clone().unwrap_or_else(|| 聚合.模块路径.join("."))
                } else {
                    聚合.模块路径.join(".")
                };
                if let Some(环) = Self::检测环形聚合(模块映射, &目标键, 路径栈) {
                    return Some(环);
                }
            }
        }
        路径栈.remove(当前);
        None
    }

    /// 从缓存中提取指定模块的公开符号。
    /// 返回 (符号, 原全名)：聚合重导出的符号带 `Some(原全名)`（真实函数全名，供语义层登记别名归一化映射），
    /// 模块自身的符号为 `None`。
    pub fn 提取公开符号(&self, 模块名: &str, 注册模块名: &str) -> Result<Vec<(符号, Option<String>)>, String> {
        let mut 已访问: HashSet<String> = HashSet::new();
        self.提取公开符号_内(模块名, 注册模块名, &mut 已访问)
    }

    /// 递归提取：自身公开符号 + （若为聚合模块）各聚合目标的公开符号，按形态塑形并同源去重。
    /// 已访问 集合同时承担环形聚合守卫，防止死递归。
    fn 提取公开符号_内(&self, 模块名: &str, 注册模块名: &str, 已访问: &mut HashSet<String>) -> Result<Vec<(符号, Option<String>)>, String> {
        let 数据 = self.已加载缓存.get(模块名).ok_or_else(|| format!("模块【{}】未加载", 模块名))?;
        let mut 符号列表: Vec<(符号, Option<String>)> = self.提取符号列表(&[数据.clone()], 注册模块名)
            .into_iter().map(|符号| (符号, None)).collect();
        if !已访问.insert(模块名.to_string()) {
            return Ok(符号列表);
        }
        if !数据.导入列表.iter().any(|i| i.是否聚合) {
            return Ok(符号列表);
        }
        // 对外名 → 原始身份：同一原始符号（钻石依赖多条路径到达）去重，不视为冲突
        let mut 已导出: HashMap<String, String> = HashMap::new();
        for 聚合 in 数据.导入列表.iter().filter(|i| i.是否聚合) {
            let 目标键 = if 聚合.是否相对 {
                聚合.解析后键.clone().unwrap_or_else(|| 聚合.模块路径.join("."))
            } else {
                聚合.模块路径.join(".")
            };
            let 目标符号列表 = match self.提取公开符号_内(&目标键, &目标键, 已访问) {
                Ok(列表) => 列表,
                Err(_) => {
                    // 🆕 标准库聚合导入（展开/别名）：标准库非「已加载模块」，但 标准库元数据 单一真相
                    //   提供其公开成员名；以「重定向到全局预注册 数学.成员」的 上游原全名 合成占位符号，
                    //   真实类型/索引由调用点 展开别名映射 归一化到真实 stdlib 符号（无需在此合成类型，见 语义分析器.rs:689）。
                    if crate::标准库元数据::按模块分组().iter().any(|(m, _)| *m == 目标键) {
                        self.合成标准库聚合符号(&目标键)
                    } else {
                        continue;
                    }
                }
            };
            let 末段 = 聚合.模块路径.last().cloned().unwrap_or_else(|| 目标键.clone());
            for (符号, 上游原全名) in 目标符号列表 {
                if !符号.是否公开 { continue; } // 私有绝不重导出
                let 内部名 = 符号.名称.clone();
                let 对外名 = Self::聚合对外名(聚合, &末段, &内部名);
                // 原全名：嵌套聚合沿用上游（真实函数全名）；本层首次导出时按「目标键.内部名」构造
                let 原全名 = 上游原全名.unwrap_or_else(|| format!("{}.{}", 目标键, 内部名));
                let 身份 = format!("{}::{}", 目标键, 内部名);
                if 已导出.contains_key(&对外名) {
                    continue; // 已由同一/其他来源导出；异源同名由语义层报告
                }
                已导出.insert(对外名.clone(), 身份);
                let mut 新符号 = 符号.clone();
                新符号.名称 = 对外名;
                新符号.是否公开 = true;
                符号列表.push((新符号, Some(原全名)));
            }
        }
        Ok(符号列表)
    }

    /// 🆕 标准库聚合导入（展开/别名）支撑：从 标准库元数据 单一真相合成聚合成员符号。
    /// 仅合成「名称 + 上游原全名(数学.成员)」占位；真实类型/索引由调用点 展开别名映射
    /// 归一化到全局预注册符号（语义分析器.rs:689），故无需在此合成类型。
    /// 模块公开函数 / 并发函数 / 句柄方法 视为可聚合的公开成员（与 类型推导::预注册内置模块符号 注入口径一致）。
    fn 合成标准库聚合符号(&self, 模块名: &str) -> Vec<(符号, Option<String>)> {
        let mut 列表 = Vec::new();
        for (模块, 条目组) in crate::标准库元数据::按模块分组() {
            if 模块 != 模块名 { continue; }
            for 条目 in 条目组 {
                let 是公开成员 = matches!(
                    条目.种类,
                    标准库种类::模块公开函数 | 标准库种类::并发函数 | 标准库种类::句柄方法
                );
                if !是公开成员 { continue; }
                let 符号 = 符号 {
                    名称: 条目.函数名.to_string(),
                    符号种类: 符号种类::函数 {
                        是否公开: true,
                        签名: 函数签名 {
                            // ⚠ 形参**元数**必须与真实标准库成员一致：裸名形态（展开）经标识符调用分支
                            //   在**归一化之前**先做元数校验（与「别名.成员」模块调用分支不同，后者先归一化）。
                            //   类型留 未推断 即可——降级层经 展开别名映射 重定向到全局预注册的 数学.成员
                            //   （类型为真），此处仅占位。元数写 0 会误报「实参过多」。
                            形参类型: vec![类型信息::未推断; 条目.形参.len()],
                            形参名称: 条目.形参.iter().map(|(n, _)| n.to_string()).collect(),
                            返回类型: Some(类型信息::未推断),
                        },
                    },
                    是否公开: true,
                    是否可变: false,
                    定义位置: 源码位置::新(模块名.to_string(), 0, 0),
                    所属模块: Some(模块名.to_string()),
                };
                let 原全名 = format!("{}.{}", 模块名, 条目.函数名);
                列表.push((符号, Some(原全名)));
            }
        }
        列表
    }

    pub fn 提取符号列表(&self, 模块: &[模块数据], 注册模块名: &str) -> Vec<符号> {
        let mut 符号列表 = Vec::new();
        for 数据 in 模块 {
            let 模块名 = 注册模块名;
            for 定义 in &数据.顶层定义列表 {
                match 定义 {
                    顶层定义::函数定义(func) => {
                        // 🆕 私有顶层函数也注册进符号表（全限定键），仅对外部模块不可见；
                        // 公开函数保持裸名（保持现有模块调用机制不变）。
                        let 全限定名 = format!("{}.{}", 模块名, func.名称);
                        let 形参类型: Vec<类型信息> = func.形参列表.iter().map(|p| self.解析形参类型(p)).collect();
                        let 形参名称: Vec<String> = func.形参列表.iter().map(|p| p.名称.clone()).collect();
                        let 返回类型 = self.解析顶层返回类型(&func.返回类型);
                        符号列表.push(符号 { 名称: if func.是否私有 { 全限定名 } else { func.名称.clone() }, 符号种类: 符号种类::函数 { 签名: 函数签名 { 形参类型, 形参名称, 返回类型 }, 是否公开: true }, 是否公开: !func.是否私有, 是否可变: false, 定义位置: func.位置.clone(), 所属模块: Some(模块名.to_string()) });
                    }
                    顶层定义::结构体定义(结构体) => {
                        // 🆕 私有结构体也注册（全限定键）
                        let 全限定名 = format!("{}.{}", 模块名, 结构体.名称);
                        let 字段列表: Vec<字段符号> = 结构体.成员列表.iter().filter_map(|m| match m { 结构体成员::字段 { 名称, 类型标注, 初始值, 是否私有, 是否可变, .. } => Some(字段符号 { 名称: 名称.clone(), 类型: self.推断字段类型(类型标注, 初始值), 是否公开: !*是否私有, 是否可变: *是否可变 }), _ => None }).collect();
                        // 提取结构体方法（对齐 声明分析 方法注册：成员列表中 方法/初始化 两种定义）
                        let 方法列表: Vec<函数符号> = 结构体.成员列表.iter().filter_map(|m| match m {
                            结构体成员::方法(f) | 结构体成员::初始化(f) => {
                                let 形参类型: Vec<类型信息> = f.形参列表.iter().map(|p| self.解析形参类型(p)).collect();
                                let 返回类型 = self.解析顶层返回类型(&f.返回类型);
                                Some(函数符号 { 名称: f.名称.clone(), 形参类型, 返回类型, 是否公开: true })
                            }
                            _ => None,
                        }).collect();
                        符号列表.push(符号 { 名称: if 结构体.是否私有 { 全限定名 } else { 结构体.名称.clone() }, 符号种类: 符号种类::结构体 { 字段列表, 方法列表 }, 是否公开: !结构体.是否私有, 是否可变: false, 定义位置: 结构体.位置.clone(), 所属模块: Some(模块名.to_string()) });
                    }
                    顶层定义::枚举定义(枚举) => {
                        // 🆕 私有枚举也注册（全限定键，含其成员符号）
                        let 全限定名 = format!("{}.{}", 模块名, 枚举.名称);
                        // 对齐 声明分析.rs 枚举注册：枚举类型符号 + 枚举名.成员名 变量符号
                        let 枚举成员信息列表: Vec<枚举成员信息> = 枚举.成员列表.iter().map(|m| {
                            let 数据参数类型 = match &m.数据参数 {
                                Some(形参列表) => 形参列表.iter().map(|p| self.解析形参类型(p)).collect(),
                                None => vec![],
                            };
                            枚举成员信息 { 名称: m.名称.clone(), 数据参数类型 }
                        }).collect();
                        符号列表.push(符号 { 名称: if 枚举.是否私有 { 全限定名 } else { 枚举.名称.clone() }, 符号种类: 符号种类::枚举 { 枚举成员列表: 枚举成员信息列表 }, 是否公开: !枚举.是否私有, 是否可变: false, 定义位置: 枚举.位置.clone(), 所属模块: Some(模块名.to_string()) });
                        for 成员 in &枚举.成员列表 {
                            let 成员全限定名 = format!("{}.{}", 枚举.名称, 成员.名称);
                            let 成员私有全限定名 = format!("{}.{}.{}", 模块名, 枚举.名称, 成员.名称);
                            符号列表.push(符号 { 名称: if 枚举.是否私有 { 成员私有全限定名 } else { 成员全限定名 }, 符号种类: 符号种类::变量 { 类型: 类型信息::枚举(枚举.名称.clone()) }, 是否公开: !枚举.是否私有, 是否可变: false, 定义位置: 枚举.位置.clone(), 所属模块: Some(模块名.to_string()) });
                        }
                    }
                    顶层定义::变量声明(v) => {
                        // 🆕 私有变量也注册（全限定键）。类型从 类型标注/初始值字面量 推断。
                        let 全限定名 = format!("{}.{}", 模块名, v.名称);
                        let 全局变量类型 = self.推断字段类型(&v.类型标注, &v.初始值);
                        符号列表.push(符号 {
                            名称: if v.是否私有 { 全限定名 } else { v.名称.clone() },
                            符号种类: 符号种类::变量 { 类型: 全局变量类型 },
                            是否公开: !v.是否私有,
                            是否可变: true,
                            定义位置: v.位置.clone(),
                            所属模块: Some(模块名.to_string()),
                        });
                    }
                    顶层定义::常量声明(c) => {
                        // 🆕 私有常量也注册（全限定键）
                        let 全限定名 = format!("{}.{}", 模块名, c.名称);
                        let 常量类型 = self.从表达式字面值推断类型(&c.初始值);
                        符号列表.push(符号 {
                            名称: if c.是否私有 { 全限定名 } else { c.名称.clone() },
                            符号种类: 符号种类::变量 { 类型: 常量类型 },
                            是否公开: !c.是否私有,
                            是否可变: false,
                            定义位置: c.位置.clone(),
                            所属模块: Some(模块名.to_string()),
                        });
                    }
                    顶层定义::接口定义(接口) => {
                        // 🆕 私有接口也注册（全限定键）
                        let 全限定名 = format!("{}.{}", 模块名, 接口.名称);
                        // 对齐 声明分析.rs 接口注册
                        let 方法声明列表: Vec<方法声明> = 接口.方法声明列表.iter().map(|m| 方法声明 {
                            名称: m.名称.clone(),
                            形参类型: m.形参列表.iter().map(|p| self.解析形参类型(p)).collect(),
                            返回类型: self.解析顶层返回类型(&m.返回类型),
                        }).collect();
                        符号列表.push(符号 { 名称: if 接口.是否私有 { 全限定名 } else { 接口.名称.clone() }, 符号种类: 符号种类::接口 { 方法声明列表 }, 是否公开: !接口.是否私有, 是否可变: false, 定义位置: 接口.位置.clone(), 所属模块: Some(模块名.to_string()) });
                    }
                    顶层定义::外部块(外部块) => {
                        for 项 in &外部块.项列表 {
                            match 项 {
                                外部块的项::外部函数定义(外部函数) => {
                                    let 形参类型: Vec<类型信息> = 外部函数.形参列表.iter().map(|p| self.解析形参类型(p)).collect();
                                    let 返回类型 = self.解析顶层返回类型(&外部函数.返回类型);
                                    // 🆕 命名空间前缀补全：全名 + 裸名双键注册（跨文件 前缀.名 / 同文件 裸名）
                                    let 全名 = if let Some(前缀) = &外部函数.命名空间前缀 {
                                        format!("{}.{}", 前缀, 外部函数.名称)
                                    } else { 外部函数.名称.clone() };
                                    let 裸名 = 外部函数.名称.clone();
                                    self.注册外部函数符号(&mut 符号列表, &全名, &形参类型, &返回类型, &外部函数.位置);
                                    if 全名 != 裸名 { self.注册外部函数符号(&mut 符号列表, &裸名, &形参类型, &返回类型, &外部函数.位置); }
                                }
                                外部块的项::外部结构体定义(外部结构体) => {
                                    // 【字段类型须真实解析】外部结构体成员带 类型标注（`横坐标: 整数`），
                                    // 原实现一律填 未推断，跨文件导入后 `位置.横坐标` 拿不到字段类型，
                                    // 读取退化为 空值。此处按标注解析，与普通结构体字段登记保持一致。
                                    let 字段列表: Vec<字段符号> = 外部结构体.字段列表.iter().map(|f| 字段符号 { 名称: f.名称.clone(), 类型: self.类型表达式转类型信息(&f.类型标注), 是否公开: true, 是否可变: true }).collect();
                                    符号列表.push(符号 { 名称: 外部结构体.名称.clone(), 符号种类: 符号种类::结构体 { 字段列表, 方法列表: vec![] }, 是否公开: true, 是否可变: false, 定义位置: 外部结构体.位置.clone(), 所属模块: Some(模块名.to_string()) });
                                }
                                外部块的项::外部变量定义(外部变量) => {
                                    let 返回类型 = self.解析顶层返回类型(&Some(外部变量.类型.clone()));
                                    let 全名 = if let Some(前缀) = &外部变量.命名空间前缀 {
                                        format!("{}.{}", 前缀, 外部变量.名称)
                                    } else { 外部变量.名称.clone() };
                                    let 裸名 = 外部变量.名称.clone();
                                    self.注册外部函数符号(&mut 符号列表, &全名, &vec![], &返回类型, &外部变量.位置);
                                    if 全名 != 裸名 { self.注册外部函数符号(&mut 符号列表, &裸名, &vec![], &返回类型, &外部变量.位置); }
                                }
                                外部块的项::外部库声明(_库) => {
                                    // 库声明不产生符号，由语义分析器处理
                                }
                                外部块的项::外部函数映射声明(_映射) => {
                                    // 【关联行不产生符号】`中文别名 关联 C符号名` 是「别名→C 符号」的纯映射元数据，
                                    // 真实签名由同块内的 外部函数定义（`名(形参) 返回类型:`）提供。
                                    //
                                    // 原实现在此按 中文别名 注册了一条 形参=[]、返回类型=None 的空签名函数符号，
                                    // 与随后（或此前）由 外部函数定义 注册的真实签名同名共存。跨文件导入时调用方
                                    // 命中这条空签名 → 返回类型被判定为 未推断，文本返回值退化（`问候("世界")`
                                    // 拿回入参回显而非 `你好, 世界!`）。关联行与签名行「无顺序要求」，故不能靠
                                    // 顺序覆盖消除，必须彻底不注册。
                                    //
                                    // 注：语义分析器 仍从 外部函数映射声明 读取 C 符号名完成 别名→c符号 绑定，
                                    // 此处只是不再向「符号表」贡献可调用函数符号。
                                }
                                外部块的项::外部变量映射声明(_) => {}
                                外部块的项::外部常量(_) => {}
                            }
                        }
                    }
                    顶层定义::导出块(导出块) => {
                        for 项 in &导出块.项列表 {
                            match 项 {
                                导出块的项::导出函数(函数) => {
                                    let 形参类型: Vec<类型信息> = 函数.形参列表.iter().map(|p| self.解析形参类型(p)).collect();
                                    let 形参名称: Vec<String> = 函数.形参列表.iter().map(|p| p.名称.clone()).collect();
                                    let 返回类型 = self.解析顶层返回类型(&函数.返回类型);
                                    符号列表.push(符号 { 名称: 函数.名称.clone(), 符号种类: 符号种类::函数 { 签名: 函数签名 { 形参类型, 形参名称, 返回类型 }, 是否公开: true }, 是否公开: true, 是否可变: false, 定义位置: 函数.位置.clone(), 所属模块: Some(模块名.to_string()) });
                                }
                                导出块的项::导出变量(_) => {}
                                导出块的项::导出引用(名称) => {
                                    // 裸名导出：标记此前已声明的同名符号为公开。
                                    // 🆕 兼容私有全限定键：若按裸名未命中，则尝试 模块名.裸名 全限定键。
                                    for 符号 in 符号列表.iter_mut() {
                                        if 符号.名称 == *名称 || 符号.名称 == format!("{}.{}", 模块名, 名称) {
                                            符号.是否公开 = true;
                                            break;
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
        符号列表
    }

    /// 🆕 注册外部函数符号（跨文件 前缀.名 与 同文件 裸名 共用）
    fn 注册外部函数符号(&self, 符号列表: &mut Vec<符号>, 名称: &str, 形参类型: &[类型信息], 返回类型: &Option<类型信息>, 位置: &源码位置) {
        if 名称.is_empty() { return; }
        符号列表.push(符号 {
            名称: 名称.to_string(),
            符号种类: 符号种类::函数 { 签名: 函数签名 { 形参类型: 形参类型.to_vec(), 形参名称: vec![], 返回类型: 返回类型.clone() }, 是否公开: true },
            是否公开: true, 是否可变: false, 定义位置: 位置.clone(),
            所属模块: None,
        });
    }

    /// 🆕 2026-09-04 FFI 隔离补全：FFI 精确类型名 → 核心类型（仅类型信息侧）。
    /// 与 语义分析器::FFI精确类型码 的类型侧同源（语义分析器 兼持精确码，模块加载器 只需类型）。
    /// 普通代码不写这些名字（外部块声明层专属），故仅在 外部块 跨模块符号收集时命中。
    fn FFI名到核心类型(名称: &str) -> Option<类型信息> {
        // ★单源★ 表在 `名称身份::FFI标量类型表`（取代原手写 3 组 match；此前与
        // 语义分析器的表内容漂移——本表曾多出 有符号字符/无符号字符）。此处仅桥接整数/小数两类，
        // 逻辑/文本/空值 由调用方前置分支处理，保持行为等价。
        let (类型文本, _码) = crate::名称身份::FFI标量类型(名称)?;
        match 类型文本 {
            "整数" => Some(类型信息::整数类型()),
            "小数" => Some(类型信息::小数类型()),
            _ => None,
        }
    }

    /// 把语法层 类型表达式 递归转为语义 类型信息。
    /// 模块加载器运行在 语法分析产物 上、无法查符号表，故用户自定义命名类型（结构体/接口/枚举）
    /// 按「结构体占位」处理（与 类型推导::解析类型标注 的回退分支一致），下游字段访问会据结构体名
    /// 从符号表解析真实字段。此前的实现只认内置基本类型，跨模块返回 数组<学生>/映射<…>/自定义类型 的
    /// 函数返回类型被丢成 未推断，导致调用方拿不到成员类型（如「生.学号」无法访问）。
    fn 类型表达式转类型信息(&self, 类型: &类型表达式) -> 类型信息 {
        match 类型 {
            类型表达式::基本类型(名称) => match 名称.as_str() {
                "整数" => 类型信息::整数类型(),
                "小数" => 类型信息::小数类型(),
                "文本" => 类型信息::文本类型(),
                "逻辑" => 类型信息::逻辑类型(),
                "空值" => 类型信息::基本型(基本类型::空值),
                "数组" => 类型信息::数组(Box::new(类型信息::未推断)),
                "映射" => 类型信息::映射(Box::new(类型信息::未推断), Box::new(类型信息::未推断)),
                // FFI 精确名（外部块声明层专属）→ 核心类型（2026-09-04 隔离补全）
                _ => match Self::FFI名到核心类型(名称) {
                    Some(t) => t,
                    // 用户自定义命名类型（结构体/接口/枚举）→ 结构体占位（下游据名解析）
                    None => 类型信息::结构体(名称.clone(), vec![]),
                },
            },
            类型表达式::数组(元素类型) => {
                类型信息::数组(Box::new(self.类型表达式转类型信息(元素类型)))
            }
            类型表达式::映射(键类型, 值类型) => {
                类型信息::映射(
                    Box::new(self.类型表达式转类型信息(键类型)),
                    Box::new(self.类型表达式转类型信息(值类型)),
                )
            }
            类型表达式::泛型 { 名称, 类型参数 } => {
                let 参数: Vec<类型信息> = 类型参数.iter().map(|t| self.类型表达式转类型信息(t)).collect();
                类型信息::结构体(名称.clone(), 参数)
            }
            类型表达式::任意类型 { 标记名称: _, 约束范围 } => {
                let 约束: Vec<类型信息> = 约束范围.iter().map(|t| self.类型表达式转类型信息(t)).collect();
                类型信息::任意类型 { 约束范围: 约束, 变量索引: 0 }
            }
            类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
                let 参数: Vec<类型信息> = 参数类型列表.iter().map(|t| self.类型表达式转类型信息(t)).collect();
                let 返回 = self.类型表达式转类型信息(返回类型);
                类型信息::函数类型(参数, Box::new(返回))
            }
        }
    }

    fn 解析形参类型(&self, 形参: &crate::语法分析::形参) -> 类型信息 {
        match &形参.类型标注 {
            Some(类型) => self.类型表达式转类型信息(类型),
            None => 类型信息::未推断,
        }
    }

    fn 解析顶层返回类型(&self, 返回类型: &Option<类型表达式>) -> Option<类型信息> {
        match 返回类型 {
            Some(类型) => Some(self.类型表达式转类型信息(类型)),
            None => None,
        }
    }

    fn 推断字段类型(&self, 类型标注: &Option<类型表达式>, 初始值: &Option<crate::语法分析::表达式>) -> 类型信息 {
        if let Some(类型) = 类型标注 {
            return self.类型表达式转类型信息(类型);
        }
        if let Some(初始表达式) = 初始值 {
            self.从表达式字面值推断类型(初始表达式)
        } else { 类型信息::未推断 }
    }

    fn 从表达式字面值推断类型(&self, 表达式: &crate::语法分析::表达式) -> 类型信息 {
        match 表达式 { crate::语法分析::表达式::字面值(字面) => self.从语法字面值推断(字面), _ => 类型信息::未推断 }
    }

    fn 从语法字面值推断(&self, 字面: &crate::语法分析::字面值) -> 类型信息 {
        use crate::语法分析::字面值;
        match 字面 {
            字面值::整数(_) => 类型信息::整数类型(),
            字面值::小数(_) => 类型信息::小数类型(),
            字面值::文本(_) => 类型信息::文本类型(),
            字面值::逻辑(_) => 类型信息::逻辑类型(),
            字面值::空值 => 类型信息::空值类型(),
            字面值::数组(元素列表, 元素类型标注) => {
                // 优先用显式元素类型标注；否则从首个元素字面量推断（空数组→未推断元素）
                let 元素类型 = if let Some(标注) = 元素类型标注 {
                    self.类型表达式转类型信息(标注)
                } else if let Some(首个) = 元素列表.first() {
                    self.从表达式字面值推断类型(首个)
                } else {
                    类型信息::未推断
                };
                类型信息::数组(Box::new(元素类型))
            }
            字面值::映射(键值对列表) => {
                // ★ 2026-10-02（**F30 修复**）：原实现**只取首对**推断键/值类型 ✗ ——
                //   与 `语义/类型推断.rs` 的映射字面量分支**同一根因**（模块级字面量走本函数 ✓）：
                //   异构字面量（如 `{"甲": {…}, "丙": [1,2,3]}`）的值类型被推成**首对类型**（映射 ✗）
                //   ⇒ 取回的数组被按映射静态分派 ⇒ `.长度()` 恒 0 ✗（静默错值，双模一致 ✗）。
                //   修法：**全对求统一类型**，出现不同 ⇒ 未推断（运行时按实际类型分派 ✓）；空映射双向未推断 ✓。
                if 键值对列表.is_empty() {
                    return 类型信息::映射(Box::new(类型信息::未推断), Box::new(类型信息::未推断));
                }
                let 键类型集: Vec<类型信息> = 键值对列表.iter().map(|(k, _)| self.从表达式字面值推断类型(k)).collect();
                let 值类型集: Vec<类型信息> = 键值对列表.iter().map(|(_, v)| self.从表达式字面值推断类型(v)).collect();
                let 统一 = |列表: &Vec<类型信息>| -> 类型信息 {
                    let 首 = 列表[0].clone();
                    if 列表.iter().all(|t| *t == 首) { 首 } else { 类型信息::未推断 }
                };
                类型信息::映射(Box::new(统一(&键类型集)), Box::new(统一(&值类型集)))
            }
        }
    }
}
