// 文件: 前端/src/标准库门面生成.rs
// 职责: ★门面机械生成器★ —— 从 标准库元数据.rs 单一真相机械投影出 标准库/*.智 门面。
//
// 设计要点（彻底单源）：
//   ① 门面是「内建跳过」文件，不参与编译/解释，仅作 API 参考；其存在意义只是人类可读投影。
//   ② 本生成器是元数据 → 门面 的唯一投影通道：函数签名来自元数据，函数体一律
//      `返回 模块.函数(实参)` 形式（由定义名 + 模块 机械推导），因此：
//        - 裸融合名（系统网络XXX / 系统XXX）从机制上不可能出现；
//        - 函数体接错线（如 连接设置超时 体接 连接设置无延迟）从机制上不可能出现（体=定义名推导）。
//   ③ 手改门面会被下次生成覆盖（git 可见），从机制上杜绝「双份手写声明漂移」。
//   ④ 全部落在共享前端层，解释/编译双模式零改动、零 parity 风险（门面本就被两模跳过）。
//
// 跨平台：输出目录经 env!(CARGO_MANIFEST_DIR) 推导（编译期固定为 前端 源目录），
//         join("../标准库") 在 Windows/macOS/Linux 均由 std::path 规范化，无需手写 cfg。

use crate::标准库元数据::{标准库条目, 标准库种类, 按模块分组};
use std::fs;
use std::path::{Path, PathBuf};

/// 生成全部 7 个模块门面，返回 (模块名, 文件内容) 列表。
pub fn 生成所有门面() -> Vec<(String, String)> {
    按模块分组()
        .into_iter()
        .map(|(模块, 条目)| (模块.to_string(), 生成模块内容(模块, &条目)))
        .collect()
}

/// 生成并写入到指定输出目录（默认应为 源码/标准库）。目录不存在时自动创建。
pub fn 生成并写入(输出目录: &str) -> Result<(), String> {
    let 目录 = Path::new(输出目录);
    fs::create_dir_all(目录).map_err(|e| format!("创建目录 {} 失败: {}", 目录.display(), e))?;
    for (模块, 内容) in 生成所有门面() {
        let 路径 = 目录.join(format!("{}.智", 模块));
        fs::write(&路径, 内容).map_err(|e| format!("写入 {} 失败: {}", 路径.display(), e))?;
        eprintln!("[门面生成] 已生成 标准库/{}.智", 模块);
    }
    Ok(())
}

/// 推导默认输出目录：`<仓库根>/源码/标准库`。
///
/// ⚠ 2026-11-16 发布安全：**不得用 `env!("CARGO_MANIFEST_DIR")`**。
///   该宏把编译期绝对路径**固化成字符串常量**编进二进制（`--remap-path-prefix` 只管调试信息里的
///   路径记录，管不到这种字面量）⇒ 发布出去的 exe 里能读到 `d:\...\智语言\源码\前端`，
///   泄漏开发者目录结构（实测 `智语言开发套件.exe` 因此残留仓库绝对路径）。
///   故改为**运行时**推导：从当前工作目录向上找含 `Cargo.toml` 的仓库根（CLI 约定在仓库根执行）。
pub fn 默认输出目录() -> String {
    match 推导仓库根() {
        Some(根) => 根.join("源码").join("标准库").to_string_lossy().into_owned(),
        // 找不到仓库根（例如从别处调用）：回退相对路径，由调用方显式指定更稳妥
        None => Path::new("源码").join("标准库").to_string_lossy().into_owned(),
    }
}

/// 从当前工作目录逐级向上找含 `Cargo.toml` 的目录（**运行时**推导，避免编译期路径固化）。
pub(crate) fn 推导仓库根() -> Option<PathBuf> {
    let mut 目录 = std::env::current_dir().ok()?;
    loop {
        if 目录.join("Cargo.toml").is_file() {
            return Some(目录);
        }
        if !目录.pop() {
            return None;
        }
    }
}

fn 生成模块内容(模块: &str, 条目: &[&标准库条目]) -> String {
    let mut s = String::new();
    s.push_str(&format!("// 文件: 标准库/{}.智\n", 模块));
    s.push_str("// ══ 内建模块 API 说明（随包参考，自动生成，请勿手改）══\n");
    s.push_str("// 身份: 本文件是「内建标准库门面」，被编译器与解释器同时「内建跳过」，不参与编译/解释，函数体不被求值。\n");
    s.push_str("// 作用: 随开发套件分发的 API 参考——每个函数都给出可直接照抄的签名与用法。\n");
    s.push_str("// 写法: 函数体一律 `返回 模块.函数(实参)`（canonical 名字标注）。数学内建类型方法按用户可见签名展示——\n");
    s.push_str("//       写在所属结构体内、去「自身」（自身由调用对象隐式提供，见《语言参考》2.6.7 节），如 结构体 精确小数(值): 加法(精确小数 另一个) 精确小数: 返回 数学.精确小数.加法(另一个) 结束。\n");
    s.push_str("// 说明: 真实实现内置于运行时；完整 API 说明见随包文档 `文档/标准库说明.文档`。\n");
    s.push_str(&format!("// {}\n\n", 模块说明(模块)));

    // 分派：方法类条目（数学内建类型方法 + 句柄方法）→ 所属结构体壳子块；
    // 其余（模块公开函数/并发函数）→ 平面函数。
    let (方法条目, 函数条目): (Vec<&标准库条目>, Vec<&标准库条目>) =
        条目.iter().copied().partition(|e| {
            e.种类 == 标准库种类::数学内建方法 || e.种类 == 标准库种类::句柄方法
        });

    for 条 in 函数条目 {
        s.push_str(&生成函数(条));
        s.push('\n');
    }

    // 数学内建类型方法按所属类型分组，包成完整结构体壳子（结构体形参 + 私有字段 + 初始化 + 方法）。
    let mut 类型顺序: Vec<&'static str> = Vec::new();
    let mut 类型方法表: std::collections::HashMap<&'static str, Vec<&标准库条目>> =
        std::collections::HashMap::new();
    for 条 in &方法条目 {
        let 类型名 = 条.函数名.split('.').next().unwrap_or(条.函数名);
        if !类型顺序.contains(&类型名) {
            类型顺序.push(类型名);
        }
        类型方法表.entry(类型名).or_default().push(条);
    }
    for 类型名 in 类型顺序 {
        if let Some(方法列表) = 类型方法表.get(&类型名) {
            s.push_str(&生成结构体块(类型名, 方法列表));
            s.push('\n');
        }
    }
    s
}

/// 完整结构体壳子：`结构体 X(形参):` + 私有字段 + 初始化 + 方法（依据规范 §5.1.11~5.1.15）。
/// 壳子数据来自 标准库元数据.rs::内置结构体壳子（单源）；方法由元数据投影。
fn 生成结构体块(类型名: &str, 方法条目: &[&标准库条目]) -> String {
    let mut s = String::new();
    let 壳子 = crate::标准库元数据::查结构体壳子(类型名);
    let 结构体形参 = 壳子.map(|c| c.结构体形参).unwrap_or("");
    let 构造内部名 = 壳子.map(|c| c.构造内部名).unwrap_or("");
    let 字段列表 = 壳子.map(|c| c.字段列表).unwrap_or(&[]);
    // 形参名 = 结构体形参声明 末词（如 "任意<整数|小数|文本> 值" → 值）
    let 形参名 = 结构体形参.rsplit(' ').next().unwrap_or("值").trim();

    // 数学内建类型为数值结构体；并发/网络句柄为不透明句柄结构体，统称「内置结构体」
    s.push_str(&format!("// 内置结构体：{}\n", 类型名));
    if 结构体形参.is_empty() {
        s.push_str(&format!("结构体 {}():\n", 类型名));
    } else {
        s.push_str(&format!("结构体 {}({}):\n", 类型名, 结构体形参));
    }
    for (名, 类型, 初始值) in 字段列表 {
        s.push_str(&format!("    私有 {} {} = {}\n", 类型, 名, 初始值));
    }
    if !构造内部名.is_empty() {
        s.push_str(&format!(
            "    初始化():\n        返回 {}({})\n    结束\n",
            构造内部名, 形参名
        ));
    }
    for 条 in 方法条目 {
        s.push_str(&生成方法(条));
    }
    s.push_str("结束\n");
    s
}

/// 结构体内的方法投影：方法名用短名（去「类型.」前缀）、去「自身」、缩进 4 空格，
/// 函数体仍为 canonical `模块.类型.方法(非自身实参)` 标注。
fn 生成方法(条: &标准库条目) -> String {
    let mut s = String::new();
    if let Some(文档) = 条.文档 {
        s.push_str(&format!("    // {}\n", 文档));
    } else {
        s.push_str(&format!("    // 说明见 文档/标准库说明.文档：{}.{}\n", 条.模块, 条.函数名));
    }
    let 短名 = 条.函数名.rsplit('.').next().unwrap_or(条.函数名);
    let 去自身 = 条.形参.first().map_or(false, |f| f.0 == "自身");
    let 可见形参 = if 去自身 { &条.形参[1..] } else { &条.形参[..] };
    let 可见默认 = if 去自身 { 条.默认值.map(|d| &d[1..]) } else { 条.默认值 };
    let 形参串 = 格式化形参(可见形参, 可见默认);
    let 签名 = match 条.返回 {
        Some(返) => format!("    {}({}) {}:\n", 短名, 形参串, 返),
        None => format!("    {}({}):\n", 短名, 形参串),
    };
    s.push_str(&签名);
    let 实参串 = 可见形参.iter().map(|(名, _)| *名).collect::<Vec<_>>().join(", ");
    let 体 = match 条.返回 {
        Some(_) => format!("        返回 {}.{}({})\n", 条.模块, 条.函数名, 实参串),
        None => format!("        {}.{}({})\n", 条.模块, 条.函数名, 实参串),
    };
    s.push_str(&体);
    s.push_str("    结束\n");
    s
}

fn 生成函数(条: &标准库条目) -> String {
    let mut s = String::new();
    // 文档注释：来自元数据 文档 字段；无则回退为**随包文档**的定位指针
    // （不写 Rust 源码路径：门面随开发套件分发给用户，源码路径用户手上不存在、查不到）
    if let Some(文档) = 条.文档 {
        s.push_str(&format!("// {}\n", 文档));
    } else {
        s.push_str(&format!("// 说明见 文档/标准库说明.文档：{}.{}\n", 条.模块, 条.函数名));
    }
    // 数学内建类型方法：门面展示用户可见签名——去「自身」（自身由调用对象隐式提供，规范 2.6.7）。
    // 门面函数体只传非自身实参，对应 精确小数.加法(精确小数 另一个) → 返回 数学.精确小数.加法(另一个)。
    let 去自身 = 条.种类 == 标准库种类::数学内建方法
        && 条.形参.first().map_or(false, |f| f.0 == "自身");
    let 可见形参 = if 去自身 { &条.形参[1..] } else { &条.形参[..] };
    let 可见默认 = if 去自身 { 条.默认值.map(|d| &d[1..]) } else { 条.默认值 };
    // 函数签名
    let 形参串 = 格式化形参(可见形参, 可见默认);
    // 语法：方法定义以冒号结尾（`名(形参) 返回类型:` / `名(形参):`），与 智语言 方法定义语法一致
    let 签名 = match 条.返回 {
        Some(返) => format!("{}({}) {}:\n", 条.函数名, 形参串, 返),
        None => format!("{}({}):\n", 条.函数名, 形参串),
    };
    s.push_str(&签名);
    // 函数体：由定义名 + 模块 机械推导（杜绝裸名/接错线）；数学内建方法仅传非自身实参
    let 实参串 = 可见形参.iter().map(|(名, _)| *名).collect::<Vec<_>>().join(", ");
    let 体 = match 条.返回 {
        Some(_) => format!("    返回 {}.{}({})\n", 条.模块, 条.函数名, 实参串),
        None => format!("    {}.{}({})\n", 条.模块, 条.函数名, 实参串),
    };
    s.push_str(&体);
    s.push_str("结束\n");
    s
}

/// 形参列表格式化：类型 名 [= 默认值]。
/// 调用方对数学内建方法已传入「去自身」的可见形参与对应默认值。
fn 格式化形参(形参: &[(&'static str, &'static str)], 默认: Option<&'static [&'static str]>) -> String {
    let 默认表 = 默认.unwrap_or(&[]);
    形参
        .iter()
        .enumerate()
        .map(|(i, (名, 类型))| {
            let 默认文本 = 默认表
                .get(i)
                .filter(|d| !d.is_empty())
                .map(|d| format!(" = {}", d))
                .unwrap_or_default();
            format!("{} {}{}", 类型, 名, 默认文本)
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// 各模块门面头部说明（架构性注释，单源投影模板的一部分）
