    /// 🆕 解析点分的外部标识符路径（C 符号名，可含 `.` 如 sqlite3.open，或裸名 open）
    ///
    /// ★只有 `.` 能连接后续段。此前实现无条件连吃相邻标识符，导致
    /// `导入 样例库 智语言`（智语言=扁平契约逃生舱关键字）被拼成库名 `样例库智语言`，
    /// 进而生成非 ASCII 的 `#[link(name=..)]`/DLL 名而链接失败。
    fn 解析外部标识符路径(&mut self) -> String {
        let mut 路径 = String::new();
        // 首段
        match self.当前类型().cloned() {
            Some(词条类型::外部标识符(s)) | Some(词条类型::标识符(s)) => {
                self.消耗();
                路径.push_str(&s);
            }
            _ => return 路径,
        }
        // 后续段：必须由 `.` 引导
        while matches!(self.当前类型(), Some(词条类型::点)) {
            self.消耗();
            路径.push('.');
            match self.当前类型().cloned() {
                Some(词条类型::外部标识符(s)) | Some(词条类型::标识符(s)) => {
                    self.消耗();
                    路径.push_str(&s);
                }
                _ => break,
            }
        }
        路径
    }

