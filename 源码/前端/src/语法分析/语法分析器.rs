#[derive(Debug, Clone)]
pub enum 顶层定义 {
    变量声明(变量声明),
    常量声明(常量声明),
    函数定义(函数定义),
    结构体定义(结构体定义),
    枚举定义(枚举定义),
    接口定义(接口定义),
    外部块(外部块定义),
    导出块(导出块定义),
}

impl 顶层定义 {
    /// 🆕 文档命令：提取定义类别与名称（用于关联文档注释）；空名（错误兜底节点）返回 None
    pub(crate) fn 元数据(&self) -> Option<(文档类别, String)> {
        let 结果 = match self {
            顶层定义::变量声明(v) => Some((文档类别::变量, v.名称.clone())),
            顶层定义::常量声明(c) => Some((文档类别::常量, c.名称.clone())),
            顶层定义::函数定义(f) => Some((文档类别::函数, f.名称.clone())),
            顶层定义::结构体定义(s) => Some((文档类别::结构体, s.名称.clone())),
            顶层定义::枚举定义(e) => Some((文档类别::枚举, e.名称.clone())),
            顶层定义::接口定义(i) => Some((文档类别::接口, i.名称.clone())),
            顶层定义::外部块(_) | 顶层定义::导出块(_) => None,
        };
        match 结果 {
            Some((类别, 名称)) if !名称.is_empty() => Some((类别, 名称)),
            _ => None,
        }
    }

    /// 该定义的源码位置（★2026-10-17：供 §2.4.7「模块名 vs 顶层标识符」等跨模块诊断落点使用）。
    pub(crate) fn 位置(&self) -> &源码位置 {
        match self {
            顶层定义::变量声明(v) => &v.位置,
            顶层定义::常量声明(c) => &c.位置,
            顶层定义::函数定义(f) => &f.位置,
            顶层定义::结构体定义(s) => &s.位置,
            顶层定义::枚举定义(e) => &e.位置,
            顶层定义::接口定义(i) => &i.位置,
            顶层定义::外部块(b) => &b.位置,
            顶层定义::导出块(b) => &b.位置,
        }
    }
}

