    pub(crate) fn 解析条件语句(&mut self) -> 条件语句 {
        let 位置 = self.当前().unwrap().位置.clone();
        let mut 分支列表 = Vec::new();
        self.期望(词条类型::如果, "期望【如果】");
        let 条件 = self.解析表达式();
        self.期望(词条类型::冒号, "期望:");
        let 代码块 = self.解析代码块();
        分支列表.push((条件, 代码块));

        let mut 否则分支 = None;
        while self.检查(&词条类型::否则如果) {
            self.消耗();
            let 条件 = self.解析表达式();
            self.期望(词条类型::冒号, "期望:");
            let 代码块 = self.解析代码块();
            分支列表.push((条件, 代码块));
        }
        if self.匹配(&词条类型::否则) {
            self.期望(词条类型::冒号, "期望:");
            否则分支 = Some(self.解析代码块());
        }
        self.期望(词条类型::结束, "期望【结束】");

        条件语句 {
            分支列表,
            否则分支,
            位置,
        }
    }

    pub(crate) fn 解析循环相关(&mut self) -> 语句 {
        let 位置 = self.当前().unwrap().位置.clone();
        self.消耗(); // 消耗【循环】
        let 回退位置 = self.位置;
        if let Some(词条类型::标识符(_)) = self.当前类型() {
            let 变量名 = if let Some(词条类型::标识符(名称)) = self.当前类型().cloned() {
                名称
            } else {
                String::new()
            };
            self.消耗();
            // 🆕 循环引导词诊断：规范循环语法只有 `循环 条件:` 与 `循环 初始值, 条件, 步进:`，
            // 没有 `循环 当 ...` 的写法。`当` 后若紧跟另一标识符（如 `循环 当 索引 <= 数量:`），
            // 过去会被误解析成「类型标注表达式(当, 索引)」→ 条件恒假、循环静默零次执行，
            // 且报错信息让用户误以为 `当` 是个类型名。这里在语法层直接给出清晰纠正。
            // 此处已消耗「当」，当前 token 是其后的第一个（如 索引 / <=），只当后跟标识符时
            // 判定为笔误；`循环 当 <= 3:`（`当` 是普通变量）后跟运算符，不受影响。
            if 变量名 == "当" {
                if let Some(词条类型::标识符(_)) = self.当前类型() {
                    let 当位置 = 位置.clone();
                    self.诊断.报告(crate::公共数据结构::诊断信息 {
                        级别: crate::公共数据结构::诊断级别::错误,
                        错误类型: crate::公共数据结构::错误类型::语法错误,
                        描述: "循环语法中不合法跟随【当】（循环没有 `当` 引导词）".to_string(),
                        位置: 当位置,
                        帮助信息: Some("正确写法：`循环 条件:`（如 `循环 索引 <= 数量:`），或区间循环 `循环 索引 = 1, 索引 <= 数量, 索引 = 索引 + 1:`".to_string()),
                            也见于: Vec::new(),
                            是否是指: None,
                            标记说明: None,
                    });
                    // 安全跳过出错的循环条件（直到冒号），再正常解析循环体到 结束，
                    // 避免继续解析 `当` 后的残余 token 产生第二条误导性错误。
                    while let Some(t) = self.当前().cloned() {
                        if t.类型 == 词条类型::冒号 { break; }
                        self.消耗();
                    }
                    self.期望(词条类型::冒号, "期望:");
                    let 循环体 = self.解析循环体();
                    self.期望(词条类型::结束, "期望【结束】");
                    return 语句::循环语句(循环语句 {
                        初始值: None,
                        条件: 表达式::字面值(字面值::逻辑(false)),
                        步进: None,
                        循环体,
                        位置,
                    });
                }
            }
            if self.检查(&词条类型::赋值) {
                self.消耗();
                let 起始 = self.解析表达式();
                // ── 循环三段式不能用分号替代逗号（2.2.9）──
                if self.检查(&词条类型::分号) {
                    let 分号位置 = self.当前().unwrap().位置.clone();
                    self.诊断.报告(crate::公共数据结构::诊断信息 {
                        级别: crate::公共数据结构::诊断级别::错误,
                        错误类型: crate::公共数据结构::错误类型::语法错误,
                        描述: "循环三段式中不能使用分号，请使用逗号".to_string(),
                        位置: 分号位置,
                        帮助信息: Some("请使用逗号分隔循环的三段式，如：循环 i=1, i<=10, i+=1:".to_string()),
                            也见于: Vec::new(),
                            是否是指: None,
                            标记说明: None,
                        });
                    self.消耗();
                }
                self.期望(词条类型::逗号, "期望,");
                let 条件 = self.解析表达式();
                // 第二段后也检查分号
                if self.检查(&词条类型::分号) {
                    let 分号位置 = self.当前().unwrap().位置.clone();
                    self.诊断.报告(crate::公共数据结构::诊断信息 {
                        级别: crate::公共数据结构::诊断级别::错误,
                        错误类型: crate::公共数据结构::错误类型::语法错误,
                        描述: "循环三段式中不能使用分号，请使用逗号".to_string(),
                        位置: 分号位置,
                        帮助信息: Some("请使用逗号分隔循环的三段式".to_string()),
                            也见于: Vec::new(),
                            是否是指: None,
                            标记说明: None,
                        });
                    self.消耗();
                }
                self.期望(词条类型::逗号, "期望,");
                let 步进 = self.解析赋值语句();
                self.期望(词条类型::冒号, "期望:");
                let 循环体 = self.解析循环体();
                self.期望(词条类型::结束, "期望【结束】");
                return 语句::循环语句(循环语句 { 初始值: Some((变量名, 起始)), 条件, 步进: Some(步进), 循环体, 位置 });
            } else if self.检查(&词条类型::逗号) {
                let mut 循环变量 = vec![变量名];
                while self.匹配(&词条类型::逗号) {
                    if let Some(词条类型::标识符(名称)) = self.当前类型().cloned() {
                        循环变量.push(名称);
                        self.消耗();
                    }
                }
                self.期望(词条类型::遍历, "期望【遍历】关键字");
                let 容器 = self.解析表达式();
                self.期望(词条类型::冒号, "期望:");
                let 循环体 = self.解析循环体();
                self.期望(词条类型::结束, "期望【结束】");
                return 语句::遍历语句(遍历语句 { 循环变量, 容器, 循环体, 位置 });
            } else if self.检查(&词条类型::遍历) {
                let 循环变量 = vec![变量名];
                self.消耗();
                let 容器 = self.解析表达式();
                self.期望(词条类型::冒号, "期望:");
                let 循环体 = self.解析循环体();
                self.期望(词条类型::结束, "期望【结束】");
                return 语句::遍历语句(遍历语句 { 循环变量, 容器, 循环体, 位置 });
            } else {
                // 不是 for 循环模式，回退位置以解析 while 风格循环
                self.位置 = 回退位置;
            }
        }
        // 注意：`循环 真:` 不再特判为独立的 无限循环语句（该节点在语义分析/降级阶段
        // 无对应处理会被静默丢弃）。改为走通用路径，`真` 被解析为 字面值::逻辑(true)，
        // 生成 循环语句{条件:逻辑(true)}，复用现成的条件循环降级与 VM 判真逻辑（恒真=无限循环）。
        let 条件 = self.解析表达式();
        self.期望(词条类型::冒号, "期望:");
        let 循环体 = self.解析循环体();
        self.期望(词条类型::结束, "期望【结束】");
        语句::循环语句(循环语句 { 初始值: None, 条件, 步进: None, 循环体, 位置 })
    }

    pub(crate) fn 解析异常控制(&mut self) -> 异常控制 {
        let 位置 = self.当前().unwrap().位置.clone();
        self.期望(词条类型::捕获, "期望【捕获】");
        self.期望(词条类型::冒号, "期望:");
        let 危险块 = self.解析代码块();
        // 偏差A：异常块可选——缺省表示不捕获异常（经始终块释放资源后向上传播）
        let (存在异常块, 异常块) = if self.检查(&词条类型::异常) {
            self.消耗();
            self.期望(词条类型::冒号, "期望:");
            (true, self.解析异常块内容())
        } else {
            (false, Vec::new())
        };
        // 🆕 始终块（可选）：若当前为【始终】，则解析始终块代码
        let 始终块 = if self.检查(&词条类型::始终) {
            self.消耗();
            self.期望(词条类型::冒号, "期望:");
            self.解析代码块()
        } else {
            Vec::new()
        };
        self.期望(词条类型::结束, "期望【结束】");
        异常控制 { 危险块, 异常块, 始终块, 存在异常块, 位置 }
    }

    /// 解析异常块内的语句，在遇到【始终】或【结束】时停止（不消耗终止词条）。
    fn 解析异常块内容(&mut self) -> Vec<语句> {
        let mut 语句列表 = Vec::new();
        loop {
            while self.检查(&词条类型::换行) { self.消耗(); }
            match self.当前类型() {
                Some(词条类型::始终 | 词条类型::结束 | 词条类型::文件结束) => break,
                None => break,
                _ => {
                    let 开始位置 = self.位置;
                    // 🔒 函数体内禁止定义具名函数（具名函数只能在模块顶层）：检测 标识符( ... ) [: 类型] : 模式
                    if self.在函数体内 && self.是具名函数签名开始() {
                        let 位置 = self.当前().map(|t| t.位置.clone()).unwrap_or(crate::公共数据结构::源码位置::新("未知".into(), 0, 0));
                        let 名 = if let Some(词条类型::标识符(名)) = self.当前类型().cloned() { 名 } else { String::new() };
                        self.诊断.报告(crate::公共数据结构::诊断信息 {
                            级别: crate::公共数据结构::诊断级别::错误,
                            错误类型: crate::公共数据结构::错误类型::语法错误,
                            描述: format!("函数体内不能定义具名函数【{}】", 名),
                            位置,
                            帮助信息: Some("具名函数只能定义在模块顶层；函数体内请使用匿名函数：函数(参数) 返回类型: ... 结束（可直接返回或先赋值给变量再返回）".to_string()),
                            也见于: Vec::new(), 是否是指: None, 标记说明: None,
                        });
                        // 吃掉整段伪定义，避免后续级联误报
                        let _ = self.解析函数定义();
                        continue;
                    }
                    if let Some(语句) = self.解析语句() {
                        if self.位置 == 开始位置 {
                            // 位置未推进：强制跳过，防止无限循环/OOM
                            self.强制推进();
                        }
                        语句列表.push(语句);
                    } else if self.位置 == 开始位置 {
                        self.强制推进();
                    }
                }
            }
        }
        语句列表
    }

    pub(crate) fn 解析常量声明(&mut self) -> 常量声明 {
        let 位置 = self.当前().unwrap().位置.clone();
        self.期望(词条类型::常量, "期望【常量】");
        // 支持「常量 类型 名称 = 值」：类型标注写在名称前（与变量声明一致）
        let 类型标注 = self.是类型标注开始();
        let 有类型标注 = 类型标注.is_some() || self.检查(&词条类型::任意);
        let (类型标注, 名称) = if 有类型标注 {
            let 解析出的类型 = self.解析类型表达式();
            while self.检查(&词条类型::换行) { self.消耗(); }
            let 名称 = if let Some(词条类型::标识符(名称)) = self.当前类型().cloned() {
                self.消耗(); 名称
            } else { String::new() };
            (Some(解析出的类型), 名称)
        } else {
            let 名称 = if let Some(词条类型::标识符(名称)) = self.当前类型().cloned() {
                self.消耗(); 名称
            } else { String::new() };
            (None, 名称)
        };
        self.期望(词条类型::赋值, "期望=");
        let 初始值 = self.解析表达式();
        常量声明 { 名称, 类型标注, 初始值, 是否私有: false, 位置 }
    }

    pub(crate) fn 解析代码块(&mut self) -> Vec<语句> {
        let mut 语句列表 = Vec::new();
        loop {
            // ── 跳过换行词条（换行是语句分隔符，不是语句本身）──
            while self.检查(&词条类型::换行) {
                self.消耗();
            }
            match self.当前类型() {
                Some(词条类型::结束 | 词条类型::否则 | 词条类型::否则如果 | 词条类型::异常 | 词条类型::始终 | 词条类型::文件结束) => break,
                None => break,
                _ => {
                    let 开始位置 = self.位置;
                    // 🔒 函数体内禁止定义具名函数（具名函数只能在模块顶层）：检测 标识符( ... ) [: 类型] : 模式
                    if self.在函数体内 && self.是具名函数签名开始() {
                        let 位置 = self.当前().map(|t| t.位置.clone()).unwrap_or(crate::公共数据结构::源码位置::新("未知".into(), 0, 0));
                        let 名 = if let Some(词条类型::标识符(名)) = self.当前类型().cloned() { 名 } else { String::new() };
                        self.诊断.报告(crate::公共数据结构::诊断信息 {
                            级别: crate::公共数据结构::诊断级别::错误,
                            错误类型: crate::公共数据结构::错误类型::语法错误,
                            描述: format!("函数体内不能定义具名函数【{}】", 名),
                            位置,
                            帮助信息: Some("具名函数只能定义在模块顶层；函数体内请使用匿名函数：函数(参数) 返回类型: ... 结束（可直接返回或先赋值给变量再返回）".to_string()),
                            也见于: Vec::new(), 是否是指: None, 标记说明: None,
                        });
                        // 吃掉整段伪定义，避免后续级联误报
                        let _ = self.解析函数定义();
                        continue;
                    }
                    if let Some(语句) = self.解析语句() {
                        if self.位置 == 开始位置 {
                            // 位置未推进：强制跳过，防止无限循环/OOM，并报告诊断便于定位根因
                            let 位置 = self.当前().map(|t| t.位置.clone()).unwrap_or(crate::公共数据结构::源码位置::新("未知".into(), 0, 0));
                            let 当前内容 = self.当前().map(|t| format!("{:?}", t.类型)).unwrap_or_else(|| "文件结束".to_string());
                            self.诊断.报告(crate::公共数据结构::诊断信息 {
                                级别: crate::公共数据结构::诊断级别::错误,
                                错误类型: crate::公共数据结构::错误类型::语法错误,
                                描述: format!("解析器内部错误：语句解析未推进词条位置（当前词条【{}】），已强制跳过以防无限循环", 当前内容),
                                位置,
                                帮助信息: Some("此位置附近的语法可能不完整，请检查代码块是否闭合".to_string()),
                                也见于: Vec::new(),
                                是否是指: None,
                                标记说明: None,
                            });
                            self.强制推进();
                        }
                        语句列表.push(语句);
                    } else if self.位置 == 开始位置 {
                        self.强制推进();
                    }
                }
            }
        }
        语句列表
    }

    /// 探测当前位置是否为「具名函数定义签名」开头：标识符 ( 平衡括号 ) [返回类型] :
    /// 仅用于函数体内的显式诊断（具名函数只能定义在模块顶层）。
    /// 普通调用语句 `计算(5)` 后不跟冒号，不会误判。
    fn 是具名函数签名开始(&self) -> bool {
        let mut i = self.位置;
        if !matches!(self.词条流.get(i).map(|t| &t.类型), Some(词条类型::标识符(_))) { return false; }
        i += 1;
        if !matches!(self.词条流.get(i).map(|t| &t.类型), Some(词条类型::左括号)) { return false; }
        i += 1;
        let mut 深度 = 1;
        while i < self.词条流.len() && 深度 > 0 {
            match &self.词条流[i].类型 {
                词条类型::左括号 => 深度 += 1,
                词条类型::右括号 => 深度 -= 1,
                _ => {}
            }
            i += 1;
        }
        if 深度 != 0 { return false; }
        // 不允许跨语句换行：签名 (...) 与随后的冒号必须紧邻（至多夹一个返回类型标识符/任意）。
        // 原实现跨换行向前寻找冒号，会把下一句的 `设备: 可移动 = ...` 里的冒号误判为本句的签名后缀，
        // 导致上一句普通调用（如 `输出(...)`）被当成「函数体内具名函数定义」而误报。
        match self.词条流.get(i).map(|t| &t.类型) {
            Some(词条类型::冒号) => return true,
            Some(词条类型::标识符(_)) | Some(词条类型::任意) => {
                // 返回类型标识符，其后必须紧跟冒号（不跨语句换行）
                matches!(self.词条流.get(i + 1).map(|t| &t.类型), Some(词条类型::冒号))
            }
            _ => false,
        }
    }

    pub(crate) fn 解析函数定义(&mut self) -> 函数定义 {
        let 位置 = self.当前().unwrap().位置.clone();
        if self.检查(&词条类型::函数) {
            self.消耗();
        }
        let 名称 = if let Some(词条类型::标识符(名称)) = self.当前类型().cloned() {
            self.消耗();
            名称
        } else {
            String::new()
        };
        let 形参列表 = self.解析形参列表();
        let 返回类型 = self.解析返回类型();
        self.期望(词条类型::冒号, "期望:");
        // ── 进入函数体上下文（唯一入口：函数边界进嵌套栈；用于分号检查与跳出/继续校验）──
        let 函数体 = self.解析函数代码块();
        self.期望(词条类型::结束, "期望【结束】");
        函数定义 { 名称, 形参列表, 返回类型, 函数体, 是否私有: false, 位置, 链接名: String::new() }
    }
