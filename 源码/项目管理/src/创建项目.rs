// 文件: 项目管理/src/创建项目.rs
// 职责: 项目创建业务逻辑 — 校验项目名、生成目录结构、写入模板文件
//       不含任何 I/O 交互输出（eprintln! / println!），由 CLI 层调用后自行打印

use std::fs;
use std::path::Path;

/// 创建项目目录结构和模板文件
/// 返回 Ok(()) 或 Err(错误信息)
pub fn 生成项目(项目名: &str, 目标路径: &Path, 全部模版: bool) -> Result<(), String> {
    校验项目名(项目名)?;

    if 目标路径.exists() {
        return Err(format!("目录 '{}' 已存在", 目标路径.display()));
    }

    let 时间 = 当前时间戳();
    let mut 目录列表 = vec![
        目标路径.join("配置"),
        目标路径.join("源码"),
        目标路径.join("测试"),
        目标路径.join("外部语言"),  // 🆕 FFI: 默认创建外部语言目录
    ];
    if 全部模版 {
        目录列表.push(目标路径.join("文档"));
        目录列表.push(目标路径.join("库"));
        目录列表.push(目标路径.join("产出"));
        目录列表.push(目标路径.join("日志"));
    }

    for d in &目录列表 {
        fs::create_dir_all(d)
            .map_err(|e| format!("创建目录失败 '{}': {}", d.display(), e))?;
    }

    fs::write(目标路径.join(".gitignore"), "产出/\n库/\n")
        .map_err(|e| format!("写入 .gitignore 失败: {}", e))?;

    fs::write(
        目标路径.join("配置/项目.配置"),
        if 全部模版 {
            全部配置模板(项目名)
        } else {
            精简配置模板(项目名)
        },
    )
    .map_err(|e| format!("写入 项目.配置 失败: {}", e))?;

    fs::write(
        目标路径.join("配置/项目依赖.配置"),
        "// 此文件由工具链自动生成，请勿手动编辑\n\n// 智语言库\n//数学 = { 版本 = \"1.2.0\", 路径 = \".智语言/库/数学1.2.0/源码/\", 哈希 = \"sha256:a1b2...\" }\n//网络 = { 版本 = \"2.3.1\", 路径 = \".智语言/库/网络2.3.1/源码/\", 哈希 = \"sha256:b2c3...\" }\n\n// 外部语言库\n//sqlite3 = { 版本 = \"3.42.0\", 路径 = \"外部语言/sqlite3-3.42.0/头文件/\", 哈希 = \"sha256:c3d4...\" }\n\n// 远程库\n//数学 = { 源地址 = \"https://库.库.xxxxx.org/数学/1.2.0\", 哈希 = \"sha256:d4e5...\" }\n\n// 外部单个文件\n//工具 = { 路径 = \"外部语言/自定义/工具.c\" }\n",
    )
    .map_err(|e| format!("写入 项目依赖.配置 失败: {}", e))?;

    if 全部模版 {
        fs::write(目标路径.join("配置/项目清单.配置"), 清单模板())
            .map_err(|e| format!("写入 项目清单.配置 失败: {}", e))?;
    }

    // 启动程序.智（两种模版都生成）
    fs::write(
        目标路径.join("源码/启动程序.智"),
        format!(
            "// 程序入口\n// 项目：{}\n// 创建时间：{}\n\n启动程序():\n    输出(\"你好，智语言！\")\n结束\n",
            项目名, 时间
        ),
    )
    .map_err(|e| format!("写入 启动程序.智 失败: {}", e))?;

    // 测试文件（两种模版都生成）
    // 自包含用例：入口模块「启动程序」为保留关键字不可被导入，故测试不依赖导入，
    // 直接做基础校验（规范 §6.4.3：测试验证用 抛出 异常实现，不提供 断定 方法），
    // 保证「创建」后「测试」开箱即用。
    fs::write(
        目标路径.join("测试/启动程序测试.智"),
        format!(
            "// 测试文件\n// 项目：{}\n\n测试启动程序():\n    结果 = 1 + 1\n    如果 结果 != 2:\n        抛出 异常错误(\"基础计算错误\")\n    结束\n    输出(\"测试通过\")\n结束\n",
            项目名
        ),
    )
    .map_err(|e| format!("写入 启动程序测试.智 失败: {}", e))?;

    // 全部模版：文档文件
    if 全部模版 {
        fs::write(目标路径.join("文档/项目说明.文档"), 说明文档模板(项目名))
            .map_err(|e| format!("写入 项目说明.文档 失败: {}", e))?;
        fs::write(目标路径.join("文档/项目许可.文档"), 许可文档模板())
            .map_err(|e| format!("写入 项目许可.文档 失败: {}", e))?;
    }

    Ok(())
}

fn 校验项目名(名: &str) -> Result<(), String> {
    if 名.is_empty() {
        return Err("项目名称不能为空".into());
    }
    for c in 名.chars() {
        if c.is_alphanumeric()
            || c == '_'
            || c == '-'
            || c == '.'
            || ('\u{4e00}'..='\u{9fff}').contains(&c)
        {
            continue;
        }
        return Err(format!(
            "项目名称包含非法字符'{}', 只允许中文、字母、数字、下划线、连字符、点号",
            c
        ));
    }
    Ok(())
}

fn 当前时间戳() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    let 时间差 = SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default();
    let 秒数 = 时间差.as_secs();
    // 简单 UTC→本地偏移（+8）
    let 本地时间 = 秒数 + 8 * 3600;
    let 天数 = 本地时间 / 86400;
    let (年, 月, 日) = 纪元到日期(天数);
    let 剩余秒 = 本地时间 % 86400;
    format!(
        "{:04}-{:02}-{:02} {:02}:{:02}:{:02}",
        年,
        月,
        日,
        剩余秒 / 3600,
        (剩余秒 % 3600) / 60,
        剩余秒 % 60
    )
}

fn 纪元到日期(天数: u64) -> (u64, u64, u64) {
    let mut 年 = 1970u64;
    let mut 剩余天 = 天数;
    loop {
        let 闰 = if (年 % 4 == 0 && 年 % 100 != 0) || 年 % 400 == 0 {
            366
        } else {
            365
        };
        if 剩余天 < 闰 {
            break;
        } else {
            剩余天 -= 闰;
            年 += 1;
        }
    }
    let 月天数数组 = if (年 % 4 == 0 && 年 % 100 != 0) || 年 % 400 == 0 {
        [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    } else {
        [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    };
    let mut 月 = 1;
    for &月天数 in &月天数数组 {
        if 剩余天 < 月天数 {
            break;
        }
        剩余天 -= 月天数;
        月 += 1;
    }
    (年, 月, 剩余天 + 1)
}

