// 文件: 工程管理/src/全局配置.rs
// 职责: 全局.配置 读写（缺失则按默认自动生成，软实现）
// 规范 6.1.8：所有全局配置集中在 全局.配置 一个文件中，含 4 个配置段：
//   [开发套件]     工具包专属：版本/回退/安装路径 + 自动检查更新/检查频率/体验改进计划启用
//   [全局路径配置]   全局数据/依赖路径：全局目录/库安装路径/库中间产物路径
//   [网络]           工具包下载 + 库下载 共用
//   [安全]           工具包下载 + 库下载 共用
// 使用 配置读取器 统一解析（裸中文键 + 中文逻辑 真/假，对齐规范 §6.1.9）

use std::path::PathBuf;
use super::配置读取器;

#[derive(Debug, Clone)]
pub struct 开发套件段 {
    pub 开发套件版本: String,
    pub 回退记录: String,
    pub 安装路径: String,
}

/// 全局路径配置（规范 6.1.8：全局数据根/库安装根/库中间产物路径）
#[derive(Debug, Clone)]
pub struct 全局路径配置段 {
    pub 全局目录: String,
    pub 库安装路径: String,
    // 注：全局库中间文件输出路径已移出全局配置，改由 项目.配置 [产出文件目录] 控制
    //     （相对路径=项目目录+路径，绝对路径直接读取；未设置则默认 全局目录/产出/库中间文件/）
}

#[derive(Debug, Clone)]
pub struct 网络段 {
    pub 代理: String,
    pub 并发下载数: u32,
    pub 超时: u32,
    pub 重试次数: u32,
    pub 离线模式: bool,
}

#[derive(Debug, Clone)]
pub struct 安全段 {
    pub 校验策略: String,
}

/// 镜像源配置（规范 6.1.10：[镜像源] 段，单值键，空 = 官方源）
#[derive(Debug, Clone)]
pub struct 镜像源段 {
    pub 开发套件镜像源: String,
    pub 库镜像源: String,
}

/// 官方源地址常量（内置程序，不落配置；空键回退到此）
pub const 官方开发套件源: &str = "https://智语言.org";
pub const 官方库源: &str = "https://库.智语言.org";

#[derive(Debug, Clone)]
pub struct 更新段 {
    pub 自动检查: bool,
    pub 检查频率: String,
}

#[derive(Debug, Clone)]
pub struct 体验改进计划段 {
    pub 启用: bool,
}

#[derive(Debug, Clone)]
pub struct 全局配置 {
    pub 开发套件: 开发套件段,
    pub 全局路径配置: 全局路径配置段,
    pub 网络: 网络段,
    pub 安全: 安全段,
    /// 镜像源（读写映射到 [镜像源] 段）
    pub 镜像源: 镜像源段,
    /// 更新检查（读写映射到 [开发套件] 段）
    pub 更新: 更新段,
    /// 体验改进计划（读写映射到 [开发套件] 段）
    pub 体验改进计划: 体验改进计划段,
}

impl 全局配置 {
    /// 默认配置（安装程序首次运行时应写入实际绝对路径）
    pub fn 默认() -> Self {
        全局配置 {
            开发套件: 开发套件段 {
                开发套件版本: "0.0.1".to_string(),
                回退记录: String::new(),
                安装路径: String::new(),
            },
            全局路径配置: 全局路径配置段 {
                全局目录: String::new(),
                库安装路径: String::new(),
            },
            网络: 网络段 {
                代理: String::new(),
                并发下载数: 4,
                超时: 30,
                重试次数: 3,
                离线模式: false,
            },
            安全: 安全段 {
                校验策略: "严格".to_string(),
            },
            镜像源: 镜像源段 {
                开发套件镜像源: String::new(),
                库镜像源: String::new(),
            },
            更新: 更新段 {
                自动检查: true,
                检查频率: "每周".to_string(),
            },
            // ⚠ 2026-11-16 隐私修复：**默认关闭**（原为 true）。
            //   理由：这是数据收集类开关，默认开启且原先**没有任何关闭入口**（`设置` 键表里没有它，
            //   用户只能在 `诊断` 里看到「已启用」却改不了）。现在默认关闭，并且 `设置`/`恢复`
            //   支持 `体验改进计划 真/假`。当前三个程序**均未实现任何上报**（无上报代码、无端点），
            //   该开关仅为预留，故默认关闭不影响任何既有功能。
            体验改进计划: 体验改进计划段 { 启用: false },
        }
    }

    /// 当前激活的开发套件版本（双模式共享真相源）
    pub fn 开发套件版本(&self) -> String {
        self.开发套件.开发套件版本.clone()
    }

    /// 生效的开发套件镜像源地址（空 = 内置官方源）
    pub fn 开发套件镜像源地址(&self) -> String {
        if self.镜像源.开发套件镜像源.is_empty() { 官方开发套件源.to_string() }
        else { self.镜像源.开发套件镜像源.clone() }
    }

    /// 生效的库镜像源地址（空 = 内置官方源）
    pub fn 库镜像源地址(&self) -> String {
        if self.镜像源.库镜像源.is_empty() { 官方库源.to_string() }
        else { self.镜像源.库镜像源.clone() }
    }

    /// 开发套件镜像源是否用户自定义（用于 诊断 标注）
    pub fn 开发套件镜像源是用户设置(&self) -> bool {
        !self.镜像源.开发套件镜像源.is_empty()
    }

    /// 库镜像源是否用户自定义（用于 诊断 标注）
    pub fn 库镜像源是用户设置(&self) -> bool {
        !self.镜像源.库镜像源.is_empty()
    }

    /// 将配置写回 全局.配置（不调用 读取，避免递归）
    pub fn 保存(&self) -> std::io::Result<()> {
        写入(self, &crate::目录::全局配置文件())
    }

    /// 切换默认激活版本（原版本记入回退记录，便于 回退版本）
    pub fn 切换版本(&mut self, 新版本: &str) -> Result<(), String> {
        if self.开发套件.开发套件版本 == 新版本 {
            return Ok(());
        }
        self.开发套件.回退记录 = self.开发套件.开发套件版本.clone();
        self.开发套件.开发套件版本 = 新版本.to_string();
        self.保存().map_err(|e| format!("保存全局配置失败: {}", e))
    }

    /// 回退到上一个激活版本
    pub fn 回退版本(&mut self) -> Result<String, String> {
        if self.开发套件.回退记录.is_empty() {
            return Err("没有可回退的版本记录".to_string());
        }
        let 上一个 = self.开发套件.回退记录.clone();
        self.开发套件.回退记录 = self.开发套件.开发套件版本.clone();
        self.开发套件.开发套件版本 = 上一个.clone();
        self.保存().map_err(|e| format!("保存全局配置失败: {}", e))?;
        Ok(上一个)
    }

    /// 缺失路径字段填充为绝对操作系统默认路径（仅当为空时）
    pub fn 填充默认路径(&mut self) {
        if self.全局路径配置.全局目录.is_empty() {
            self.全局路径配置.全局目录 =
                crate::目录::全局目录().to_string_lossy().to_string();
        }
        if self.开发套件.安装路径.is_empty() {
            self.开发套件.安装路径 =
                crate::目录::默认安装路径().to_string_lossy().to_string();
        }
        if self.全局路径配置.库安装路径.is_empty() {
            self.全局路径配置.库安装路径 =
                crate::目录::全局库根().to_string_lossy().to_string();
        }
    }

    /// 是否有路径字段被填充（用于判断是否需要落盘）
    fn 需写回(&self) -> bool {
        self.全局路径配置.全局目录.is_empty()
            || self.开发套件.安装路径.is_empty()
            || self.全局路径配置.库安装路径.is_empty()
    }
}

/// 读取全局.配置；文件**确实不存在**或解析失败时按默认生成并写回（软实现）。
/// 读取后自动填充缺失的默认路径并落盘（首次安装软实现）。
///
/// ★ 2026-10-25 修复（P1，静默覆盖用户配置）：
///   原实现把「**任何** `read_to_string` 失败」都当成"文件缺失" ⇒ 配置退化为默认，
///   随后因 `需写回()` 为真而 **把默认值写回磁盘，覆盖用户已有配置**（自定义 `安装路径`、
///   镜像源等全部丢失）。Windows 上刚被写过的文件会短时被扫描/索引进程占用（实测
///   `设置 开发套件镜像源` **20 次中 5 次** 复现：命令报"已设置"，配置文件却被重置为默认模板、
///   地址反而消失），属真实用户可见事故。
///   现改为：
///     ① 读失败先**短暂重试**（3 次 × 30ms），消解瞬时共享冲突；
///     ② 仅 `ErrorKind::NotFound` 才按默认并落盘（首次运行）；
///     ③ 其它 IO 错误 ⇒ 本次用默认**但不落盘**，并打印警告（宁可用默认跑，也不覆盖用户文件）。
pub fn 读取配置() -> 全局配置 {
    let 路径 = crate::目录::全局配置文件();
    // 文件缺失 = 首次运行的显式落盘条件；且「是否有路径字段缺空」必须在填充默认路径
    // 之前判断——填充后 5 个路径字段全满，需写回() 恒 false，导致从不落盘。
    // 只修此处不修 BOM 会有覆盖风险：带 BOM 旧配置读不出首段 → 路径字段全空 → 落盘
    // 用系统默认路径覆盖用户自定义值。必须与 配置读取器 的 BOM 容错成对落地。
    let 文件存在 = 路径.exists();

    // 读取（带重试）：把「IO 错误」与「读到空白内容」都视作**瞬时未就绪**并重试。
    // 后者尤其关键：`fs::write` 是"截断 + 写入"，另一处并发读会拿到 0 字节 ⇒
    // 若直接当默认配置并落盘，就把用户配置整份抹掉（实测复现过）。
    let mut 读到: Option<String> = None;
    let mut 最后错误: Option<std::io::Error> = None;
    for 尝试 in 0..4 {
        if 尝试 > 0 {
            std::thread::sleep(std::time::Duration::from_millis(30));
        }
        match std::fs::read_to_string(&路径) {
            Ok(内容) if !内容.trim().is_empty() => {
                读到 = Some(内容);
                break;
            }
            Ok(_) => {
                最后错误 = None; // 空/半写文件：继续重试
            }
            Err(错误) => {
                最后错误 = Some(错误);
            }
        }
    }

    let (mut 配置, 可落盘) = match 读到 {
        Some(内容) => (从文档构建全局配置(&配置读取器::解析配置(&内容)), true),
        None => {
            let 是不存在 = match &最后错误 {
                Some(错误) => 错误.kind() == std::io::ErrorKind::NotFound,
                None => !文件存在, // 文件存在但内容为空 ⇒ 不是"首次运行"
            };
            if 是不存在 {
                (全局配置::默认(), true)
            } else {
                // ⚠ 绝不因为"读不到/读到空"就覆盖用户文件——否则一次瞬时占用就抹掉
                //   用户的安装路径/镜像源（实测 20 次中 5 次丢配置）
                let 说明 = 最后错误
                    .as_ref()
                    .map(|e| e.to_string())
                    .unwrap_or_else(|| "文件内容为空或正在写入".to_string());
                eprintln!(
                    "[智语言] 警告：读取全局配置失败（{}）：{}；本次按默认配置运行，且**不会改写**该文件",
                    路径.display(), 说明
                );
                (全局配置::默认(), false)
            }
        }
    };

    let 需落盘 = 可落盘 && (!文件存在 || 配置.需写回());
    配置.填充默认路径();
    if 需落盘 {
        let _ = 配置.保存();
    }
    配置
}

/// 当前激活版本（供命令/构建签名复用）
pub fn 当前激活版本() -> String {
    读取配置().开发套件.开发套件版本
}

/// 写入全局配置（使用 配置读取器 统一序列化）
///
/// ★ 2026-10-25：改为**原子写**（写同目录临时文件 → rename 覆盖）。
///   原实现 `fs::write` 是"截断 + 写入"两步，若此刻另一处（并发线程/另一进程）读取，
///   会读到 **0 字节或半截文件** ⇒ 解析成全默认 ⇒ 又因"路径字段为空"触发落盘
///   ⇒ **用默认值覆盖用户配置**（实测 `设置 开发套件镜像源` 20 次中 5 次丢配置）。
///   rename 在同一目录内是原子的，读者只会看到"完整旧文件"或"完整新文件"。
fn 写入(配置: &全局配置, 路径: &PathBuf) -> std::io::Result<()> {
    if let Some(父) = 路径.parent() {
        std::fs::create_dir_all(父)?;
    }
    let 文档 = 从全局配置构建文档(配置);
    let 文本 = 配置读取器::序列化配置文档(&文档);

    let 临时 = 路径.with_extension("配置.临时");
    std::fs::write(&临时, &文本)?;
    match std::fs::rename(&临时, 路径) {
        Ok(()) => Ok(()),
        Err(错误) => {
            // 极端情况（目标被独占/跨卷）：退回直接写，并清掉临时文件
            let _ = std::fs::remove_file(&临时);
            std::fs::write(路径, &文本).map_err(|_| 错误)
        }
    }
}

