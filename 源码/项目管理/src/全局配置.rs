/// 从解析后的配置文档构建全局配置结构体
fn 从文档构建全局配置(文档: &配置读取器::配置文档) -> 全局配置 {
    let 默认 = 全局配置::默认();

    let 取整数默 = |段名: &str, 键: &str, 默认值: u32| -> u32 {
        配置读取器::取段(文档, 段名)
            .and_then(|段| 配置读取器::取整数(段, 键))
            .map(|v| v as u32)
            .unwrap_or(默认值)
    };

    let 取逻辑默 = |段名: &str, 键: &str, 默认值: bool| -> bool {
        配置读取器::取段(文档, 段名)
            .and_then(|段| 配置读取器::取逻辑(段, 键))
            .unwrap_or(默认值)
    };

    // 取文本（从指定段读取指定键，读取 [开发套件]/[全局路径配置]/[网络]/[安全] 段）
    let 取文本多段 = |段名: &str, 键名: &str, 默认值: &str| -> String {
        配置读取器::取段(文档, 段名)
            .and_then(|段| 配置读取器::取文本(段, 键名))
            .unwrap_or_else(|| 默认值.to_string())
    };

    // 注：原 `取逻辑多段` 已被 `[开发套件] → [更新]/[体验改进计划] 旧段` 的两级取值取代，
    //     删除以免留下"看起来还在用"的死闭包（编译器会报 unused）。
    全局配置 {
        开发套件: 开发套件段 {
            开发套件版本: 取文本多段("开发套件", "开发套件版本", &默认.开发套件.开发套件版本),
            回退记录: 取文本多段("开发套件", "回退记录", &默认.开发套件.回退记录),
            安装路径: 取文本多段("开发套件", "安装路径", &默认.开发套件.安装路径),
        },
        全局路径配置: 全局路径配置段 {
            全局目录: 取文本多段("全局路径配置", "全局目录", &默认.全局路径配置.全局目录),
            库安装路径: 取文本多段("全局路径配置", "库安装路径", &默认.全局路径配置.库安装路径),
        },
        网络: 网络段 {
            代理: 取文本多段("网络", "代理", &默认.网络.代理),
            并发下载数: 取整数默("网络", "并发下载数", 默认.网络.并发下载数),
            超时: 取整数默("网络", "超时", 默认.网络.超时),
            重试次数: 取整数默("网络", "重试次数", 默认.网络.重试次数),
            离线模式: 取逻辑默("网络", "离线模式", 默认.网络.离线模式),
        },
        安全: 安全段 {
            校验策略: 取文本多段("安全", "校验策略", &默认.安全.校验策略),
        },
        镜像源: 镜像源段 {
            开发套件镜像源: 取文本多段("镜像源", "开发套件镜像源", &默认.镜像源.开发套件镜像源),
            库镜像源: 取文本多段("镜像源", "库镜像源", &默认.镜像源.库镜像源),
        },
        更新: 更新段 {
            // ⚠ 2026-11-16 修正既有缺陷：`[更新]` / `[体验改进计划]` 旧段兼容此前**只写在注释里**
            //   （下方 427 行注释声称"旧段仍由读取候选回退兼容"），代码却只查 `[开发套件]` ⇒
            //   旧配置里的这两段被静默忽略、回退默认值。旧单测 `格式_中文逻辑解析` 之所以"通过"，
            //   是因为当时默认值(true)恰好等于期望值 ⇒ **假通过**。现按「新段 → 旧段 → 默认」取值。
            自动检查: {
                let 新段 = 配置读取器::取段(文档, "开发套件")
                    .and_then(|段| 配置读取器::取逻辑(段, "自动检查"));
                let 旧段 = 配置读取器::取段(文档, "更新")
                    .and_then(|段| 配置读取器::取逻辑(段, "自动检查"));
                新段.or(旧段).unwrap_or(默认.更新.自动检查)
            },
            检查频率: {
                let 新段 = 配置读取器::取段(文档, "开发套件")
                    .and_then(|段| 配置读取器::取文本(段, "检查频率"));
                let 旧段 = 配置读取器::取段(文档, "更新")
                    .and_then(|段| 配置读取器::取文本(段, "检查频率"));
                新段.or(旧段).unwrap_or_else(|| 默认.更新.检查频率.clone())
            },
        },
        体验改进计划: 体验改进计划段 {
            启用: {
                let 新段 = 配置读取器::取段(文档, "开发套件")
                    .and_then(|段| 配置读取器::取逻辑(段, "改进计划启用"));
                let 旧段 = 配置读取器::取段(文档, "体验改进计划")
                    .and_then(|段| 配置读取器::取逻辑(段, "启用"));
                新段.or(旧段).unwrap_or(默认.体验改进计划.启用)
            },
        },
    }
}

/// 从全局配置构建配置文档（供序列化使用）
fn 从全局配置构建文档(配置: &全局配置) -> 配置读取器::配置文档 {
    let mut 文档 = 配置读取器::配置文档 {
        顶层: vec![],
        段: vec![],
    };

    // [开发套件]（规范 6.1.10：工具包专属状态 + 更新检查/体验改进计划并入本段）
    文档.段.push(配置读取器::配置段 {
        段名: "开发套件".to_string(),
        键值: vec![
            ("开发套件版本".into(), 配置读取器::配置值::文本(配置.开发套件.开发套件版本.clone())),
            ("安装路径".into(), 配置读取器::配置值::文本(配置.开发套件.安装路径.clone())),
            ("回退记录".into(), 配置读取器::配置值::文本(配置.开发套件.回退记录.clone())),
            ("自动检查".into(), 配置读取器::配置值::逻辑(配置.更新.自动检查)),
            ("检查频率".into(), 配置读取器::配置值::文本(配置.更新.检查频率.clone())),
            ("改进计划启用".into(), 配置读取器::配置值::逻辑(配置.体验改进计划.启用)),
        ],
    });

    // [全局路径配置]（全局数据根/库安装根/库中间产物路径）
    文档.段.push(配置读取器::配置段 {
        段名: "全局路径配置".to_string(),
        键值: vec![
            ("全局目录".into(), 配置读取器::配置值::文本(配置.全局路径配置.全局目录.clone())),
            ("库安装路径".into(), 配置读取器::配置值::文本(配置.全局路径配置.库安装路径.clone())),
        ],
    });

    // [网络]（代理 + 下载参数；镜像源已独立为 [镜像源] 段）
    文档.段.push(配置读取器::配置段 {
        段名: "网络".to_string(),
        键值: vec![
            ("代理".into(), 配置读取器::配置值::文本(配置.网络.代理.clone())),
            ("并发下载数".into(), 配置读取器::配置值::整数(配置.网络.并发下载数 as i64)),
            ("超时".into(), 配置读取器::配置值::整数(配置.网络.超时 as i64)),
            ("重试次数".into(), 配置读取器::配置值::整数(配置.网络.重试次数 as i64)),
            ("离线模式".into(), 配置读取器::配置值::逻辑(配置.网络.离线模式)),
        ],
    });

    // [镜像源]（开发套件源 + 库源，空 = 官方源）
    文档.段.push(配置读取器::配置段 {
        段名: "镜像源".to_string(),
        键值: vec![
            ("开发套件镜像源".into(), 配置读取器::配置值::文本(配置.镜像源.开发套件镜像源.clone())),
            ("库镜像源".into(), 配置读取器::配置值::文本(配置.镜像源.库镜像源.clone())),
        ],
    });

    // [安全]
    文档.段.push(配置读取器::配置段 {
        段名: "安全".to_string(),
        键值: vec![
            ("校验策略".into(), 配置读取器::配置值::文本(配置.安全.校验策略.clone())),
        ],
    });

    // 注：[更新] 与 [体验改进计划] 已并入 [开发套件] 段（自动检查/检查频率/改进计划启用），
    // 不再单独生成；旧配置文件中的 [更新]/[体验改进计划] 段仍由读取候选回退兼容。

    文档
}

