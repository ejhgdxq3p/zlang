// 文件: 编辑器服务/src/定义跳转.rs
// 职责: **第一阶段**定义跳转（同文件、不依赖类型推断），复用**共享前端词法分析器**
//
// 为什么必须用词法词条、而不是对每一行做字符串 `starts_with`（改造前实现的做法）：
//   注释与字符串字面量里的 `结束` / `名字(` 会被正则误认；词法词条天然排除它们。
//
// 本阶段覆盖（跳转方案 §8 第一阶段）：
//   ① 局部变量 / 局部常量 / 函数形参 / 结构体参数 / 循环变量 → 声明位置
//   ② 裸名函数调用 → 函数定义；结构体实例化 / 自定义类型标注 → 结构体·枚举·接口 定义
//   ③ `本模块.X` → 本模块顶层成员
//   ④ `导入` / `聚合导入` → 模块文件（**真实文件 URI**）
//   ⑤ 配对跳转：`结束` ↔ 块头
// 本阶段**不覆盖**（留给第二~五阶段；**返回空而不猜**）：
//   实例.成员（需类型推断）、`自身.成员`、接口→实现、运算符重载、展开导入成员、聚合成员下钻
//
// ⚠ 可见性规则（本文件的核心设计，替代"全文按名字搜"）：
//   每条声明记录 `所属容器行`（结构体/函数块头行；模块级 = None）。
//   **声明可见 ⟺ 所属容器行为 None，或该行仍在光标处的块栈里，或就是光标所在行**
//   ⇒ 函数/`如果` 块结束后其局部不再可见（改造前实现会误跳到别处的同名变量）。

use crate::位置映射::行索引;
use frontend::词法分析::{词条, 词条类型};
use lsp_types::{Location, Position, Range, Url};
use std::collections::HashMap;
use std::path::{Path, PathBuf};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum 种类 {
    函数,
    结构体,
    枚举,
    接口,
    字段,
    变量,
    常量,
    局部,
    形参,
    循环变量,
}

#[derive(Clone, Debug)]
struct 声明 {
    名字: String,
    行号: usize, // 1-based（前端口径）
    列号: usize, // 1-based 字符列
    字符数: usize,
    所属容器行: Option<usize>,
    种类: 种类,
}

#[derive(Clone, Debug)]
struct 导入项 {
    行号: usize,
    模块名: String, // 形如 `数学` 或 `数学/几何/圆形`
    别名: Option<String>,
    模块名列: usize, // 1-based 字符列（模块名首段位置）
    模块名字符数: usize,
    别名列: Option<usize>,
}

#[derive(Default)]
struct 分析 {
    声明: Vec<声明>,
    导入: Vec<导入项>,
    配对: HashMap<usize, usize>, // 行号 ↔ 配对行号（双向各存一条）
}

/// 块信息（供"块栈可见性"与配对跳转共用）
#[derive(Clone, Copy)]
struct 块 {
    行号: usize,
    是函数块: bool,
}

/// 块配对表（块头行 ↔ 配对 `结束` 行，**双向各存一条**）。
///
/// ★ **单源**：文档符号要算"一个定义占几行"，必须与配对跳转用**同一套块栈**；
///   若在符号模块里另写一份配对逻辑，两处对"`结束` 归属哪个块"的判定迟早漂移
///   （`否则`/`否则如果` 续块、`结束` 弹出等细节极易写错）。
pub(crate) fn 块配对(源码: &str) -> HashMap<usize, usize> {
    let 词条列表 = 词法分析(源码);
    if 词条列表.is_empty() {
        return HashMap::new();
    }
    分析(&切分逻辑行(&词条列表)).配对
}

/// 跳转入口。返回空 = **本阶段不提供跳转**（不是错误）。
pub fn 查找定义(
    源码: &str,
    文档URI: &Url,
    文件路径: Option<&Path>,
    位置: Position,
) -> Vec<Location> {
    let 索引 = 行索引::新建(源码);
    let 光标行0 = 位置.line as usize;
    let Some(光标字符下标) = 索引.行列到字符下标(光标行0, 位置.character as usize) else {
        return Vec::new();
    };
    let 光标行号 = 光标行0 + 1;
    let 光标字符列 = 光标字符下标 + 1;

    let 词条列表 = 词法分析(源码);
    if 词条列表.is_empty() {
        return Vec::new();
    }
    let 行列表 = 切分逻辑行(&词条列表);
    let 结果 = 分析(&行列表);

    let Some((行下标, 词下标)) = 定位光标词条(&行列表, 光标行号, 光标字符列) else {
        return Vec::new();
    };
    let 行 = &行列表[行下标];
    let 当前块栈 = 块栈_at(&行列表, 光标行号);
    let 可见容器行: Vec<usize> = 当前块栈.iter().map(|b| b.行号).collect();

    // ── 场景⑤ 配对跳转（正向：光标在 `结束` 上）──
    if matches!(行[词下标].类型, 词条类型::结束) {
        if let Some(&配对行) = 结果.配对.get(&光标行号) {
            return 跳到行首(&索引, 配对行, 文档URI).into_iter().collect();
        }
        return Vec::new();
    }
    // ── 配对跳转（反向：光标在块头首词上）──
    if 词下标 == 0 && 是块头(行) {
        if let Some(&配对行) = 结果.配对.get(&光标行号) {
            return 跳到行首(&索引, 配对行, 文档URI).into_iter().collect();
        }
    }

    // ── 场景④ 导入行 ──
    if 行首是导入关键字(行) {
        for 项 in 结果.导入.iter().filter(|i| i.行号 == 光标行号) {
            let 命中模块名 = 命中区间(光标字符列, 项.模块名列, 项.模块名字符数);
            let 命中别名 = match 项.别名列 {
                Some(列) => 命中区间(光标字符列, 列, 项.别名.as_ref().map(|s| 字符数(s)).unwrap_or(0)),
                None => false,
            };
            if 命中模块名 || 命中别名 {
                // 别名与模块名指向同一文件
                if let Some(路径) = 解析模块文件(&项.模块名, 文件路径) {
                    // ⚠ 盘符规范成小写（与编辑器发出的文档 URI 同形）
                    if let Some(uri) = crate::位置映射::文件URI(&路径) {
                        return vec![Location {
                            uri,
                            range: Range::new(Position::new(0, 0), Position::new(0, 0)),
                        }];
                    }
                }
                return Vec::new();
            }
        }
        return Vec::new();
    }

    // ── 场景③ `本模块.X` ──
    // 形态 a：光标在成员名上（`本模块` `.` `X`）
    if 是点号成员访问(行, 词下标) && 是关键字词(&行[词下标 - 2].类型, "本模块") {
        return 按名找模块级成员(&索引, &结果, 标识符名(&行[词下标].类型), 文档URI);
    }
    // 形态 b：光标在 `本模块` 上
    if matches!(行[词下标].类型, 词条类型::本模块) {
        if 是点号(行.get(词下标 + 1)) {
            let 名 = 行.get(词下标 + 2).and_then(|t| 标识符名(&t.类型));
            return 按名找模块级成员(&索引, &结果, 名, 文档URI);
        }
        return Vec::new();
    }

    // ── `自身.成员` / 其它 `X.成员` / 光标在 `点` 上：第二~三阶段支持 ⇒ 返回空（不猜）──
    if 是点号成员访问(行, 词下标) || 是点号(Some(&行[词下标])) {
        return Vec::new();
    }

    // ── 场景①②：裸名 → 最近的**可见**声明（局部优先于模块级）──
    if let Some(名) = 标识符名(&行[词下标].类型) {
        let 最近 = 结果
            .声明
            .iter()
            .filter(|d| d.名字 == 名)
            .filter(|d| 声明可见(d, &可见容器行, 光标行号))
            // 排序键：① 局部/形参/循环变量 优先于结构体字段（规范「参数优先于同名字段」）
            //         ② 块内声明优先于模块级  ③ 同层取**最近声明**（行号最大）
            .max_by_key(|d| (种类优先级(d.种类), d.所属容器行.is_some(), d.行号));
        if let Some(d) = 最近 {
            if let Some(位于) = 定位声明(&索引, d, 文档URI) {
                return vec![位于];
            }
        }
    }

    Vec::new()
}

fn 按名找模块级成员(
    索引: &行索引,
    结果: &分析,
    名: Option<String>,
    文档URI: &Url,
) -> Vec<Location> {
    let Some(名) = 名 else { return Vec::new() };
    if let Some(d) = 结果.声明.iter().find(|d| d.所属容器行.is_none() && d.名字 == 名) {
        if let Some(位于) = 定位声明(索引, d, 文档URI) {
            return vec![位于];
        }
    }
    Vec::new()
}

// ============================================================
// 声明可见性
// ============================================================
fn 声明可见(d: &声明, 可见容器行: &[usize], 光标行号: usize) -> bool {
    match d.所属容器行 {
        None => true,
        Some(行) => 行 == 光标行号 || 可见容器行.contains(&行),
    }
}

/// 同名同层时的优先级：局部/形参/循环变量 > 模块级/函数/类型 > 结构体字段
/// （规范：结构体参数通过名称直接访问，**参数优先于同名字段**）
fn 种类优先级(种类: 种类) -> u8 {
    match 种类 {
        种类::局部 | 种类::形参 | 种类::循环变量 => 2,
        种类::字段 => 0,
        _ => 1,
    }
}

// ============================================================
// 逻辑行切分（按物理行；词条自带行号）
// ============================================================
fn 切分逻辑行(词条列表: &[词条]) -> Vec<Vec<&词条>> {
    let mut 行列表: Vec<Vec<&词条>> = Vec::new();
    let mut 当前: Vec<&词条> = Vec::new();
    let mut 当前行号 = 0usize;
    for t in 词条列表 {
        if matches!(t.类型, 词条类型::文件结束) {
            break;
        }
        if matches!(t.类型, 词条类型::换行 | 词条类型::文档注释内容(_)) {
            continue;
        }
        if t.位置.行号 != 当前行号 {
            if !当前.is_empty() {
                行列表.push(std::mem::take(&mut 当前));
            }
            当前行号 = t.位置.行号;
        }
        当前.push(t);
    }
    if !当前.is_empty() {
        行列表.push(当前);
    }
    行列表
}

// ============================================================
// 词法分析（复用共享前端；词法错误不阻断跳转，只丢弃诊断）
// ============================================================
/// ⚠ 走**内容缓存**（`crate::缓存`）：本函数在每次请求里都会被调用（`块配对` 也要一遍），
///   重复词法是当前主要开销。返回值是 `Rc<Vec<词条>>`（调用点按 `&[词条]` 用，自动解引用）。
fn 词法分析(源码: &str) -> std::rc::Rc<Vec<词条>> {
    crate::缓存::词法分析("<编辑器>", 源码)
}

// ============================================================
// 块栈与块头判定
// ============================================================
/// 光标行之前（不含光标行）已开启、且尚未关闭的块
fn 块栈_at(行列表: &[Vec<&词条>], 光标行号: usize) -> Vec<块> {
    let mut 栈: Vec<块> = Vec::new();
    for 行 in 行列表 {
        let 行号 = 词条行号(行);
        if 行号 >= 光标行号 {
            break;
        }
        if matches!(行[0].类型, 词条类型::结束) {
            栈.pop();
            continue;
        }
        if 是块头(行) && !是续块关键字(&行[0].类型) {
            栈.push(块 { 行号, 是函数块: 是函数块头(行) });
        }
    }
    栈
}

/// 行末为 `冒号`（全角冒号由词法层报错，此处不兜底）
fn 是块头(行: &[&词条]) -> bool {
    行.last().map(|t| matches!(t.类型, 词条类型::冒号)).unwrap_or(false)
}

/// `否则` / `否则如果` 继续同一个块，不新开块
fn 是续块关键字(t: &词条类型) -> bool {
    matches!(t, 词条类型::否则 | 词条类型::否则如果)
}

/// 函数/方法/入口块头：`[私有] 名字 ( ... ) [类型] :`
///
/// ⚠ 必须同时满足 `是块头(行)`（行末冒号）：否则**调用表达式**会被误判成函数定义 ——
///   实测 `输出(结果)` 满足"标识符 + 左括号"，会被当成函数定义头 ⇒ 凭空多出一个 `输出` 函数
///   和一个 `结果` 形参 ⇒ 跳转把 `结果` 解析到**自己身上**（真 bug，已由用例 ② 抓出）。
fn 是函数块头(行: &[&词条]) -> bool {
    if !是块头(行) {
        return false;
    }
    let 名下标 = if matches!(行[0].类型, 词条类型::私有) { 1 } else { 0 };
    matches!(行.get(名下标).map(|t| &t.类型), Some(词条类型::标识符(_)))
        && matches!(行.get(名下标 + 1).map(|t| &t.类型), Some(词条类型::左括号))
}

// ============================================================
// 分析：收集声明 / 导入 / 配对
// ============================================================
fn 分析(行列表: &[Vec<&词条>]) -> 分析 {
    let mut 结果 = 分析::default();
    let mut 块栈: Vec<块> = Vec::new();

    for 行 in 行列表 {
        let 行号 = 词条行号(行);

        if matches!(行[0].类型, 词条类型::结束) {
            if let Some(块) = 块栈.pop() {
                结果.配对.insert(块.行号, 行号);
                结果.配对.insert(行号, 块.行号);
            }
            continue;
        }

        let 容器 = 块栈.last().copied();
        收集行(行, 容器, &mut 结果);

        if 是块头(行) && !是续块关键字(&行[0].类型) {
            块栈.push(块 { 行号, 是函数块: 是函数块头(行) });
        }
    }
    结果
}

/// 收集某一行的声明与导入
fn 收集行(行: &[&词条], 容器: Option<块>, 结果: &mut 分析) {
    let 行号 = 词条行号(行);
    let 首 = &行[0].类型;
    let 起始下标 = if matches!(首, 词条类型::私有) { 1 } else { 0 };

    // ── 导入 / 聚合导入 ──
    if matches!(首, 词条类型::导入 | 词条类型::聚合导入) {
        if let Some(项) = 解析导入行(行, 行号) {
            结果.导入.push(项);
        }
        return;
    }

    let 容器行 = 容器.map(|b| b.行号);
    // `名 = 值` / `类型 名 = 值` 落在**函数块**里 ⇒ 局部；落在模块级 ⇒ 模块成员；其余（结构体/接口体内）⇒ 字段
    let 声明种类 = match 容器 {
        None => None, // 由下面的分支决定（变量/常量/函数/结构体/枚举/接口）
        Some(b) if b.是函数块 => Some(种类::局部),
        Some(_) => Some(种类::字段),
    };

    let Some(名种类词) = 行.get(起始下标) else { return };

    // ── 结构体 / 枚举 / 接口 ──
    // （同样要求 `是块头`：类型**定义**必然以 `:` 结尾，避免把表达式的裸类型名当定义）
    match &名种类词.类型 {
        词条类型::结构体 | 词条类型::枚举 | 词条类型::接口 if 是块头(行) => {
            let 种类 = match 名种类词.类型 {
                词条类型::结构体 => 种类::结构体,
                词条类型::枚举 => 种类::枚举,
                _ => 种类::接口,
            };
            if let Some(名) = 行.get(起始下标 + 1).and_then(|t| 标识符名(&t.类型)) {
                结果.声明.push(构造声明(名, 行号, 行.get(起始下标 + 1).unwrap(), 容器行, 种类));
                if 种类 == 种类::结构体 {
                    // 结构体构造参数（无前缀通道）⇒ 容器记为**结构体自身行**，方法体内可见
                    for 形参 in 括号内形参(行, 起始下标) {
                        结果.声明.push(构造声明(形参.名字, 行号, 形参.词, Some(行号), 种类::形参));
                    }
                }
            }
            return;
        }
        词条类型::常量 => {
            if let Some((名, t)) = 赋值前末个标识符(行, 起始下标) {
                let 种类 = 声明种类.unwrap_or(种类::常量);
                结果.声明.push(构造声明(名, 行号, t, 容器行, 种类));
            }
            return;
        }
        词条类型::循环 if 是块头(行) => {
            for (名, t) in 循环变量(行) {
                结果.声明.push(构造声明(名, 行号, t, 容器行, 种类::循环变量));
            }
            return;
        }
        _ => {}
    }

    // ── 函数 / 方法 / 入口定义 ──
    if 是函数块头(行) {
        if let Some(名) = 行.get(起始下标).and_then(|t| 标识符名(&t.类型)) {
            结果.声明.push(构造声明(名, 行号, 行.get(起始下标).unwrap(), 容器行, 种类::函数));
            // 形参属于**本函数块**（容器 = 本行）
            for 形参 in 括号内形参(行, 起始下标) {
                结果.声明.push(构造声明(形参.名字, 行号, 形参.词, Some(行号), 种类::形参));
            }
        }
        return;
    }

    // ── 形态一：`名 = 值`（声明与赋值同形；规范要求函数内裸名 = 隐式声明局部）──
    if let (Some(名), Some(二)) = (行.get(起始下标).and_then(|t| 标识符名(&t.类型)), 行.get(起始下标 + 1)) {
        if matches!(二.类型, 词条类型::赋值) {
            let 种类 = 声明种类.unwrap_or(种类::变量);
            结果.声明.push(构造声明(名, 行号, 行.get(起始下标).unwrap(), 容器行, 种类));
            return;
        }
    }

    // ── 形态二：`类型 名 = 值`（含泛型 `数组<整数> 列表 = []`、`任意<甲: 整数|小数> 数据 = 空值`）──
    //    用"赋值前最后一个标识符"取名字，可同时覆盖基本类型/自定义类型/泛型/任意 四种写法。
    //    守卫：赋值之前**不得出现 `点` 或 `[`**（否则 `甲.字段 = 值` / `甲[0] = 值` 会被误当声明）。
    if 行.get(起始下标).map(|t| 是类型外观(&t.类型)).unwrap_or(false) {
        let Some(赋值位) = 行.iter().position(|t| matches!(t.类型, 词条类型::赋值)) else { return };
        let 之前 = &行[起始下标..赋值位];
        let 有干扰 = 之前.iter().any(|t| matches!(t.类型, 词条类型::点 | 词条类型::左方括号));
        if 赋值位 >= 起始下标 + 2 && !有干扰 {
            if let Some((名, t)) = 赋值前末个标识符(行, 起始下标) {
                let 种类 = 声明种类.unwrap_or(种类::变量);
                结果.声明.push(构造声明(名, 行号, t, 容器行, 种类));
            }
        }
    }
}

fn 构造声明(名字: String, 行号: usize, 词: &词条, 所属容器行: Option<usize>, 种类: 种类) -> 声明 {
    let 字符数 = 字符数(&名字);
    声明 { 名字, 行号, 列号: 词.位置.列号, 字符数, 所属容器行, 种类 }
}

/// 形参的临时记录
struct 形参记录<'a> {
    名字: String,
    词: &'a 词条,
}

/// 从 `名字 (...)` 取括号内每个参数的**最后一个标识符**作为形参名
/// （`整数 甲` / `学生 甲` / `文本 消息 = "…"` / `任意<甲: 整数|小数> 参数` 都能取对）
fn 括号内形参<'a>(行: &[&'a 词条], 名下标: usize) -> Vec<形参记录<'a>> {
    let mut 结果: Vec<形参记录<'a>> = Vec::new();
    let Some(开) = 行.iter().position(|t| matches!(t.类型, 词条类型::左括号)) else {
        return 结果;
    };
    if 开 <= 名下标 {
        return 结果;
    }

    let 收 = |候选: Option<&'a 词条>, 结果: &mut Vec<形参记录<'a>>| {
        if let Some(词) = 候选 {
            if let Some(名字) = 标识符名(&词.类型) {
                结果.push(形参记录 { 名字, 词 });
            }
        }
    };

    let mut 深度 = 0i32;
    let mut 候选: Option<&'a 词条> = None;
    for 词 in 行.iter().skip(开).copied() {
        match &词.类型 {
            词条类型::左括号 | 词条类型::左方括号 => 深度 += 1,
            词条类型::右方括号 => 深度 -= 1,
            词条类型::右括号 => {
                深度 -= 1;
                if 深度 <= 0 {
                    收(候选.take(), &mut 结果);
                    break;
                }
            }
            词条类型::逗号 if 深度 == 1 => 收(候选.take(), &mut 结果),
            _ => {
                // 只在**参数层**（深度 ≤ 1）收集；泛型/数组内部的类型名不算形参名
                if 深度 <= 1 && 标识符名(&词.类型).is_some() {
                    候选 = Some(词);
                }
            }
        }
    }
    结果
}

/// `… 名 = …` ⇒ 取 `赋值` 之前**最后一个**标识符及其词条
fn 赋值前末个标识符<'a>(行: &[&'a 词条], 起始下标: usize) -> Option<(String, &'a 词条)> {
    let 赋值位 = 行.iter().position(|t| matches!(t.类型, 词条类型::赋值))?;
    let mut 候选: Option<&'a 词条> = None;
    for t in 行.iter().take(赋值位).skip(起始下标) {
        if 标识符名(&t.类型).is_some() {
            候选 = Some(t);
        }
    }
    候选.and_then(|t| 标识符名(&t.类型).map(|名| (名, t)))
}

/// `循环 名[, 名] 遍历 …`
fn 循环变量<'a>(行: &[&'a 词条]) -> Vec<(String, &'a 词条)> {
    let mut 结果 = Vec::new();
    for t in 行.iter().skip(1) {
        if matches!(t.类型, 词条类型::遍历) {
            break;
        }
        if let Some(名) = 标识符名(&t.类型) {
            结果.push((名, *t));
        }
    }
    结果
}

/// `导入 数学/几何/圆形 [别名 用户] [展开]`
fn 解析导入行(行: &[&词条], 行号: usize) -> Option<导入项> {
    let mut 段: Vec<String> = Vec::new();
    let mut 模块名列 = 0usize;
    let mut 模块名字符数 = 0usize;
    let mut 别名: Option<String> = None;
    let mut 别名列: Option<usize> = None;
    let mut 期望别名 = false;

    for t in 行.iter().skip(1) {
        if 期望别名 {
            if let Some(名) = 标识符名(&t.类型) {
                别名 = Some(名);
                别名列 = Some(t.位置.列号);
            }
            期望别名 = false;
            continue;
        }
        match &t.类型 {
            词条类型::别名 => 期望别名 = true,
            词条类型::展开 => {}
            词条类型::标识符(名) => {
                if 段.is_empty() {
                    模块名列 = t.位置.列号;
                    模块名字符数 = 字符数(名);
                }
                段.push(名.clone());
            }
            // 导入语境下 `/` 是路径分隔符（词法层是 `除`）
            词条类型::除 => 段.push("/".to_string()),
            _ => {}
        }
    }
    if 段.is_empty() {
        return None;
    }
    Some(导入项 { 行号, 模块名: 段.join(""), 别名, 模块名列, 模块名字符数, 别名列 })
}

// ============================================================
// 光标定位与命中判定
// ============================================================
fn 定位光标词条(行列表: &[Vec<&词条>], 光标行号: usize, 光标字符列: usize) -> Option<(usize, usize)> {
    for (行下标, 行) in 行列表.iter().enumerate() {
        if 词条行号(行) != 光标行号 {
            continue;
        }
        for (词下标, t) in 行.iter().enumerate() {
            let 起 = t.位置.列号; // 1-based 字符列
            // ⚠ 右端必须是 `起 + 长度 - 1`（**闭区间到最后一个字符**）。
            //   写成 `起 + 长度` 会让**前一个词条吞掉后一个词条的起始列**：
            //   实测 `输出(结果)` 光标落在 `结果` 上时命中了它前面的 `(`（返回空 ⇒ 跳转失效）。
            let 止 = 起 + 词条长度(&t.类型).saturating_sub(1);
            if 光标字符列 >= 起 && 光标字符列 <= 止 {
                return Some((行下标, 词下标));
            }
        }
        return None;
    }
    None
}

fn 词条行号(行: &[&词条]) -> usize {
    行.first().map(|t| t.位置.行号).unwrap_or(0)
}

fn 命中区间(列: usize, 起: usize, 长度: usize) -> bool {
    起 != 0 && 列 >= 起 && 列 <= 起 + 长度
}

fn 是点号成员访问(行: &[&词条], 词下标: usize) -> bool {
    词下标 >= 2 && 是点号(行.get(词下标 - 1))
}

fn 是点号(t: Option<&&词条>) -> bool {
    matches!(t.map(|t| &t.类型), Some(词条类型::点))
}

fn 行首是导入关键字(行: &[&词条]) -> bool {
    matches!(行[0].类型, 词条类型::导入 | 词条类型::聚合导入)
}

fn 是关键字词(t: &词条类型, 关键字: &str) -> bool {
    词条关键字文本(t).map(|s| s == 关键字).unwrap_or(false)
}

fn 标识符名(t: &词条类型) -> Option<String> {
    match t {
        词条类型::标识符(s) | 词条类型::类型关键字(s) | 词条类型::外部标识符(s) => Some(s.clone()),
        _ => None,
    }
}

/// 可能出现在类型位置的外观：基本类型关键字 / 自定义类型名 / `任意`
fn 是类型外观(t: &词条类型) -> bool {
    matches!(t, 词条类型::类型关键字(_) | 词条类型::标识符(_) | 词条类型::任意)
}

fn 字符数(s: &str) -> usize {
    s.chars().count()
}

/// 词条在源码中占的**字符数**（只对第一阶段场景精确；其余给 1 足够命中判定）
