// 文件: 编辑器服务/src/悬停.rs
// 职责: 悬停提示（hover）—— 复用共享前端的**真语法树**给出**真实声明信息**
//
// ★ 改造前是什么样（`主程序.rs` 里被删掉的 `分析悬停` + `分析标识符`）：
//   取光标处单词 → 查一张**硬编码 16 个词的关键词表** → 命中给一句固定说明，
//   未命中一律返回 `` `X` — 标识符 ``。⇒ 对**任何**用户自定义符号都没有信息量：
//   函数签名、形参、返回类型、结构体字段、枚举成员、所属文件、声明行…… 一个都没有。
//
// 现在给出：
//   · **种类**（函数/方法/结构体字段/结构体/枚举/枚举成员/接口/接口方法/变量/常量/模块…）
//   · **签名**（`基数() 整数`、`打招呼(文本 名字) 文本`、`结构体 学生(文本 姓名, 整数 年龄)` …）
//     由 AST 的 `类型表达式` 现渲染 —— **不猜**、也不转写到另一套类型体系（避免两边语义漂移）
//   · **声明位置**：本文件第 N 行，或**跨文件**（`数学工具.基数` → `数值常量.智`）
//   · 局部变量/形参标为"局部作用域（第 N 行）"（其种类由 `定义跳转` 的同一套作用域规则判定）
//
// ⚠ 本阶段仍不支持的（**如实说明**，不假装有信息）：
//   实例成员 `甲.字段`（需类型推断）、接口→实现、运算符重载。

use crate::位置映射::行索引;
use crate::符号与引用 as 符号;
use frontend::语法分析::{
    参数传递方式, 形参, 导出块的项, 外部块的项, 函数定义, 顶层定义, 类型表达式, 结构体成员,
};
use lsp_types::{Position, Range, Url};
use std::path::Path;

/// 悬停入口。返回 `None` = 光标处没有可解释的东西（调用方回退到"无内容"）。
pub fn 悬停(
    源码: &str,
    文档URI: &Url,
    文件路径: Option<&Path>,
    位置: Position,
) -> Option<(String, Option<Range>)> {
    let 索引 = 行索引::新建(源码);
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return None;
    }
    // 光标处的词条：优先"标识符类"；否则退回**纯关键字**词条。
    // ⚠ 关键字悬停是**旧实现就有的能力**（它按文本取词），新实现若只认标识符词条会把
    //   `返回`/`如果`/`结束` 等的悬停整个丢掉 —— 实测被用例抓出，故必须显式兜住。
    let 光标下标 = match 符号::定位标识符(&索引, &词条列表, 位置) {
        Some(i) => i,
        None => 定位关键字词条(&索引, &词条列表, 位置)?,
    };
    let 词条 = &词条列表[光标下标];
    let 是标识符类 = 符号::标识符文本(&词条.类型).is_some();
    let 名 = match 符号::标识符文本(&词条.类型) {
        Some(s) => s,
        None => crate::定义跳转::词条关键字文本(&词条.类型)?.to_string(),
    };
    let 光标行号 = 词条.位置.行号; // 1-based（前端口径）
    let 光标范围 = 索引.前端范围(光标行号, 词条.位置.列号, 名.chars().count());

    // ── ① 关键字：这类没有声明可解析，给语言层面的固定说明 ──
    if let Some(说明) = 关键字说明(&名) {
        // `自身` 额外点出"当前所在结构体"（纯语法可得，不需要类型推断）
        let 附加 = if 名 == "自身" {
            crate::成员解析::所在结构体名(源码, 光标行号)
                .map(|s| format!("\n\n当前所在结构体：`{}`", s))
                .unwrap_or_default()
        } else {
            String::new()
        };
        return Some((format!("**关键字** · `{}`\n\n{}{}", 名, 说明, 附加), 光标范围));
    }
    if !是标识符类 {
        // 其余关键字（如 `否则如果` 之外的表外词）也如实说明，至少不返回空
        return Some((format!("**关键字** · `{}`", 名), 光标范围));
    }
    let 基础 = 符号::成员基础(&词条列表, 光标下标);
    let 本文件条目 = 收集条目(源码);

    // ── ② 成员访问 `基础.名`（解析顺序与 `主程序` 的跳转链保持一致）──
    if let Some(基) = 基础 {
        // ②a 模块成员（跨文件）：普通导入/别名/相对路径/聚合展开/聚合别名/展开裸名
        if let Some(文件) = 文件路径 {
            if let Some(命中) = crate::跨文件跳转::解析引用(源码, 文档URI, Some(文件), 位置)
                .into_iter()
                .find(|(_, 成员名, _)| 成员名 == &名)
            {
                if let Some(渲染文本) = 渲染跨文件(&命中.0, &名) {
                    return Some((渲染文本, 光标范围));
                }
            }
        }
        // ②b 第二阶段：`自身.成员` / 实例成员 `对象.成员`（轻量类型推断 + 跨文件类型定义）
        if let Some(命中) = crate::成员解析::解析成员(源码, 文件路径, &基, &名, 光标行号) {
            let 行号 = 命中.范围.start.line as usize + 1;
            let 文本 = match &命中.文件 {
                None => 查条目(&本文件条目, &名, Some(行号))
                    .map(渲染本文件)
                    .unwrap_or_else(|| format!("**`{}`** · 成员（本文件第 {} 行）", 名, 行号)),
                Some(f) => 渲染跨文件(f, &名).unwrap_or_else(|| {
                    let 文件名 = f
                        .file_name()
                        .map(|s| s.to_string_lossy().to_string())
                        .unwrap_or_default();
                    format!("**`{}`** · 成员（`{}`）", 名, 文件名)
                }),
            };
            return Some((文本, 光标范围));
        }
        // ②c 都解不了：**如实说清卡在哪一步**（三种原因不能混成一句），不编造声明信息
        let 提示 = match crate::成员解析::推断类型名_从源码(源码, &基, 光标行号) {
            // 推断出了类型，且该类型**确实存在**（本文档或导入的模块里）⇒ 真正的原因是**成员名不存在**
            Some(t) if crate::成员解析::有该类型(源码, 文件路径, &t) => format!(
                "`{}` 的类型推断为 `{}`，但该结构体（含其导入的模块）里**没有名为 `{}` 的字段或方法**。",
                基, t, 名
            ),
            // 推断出了类型名，但**找不到这个类型的定义** ⇒ 如实说"没找到类型"，不说"没有该成员"
            Some(t) => format!(
                "`{}` 的类型推断为 `{}`，但在本文档与导入的模块里都**没有找到 `{}` 的定义**。",
                基, t, t
            ),
            None => format!(
                "`{}` 的类型无法从本文档推断（既无类型标注，也非 `类型名(...)` 构造调用）。",
                基
            ),
        };
        return Some((
            format!("**`{}`** · 成员 · 所属对象 `{}`\n\n⚠ {}", 名, 基, 提示),
            光标范围,
        ));
    }

    // ── ③ 光标正落在**声明自己的名字**上（含块头首词）──
    //   ⚠ 必须先判这一条：否则会走 `定义跳转`，而它对"块头首词"返回的是**配对的 `结束` 行**
    //     （第一阶段既定的配对跳转语义）⇒ 之后按那行查声明必然落空、误报成"局部作用域"。
    if let Some(条目) = 查条目(&本文件条目, &名, Some(光标行号)) {
        return Some((渲染本文件(条目), 光标范围));
    }

    // ── ④ 同文件引用：用 `定义跳转`（同一套作用域/可见性规则）定位声明行 ──
    if let Some(声明) = crate::定义跳转::查找定义(源码, 文档URI, 文件路径, 位置)
        .into_iter()
        .next()
    {
        if 声明.uri == *文档URI {
            let 声明行号 = 声明.range.start.line as usize + 1;
            if let Some(条目) = 查条目(&本文件条目, &名, Some(声明行号)) {
                return Some((渲染本文件(条目), 光标范围));
            }
            // 展示"类型"：可能来自**显式标注**，也可能来自**构造调用推断** ⇒ 措辞用中性的"类型"
            // （说"推断为"在显式标注场景是错的）。内建基本类型不展示（声明行本身已写明，纯噪声）。
            let 推断 = crate::成员解析::推断类型名_从源码(源码, &名, 光标行号)
                .filter(|t| !matches!(t.as_str(), "整数" | "小数" | "文本" | "逻辑" | "空值"))
                .map(|t| format!(" · 类型 `{}`", t))
                .unwrap_or_default();
            return Some((
                format!("**`{}`** · 局部作用域内的声明（本文件第 {} 行）{}", 名, 声明行号, 推断),
                光标范围,
            ));
        }
    }

    // ── ⑤ 裸名也可能是跨文件来的（`导入 X 展开` 后的裸名）──
    if let Some(文件) = 文件路径 {
        if let Some(命中) = crate::跨文件跳转::解析引用(源码, 文档URI, Some(文件), 位置)
            .into_iter()
            .find(|(_, 成员名, _)| 成员名 == &名)
        {
            if let Some(渲染文本) = 渲染跨文件(&命中.0, &名) {
                return Some((渲染文本, 光标范围));
            }
        }
    }

    // ── ⑥ 链首是导入的模块名（光标在 `数学工具` 本身）──
    if let Some(模块路径) = 查导入模块(源码, &名) {
        return Some((
            format!(
                "**模块** · 导入自 `{}`\n\n（写 `{}.成员` 可跳到该模块的成员；`导入 … 展开` 后可写裸名）",
                模块路径, 名
            ),
            光标范围,
        ));
    }

    // ── ⑦ 实在解析不到：如实说，不编 ──
    Some((
        format!("**`{}`** · 未解析到声明（可能未定义，或属于实例成员）", 名),
        光标范围,
    ))
}

/// 光标落在**纯关键字**词条上时定位该词条（标识符类的由 `符号::定位标识符` 负责）。
fn 定位关键字词条(
    索引: &行索引,
    词条列表: &[frontend::词法分析::词条],
    位置: Position,
) -> Option<usize> {
    let 行号 = 位置.line as usize + 1;
    let (_, 列号) = 索引.LSP到前端(位置)?;
    for (i, 词) in 词条列表.iter().enumerate() {
        if 词.位置.行号 != 行号 {
            continue;
        }
        let Some(文本) = crate::定义跳转::词条关键字文本(&词.类型) else { continue };
        let 起 = 词.位置.列号;
        let 止 = 起 + 文本.chars().count();
        if 列号 >= 起 && 列号 <= 止 {
            return Some(i);
        }
    }
    None
}

/// 跨文件命中：读目标文件 → 按名取条目 → 渲染（带文件名）
fn 渲染跨文件(目标文件: &Path, 名: &str) -> Option<String> {
    let 目标源码 = std::fs::read_to_string(目标文件).ok()?;
    let 条目集 = 收集条目(&目标源码);
    let 条目 = 查条目(&条目集, 名, None)?;
    let 文件名 = 目标文件
        .file_name()
        .map(|s| s.to_string_lossy().to_string())
        .unwrap_or_default();
    Some(渲染(条目, Some(&文件名)))
}

fn 渲染本文件(条目: &条目) -> String {
    渲染(条目, None)
}

fn 渲染(条目: &条目, 文件名: Option<&str>) -> String {
    let 位置说明 = match (文件名, 条目.容器.as_deref()) {
        (Some(f), _) => format!("声明于 `{}`", f),
        (None, Some(容器)) => format!("声明于本文件第 {} 行（`{}` 的成员）", 条目.行号, 容器),
        (None, None) => format!("声明于本文件第 {} 行", 条目.行号),
    };
    format!("**{}** · `{}`\n\n{}", 条目.种类, 条目.签名, 位置说明)
}

// ============================================================
// 条目：由 AST 现算的"名字 → 声明信息"
// ============================================================
/// 一条声明信息。`签名` 直接由 AST 现渲染（不转写到另一套类型体系，避免两边语义漂移）。
struct 条目 {
    名字: String,
    种类: &'static str,
    签名: String,
    行号: usize,          // 1-based（前端口径）
    容器: Option<String>, // 结构体/枚举成员所属类型名
}

/// 查条目：给了 `行号` 就要求同行（用于"光标就在声明上"）；否则取首个同名。
fn 查条目<'a>(条目集: &'a [条目], 名: &str, 行号: Option<usize>) -> Option<&'a 条目> {
    条目集
        .iter()
        .find(|e| e.名字 == 名 && 行号.map(|h| h == e.行号).unwrap_or(true))
}

fn 造条目(
    名字: &str,
    种类: &'static str,
    签名: String,
    行号: usize,
    容器: Option<String>,
) -> 条目 {
    条目 { 名字: 名字.to_string(), 种类, 签名, 行号, 容器 }
}

fn 收集条目(源码: &str) -> Vec<条目> {
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return Vec::new();
    }
    let 程序 = 符号::解析(源码);
    let mut 出: Vec<条目> = Vec::new();

    for 定义 in &程序.顶层定义列表 {
        match 定义 {
            顶层定义::函数定义(f) => {
                出.push(造条目(&f.名称, "函数", 函数签名(f), f.位置.行号, None));
            }
            顶层定义::变量声明(v) => {
                出.push(造条目(&v.名称, "变量", 变量签名(&v.名称, v.类型标注.as_ref()), v.位置.行号, None));
            }
            顶层定义::常量声明(c) => {
                出.push(造条目(&c.名称, "常量", 变量签名(&c.名称, c.类型标注.as_ref()), c.位置.行号, None));
            }
            顶层定义::结构体定义(s) => {
                let 形参 = s
                    .形参列表
                    .iter()
                    .map(|p| match &p.类型标注 {
                        Some(t) => format!("{} {}", 类型文本(t), p.名称),
                        None => p.名称.clone(),
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                出.push(造条目(
                    &s.名称,
                    "结构体",
                    format!("结构体 {}({})", s.名称, 形参),
                    s.位置.行号,
                    None,
                ));
                // **构造参数**：无前缀通道 ⇒ 方法体内裸名可访问，`自身.参数` 也可访问
                // （`定义跳转`/`成员解析` 都把它们当可见成员，悬停的口径必须一致，否则
                //  `自身.姓名` 只能退化成"成员（本文件第 N 行）"，信息量骤降 —— 实测踩过）
                for p in &s.形参列表 {
                    出.push(造条目(
                        &p.名称,
                        "构造参数",
                        变量签名(&p.名称, p.类型标注.as_ref()),
                        p.位置.行号,
                        Some(s.名称.clone()),
                    ));
                }
                for 成员 in &s.成员列表 {
                    match 成员 {
                        结构体成员::字段 { 名称, 类型标注, 位置, .. } => 出.push(造条目(
                            名称,
                            "结构体字段",
                            变量签名(名称, 类型标注.as_ref()),
                            位置.行号,
                            Some(s.名称.clone()),
                        )),
                        结构体成员::方法(f) | 结构体成员::初始化(f) => 出.push(造条目(
                            &f.名称,
                            "结构体方法",
                            函数签名(f),
                            f.位置.行号,
                            Some(s.名称.clone()),
                        )),
                    }
                }
            }
            顶层定义::枚举定义(e) => {
                出.push(造条目(&e.名称, "枚举", format!("枚举 {}", e.名称), e.位置.行号, None));
                for 成员 in &e.成员列表 {
                    出.push(造条目(
                        &成员.名称,
                        "枚举成员",
                        成员.名称.clone(),
                        成员.位置.行号,
                        Some(e.名称.clone()),
                    ));
                }
            }
            顶层定义::接口定义(i) => {
                出.push(造条目(&i.名称, "接口", format!("接口 {}", i.名称), i.位置.行号, None));
                for 方法 in &i.方法声明列表 {
                    出.push(造条目(
                        &方法.名称,
                        "接口方法",
                        签名文本(&方法.名称, &方法.形参列表, 方法.返回类型.as_ref()),
                        方法.位置.行号,
                        Some(i.名称.clone()),
                    ));
                }
            }
            顶层定义::外部块(块) => {
                for 项 in &块.项列表 {
                    match 项 {
                        外部块的项::外部函数定义(f) => 出.push(造条目(
                            &f.名称,
                            "外部函数",
                            签名文本(&f.名称, &f.形参列表, f.返回类型.as_ref()),
                            f.位置.行号,
                            None,
                        )),
                        外部块的项::外部变量定义(v) => 出.push(造条目(
                            &v.名称,
                            "外部变量",
                            format!("{} {}", 类型文本(&v.类型), v.名称),
                            v.位置.行号,
                            None,
                        )),
                        外部块的项::外部结构体定义(s) => 出.push(造条目(
                            &s.名称,
                            "外部结构体",
                            format!("结构体 {}", s.名称),
                            s.位置.行号,
                            None,
                        )),
                        外部块的项::外部常量(c) => 出.push(造条目(
                            &c.名称,
                            "外部常量",
                            变量签名(&c.名称, c.类型标注.as_ref()),
                            c.位置.行号,
                            None,
                        )),
                        外部块的项::外部库声明(_)
                        | 外部块的项::外部函数映射声明(_)
                        | 外部块的项::外部变量映射声明(_) => {}
                    }
                }
            }
            顶层定义::导出块(块) => {
                for 项 in &块.项列表 {
                    match 项 {
                        导出块的项::导出函数(f) => {
                            出.push(造条目(&f.名称, "导出函数", 函数签名(f), f.位置.行号, None));
                        }
                        导出块的项::导出变量(v) => 出.push(造条目(
                            &v.名称,
                            "导出变量",
                            变量签名(&v.名称, v.类型标注.as_ref()),
                            v.位置.行号,
                            None,
                        )),
                        导出块的项::导出引用(_) => {}
                    }
                }
            }
        }
    }

    // 程序入口
    if let Some(入口) = &程序.入口 {
        出.push(造条目(
            "启动程序",
            "程序入口",
            "启动程序()".to_string(),
            入口.位置.行号,
            None,
        ));
    }
    出
}

fn 变量签名(名: &str, 类型标注: Option<&类型表达式>) -> String {
    match 类型标注 {
        Some(t) => format!("{} {}", 类型文本(t), 名),
        None => format!("{}（类型由初始值推断）", 名),
    }
}

fn 函数签名(f: &函数定义) -> String {
    签名文本(&f.名称, &f.形参列表, f.返回类型.as_ref())
}

fn 签名文本(名: &str, 形参列表: &[形参], 返回类型: Option<&类型表达式>) -> String {
    let 形参 = 形参列表
        .iter()
        .map(|p| {
            let 主体 = match &p.类型标注 {
                Some(t) => format!("{} {}", 类型文本(t), p.名称),
                None => p.名称.clone(),
            };
            // 传递方式：不臆测语法顺序，如实附注
            if matches!(p.传递方式, 参数传递方式::传引用) {
                format!("{}（传引用）", 主体)
            } else {
                主体
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    let 返回 = 返回类型.map(|t| format!(" {}", 类型文本(t))).unwrap_or_default();
    format!("{}({}){}", 名, 形参, 返回)
}

/// `类型表达式` → 文本（**展示层唯一转换点**）。
fn 类型文本(类型: &类型表达式) -> String {
    match 类型 {
        类型表达式::基本类型(名) => 名.clone(),
        类型表达式::数组(元素) => format!("数组<{}>", 类型文本(元素)),
        类型表达式::映射(键, 值) => format!("映射<{}, {}>", 类型文本(键), 类型文本(值)),
        类型表达式::泛型 { 名称, 类型参数 } => {
            let 参数 = 类型参数.iter().map(类型文本).collect::<Vec<_>>().join(", ");
            format!("{}<{}>", 名称, 参数)
        }
        类型表达式::任意类型 { 标记名称, 约束范围 } => {
            let 约束 = 约束范围.iter().map(类型文本).collect::<Vec<_>>().join("|");
            match (标记名称, 约束.is_empty()) {
                (Some(名), false) => format!("任意<{}: {}>", 名, 约束),
                (Some(名), true) => format!("任意<{}>", 名),
                (None, false) => format!("任意<{}>", 约束),
                (None, true) => "任意".to_string(),
            }
        }
        类型表达式::函数类型 { 参数类型列表, 返回类型 } => {
            let 参数 = 参数类型列表.iter().map(类型文本).collect::<Vec<_>>().join(", ");
            format!("({}) -> {}", 参数, 类型文本(返回类型))
        }
    }
}

/// 链首是否命中某个导入声明的**可用名**（别名或模块路径末段）⇒ 返回完整模块路径。
fn 查导入模块(源码: &str, 名: &str) -> Option<String> {
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return None;
    }
    let 程序 = 符号::解析(源码);
    for 导入 in &程序.导入列表 {
        let 可用 = 导入
            .别名
            .clone()
            .or_else(|| 导入.模块路径.last().cloned())
            .unwrap_or_default();
        if 可用 == 名 {
            return Some(导入.模块路径.join("/"));
        }
    }
    None
}

