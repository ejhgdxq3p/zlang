// 文件: 编辑器服务/src/成员解析.rs
// 职责: **第二阶段** —— `自身.成员` 与**实例成员** `对象.成员` 的解析
//
// 为什么需要"类型"：`对象.成员` 必须先知道 `对象` 是什么类型，才能确定成员声明在哪。
// 本模块用**轻量推断**（**明确不假装是完整类型系统**）：
//   ① **`自身.成员`**：纯语法即可 —— 找到光标所在的 `结构体` 定义，在其成员列表里查名。
//      这也是规范里最常用、收益最大的形态（结构体方法内访问字段）。
//   ② **实例成员**：先推断"变量/形参/构造参数"的**类型名**，再在该类型的成员列表里查名。类型名来源（按优先级）：
//        a. **显式类型标注**（`学生 甲 = …`、形参 `学生 甲`、结构体构造参数）
//        b. **构造调用**（`甲 = 学生(…)` ⇒ 类型名就是被调用者名）
//      取**光标行之前最近一次**该名字的声明（近似"最近声明优先"；不追求完整作用域消解 —— 见下）
//
// ⚠ 边界（**如实标注，不宣称超出能力**）：
//   · 成员所属**结构体必须定义在本文档内**（跨文件的类型定义暂不解，属下一步）；
//   · 不做完整作用域/遮蔽消解，也不做赋值传播（`甲 = 学生(); 甲 = 别的` 仍按最近声明取类型）；
//   · 不做泛型/接口/适配解析。这些都不影响"能用"：解析不到就返回空，由上层如实说明。

use crate::位置映射::行索引;
use crate::符号与引用 as 符号;
use frontend::语法分析::{
    形参, 表达式, 顶层定义, 类型表达式, 结构体定义, 结构体成员, 语句, 程序,
};
use lsp_types::{Location, Position, Range, Url};
use std::collections::HashMap;
use std::path::{Path, PathBuf};

/// 解析命中：目标文件（`None` = 当前文档）+ 成员名 + 范围
pub(crate) struct 命中 {
    pub 文件: Option<PathBuf>,
    pub 名字: String,
    pub 范围: Range,
}

/// 解析 `基础.成员`。返回 `None` = 本阶段解不了（上层如实说明，不猜）。
pub(crate) fn 解析成员(
    源码: &str,
    当前文件: Option<&Path>,
    基础名: &str,
    成员名: &str,
    光标行号: usize,
) -> Option<命中> {
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return None;
    }
    let 程序 = 符号::解析(源码);
    let 索引 = 行索引::新建(源码);
    let 配对 = crate::定义跳转::块配对(源码);
    let 上下文 = 上行文 { 索引: &索引, 词条列表: &词条列表 };

    // ── ① `自身.成员`：找光标所在的 `结构体`，在其成员里查 ──
    if 基础名 == "自身" {
        let 结构体 = 所在结构体(&程序, &配对, 光标行号)?;
        let 范围 = 上下文.成员范围(结构体, 成员名)?;
        return Some(命中 { 文件: None, 名字: 成员名.to_string(), 范围 });
    }

    // ── ② 实例成员：先推断类型名 ──
    let 类型名 = 推断类型名(&程序, &配对, 基础名, 光标行号)?;

    // ②a 类型定义在**本文档**内
    for 定义 in &程序.顶层定义列表 {
        if let 顶层定义::结构体定义(s) = 定义 {
            if s.名称 == 类型名 {
                let 范围 = 上下文.成员范围(s, 成员名)?;
                return Some(命中 { 文件: None, 名字: 成员名.to_string(), 范围 });
            }
        }
    }

    // ②b 类型定义在**导入的模块**里（跨文件类型定义）
    if let Some(文件) = 当前文件 {
        return 跨文件查成员(源码, 文件, &类型名, 成员名);
    }
    None
}

/// 在**本文档导入到的模块文件**里找同名 `结构体`，并解析其成员。
///
/// ★ 为什么必须做：`甲 = 学生(…)` 里的 `学生` 常常定义在**另一个模块**（`导入 核心库/学生`）。
///   不做这一步，这类（很常见的）实例成员就永远只能给出"跨文件类型定义待支持"的提示。
/// ⚠ 文件集合交给 `跨文件跳转::已加载模块文件` —— 它走的是**编译器的模块加载器**
///   （项目根/源码根/标准库/已安装库 四类搜索根 + 相对导入 + 聚合再导出），不自己拼路径。
/// ⚠ 命中多个同名结构体时取**第一个能解析出该成员**的（同名类型在不同模块里成员可能不同）。
fn 跨文件查成员(源码: &str, 当前文件: &Path, 类型名: &str, 成员名: &str) -> Option<命中> {
    for 文件 in crate::跨文件跳转::已加载模块文件(源码, 当前文件) {
        let Ok(内容) = std::fs::read_to_string(&文件) else { continue };
        // ⚠ 别的文件必须传**真实路径**：参与缓存键，也决定 AST 里 `源码位置.文件路径`
        let 路径文本 = 文件.to_string_lossy().to_string();
        let 词条列表 = crate::缓存::词法分析(&路径文本, &内容);
        if 词条列表.is_empty() {
            continue;
        }
        let 程序 = 符号::解析带路径(&路径文本, &内容);
        let Some(结构体) = 程序.顶层定义列表.iter().find_map(|d| match d {
            顶层定义::结构体定义(s) if s.名称 == 类型名 => Some(s),
            _ => None,
        }) else {
            continue;
        };
        let 索引 = 行索引::新建(&内容);
        let 上下文 = 上行文 { 索引: &索引, 词条列表: &词条列表 };
        if let Some(范围) = 上下文.成员范围(结构体, 成员名) {
            return Some(命中 { 文件: Some(文件), 名字: 成员名.to_string(), 范围 });
        }
    }
    None
}

/// 便利入口：直接从「光标处词条」取出 `基础名.成员名` 再解析，产出 LSP `Location`。
/// **只在"光标位于成员位置"时生效**（`符号::成员基础` 为 `None` 时直接返回空）。
pub(crate) fn 查找定义(
    源码: &str,
    文档URI: &Url,
    文件路径: Option<&Path>,
    位置: Position,
) -> Vec<Location> {
    let 索引 = 行索引::新建(源码);
    let 词条列表 = 符号::词法分析(源码);
    let Some(下标) = 符号::定位标识符(&索引, &词条列表, 位置) else {
        return Vec::new();
    };
    let Some(成员名) = 符号::标识符文本(&词条列表[下标].类型) else {
        return Vec::new();
    };
    let Some(基础名) = 符号::成员基础(&词条列表, 下标) else {
        return Vec::new();
    };
    let 光标行号 = 词条列表[下标].位置.行号;
    let Some(命中) = 解析成员(源码, 文件路径, &基础名, &成员名, 光标行号) else {
        return Vec::new();
    };
    let uri = match &命中.文件 {
        // ⚠ 盘符规范成小写（与编辑器发出的文档 URI 同形）
        Some(文件) => match crate::位置映射::文件URI(文件) {
            Some(u) => u,
            None => return Vec::new(),
        },
        None => 文档URI.clone(),
    };
    vec![Location { uri, range: 命中.范围 }]
}

/// 本文档里是否有名为 `类型名` 的 `结构体` 定义。
/// 供悬停**区分**提示口径：成员名不存在 / 类型定义在别的文件 —— 两者原因不同，不能说成一句。
pub(crate) fn 本文件有结构体(源码: &str, 类型名: &str) -> bool {
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return false;
    }
    let 程序 = 符号::解析(源码);
    程序.顶层定义列表.iter().any(|d| match d {
        顶层定义::结构体定义(s) => s.名称 == 类型名,
        _ => false,
    })
}

/// 该类型名是否有 `结构体` 定义（本文档 **或** 导入的模块里）。
/// 供悬停**区分**提示口径："成员名不存在" 与 "类型根本没定义" 是两种不同的原因。
pub(crate) fn 有该类型(源码: &str, 当前文件: Option<&Path>, 类型名: &str) -> bool {
    if 本文件有结构体(源码, 类型名) {
        return true;
    }
    let Some(文件) = 当前文件 else { return false };
    for 模块文件 in crate::跨文件跳转::已加载模块文件(源码, 文件) {
        let Ok(内容) = std::fs::read_to_string(&模块文件) else { continue };
        if 本文件有结构体(&内容, 类型名) {
            return true;
        }
    }
    false
}

/// 便利入口：从源码现解析后推断类型名（供悬停展示"推断为 X"）。
pub(crate) fn 推断类型名_从源码(源码: &str, 名: &str, 光标行号: usize) -> Option<String> {
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return None;
    }
    let 程序 = 符号::解析(源码);
    推断类型名(&程序, &crate::定义跳转::块配对(源码), 名, 光标行号)
}

/// 光标所在的 `结构体`（取**最内层**：块范围包含光标行、且起行最大者）。
pub(crate) fn 所在结构体名(源码: &str, 光标行号: usize) -> Option<String> {
    let 词条列表 = 符号::词法分析(源码);
    if 词条列表.is_empty() {
        return None;
    }
    let 程序 = 符号::解析(源码);
    let 配对 = crate::定义跳转::块配对(源码);
    所在结构体(&程序, &配对, 光标行号).map(|s| s.名称.clone())
}

fn 所在结构体<'a>(
    程序: &'a 程序,
    配对: &HashMap<usize, usize>,
    光标行号: usize,
) -> Option<&'a 结构体定义> {
    let mut 最佳: Option<&结构体定义> = None;
    for 定义 in &程序.顶层定义列表 {
        let 顶层定义::结构体定义(s) = 定义 else { continue };
        let 起 = s.位置.行号;
        let 止 = 配对.get(&起).copied().unwrap_or(起);
        if 光标行号 < 起 || 光标行号 > 止 {
            continue;
        }
        if 最佳.map(|b| 起 > b.位置.行号).unwrap_or(true) {
            最佳 = Some(s);
        }
    }
    最佳
}

/// 推断某个名字的**类型名**（供上层在悬停里显示"推断为 X"）。
///
/// ⚠ **只看光标所在作用域**：先前的版本扫了**全部函数**的形参/局部，跨函数同名会给出**错误结果**
/// （典型：`甲` 是另一个函数的形参，却在本文档别处被"推断"成那个类型）。现在按可见范围收敛：
///   ① 模块级变量/常量（全模块可见）
///   ② **光标所在函数**（最内层）的形参与局部语句
///   ③ **光标所在结构体**的构造参数（仅其方法内可见）
pub(crate) fn 推断类型名(
    程序: &程序,
    配对: &HashMap<usize, usize>,
    名: &str,
    光标行号: usize,
) -> Option<String> {
    let 函数名集 = 顶层函数名集(程序);
    // ★ 按**名字**建表（而不是只收集目标名的候选）：沿「取自」链要能查到中间变量。
    //   收集范围与原来**完全一致**（模块级 + 光标所在函数/入口 + 所在结构体构造参数），
    //   所以作用域收敛反证（同名形参不被别的函数污染）依旧成立。
    let mut 表: HashMap<String, Vec<(usize, 类型来源)>> = HashMap::new();

    // ① 模块级
    for 定义 in &程序.顶层定义列表 {
        match 定义 {
            顶层定义::变量声明(v) => 插(
                &mut 表,
                &v.名称,
                v.位置.行号,
                声明来源(v.类型标注.as_ref(), v.初始值.as_ref(), &函数名集),
            ),
            顶层定义::常量声明(c) => 插(
                &mut 表,
                &c.名称,
                c.位置.行号,
                声明来源(c.类型标注.as_ref(), Some(&c.初始值), &函数名集),
            ),
            _ => {}
        }
    }

    // ② 光标所在函数（或程序入口）的形参与局部
    if let Some(f) = 所在函数(程序, 配对, 光标行号) {
        形参里找(&f.形参列表, &mut 表);
        语句里找(&f.函数体, &mut 表, &函数名集);
    } else if let Some(入口) = &程序.入口 {
        if 范围含(配对, 入口.位置.行号, 光标行号) {
            语句里找(&入口.函数体, &mut 表, &函数名集);
        }
    }

    // ③ 光标所在结构体的构造参数（结构体方法内按裸名可见）
    if let Some(s) = 所在结构体(程序, 配对, 光标行号) {
        形参里找(&s.形参列表, &mut 表);
    }

    resolve(名, 光标行号, &表, &mut Vec::new())
}

/// 一个名字在某处的类型**从哪来**。
///
/// ★ 为什么要区分两种来源：`甲 = 学生(…)`（**直接**构造）与 `乙 = 甲`（**取自**另一个变量）。
///   后者是**变量间拷贝**——极常见的写法；原先只认"构造调用"，`乙` 的值是标识符 ⇒ 类型推不出
///   ⇒ `乙.字段` 无法跳转。这是真实缺口（不是"按最近声明取"的措辞问题）。
#[derive(Clone, Debug, PartialEq)]
enum 类型来源 {
    /// 类型名已直接确定（显式标注，或构造调用）
    直接(String),
    /// 类型等同于另一个变量的类型（`乙 = 甲`）⇒ 需**继续沿它解析**
    取自(String),
}

/// 声明/赋值处的类型来源：**标注优先**，否则看初始值（构造调用 or 另一个变量）。
fn 声明来源(
    标注: Option<&类型表达式>,
    初始值: Option<&表达式>,
    函数名集: &std::collections::HashSet<String>,
) -> Option<类型来源> {
    if let Some(t) = 标注名(标注) {
        return Some(类型来源::直接(t));
    }
    初始值来源(初始值, 函数名集)
}

/// 初始值能给出什么类型：`学生(…)` ⇒ 直接；`甲` ⇒ 取自 `甲`；其余（字面量/调用函数）⇒ 无。
fn 初始值来源(
    初始值: Option<&表达式>,
    函数名集: &std::collections::HashSet<String>,
) -> Option<类型来源> {
    match 初始值? {
        表达式::标识符(名, _) => Some(类型来源::取自(名.clone())),
        _ => 构造名(Some(初始值?), 函数名集).map(类型来源::直接),
    }
}

/// 沿「取自」链把类型解析到底。
///
/// ⚠ `环` 是**必需的环保护**：`甲 = 乙` / `乙 = 甲` 在真实代码里会出现，
///   无保护会**无限递归**（爆栈）。成环时返回 `None` = 如实解不出，与整体约定一致。
/// ⚠ 光标行号**始终用调用方那个**：链条中间的变量可能声明在光标之后，
///   但对"光标处这个变量到底是什么"而言，仍以光标位置为准取最近声明（保持原语义不变）。
fn resolve(
    名: &str,
    光标行号: usize,
    表: &HashMap<String, Vec<(usize, 类型来源)>>,
    环: &mut Vec<String>,
) -> Option<String> {
    if 环.iter().any(|n| n == 名) {
        return None; // 已在解析链上 ⇒ 成环
    }
    let 候选 = 表.get(名)?;
    // 「最近声明优先」：取**光标行之前**最靠后的一条；都没有则退回最后一条
    let 选中 = 候选
        .iter()
        .rev()
        .find(|(行, _)| *行 <= 光标行号)
        .or_else(|| 候选.last())?;
    match &选中.1 {
        类型来源::直接(t) => Some(t.clone()),
        类型来源::取自(下一个) => {
            环.push(名.to_string());
            let 出 = resolve(下一个, 光标行号, 表, 环);
            环.pop();
            出
        }
    }
}

fn 范围含(配对: &HashMap<usize, usize>, 起行: usize, 光标行号: usize) -> bool {
    let 止 = 配对.get(&起行).copied().unwrap_or(起行);
    光标行号 >= 起行 && 光标行号 <= 止
}

/// 光标所在的**最内层函数定义**（含结构体方法/初始化；程序入口无 `函数定义`，由调用方单独处理）
fn 所在函数<'a>(
    程序: &'a 程序,
    配对: &HashMap<usize, usize>,
    光标行号: usize,
) -> Option<&'a frontend::语法分析::函数定义> {
    let mut 最佳: Option<&frontend::语法分析::函数定义> = None;
    let mut 试 = |f: &'a frontend::语法分析::函数定义| {
        if 范围含(配对, f.位置.行号, 光标行号)
            && 最佳.map(|b| f.位置.行号 > b.位置.行号).unwrap_or(true)
        {
            最佳 = Some(f);
        }
    };
    for 定义 in &程序.顶层定义列表 {
        match 定义 {
            顶层定义::函数定义(f) => 试(f),
            顶层定义::结构体定义(s) => {
                for 成员 in &s.成员列表 {
                    match 成员 {
                        结构体成员::方法(f) | 结构体成员::初始化(f) => 试(f),
                        _ => {}
                    }
                }
            }
            _ => {}
        }
    }
    最佳
}

/// 往表里插一条候选（行号 + 类型来源）；无来源（推不出类型）则**不插**。
fn 插(
    表: &mut HashMap<String, Vec<(usize, 类型来源)>>,
    名: &str,
    行号: usize,
    来源: Option<类型来源>,
) {
    if let Some(源) = 来源 {
        表.entry(名.to_string()).or_default().push((行号, 源));
    }
}

fn 形参里找(形参列表: &[形参], 表: &mut HashMap<String, Vec<(usize, 类型来源)>>) {
    for p in 形参列表 {
        插(
            表,
            &p.名称,
            p.位置.行号,
            标注名(p.类型标注.as_ref()).map(类型来源::直接),
        );
    }
}

/// 顶层函数名集合（用于排除"调用普通函数被误当构造"）
fn 顶层函数名集(程序: &程序) -> std::collections::HashSet<String> {
    let mut 集 = std::collections::HashSet::new();
    for 定义 in &程序.顶层定义列表 {
        if let 顶层定义::函数定义(f) = 定义 {
            集.insert(f.名称.clone());
        }
    }
    集
}

/// 递归遍历语句，收集同名变量/常量的类型候选
fn 语句里找(
    语句列表: &[语句],
    表: &mut HashMap<String, Vec<(usize, 类型来源)>>,
    函数名集: &std::collections::HashSet<String>,
) {
    for 条 in 语句列表 {
        match 条 {
            语句::变量声明(v) => 插(
                表,
                &v.名称,
                v.位置.行号,
                声明来源(v.类型标注.as_ref(), v.初始值.as_ref(), 函数名集),
            ),
            语句::常量声明(c) => 插(
                表,
                &c.名称,
                c.位置.行号,
                声明来源(c.类型标注.as_ref(), Some(&c.初始值), 函数名集),
            ),
            // ⚠ **隐式声明 `甲 = 值`** 会被解析成 `语句::赋值`，而不是 `变量声明`
            //   （规范：声明与赋值同形，靠"当前作用域是否已有该名字"区分 —— 语法层无从判别）
            //   漏掉这一支 ⇒ 最常见的 `实例甲 = 学生(…)` **推断不出类型**（实测被用例抓出）。
            // ★ 这里也用 `初始值来源`（而非 `构造名`）⇒ `乙 = 甲` 会记成「取自 甲」，可继续传递。
            语句::赋值(赋) => {
                if let 表达式::标识符(目标名, 位置) = &赋.目标 {
                    插(
                        表,
                        目标名,
                        位置.行号,
                        初始值来源(Some(&赋.值), 函数名集),
                    );
                }
            }
            语句::条件语句(条件) => {
                for (_, 体) in &条件.分支列表 {
                    语句里找(体, 表, 函数名集);
                }
                if let Some(体) = &条件.否则分支 {
                    语句里找(体, 表, 函数名集);
                }
            }
            语句::循环语句(循环) => 语句里找(&循环.循环体, 表, 函数名集),
            语句::遍历语句(遍历) => 语句里找(&遍历.循环体, 表, 函数名集),
            语句::无限循环语句(循环) => 语句里找(&循环.循环体, 表, 函数名集),
            语句::异常控制(异常) => {
                语句里找(&异常.危险块, 表, 函数名集);
                语句里找(&异常.异常块, 表, 函数名集);
                语句里找(&异常.始终块, 表, 函数名集);
            }
            语句::代码块(体) => 语句里找(体, 表, 函数名集),
            _ => {}
        }
    }
}

/// 显式类型标注里的类型名（`学生 甲` / `数组<学生>` 取外层名）
fn 标注名(类型标注: Option<&类型表达式>) -> Option<String> {
    match 类型标注? {
        类型表达式::基本类型(名) => Some(名.clone()),
        类型表达式::泛型 { 名称, .. } => Some(名称.clone()),
        _ => None,
    }
}

/// 构造调用 `类型名(...)` ⇒ 类型名就是被调用者名（`甲 = 学生(…)`）
///
/// ⚠ **必须排除"调用普通函数"**：`甲 = 取数()` 里 `取数` 是**函数**不是类型 ——
///   若不过滤就会把函数名当类型名，进而给出"该类型里没有成员"这类**误导性**提示（实测踩过）。
fn 构造名(初始值: Option<&表达式>, 函数名集: &std::collections::HashSet<String>) -> Option<String> {
    match 初始值? {
        表达式::调用 { 被调用者, .. } => match 被调用者.as_ref() {
            表达式::标识符(名, _) if !函数名集.contains(名) => Some(名.clone()),
            // ★ 跨模块构造：`甲 = 学生模型.学生(…)` ⇒ **类型名是成员名**（模块路径不参与类型名，
             //   与 `类型标注` 里写裸类型名一致 —— 已用探针验证该写法零诊断）。
            //   误判风险已由下游挡住：`跨文件查成员` 要求目标模块里**真有同名 `结构体`**，
            //   所以 `工具.问候()`（模块函数调用）不会被当成类型。
            表达式::成员访问 { 成员名, .. } => Some(成员名.clone()),
            _ => None,
        },
        _ => None,
    }
}

// ============================================================
// 成员范围（列必须用**词条流**取，AST 的 `位置` 是**声明起点**：
// 字段 `私有 文本 密码` 的位置落在 `私有`/`文本` 上，不是 `密码`）
// ============================================================
struct 上行文<'a> {
    索引: &'a 行索引,
    词条列表: &'a [frontend::词法分析::词条],
}

impl<'a> 上行文<'a> {
    /// 在结构体里找成员：**构造参数**（`结构体 学生(文本 姓名, …)`）与**成员列表**都算
    /// （`定义跳转` 也把构造参数当作可见声明，两处口径必须一致）。
    fn 成员范围(&self, 结构体: &结构体定义, 成员名: &str) -> Option<Range> {
        for p in &结构体.形参列表 {
            if p.名称 == 成员名 {
                return self.名字范围(p.位置.行号, &p.名称);
            }
        }
        for 成员 in &结构体.成员列表 {
            match 成员 {
                结构体成员::字段 { 名称, 位置, .. } if 名称 == 成员名 => {
                    return self.名字范围(位置.行号, 名称);
                }
                结构体成员::方法(f) | 结构体成员::初始化(f) if f.名称 == 成员名 => {
                    return self.名字范围(f.位置.行号, &f.名称);
                }
                _ => {}
            }
        }
        None
    }

    /// 在声明行上用词条流取名字的精确列（取不到再退回 AST 位置）
    fn 名字范围(&self, 行号: usize, 名: &str) -> Option<Range> {
        for 词 in self.词条列表.iter().filter(|t| t.位置.行号 == 行号) {
            if 符号::标识符文本(&词.类型).as_deref() == Some(名) {
                return self.索引.前端范围(词.位置.行号, 词.位置.列号, 名.chars().count());
            }
        }
        None
    }
}

