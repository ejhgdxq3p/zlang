// 文件: 编辑器服务/src/缓存.rs
// 职责: **内容指纹键控**的词法/语法结果复用（跳转方案 §13.4 第 4 项"增量索引"的基础设施）
//
// ★ 为什么键是「文件路径 + 内容指纹」，而不是 (uri, 版本号) 或 mtime：
//   内容就是唯一真相 —— 文本没变，词法/语法结果必然相同；文本一变，指纹就变。
//   ⇒ **结构上不可能返回陈旧结果**，也就不需要任何失效逻辑；
//     而"需要手工在某个入口失效缓存"恰恰是这类 bug 的唯一来源（漏一处就出诡异结果）。
//   ⚠ 路径必须参与键：`词条`/`源码位置` 里**内嵌文件路径**（供跨文件跳转判断"定义在哪个文件"），
//     同一份内容以不同路径加载时 AST 并不等价。
//
// ★ 为什么值得做：一次 LSP 请求（悬停/跳转/引用）会**反复**词法+语法同一份源码 ——
//   实测同一份文档在一次"转到定义"里被解析 3~4 遍（`块配对` 内部也要一遍），
//   跨文件引用扫描更是对每个候选文件都做一遍。重复解析是当前唯一的性能瓶颈。
//
// ★ 上限与淘汰：FIFO（不做真 LRU）—— 编辑器里"最近改动/查看的几份文件"天然是热点，
//   而 LRU 要多维护访问时间戳，在本负载下收益不划算。上限内即整体命中。

use frontend::诊断收集器::诊断收集器;
use frontend::词法分析::{词条, 词法分析器};
use frontend::语法分析::{语法分析器, 程序};
use std::cell::RefCell;
use std::collections::{HashMap, VecDeque};
use std::rc::Rc;

/// 一个"文件内容"对应的词法/语法结果。
/// `程序` 惰性构建：只要词条的调用方（如只做词法预筛的跨文件扫描）**不会**被迫付解析成本。
struct 条目 {
    词条列表: Rc<Vec<词条>>,
    程序: Option<Rc<程序>>,
}

/// 内容指纹键控的源码缓存。
pub struct 源码缓存 {
    上限: usize,
    顺序: VecDeque<u64>,
    映射: HashMap<u64, 条目>,
    命中: u64,
    未命中: u64,
}

impl 源码缓存 {
    pub fn 新建(上限: usize) -> Self {
        源码缓存 {
            上限: 上限.max(1),
            顺序: VecDeque::new(),
            映射: HashMap::new(),
            命中: 0,
            未命中: 0,
        }
    }

    /// (命中次数, 未命中次数) —— 供单测断言"确实省下了重复解析"
    pub fn 统计(&self) -> (u64, u64) {
        (self.命中, self.未命中)
    }

    pub fn 清空(&mut self) {
        self.顺序.clear();
        self.映射.clear();
        self.命中 = 0;
        self.未命中 = 0;
    }

    /// 取（必要时构建）某份源码的词条列表。
    pub fn 取词条(&mut self, 文件路径: &str, 源码: &str) -> Rc<Vec<词条>> {
        let 键 = 键(文件路径, 源码);
        if let Some(条目) = self.映射.get(&键) {
            self.命中 += 1;
            return 条目.词条列表.clone();
        }
        self.未命中 += 1;
        let 词条列表 = Rc::new(扫描词条(源码, 文件路径));
        self.插入(键, 条目 { 词条列表: 词条列表.clone(), 程序: None });
        词条列表
    }

    /// 取（必要时构建）某份源码的语法树。
    pub fn 取程序(&mut self, 文件路径: &str, 源码: &str) -> Rc<程序> {
        let 键 = 键(文件路径, 源码);
        if let Some(条目) = self.映射.get(&键) {
            if let Some(程序) = &条目.程序 {
                self.命中 += 1;
                return 程序.clone();
            }
            // 词条在缓存、语法树还没建 ⇒ 就地补上
            let 程序 = Rc::new(解析程序(&条目.词条列表));
            self.映射.get_mut(&键).unwrap().程序 = Some(程序.clone());
            self.命中 += 1;
            return 程序;
        }
        self.未命中 += 1;
        let 词条列表 = Rc::new(扫描词条(源码, 文件路径));
        let 程序 = Rc::new(解析程序(&词条列表));
        self.插入(
            键,
            条目 { 词条列表, 程序: Some(程序.clone()) },
        );
        程序
    }

    fn 插入(&mut self, 键: u64, 条目: 条目) {
        if self.映射.insert(键, 条目).is_none() {
            self.顺序.push_back(键);
        }
        while self.顺序.len() > self.上限 {
            if let Some(旧) = self.顺序.pop_front() {
                self.映射.remove(&旧);
            }
        }
    }
}

/// 词法分析（**允许有诊断**：编辑器里代码常是半成品，词法结果照样可用于跳转/大纲）
fn 扫描词条(源码: &str, 文件路径: &str) -> Vec<词条> {
    let mut 诊断 = 诊断收集器::新建();
    词法分析器::新建(源码, 文件路径.to_string(), &mut 诊断).扫描所有词条()
}

/// 语法分析（**允许有诊断**：`解析程序` 自带错误恢复，顶层定义通常已可用）
fn 解析程序(词条列表: &[词条]) -> 程序 {
    let mut 诊断 = 诊断收集器::新建();
    语法分析器::新建(词条列表, &mut 诊断).解析程序()
}

/// FNV-1a 64 位 —— 自实现，不引新依赖。
/// 我们只需要"内容变没变"，不需要抗碰撞强度；且未命中时会重算，碰撞的后果只是**多解析一次**。
fn 指纹(字节: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in 字节 {
        h ^= *b as u64;
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    h
}

/// (文件路径, 内容) → 键。两条各自哈希后**混合**，避免"路径 A+内容 B"与"路径 B+内容 A"同键。
fn 键(文件路径: &str, 源码: &str) -> u64 {
    指纹(文件路径.as_bytes())
        .rotate_left(31)
        .wrapping_mul(0x9e37_79b9_7f4a_7c15)
        ^ 指纹(源码.as_bytes())
}

/// 条目上限。每条约持有"词条 + AST"，宽文件上百 KB ⇒ 64 条的上界约十几 MB，可接受。
const 默认上限: usize = 64;

thread_local! {
    /// 服务进程内共用一份（LSP 是**单线程主循环** ⇒ thread_local 即可）。
    /// 这样三个入口函数保持 `&str → 结果` 的签名，**调用点零改动**，也不会污染各模块的接口。
    static 全局缓存: RefCell<源码缓存> = RefCell::new(源码缓存::新建(默认上限));
}

/// 带缓存的词法分析。`文件路径` 参与缓存键（词条里内嵌该路径）。
pub fn 词法分析(文件路径: &str, 源码: &str) -> Rc<Vec<词条>> {
    全局缓存.with(|c| c.borrow_mut().取词条(文件路径, 源码))
}

/// 带缓存的语法分析。`文件路径` 参与缓存键（`源码位置` 里内嵌该路径）。
pub fn 解析(文件路径: &str, 源码: &str) -> Rc<程序> {
    全局缓存.with(|c| c.borrow_mut().取程序(文件路径, 源码))
}

/// (命中, 未命中) —— 供诊断/单测观察缓存是否真的生效
pub fn 统计() -> (u64, u64) {
    全局缓存.with(|c| c.borrow().统计())
}

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 顶层定义个数 —— 用来判断"拿到的是不是新内容"（无需依赖其它模块）
    fn 定义数(程序: &程序) -> usize {
        程序.顶层定义列表.len()
    }

    #[test]
    fn 同内容只解析一次() {
        let mut 缓存 = 源码缓存::新建(8);
        let 源码 = "打招呼() 文本:\n    返回 \"你好\"\n结束\n";
        let a = 缓存.取程序("<测试>", 源码);
        let b = 缓存.取程序("<测试>", 源码);
        assert_eq!(定义数(&a), 1);
        assert!(Rc::ptr_eq(&a, &b), "同内容同路径必须复用同一份 AST");
        assert_eq!(缓存.统计(), (1, 1), "第二次应命中");
    }

    #[test]
    fn 内容变了绝不返回陈旧结果() {
        let mut 缓存 = 源码缓存::新建(8);
        let 一 = "甲() 整数:\n    返回 1\n结束\n";
        let 二 = "甲() 整数:\n    返回 1\n结束\n乙() 整数:\n    返回 2\n结束\n";
        assert_eq!(定义数(&缓存.取程序("<测试>", 一)), 1);
        assert_eq!(定义数(&缓存.取程序("<测试>", 二)), 2, "内容变了必须是新结果");
        assert_eq!(缓存.统计(), (0, 2), "两次都不该命中");
    }

    #[test]
    fn 同内容不同路径各自独立() {
        let mut 缓存 = 源码缓存::新建(8);
        let 源码 = "甲() 整数:\n    返回 1\n结束\n";
        let a = 缓存.取程序("a.智", 源码);
        let b = 缓存.取程序("b.智", 源码);
        assert!(!Rc::ptr_eq(&a, &b), "路径参与键 ⇒ 两份 AST 不同（位置里内嵌路径）");
        match &a.顶层定义列表[0] {
            frontend::语法分析::顶层定义::函数定义(f) => {
                assert_eq!(f.位置.文件路径, "a.智", "AST 里的文件路径必须是构建它时的那个");
            }
            _ => panic!("夹具应是函数定义"),
        }
    }

    #[test]
    fn 超出上限按插入顺序淘汰() {
        let mut 缓存 = 源码缓存::新建(2);
        let 源 = |n: usize| format!("甲{}() 整数:\n    返回 {}\n结束\n", n, n);
        let a = 源(1);
        let b = 源(2);
        let c = 源(3);
        let _ = 缓存.取程序("<测试>", &a);
        let _ = 缓存.取程序("<测试>", &b);
        let _ = 缓存.取程序("<测试>", &c); // 淘汰 a
        assert_eq!(缓存.统计(), (0, 3));
        let _ = 缓存.取程序("<测试>", &b); // 仍应在
        assert_eq!(缓存.统计(), (1, 3), "b 应命中");
        let _ = 缓存.取程序("<测试>", &a); // 已被淘汰 ⇒ 重新解析
        assert_eq!(缓存.统计(), (1, 4), "a 应已淘汰");
    }

    #[test]
    fn 只要词条时不必付解析成本() {
        let mut 缓存 = 源码缓存::新建(4);
        let 源码 = "甲() 整数:\n    返回 1\n结束\n";
        let 词条 = 缓存.取词条("<测试>", 源码);
        assert!(!词条.is_empty());
        // 仅取过词条 ⇒ AST 未构建；此时取程序应"就地补建"且**不算未命中**（词法没白做）
        let 程序 = 缓存.取程序("<测试>", 源码);
        assert_eq!(定义数(&程序), 1);
        assert_eq!(缓存.统计(), (1, 1), "词条命中 + 就地补建语法树");
    }
}
