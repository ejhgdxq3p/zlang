/// 项目内的 `.智` 源文件列表（供项目级扫描）。
///
/// ⚠ 只走**已解析出的搜索路径根**，并跳过三类：
///   · **标准库根**（`源码/标准库` / `<安装>/版本X/标准库`）—— 与用户项目无关且体积大；
///   · **非绝对路径的根**（如相对 `库`）—— 会依赖服务进程 cwd，行为不可预测；
///   · 产物/依赖目录（`产出`/`构建`/`target`/`node_modules`/`临时测试` 等）与隐藏目录。
/// ⚠ 本函数**不解析**文件内容，只列路径 —— 调用方先做**词法预筛**，再决定要不要解析。
pub(crate) fn 项目源文件(文档目录: &Path) -> Vec<PathBuf> {
    let mut 出: Vec<PathBuf> = Vec::new();
    for 根 in 搜索路径(文档目录) {
        if !根.is_absolute() || 根.to_string_lossy().contains("标准库") || !根.is_dir() {
            continue;
        }
        收集智文件(&根, 0, &mut 出);
    }
    出.sort();
    出.dedup();
    出
}

fn 收集智文件(目录: &Path, 深度: usize, 出: &mut Vec<PathBuf>) {
    if 深度 > 8 || 出.len() > 4000 {
        return; // 深度/数量上限：避免在异常目录结构上跑飞
    }
    let Ok(条目) = std::fs::read_dir(目录) else { return };
    for 项 in 条目.flatten() {
        let 路径 = 项.path();
        let Some(名) = 路径.file_name().map(|s| s.to_string_lossy().to_string()) else {
            continue;
        };
        if 名.starts_with('.') || 应跳过目录(&名) {
            continue;
        }
        if 路径.is_dir() {
            收集智文件(&路径, 深度 + 1, 出);
        } else if 名.ends_with(".智") {
            出.push(路径);
        }
    }
}

/// 这些目录名一律不进（产物 / 依赖 / 版本控制 / 非项目源码）
fn 应跳过目录(名: &str) -> bool {
    matches!(
        名,
        "产出"
            | "构建"
            | "target"
            | "node_modules"
            | "库中间文件"
            | "字节码文件"
            | "编译文件"
            | "执行文件"
            | "日志"
            | "临时测试"
    )
}

/// 某文件对"目标符号"的**可见性**：它能以哪些形态引用这个符号。
pub(crate) struct 可见性 {
    /// 可以写成 `基础名.目标名` 的基础名（模块路径末段，或别名）
    pub 基础名: Vec<String>,
    /// 该文件含 `展开` 导入 ⇒ 可以**裸名**引用
    pub 可用裸名: bool,
}

/// 判断 `文件` 能否"看到"目标符号，并给出可见形态。
///
/// ★ 为什么必须有这一步：不判可见性就是"**同名即算引用**"，会把毫不相干的模块里的
///   同名函数/字段全算进来 —— 这是"查找引用"最常见的假结果来源。
/// 判定口径与编译器一致：加载**该文件自己的导入**，问加载器 `提取公开符号` 里有没有
/// 同名公开符号、且它的**定义位置就在目标文件**（聚合导入的再导出由此自动覆盖）。
/// 返回 `None` = 该文件看不到这个符号 ⇒ 里面的同名词条**不是**对它的引用。
pub(crate) fn 文件可见性(
    文本: &str,
    文件: &Path,
    加载器: &mut 模块加载器,
    目标文件: &Path,
    目标名: &str,
) -> Option<可见性> {
    let 目录 = 文件.parent()?.to_path_buf();
    let mut 导入列表 = 解析导入列表(文本, 文件)?;
    if 导入列表.is_empty() {
        return None;
    }
    // ⚠ 复用**同一个**加载器实例（`已加载缓存` 跨文件共享）；否则每扫一个文件都要重解析全部依赖
    let _ = 加载器.加载依赖模块(&mut 导入列表, Some(&目录), &mut 解析回调, &mut HashSet::new());

    let mut 基础名: Vec<String> = Vec::new();
    let mut 可用裸名 = false;
    for 导入 in 导入列表.iter() {
        let 键 = 模块键(导入);
        let Ok(符号列表) = 加载器.提取公开符号(&键, &键) else { continue };
        let 命中 = 符号列表.iter().any(|(s, _)| {
            s.是否公开
                && s.名称 == 目标名
                && 指向同一文件(&s.定义位置.文件路径, 目标文件, &加载器.加载路径列表)
        });
        if !命中 {
            continue;
        }
        if 导入.是否展开 {
            可用裸名 = true;
        } else if let Some(别名) = &导入.别名 {
            基础名.push(别名.clone());
        } else if let Some(末段) = 导入.模块路径.last() {
            基础名.push(末段.clone());
        }
    }
    if 基础名.is_empty() && !可用裸名 {
        return None;
    }
    Some(可见性 { 基础名, 可用裸名 })
}

/// `源码位置.文件路径`（可能是**相对某搜索根**的路径）是否指向 `目标` 文件。
fn 指向同一文件(路径文本: &str, 目标: &Path, 搜索路径: &[PathBuf]) -> bool {
    let 目标规范 = std::fs::canonicalize(目标).unwrap_or_else(|_| 目标.to_path_buf());
    if let Some(p) = 绝对化(路径文本, 搜索路径) {
        return p == 目标规范;
    }
    // 拼不出来时退化为"文件名相同"（宁可宽松，也不要漏掉真实引用）
    Path::new(路径文本)
        .file_name()
        .map(|n| 目标规范.file_name() == Some(n))
        .unwrap_or(false)
}

// ============================================================
// 光标处的点号链（`基础.成员.成员`）
// ============================================================
/// 光标所在的点号链。返回 `None` = 光标不在标识符链上（或看起来是数字字面量 `3.14`）。
struct 链 {
    段: Vec<String>,
}

fn 取点号链(索引: &行索引, 行0: usize, 光标字符: usize) -> Option<链> {
    let 行 = 索引.行字符(行0)?;
    if 行.is_empty() {
        return None;
    }
    let 是词字符 = |c: char| c.is_alphanumeric() || c == '_';

    // VS Code 常在"词尾"触发请求 ⇒ 允许向左退一格
    let mut 光标 = 光标字符.min(行.len().saturating_sub(1));
    if !是词字符(行[光标]) {
        if 光标 == 0 || !是词字符(行[光标 - 1]) {
            return None;
        }
        光标 -= 1;
    }

    let mut 起 = 光标;
    while 起 > 0 && (是词字符(行[起 - 1]) || 行[起 - 1] == '.') {
        起 -= 1;
    }
    let mut 止 = 光标 + 1;
    while 止 < 行.len() && (是词字符(行[止]) || 行[止] == '.') {
        止 += 1;
    }
    // 去掉链首尾多余的 `.`（如 `返回 甲.字段.` 的行尾点号）
    while 起 < 止 && 行[起] == '.' {
        起 += 1;
    }
    while 止 > 起 && 行[止 - 1] == '.' {
        止 -= 1;
    }
    if 起 >= 止 {
        return None;
    }

    let 段: Vec<String> = 行[起..止]
        .iter()
        .collect::<String>()
        .split('.')
        .map(|s| s.to_string())
        .collect();
    // ⚠ 数字字面量（`3.14`）不是点号链：任一段为空或全为数字 ⇒ 放弃（否则会去查一个叫 "3" 的模块）
    if 段
        .iter()
        .any(|s| s.is_empty() || s.chars().all(|c| c.is_ascii_digit()))
    {
        return None;
    }
    Some(链 { 段 })
}
