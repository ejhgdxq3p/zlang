// 文件: 编辑器服务/src/跨文件跳转.rs
// 职责: 第一阶段·**跨文件**定义跳转（`导入` 的成员下钻）—— 复用**编译器自身的模块加载器**
//
// ★ 本文件的核心主张：**一条解析规则都不自己写**。
//   `frontend::模块加载器`（编译器真实使用的那个）已经实现了规范 §2.9 的全部语义：
//     · 模块搜索路径  → `pm::依赖解析::构建模块解析方案`（项目根 / 源码根 / 标准库 / 已安装库）
//     · 相对导入 `./` `../` → `解析相对导入`（基于导入语句所在文件目录）
//     · `聚合导入` 三种对外名形态（默认 / 展开 / 别名）→ `聚合对外名`
//     · **递归聚合**（钻石依赖去重、私有绝不重导出）→ `提取公开符号_内`
//   ⇒ 跳转只要「拿光标处的点号链 → 问加载器要对外名 → 取 `符号.定义位置`」即可。
//   若在此另写一套路径/聚合规则，会与编译器**立刻漂移**（编辑器跳得对、编译报错，或反之）。
//
// 覆盖（规范 §2.7 普通导入 / §2.9 聚合导入）：
//   ① `导入 核心库/数学` + `数学.计算面积`          → 跳 `核心库/数学.智`（普通导入，命名空间 = **末段**）
//   ② `导入 数学 别名 数` + `数.计算面积`            → 别名形态
//   ③ `导入 ./工具` / `导入 ../上级/模块`            → 相对导入（按**导入语句所在目录**解析）
//   ④ `导入 数学门面` + `数学门面.几何.计算周长`     → **聚合子命名空间**（聚合导入 别名 几何）
//   ⑤ `导入 数学门面` + `数学门面.计算面积`          → **聚合展开**（聚合导入 代数 展开）
//   ⑥ `导入 数学 展开` + 裸名 `计算面积`             → 展开的裸名回退
//
// 本阶段**仍不覆盖**（返回空而不猜）：
//   实例.成员（需类型推断）、`自身.成员`、接口→实现、运算符重载、**内置标准库**（`数学` 等）
//   —— 内置标准库成员由 `标准库元数据` 预注册、**没有 .智 文件位置** ⇒ 无从跳转（非本实现缺陷）。

use crate::位置映射::行索引;
use frontend::模块加载器::模块加载器;
use frontend::语法分析::{导入声明, 程序};
use lsp_types::{Location, Position, Range, Url};
use std::collections::HashSet;
use std::path::{Path, PathBuf};

/// 跳转入口。返回空 = **本阶段不提供跨文件跳转**（不是错误）。
pub fn 查找定义(
    源码: &str,
    文档URI: &Url,
    文件路径: Option<&Path>,
    位置: Position,
) -> Vec<Location> {
    解析引用(源码, 文档URI, 文件路径, 位置)
        .into_iter()
        // ⚠ 走 `位置映射::文件URI`（盘符规范成小写）—— 与编辑器发出的文档 URI 同形，
        //   否则"跳转目标是否就是本文档"这类 URI 等值判断会因大小写差异失效
        .filter_map(|(文件, _, 范围)| {
            crate::位置映射::文件URI(&文件).map(|uri| Location { uri, range: 范围 })
        })
        .collect()
}

/// 与 `查找定义` **同源**，但返回明细（目标文件 / 成员名 / 范围）。
/// 供 `悬停` 使用：悬停必须先知道"命中了哪个文件的哪个成员"，才能去读那个文件的 AST 取签名。
pub(crate) fn 解析引用(
    源码: &str,
    文档URI: &Url,
    文件路径: Option<&Path>,
    位置: Position,
) -> Vec<(PathBuf, String, Range)> {
    let _ = 文档URI; // 跳转目标一律是**另一个文件**的 URI（同文件由 `定义跳转` 负责）
    let Some(文件) = 文件路径 else { return Vec::new() };
    // 廉价前置：没有 `导入` 就不可能有跨文件引用（省掉词法/语法/模块加载的全部开销）
    if !源码.contains("导入") {
        return Vec::new();
    }

    let 索引 = 行索引::新建(源码);
    let Some(光标字符) = 索引.行列到字符下标(位置.line as usize, 位置.character as usize) else {
        return Vec::new();
    };
    let Some(链) = 取点号链(&索引, 位置.line as usize, 光标字符) else {
        return Vec::new();
    };

    let 文档目录 = 文件.parent().map(|p| p.to_path_buf()).unwrap_or_else(|| PathBuf::from("."));
    let Some(mut 导入列表) = 解析导入列表(源码, 文件) else { return Vec::new() };
    if 导入列表.is_empty() {
        return Vec::new();
    }
    let mut 加载器 = 新建加载器(&文档目录);
    // 加载本文档的全部依赖（同时**回填 `解析后键`**：相对导入靠它拿规范化绝对路径）
    let _ = 加载器.加载依赖模块(&mut 导入列表, Some(&文档目录), &mut 解析回调, &mut HashSet::new());

    // ── 形态 ①②③④⑤：`基础.成员...`（基础 = 导入模块名末段 或 别名）──
    if 链.段.len() >= 2 {
        let 基础 = 链.段[0].clone();
        if let Some(导入) = 导入列表.iter().find(|i| 命中基础(i, &基础)) {
            let 查询名 = 链.段[1..].join(".");
            let 目标键 = 模块键(导入);
            if let Ok(符号列表) = 加载器.提取公开符号(&目标键, &目标键) {
                if let Some((符号, _)) = 符号列表
                    .iter()
                    .find(|(s, _)| s.是否公开 && s.名称 == 查询名)
                {
                    return 定位明细(&符号.定义位置, &查询名, &加载器.加载路径列表)
                        .into_iter()
                        .collect();
                }
            }
            return Vec::new();
        }
    }

    // ── 形态 ⑥：裸名回退（**仅限 `展开` 导入**；否则编译期也不允许裸名访问，跳了就是误导）──
    if 链.段.len() == 1 {
        let 名 = 链.段[0].clone();
        for 导入 in 导入列表.iter().filter(|i| i.是否展开) {
            let 目标键 = 模块键(导入);
            if let Ok(符号列表) = 加载器.提取公开符号(&目标键, &目标键) {
                if let Some((符号, _)) = 符号列表
                    .iter()
                    .find(|(s, _)| s.是否公开 && s.名称 == 名)
                {
                    if let Some(命中) = 定位明细(&符号.定义位置, &名, &加载器.加载路径列表) {
                        return vec![命中];
                    }
                }
            }
        }
    }

    Vec::new()
}

/// 本文档**直接与间接导入**到的全部模块文件（用于"成员所属类型定义在别的模块里"的解析）。
///
/// ★ 为什么要走加载器而不是自己拼路径：模块可能来自 项目根/源码根/标准库/已安装库 四类搜索根，
///   还可能经过相对导入规范化、聚合再导出 —— 自己拼必然漏。加载器加载完 `已加载缓存` 里就是要的全集。
/// ⚠ `模块数据.文件路径` 可能是相对某个搜索根的路径 ⇒ 先按原样试，再逐个搜索根拼（与 `绝对化` 同口径）。
pub(crate) fn 已加载模块文件(源码: &str, 文件: &Path) -> Vec<PathBuf> {
    let 文档目录 = 文件
        .parent()
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|| PathBuf::from("."));
    let Some(mut 导入列表) = 解析导入列表(源码, 文件) else {
        return Vec::new();
    };
    if 导入列表.is_empty() {
        return Vec::new();
    }
    let mut 加载器 = 新建加载器(&文档目录);
    let _ = 加载器.加载依赖模块(
        &mut 导入列表,
        Some(&文档目录),
        &mut 解析回调,
        &mut HashSet::new(),
    );
    let mut 出: Vec<PathBuf> = Vec::new();
    for 数据 in 加载器.已加载缓存.values() {
        let 原样 = Path::new(&数据.文件路径);
        let 命中 = if 原样.is_file() {
            std::fs::canonicalize(原样).ok()
        } else {
            绝对化(&数据.文件路径, &加载器.加载路径列表)
        };
        if let Some(p) = 命中 {
            if !出.contains(&p) {
                出.push(p);
            }
        }
    }
    出
}

/// 需求：模块加载器要一个「源码 → 程序」回调用以读子模块文件。
/// ⚠ **不要求零诊断**：被导入的模块可能本身就有错（编辑器里正在编辑），
///   只要解析出了顶层定义与导入列表，跳转就仍可用（比"一处报错全链路失效"更贴合编辑器）。
fn 解析回调(文本: &str, 路径: &Path) -> Result<程序, String> {
    // 走内容缓存：项目扫描会对同一批模块文件反复解析（引用/悬停/跳转各来一遍）
    let 路径文本 = 路径.to_string_lossy().to_string();
    let 词条列表 = crate::缓存::词法分析(&路径文本, 文本);
    if 词条列表.is_empty() {
        return Err("源文件为空".to_string());
    }
    // ⚠ 返回 `Rc<程序>` 的克隆（浅拷贝）；加载器把它整份存进 `已加载缓存`
    Ok((*crate::缓存::解析(&路径文本, 文本)).clone())
}

/// 用**真解析器**取本文档的导入声明（与编译器同源；不自己扫字面量）。
/// 允许带语法错误：`解析程序` 有错误恢复，导入列表通常已可用。
fn 解析导入列表(源码: &str, 文件: &Path) -> Option<Vec<导入声明>> {
    let 路径文本 = 文件.to_string_lossy().to_string();
    let 词条列表 = crate::缓存::词法分析(&路径文本, 源码);
    if 词条列表.is_empty() {
        return None;
    }
    Some(crate::缓存::解析(&路径文本, 源码).导入列表.clone())
}

/// 模块搜索路径 —— **完全交给 `pm::依赖解析`**（与 `模块加载器::默认加载路径` 同源），
/// 但基准是**文档所在目录**（不是服务进程的 cwd：LSP 服务由编辑器拉起，cwd 不确定）。
pub(crate) fn 搜索路径(文档目录: &Path) -> Vec<PathBuf> {
    if let Some(项目根) = pm::依赖解析::检测项目根(文档目录) {
        if let Ok(方案) = pm::依赖解析::构建模块解析方案(&项目根, false) {
            return 方案.搜索路径列表();
        }
    }
    // 无项目（单文件模式）：与 `模块加载器::默认加载路径` 的回退口径一致
    let mut 列表 = vec![
        pm::目录::标准库根(false),
        pm::目录::标准库源码根(),
        文档目录.to_path_buf(),
    ];
    if let Ok(当前) = std::env::current_dir() {
        列表.push(当前);
    }
    列表.push(PathBuf::from("库"));
    列表
}

/// 新建模块加载器（**带依赖解析方案**）：规范 §2.7.5 三层分派要求第三方库
/// `导入 库名/模块路径` 经「库名（`项目.配置` 代号）⇒ 该库源码根」定向解析，
/// 故 LSP 侧也必须装载方案，否则库模块解析退化（与 `智语言` 编译/解释侧同源）。
pub(crate) fn 新建加载器(文档目录: &Path) -> 模块加载器 {
    if let Some(项目根) = pm::依赖解析::检测项目根(文档目录) {
        if let Ok(方案) = pm::依赖解析::构建模块解析方案(&项目根, false) {
            let 列表 = 搜索路径(文档目录);
            return 模块加载器::新建_带方案(方案, 列表);
        }
    }
    模块加载器::新建(搜索路径(文档目录))
}

/// 基础名是否命中该导入声明。
/// 规范 §2.7 / §2.9：**命名空间名 = 模块路径的末段**（`导入 核心库/数学` → 用 `数学.成员`
/// 引用；聚合导入同理 `聚合导入 数学基础` → `数学.数学基础.成员`）；写了别名则别名生效、
/// 原名失效（展开与别名互斥，由语法层保证）。
fn 命中基础(导入: &导入声明, 基础: &str) -> bool {
    if let Some(别名) = &导入.别名 {
        return 别名 == 基础;
    }
    if 导入.是否展开 {
        return false; // 展开后模块名与别名均失效，只剩裸名
    }
    导入.模块路径.last().map(|s| s.as_str()) == Some(基础)
}

/// 加载器内部使用的模块键：相对导入为**规范化绝对路径**（由加载器回填 `解析后键`），
/// 其余为 `模块路径` 以 `.` 连接（与 `模块加载器::递归加载模块` 的键口径一致）。
fn 模块键(导入: &导入声明) -> String {
    if 导入.是否相对 {
        导入
            .解析后键
            .clone()
            .unwrap_or_else(|| 导入.模块路径.join("."))
    } else {
        导入.模块路径.join(".")
    }
}

/// 由「前端 `源码位置`」解析出**目标文件 + 成员名 + 范围**
/// （**读目标文件另建行索引** —— 列宽必须按目标文件算，不能用当前文档的索引）。
fn 定位明细(
    定义位置: &frontend::公共数据结构::源码位置,
    成员名: &str,
    搜索路径: &[PathBuf],
) -> Option<(PathBuf, String, Range)> {
    // 合成符号（标准库聚合占位）行列均为 0 ⇒ **没有真实位置**。返回 None，不猜。
    if 定义位置.行号 == 0 || 定义位置.列号 == 0 {
        return None;
    }
    if 定义位置.文件路径.is_empty() {
        return None;
    }
    let 绝对路径 = 绝对化(&定义位置.文件路径, 搜索路径)?;
    let 目标源码 = std::fs::read_to_string(&绝对路径).ok()?;
    let 索引 = 行索引::新建(&目标源码);
    // 成员名可能是聚合对外名（`几何.计算周长`）⇒ 真正被声明的是**末段**
    let 末段 = 成员名.rsplit('.').next().unwrap_or(成员名);
    let 范围 = 索引.前端范围(定义位置.行号, 定义位置.列号, 末段.chars().count())?;
    Some((绝对路径, 末段.to_string(), 范围))
}

/// 把 `源码位置.文件路径` 变成可读的绝对路径。
/// ⚠ 该字段可能是**相对于搜索路径根**的路径（加载器按 `搜索路径.join(模块名.智)` 命中），
///   故先试原样，再逐个搜索根拼一次。
pub(crate) fn 绝对化(路径文本: &str, 搜索路径: &[PathBuf]) -> Option<PathBuf> {
    let 原样 = Path::new(路径文本);
    if 原样.is_file() {
        return std::fs::canonicalize(原样).ok();
    }
    for 根 in 搜索路径 {
        let 候选 = 根.join(路径文本);
        if 候选.is_file() {
            return std::fs::canonicalize(&候选).ok();
        }
    }
    None
}

