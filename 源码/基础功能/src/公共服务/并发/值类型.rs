// 文件: 并发运行时/src/值类型.rs
// 职责: 定义完全自包含的运行时值表示 `拥有值` 与映射键 `键值`。
//   - `拥有值` 不引用任何外部堆，可安全跨线程发送（Send）。
//   - 解释器/编译器在边界处将自身的 `值` 与 `拥有值` 互相转换，
//     从而让本 crate 与具体值布局解耦，解释模式与编译模式共用同一套并发能力。
//   - 本文件刻意不依赖解释器的 `值` 类型，保持并发运行时自包含。

/// 映射键（与解释器侧 `键值` 对齐）
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum 键值 {
    整数(i64),
    文本(String),
    逻辑(bool),
    /// 2026-10-12：与 `堆键` 同步（空值独立成键）
    空值,
    /// 2026-10-12：与 `堆键` 同步（存归一小数的位模式）
    小数(u64),
    /// 2026-10-12：与 `堆键` 同步（结构体复合键：类型索引 + 字段键序列）
    结构体键 { 类型索引: usize, 字段键: Vec<键值> },
    /// 2026-10-12：与 `堆键` 同步（枚举复合键：成员标签 + 数据键序列）
    枚举键 { 标签: i64, 数据键: Vec<键值> },
}

/// 完全自包含的运行时值。
/// 所有嵌套数据都被内联拥有（不再持有外部堆引用），因此可安全跨线程传递。
#[derive(Debug, Clone, PartialEq)]
pub enum 拥有值 {
    // ── 基本类型（内联）──
    整数(i64),
    小数(f64),
    逻辑(bool),
    空值,

    // ── 复合类型（自包含）──
    文本(String),
    数组(Vec<拥有值>),
    映射(Vec<(键值, 拥有值)>),
    结构体(usize, Vec<拥有值>),
    闭包(usize, Vec<拥有值>),

    // ── 并发资源句柄（通道/终止器/任务，自包含 id，可跨线程 Send）──
    并发句柄(u64),

    // ── 异常（任务执行失败后传递）──
    异常(String, String),
}

impl 拥有值 {
    pub fn 类型名称(&self) -> &'static str {
        match self {
            拥有值::整数(_) => "整数",
            拥有值::小数(_) => "小数",
            拥有值::逻辑(_) => "逻辑",
            拥有值::空值 => "空值",
            拥有值::文本(_) => "文本",
            拥有值::数组(_) => "数组",
            拥有值::映射(_) => "映射",
            拥有值::结构体(..) => "结构体",
            拥有值::闭包(..) => "闭包",
            拥有值::并发句柄(_) => "并发句柄",
            拥有值::异常(..) => "异常",
        }
    }

    pub fn 是否为基本类型(&self) -> bool {
        matches!(
            self,
            拥有值::整数(_) | 拥有值::小数(_) | 拥有值::逻辑(_) | 拥有值::空值
        )
    }
}
