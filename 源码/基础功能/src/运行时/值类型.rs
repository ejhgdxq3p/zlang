/// 堆统计扫描：维护回收计数与分配阈值，并顺带清理「共享计数为 0 但尚未入空闲表」的残留槽位。
///
/// 返回本次实际释放的字节数（正常情况下为 0，因为 堆释放 已在计数归零时即时回收）。
/// 保留 `堆_执行回收` 为对外名称（C-ABI `智语言_执行回收` 稳定契约依赖它），
/// 但语义已由「标记-清除」正名为「统计扫描 + 残留清理」。
/// 堆统计（可观测性）：分配槽位数 / 存活槽位数 / 空闲表长度 / 累计回收次数。
/// 用途：① 调试与内存回归（存活槽位不应随循环次数增长）；② **双模一致性新判据**
/// —— 同一用例在解释/编译两模式下执行序列相同，本统计应逐项一致。
pub fn 堆统计() -> (usize, usize, usize, u64) {
    let 堆 = 全局堆.read().unwrap();
    let 总槽位 = 堆.槽位.len();
    let 存活 = 堆.槽位.iter().filter(|s| s.is_some()).count();
    (总槽位, 存活, 堆.空闲表.len(), 堆.回收次数)
}

pub fn 堆_执行回收() -> usize {
    let mut 堆 = 全局堆.write().unwrap();
    堆.回收次数 += 1;

    // ── 残留清理：共享计数为 0 的槽位理应已由 堆释放 回收；此处兜底，防止计数归零路径遗漏。
    //    注意：不做可达性分析（见上方语义裁定），仅按引用计数判定。
    let 清除前字节: usize = 堆.槽位.iter().flatten().map(|s| 堆数据估算大小(&s.数据)).sum();
    let 待清除: Vec<u32> = 堆.槽位.iter().enumerate()
        .filter_map(|(i, s)| match s {
            Some(槽) if 槽.共享计数 == 0 => Some(i as u32),
            _ => None,
        })
        .collect();
    for i in &待清除 {
        堆.槽位[*i as usize] = None;
        堆.空闲表.push(*i);
    }
    let 清除后字节: usize = 堆.槽位.iter().flatten().map(|s| 堆数据估算大小(&s.数据)).sum();
    let 回收字节 = 清除前字节.saturating_sub(清除后字节);
    堆.累计回收字节 = 堆.累计回收字节.saturating_add(回收字节);
    上次回收后分配字节.store(0, Ordering::Release);

    // 动态调整阈值（B1: 系数 256→512、上限 16MB→64MB 降频，见 回收阈值字节 注释）
    let 存活数 = 堆.槽位.iter().filter(|s| s.is_some()).count();
    回收阈值字节.store((存活数.max(1) * 512).clamp(128 * 1024, 64 * 1024 * 1024) as u64, Ordering::Release);

    // ⚠ 必须**先释放写锁**再调用「可达性对账 / 兜底回收」（二者自身要取写锁；RwLock 不可重入 ⇒ 否则死锁）
    drop(堆);

    // 🆕 统一回收（2026-09-22）：环境变量门控 ⇒ **默认零开销、零行为变化**
    //   `智语言_内存对账=1`     ⇒ 打印一次可达性对账（mark-only，**不回收**）
    //   `智语言_内存兜底清扫=1` ⇒ 额外回收**不可达**对象（**仅在两引擎根提供者齐备时安全**）
    static 对账启用: once_cell::sync::Lazy<bool> =
        once_cell::sync::Lazy::new(|| std::env::var("智语言_内存对账").is_ok());
    static 兜底启用: once_cell::sync::Lazy<bool> =
        once_cell::sync::Lazy::new(|| std::env::var("智语言_内存兜底清扫").is_ok());
    if *对账启用 || *兜底启用 {
        // 阈值钳制：让周期对账可被触发（**仅环境变量门控 ⇒ 产品路径零影响**）；
        // 小用例不达阈值也无妨 —— 退出时由「终局对账」（最后一个根提供者注销）兜住。
        回收阈值字节.store(64 * 1024, Ordering::Release);
        let 账 = 打印对账("周期");
        let 根齐备 = 账.本线程提供者数 > 0 && 账.全局提供者数 == 账.本线程提供者数;
        if *兜底启用 && 根齐备 {
            let 回收数 = 堆_清扫不可达();
            eprintln!("[内存对账:周期] 兜底清扫：回收不可达对象 {} 个", 回收数);
        }
    }

    回收字节
}

