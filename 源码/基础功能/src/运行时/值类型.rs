pub const 类型标志_整数: u64 = 77;
pub const 类型标志_小数: u64 = 78;

/// 跨 FFI 边界的扁平值表示。
/// sizeof = 32 字节，在 x64 上可作为寄存器对传递。
///
/// 标签布局（统一架构）:
///   0 空值        — 整数/小数/句柄/逻辑 均为 0
///   1 整数        — 整数载荷
///   2 小数        — 小数载荷（位模式对应 f64）
///   3 逻辑        — 整数!=0 为真
///   4 句柄        — 句柄载荷=全局堆 u64 索引
///   5 异常        — 整数载荷=异常类型索引（系统预设：0=除零，1=类型转换，2=数组越界，3=下标越界，4=参数无效，5=返回类型不匹配，6=断定失败，7=值缺失）
///   6 函数指针    — 整数载荷=函数索引（编译期确定的函数符号），解释器直接调用；编译器用句柄指向闭包环境
///   7 局部引用    — 整数载荷=变量槽位索引（传引用 by-ref 参数）
///   8 并发句柄    — 整数载荷=并发表中的资源索引（通道/任务/终止器）
///   9 【已退役】  — 原 GC 回收标记位，随 WS-3 内存管理正名删除，勿复用
#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct 运行时值 {
    pub 标签: u64,
    pub 整数: i64,
    pub 小数: f64,
    pub 句柄: u64,
}

/// ⚡双模式⚡ 单源真相锁：运行时值 扁平结构必须恒为 32 字节。
/// 解释器与编译器（Cranelift）共用此同一内存布局跨 C ABI 传递；
/// 任何对字段的增删（例如误加对齐填充字段）都会破坏两后端的二进制契约，
/// 编译期断言可在改动落地的瞬间拦死，而非等到字节码/机器码里悄悄错位。
const _: () = assert!(std::mem::size_of::<运行时值>() == 32);
const _: () = assert!(std::mem::align_of::<运行时值>() == 8);

impl 运行时值 {
    pub fn 空值() -> Self { 运行时值 { 标签: 标签_空值, 整数: 0, 小数: 0.0, 句柄: 0 } }
    pub fn 整数(v: i64) -> Self { 运行时值 { 标签: 标签_整数, 整数: v, 小数: 0.0, 句柄: 0 } }
    pub fn 小数(v: f64) -> Self { 运行时值 { 标签: 标签_小数, 整数: 0, 小数: v, 句柄: 0 } }
    pub fn 逻辑(v: bool) -> Self { 运行时值 { 标签: 标签_逻辑, 整数: if v { 1 } else { 0 }, 小数: 0.0, 句柄: 0 } }
    pub fn 句柄(v: u64) -> Self { 运行时值 { 标签: 标签_句柄, 整数: 0, 小数: 0.0, 句柄: v } }
    /// 🆕 统一架构: 创建函数指针值（负编码：-1 - 函数索引，避免与旧 标签_句柄+句柄=0 误判）
    pub fn 函数指针(函数索引: usize) -> Self {
        运行时值 { 标签: 标签_函数指针, 整数: -(函数索引 as i64) - 1, 小数: 0.0, 句柄: 0 }
    }
    /// 🆕 统一架构: 创建局部引用值（传引用 by-ref 参数）
    pub fn 局部引用(槽位索引: usize) -> Self {
        运行时值 { 标签: 标签_局部引用, 整数: 槽位索引 as i64, 小数: 0.0, 句柄: 0 }
    }
    /// 🆕 统一架构: 创建并发资源句柄
    /// ⚡双模式⚡ 同时写入 整数 与 句柄 两个字段：解释模式用 句柄 字段，编译模式统一值表示(标签,载荷=整数)只用 整数 槽，
    /// 两字段都填资源索引，保证跨编译/解释双模语义一致。
    pub fn 并发句柄(资源索引: u64) -> Self {
        运行时值 { 标签: 标签_并发句柄, 整数: 资源索引 as i64, 小数: 0.0, 句柄: 资源索引 }
    }
}

