pub fn 堆释放(id: u64) {
    // 🔬 **内存诊断工具（长期保留）**：仅打印**指定句柄**的释放事件与**释放前计数**。
    //   用法：`智语言_释放探针句柄=<id>`（id 取自对账「分类」行的悬垂句柄 ✓）
    //   判读：同一 id 的完整账本（本处 + `级联` + `增加` + `分配`）⇒ 一眼看出"哪一次 −1 缺少持有" ✓
    //   ⚠ **默认关闭、零开销** ✓
    if 释放探针目标() == Some(id) {
        eprintln!("[释放探针] 句柄={} 释放前计数={:?}", id, 句柄共享计数(id));
    }
    // 🔬 全量账本（`智语言_账本全部=1`）：逐事件打印 −1 ✓（须在取写锁**之前**查计数 ✓）
    if 账本全开() {
        eprintln!("[释放] 句柄={} 释放前计数={:?}", id, 句柄共享计数(id));
    }

    // 🔬 临时诊断（环境变量门控，默认零开销）：智语言_调试释放=1 时每 100000 次调用打一行，
    //    分类统计「归零回收 / 计数仍>0 / 槽位不存在」，用于定位回收未生效的成因。定位后应移除。
    let 诊断 = std::env::var("智语言_调试释放").is_ok();
    if 诊断 {
        use std::sync::atomic::{AtomicU64, Ordering};
        static 计数: AtomicU64 = AtomicU64::new(0);
        static 归零回收: AtomicU64 = AtomicU64::new(0);
        static 计数仍正: AtomicU64 = AtomicU64::new(0);
        static 槽位缺失: AtomicU64 = AtomicU64::new(0);
        let 计数前 = 全局堆.read().unwrap().槽位.get(id as usize).and_then(|s| s.as_ref()).map(|s| s.共享计数);
        match 计数前 {
            None => { 槽位缺失.fetch_add(1, Ordering::Relaxed); }
            Some(1) => { 归零回收.fetch_add(1, Ordering::Relaxed); }
            Some(_) => { 计数仍正.fetch_add(1, Ordering::Relaxed); }
        }
        let n = 计数.fetch_add(1, Ordering::Relaxed) + 1;
        if n % 100000 == 0 {
            eprintln!(
                "[调试释放] 调用 {} 次；归零回收={} 计数仍>0={} 槽位缺失={}",
                n,
                归零回收.load(Ordering::Relaxed),
                计数仍正.load(Ordering::Relaxed),
                槽位缺失.load(Ordering::Relaxed)
            );
        }
    }
    let mut 堆 = 全局堆.write().unwrap();
    // 🆕 阶段 2：**入参代际校验** —— 陈旧句柄**幂等忽略**。
    //   ⚠ 必须在此校验（而非仅在级联里掩码）：若不校验，掩码后会把"**复用后新对象**"的计数误减
    //     ⇒ **过度释放** ✗ —— 这正是 ABA 的危害方向（代际标记要挡的正是它）。
    if 解码句柄(&堆, id).is_none() { return; }
    级联处理_已持锁(&mut 堆, vec![级联工作::递减(id)]);
}

/// 锁内级联工作项（唯一回收入口 `堆释放` 与 **L3 环收集** 共用同一套级联语义）。
enum 级联工作 {
    /// 引用计数 −1；归零 ⇒ 回收槽位 + 级联子句柄。
    递减(u64),
    /// **直接回收**（不再 −1）：仅由 L3 环收集使用（环成员互相持有 ⇒ 计数永不归零，必须整组直接回收）。
    直接回收(u64),
}

/// ★单源★ **锁内级联处理（调用方必须已持全局堆写锁）**：迭代（绝不递归）执行上表工作项。
///   ⚠ 全程只做纯内存操作，不得调用任何会再次获取堆锁的函数（重入 = 死锁，见文件头铁律）。
fn 级联处理_已持锁(堆: &mut 全局堆内部, 初始: Vec<级联工作>) {
    let mut 队列 = 初始;
    while let Some(项) = 队列.pop() {
        match 项 {
            级联工作::递减(当前) => {
                // 🔬 临时探针（2026-09-24，**S 副本侧取证**）：级联递减路径**绕过 `堆释放`** ✗
                //   ⇒ 必须在此同样挂钩，否则释放历史不完整（用法同 `智语言_释放探针句柄` ✓）
                if 释放探针目标() == Some(当前) {
                    let 前 = 堆.槽位.get(句柄索引(当前)).and_then(|s| s.as_ref()).map(|s| s.共享计数);
                    eprintln!("[释放探针·级联] 句柄={} 释放前计数={:?}", 当前, 前);
                }
                // 🔬 全量账本：级联 −1 事件（**该路径绕过 `堆释放`** ⇒ 必须单独记 ✓）
                if 账本全开() {
                    let 前 = 堆.槽位.get(句柄索引(当前)).and_then(|s| s.as_ref()).map(|s| s.共享计数);
                    eprintln!("[释放·级联] 句柄={} 释放前计数={:?}", 当前, 前);
                }
                // 🆕 阶段 2：句柄 → 索引需**掩码取低 32 位**（代际在解码入口已校验；
                //   此处"当前"来自 `收集子句柄`（活对象的子句柄）⇒ 索引有效）
                let 索引 = 句柄索引(当前);
                let 是否归零 = match 堆.槽位.get_mut(索引).and_then(|s| s.as_mut()) {
                    Some(槽位) => {
                        槽位.共享计数 = 槽位.共享计数.saturating_sub(1);
                        槽位.共享计数 == 0
                    }
                    // 悬垂/重复释放：幂等忽略（不 panic；悬垂守卫见 代际标记 后续项）
                    None => continue,
                };
                if !是否归零 { continue; }
                队列.push(级联工作::直接回收(当前));
            }
            级联工作::直接回收(当前) => {
                // 🆕 阶段 2：掩码取索引（代际在解码入口已校验）；回收时**保留代际表**（ABA 防线）
                let 索引 = 句柄索引(当前);
                let 子句柄列表 = match 堆.槽位.get(索引).and_then(|s| s.as_ref()) {
                    Some(槽位) => 收集子句柄(&槽位.数据),
                    None => continue, // 已被回收（重复项）：幂等忽略
                };
                堆.槽位[索引] = None;
                堆.空闲表.push(索引 as u32);
                堆.回收次数 += 1;
                for 子 in 子句柄列表 {
                    队列.push(级联工作::递减(子));
                }
            }
        }
    }
}

// ════════════════════════════════════════════════════════════════════════════
//  L3 层三：共享集环收集（trial deletion，**写锁内单遍、无 STW**）
//
//  依据（《内存管理技术方案》§11.0 / §11.2）：
//    · I2：一切 ±1 / 分配 / 释放都在 `全局堆(RwLock)` 内 ⇒ 本函数持写锁期间**计数快照一致**
//      ⇒ 不需要 STW、不需要安全点协议（区别于主流 GC）。
//    · 判据（与主流 trial deletion 同构）：`共享计数 > 内部引用数 ⇒ 有外部引用 ⇒ 可达`；
//      `相等 ⇒ 仅被集合内部引用 ⇒ 环或垃圾`。
//
//  ⚠ **候选集必须是「全部存活对象」**（实测反例）：纯 2 环 A↔B 在扫描时刻**各自计数 = 1**
//     ⇒ 若按"共享计数 > 1"筛选候选集，会**整组漏掉纯环**（环成员互相持有，谁的计数都不 >1）。
//     "计数 > 1"只能作**规模提示**，**绝不能**当筛选条件（"非拥有边 bit"同理，只能作保守超集优化）。
//
//  ⚠ 根集**无需枚举**：根（帧槽/全局表/操作数栈/任务快照）持有的是**计数引用** ⇒ 其目标必然满足
//     `共享计数 > 内部引用数` ⇒ 自动被判定为外部可达并传播（这正是 trial deletion 不需要根的原因，
//     也使其**天然适用于多线程**：不依赖"根提供者齐备"）。
//
//  🆕 阶段 5（2026-09-23）**为什么"预算"不落成"跨轮分步"**（本阶段最重要的反思结论）：
//    ① **部分扫描不安全**：判定 `计数 > 内部引用数 ⇒ 有外部引用` **依赖全局视角**。若只扫描**子集**，
//       则"外部引用来自扫描集之外"的对象会被**误判为"仅被内部引用"⇒ 误回收** ✗（内存安全级错误）。
//       业界增量版（Bacon–Rajan）能分步，是因为配了**写屏障/增量更新协议**；本项目明确**不引屏障**
//       （方案 §12.2-4：屏障成本会抵消"值语义 + Erlang 式隔离"的结构优势）。
//    ② **超预算整轮跳过会牺牲活性**：超大堆每轮都跳过 ⇒ 环**永不回收** ⇒ 无界增长 ✗
//       ⇒ 故仅提供**显式**护栏（默认 0 = 不限制），权衡由使用者明示承担。
//    ⇒ 本阶段的"预算"落点 = **单轮成本工程化**（去 `HashMap` ⇒ 槽→子表下标直取；扫描缓冲**跨轮复用**；
//      规模/耗时**可观测**）⇒ **判定与完整性一字不改 ⇒ 结果相同** ✓，而锁持时间显著下降 ✓
// ════════════════════════════════════════════════════════════════════════════

/// 🆕 阶段 5（2026-09-23）**规模护栏（显式；默认 0 = 不限制）**。
///
/// ⚠ 为什么**默认不限制**：见本节顶部"为什么不是跨轮分步"——超预算即"跳过整轮"会**牺牲活性**
///   （超大堆每轮都跳过 ⇒ 环永不回收）⇒ 默认**不埋隐藏陷阱**；使用者显式设置时，费用/活性
///   权衡由其**明示承担**（日志会打印警告）。
fn 环收集预算() -> usize {
    static 缓存: std::sync::OnceLock<usize> = std::sync::OnceLock::new();
    *缓存.get_or_init(|| {
        std::env::var("智语言_环收集预算").ok()
            .and_then(|v| v.parse::<usize>().ok())
            .unwrap_or(0)
    })
}

/// L3 扫描缓冲（**跨轮复用** ⇒ 消除每轮 4~5 次大 `Vec`/`HashMap` 分配，直接缩短锁持时间）。
/// ⚠ 仅在**持有堆写锁**时使用（`环收集` 内无重入）⇒ `take` 取出、用完放回，绝不跨调用持借用 ✓
#[derive(Default)]
struct 环收集暂存 {
    存活: Vec<bool>,
    内部引用: Vec<usize>,
    标记: Vec<bool>,
    栈: Vec<u32>,
    子表: Vec<(u32, Vec<u64>)>,
    /// **槽索引 → 子表下标**（`u32::MAX` = 非存活）。取代原先"`子表` → `HashMap`"的构建与查找。
    子表下标: Vec<u32>,
}

thread_local! {
    static 环收集缓冲: std::cell::RefCell<环收集暂存> = std::cell::RefCell::new(环收集暂存::default());
}

/// L3 环收集：回收"仅被集合内部引用"的环/垃圾（返回回收对象数）。
/// 复杂度 O(存活对象 + 存活边)；单遍完成（持写锁期间完成 ⇒ 无并发变更）。
///
/// 🔁 阶段 5（2026-09-23）**单轮成本工程化**（判定与完整性**一字不改** ⇒ 结果相同）：
///   ① 去掉 `HashMap<u32, Vec<u64>>` 邻接构建与查找 ⇒ 改为 **`槽→子表下标` 直取**（O(1) 且无哈希）；
///   ② 全部扫描缓冲 **跨轮复用**（`环收集暂存`）⇒ 消除每轮 4~5 次大分配；
///   ③ 新增**耗时/规模可观测**（`智语言_环收集日志`）⇒ 使"长锁延迟"可实测；
///   ④ 新增**显式**规模护栏 `智语言_环收集预算`（默认 0 = 不限制）。
pub fn 环收集() -> usize {
    let 起点 = std::time::Instant::now();
    let mut 堆 = 全局堆.write().unwrap();
    let 槽数 = 堆.槽位.len();
    if 槽数 == 0 { return 0; }
    // ④ 显式规模护栏（默认 0 = 不限制 ⇒ 不埋活性陷阱）
    let 预算 = 环收集预算();
    if 预算 > 0 && 槽数 > 预算 {
        if std::env::var("智语言_环收集日志").is_ok() {
            eprintln!("[L3] ⚠ 跳过本轮：槽数 {} 超显式预算 {}（环可能延迟回收）", 槽数, 预算);
        }
        return 0;
    }
    // ② 取出跨轮缓冲（用完放回 ⇒ 容量复用）
    // ⚠ 必须写 `std::mem::take(&mut *borrow)`（`环收集暂存` 自身没有 `take`；若写 `.take()`
    //   会被解析为 `Iterator::take` ⇒ 编译报 "RefMut is not an iterator"（2026-09-23 实测踩到））
    let 暂存 = 环收集缓冲.with(|b| std::mem::take(&mut *b.borrow_mut()));
    let 环收集暂存 { mut 存活, mut 内部引用, mut 标记, mut 栈, mut 子表, mut 子表下标 } = 暂存;
    存活.clear(); 存活.resize(槽数, false);
    内部引用.clear(); 内部引用.resize(槽数, 0);
    标记.clear(); 标记.resize(槽数, false);
    栈.clear();
    子表.clear();
    子表下标.clear(); 子表下标.resize(槽数, u32::MAX);
    // ① 存活集 + 每个存活对象的子句柄（**含重复** ⇒ 多重边按次数计入内部引用）+ 槽→子表下标
    for 索引 in 0..槽数 {
        let Some(槽位) = 堆.槽位[索引].as_ref() else { continue };
        存活[索引] = true;
        let 子 = 收集子句柄(&槽位.数据);
        for &c in 子.iter() {
            // 🆕 阶段 2：子句柄 = `[代际32|索引32]` ⇒ **掩码取索引**（环收集只需拓扑与计数）
            let ci = 句柄索引(c);
            if ci < 槽数 { 内部引用[ci] += 1; }
        }
        子表下标[索引] = 子表.len() as u32;
        子表.push((索引 as u32, 子));
    }
    if 子表.is_empty() {
        环收集缓冲.with(|b| *b.borrow_mut() = 环收集暂存 { 存活, 内部引用, 标记, 栈, 子表, 子表下标 });
        return 0;
    }
    // ② 外部引用判定：共享计数 > 内部引用数 ⇒ 有外部引用（根 / 集合外对象）
    for i in 0..子表.len() {
        let 索引 = 子表[i].0 as usize;
        let 计数 = 堆.槽位[索引].as_ref().map(|s| s.共享计数 as usize).unwrap_or(0);
        if 计数 > 内部引用[索引] { 栈.push(索引 as u32); }
    }
    // ③ 沿存活边传播可达（标记 = 可达）。⚠ `子表`（只读）与 `标记`/`栈` 为**不同字段** ⇒
    //   可同时借用（拆字段后借用检查器允许）⇒ 无需 `HashMap`、无需克隆子列表、无需 unsafe ✓
    let 存活引用 = &存活;
    let 子表引用 = &子表;
    while let Some(当前) = 栈.pop() {
        let i = 当前 as usize;
        if 标记[i] { continue; }
        标记[i] = true;
        let 子下标 = 子表下标[i];
        if 子下标 == u32::MAX { continue; }
        for &c in 子表引用[子下标 as usize].1.iter() {
            // 🆕 阶段 2：掩码取索引（栈内保存**索引**，不再保存句柄）
            let ci = 句柄索引(c);
            if ci < 槽数 && 存活引用[ci] && !标记[ci] { 栈.push(ci as u32); }
        }
    }
    // ④ 未标记 ⇒ 仅被集合内部引用 ⇒ 环/垃圾 ⇒ 整组直接回收 + 级联
    // 🆕 2026-09-26 **失败安全终检（belt-and-suspenders）** —— 释放前独立复验「候选的**全部**引用
    //   都来自待回收集合内部」= `共享计数 == 内部引用数`。
    //   为什么必要：trial-deletion 判定（`计数 > 内部引用 ⇒ 外部源`，再沿存活边传播标记）的
    //   正确性**完全押在「共享计数 与真实引用一一对应」这一不变量**上（见文件头 §7.2 注）。
    //   一旦某处共享句柄漏 `+1`（不变量破损），外部引用被**低计** ⇒ 该对象**貌似纯内部环** ⇒ 被直接
    //   回收 ⇒ **悬垂 / 内存损坏**。本终检把"可能的静默损坏"降级为"**可观测的泄漏**"：
    //   任一候选不满足 ⇒ **整轮放弃回收**（只回收一部分会因级联 −1 波及被跳过者 ⇒ 必须整组一致）。
    //   ⚠ 正常情况恒通过（未标记 ⟺ 计数 ≤ 内部引用；又 计数 ≥ 内部引用 ⇒ 相等）⇒ **零行为变化**；
    //     它只为**不变量破损**兜底，方向永远偏保守：宁可泄漏，绝不误回收。
    let mut 候选: Vec<usize> = Vec::with_capacity(槽数);
    let mut 终检拦截 = 0usize;
    for i in 0..槽数 {
        if 存活[i] && !标记[i] {
            let 计数 = 堆.槽位[i].as_ref().map(|s| s.共享计数 as usize).unwrap_or(0);
            if 计数 != 内部引用[i] { 终检拦截 += 1; }
            候选.push(i);
        }
    }
    let 待回收: Vec<级联工作> = if 终检拦截 > 0 {
        if std::env::var("智语言_环收集日志").is_ok() {
            eprintln!(
                "[L3] ⚠ 失败安全终检：{}/{} 候选 共享计数 ≠ 内部引用 ⇒ **整轮放弃回收**（疑似漏 +1，退化为泄漏）",
                终检拦截, 候选.len()
            );
        }
        Vec::new()
    } else {
        候选.into_iter().map(|i| 级联工作::直接回收(i as u64)).collect()
    };
    let 个数 = 待回收.len();
    // 🔬 诊断（env 门控，零产品开销）：规模/耗时 + 存活·外部可达·待回收 + 采样对象（计数 vs 内部引用）
    let 存活数 = 存活.iter().filter(|x| **x).count();
    let 外部源数 = (0..槽数).filter(|&i| 存活[i] && 标记[i]).count();
    let 扫描耗时 = 起点.elapsed();
    if std::env::var("智语言_环收集日志").is_ok() {
        eprintln!(
            "[L3] 槽数={} 存活={} 外部可达={} 待回收={} 扫描耗时={}µs（阶段 5：缓冲复用 + 去哈希）",
            槽数, 存活数, 外部源数, 个数, 扫描耗时.as_micros()
        );
        let mut 打印 = 0;
        for i in 0..槽数 {
            if !存活[i] { continue; }
            if 打印 >= 8 { break; }
            let (种类, 计数) = match 堆.槽位[i].as_ref() {
                Some(槽) => {
                    let 种 = match &槽.数据 {
                        堆数据::文本(_) | 堆数据::文本_静态(_, _) => "文本",
                        堆数据::数组(_) => "数组",
                        堆数据::映射(_) => "映射",
                        堆数据::结构体 { .. } => "结构体",
                        堆数据::闭包环境 { .. } => "闭包",
                    };
                    // 计数前打印（借用只在本语句内）
                    (种, 槽.共享计数)
                }
                None => continue,
            };
            eprintln!("     · #{} 种类={} 计数={} 内部引用={} 标记={}", i, 种类, 计数, 内部引用[i], 标记[i]);
            打印 += 1;
        }
    }
    if 个数 == 0 {
        环收集缓冲.with(|b| *b.borrow_mut() = 环收集暂存 { 存活, 内部引用, 标记, 栈, 子表, 子表下标 });
        return 0;
    }
    级联处理_已持锁(&mut 堆, 待回收);
    环收集缓冲.with(|b| *b.borrow_mut() = 环收集暂存 { 存活, 内部引用, 标记, 栈, 子表, 子表下标 });
    个数
}

/// 分配次数阈值触发（预算制，见 §11.5 ④/Go 借鉴）：每分配 `阈值` 次尝试一次 L3 环收集。
/// 阈值由 env `智语言_环收集阈值` 覆盖（0 = 关闭）；默认 **2000**（产品路径默认开启 ⇒ 环不无界增长）。
static 分配计数: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

fn 环收集阈值() -> usize {
    static 缓存: std::sync::OnceLock<usize> = std::sync::OnceLock::new();
    *缓存.get_or_init(|| {
        std::env::var("智语言_环收集阈值").ok()
            .and_then(|v| v.parse::<usize>().ok())
            .unwrap_or(2000)
    })
}

/// 供 `堆分配` 调用（**必须在释放堆锁之后调用**，否则重入死锁）。
fn 环收集_按预算() {
    let 阈值 = 环收集阈值();
    if 阈值 == 0 { return; }
    let n = 分配计数.fetch_add(1, std::sync::atomic::Ordering::Relaxed) + 1;
    if n % 阈值 == 0 {
        let 回收 = 环收集();
        if 回收 > 0 && std::env::var("智语言_环收集日志").is_ok() {
            eprintln!("[L3环收集] 第 {} 次分配触发：回收环/垃圾对象 {} 个", n, 回收);
        }
    }
}

/// ★单源★ **帧级批量释放**（统一帧契约 UFC 的**释放侧**；两引擎共用同一实现）。
///   —— 见《内存管理技术方案》§5.1（同源红线）与 §9.2（工作流 B1）。
///
/// 输入：
///   · `槽基址` —— 本函数槽位内存块（每槽 16 字节：`标签: u64` 在 +0、`载荷: i64/u64` 在 +8）。
///     解释模式 = VM `局部变量表` 对应地址；编译模式 = **影子块**（内层引用型槽镜像）。
///   · `拥有型槽索引` —— **由前端静态判定**的「拥有型槽」清单（值语义复合局部 / 接口标签局部 /
///     深拷贝临时槽 / 参数转移槽 …）。它必须**随函数元数据下发**（两引擎取同一份）⇒ 两模一致。
///
/// 语义：按「拥有型槽」清单取出其中的句柄并逐个 `堆释放`（−1，归零即回收 + 级联）
///   ⇒ 与前端逐槽发射 `操作码::释放引用` **语义等价**，只是把 N 次调用折成一次循环。
///
/// ⚠ 安全边界（**不得放宽**）：
///   ① 清单**只能含「拥有型槽」**（该槽持有一份 +1 引用：创建转移 / 深拷贝 / 标签 +1 / 存储类 +1）。
///      **借用型槽不得入清单** —— 例：`文本 s = 列表[1]`（非复合类型不深拷贝 ⇒ 槽内是**容器元素的句柄**），
///      释放它 = 误回收容器仍持有的对象（2026-09 实测：曾致 `09 传值默认行为` 等 3 例失败 + 对账 9→13）。
///      ⇒ 「引用型槽」≠「拥有型槽」，**帧级释放的清单是后者**（此为 ④ 的关键设计点）。
///   ② `标签 != 标签_句柄` 一律跳过（标量 / 空值 / 函数指针 / 局部引用 / 并发句柄 / 外部值 ⇒ 不参与计数）。
///   ③ 幂等：`堆释放` 对悬垂 / 重复释放静默忽略（不 panic）。
///
/// # Safety
/// `槽基址` 须指向至少 `max(拥有型槽索引)+1` 个 `运行时值`（**32 字节/槽**）的有效内存。
pub unsafe fn 批量释放槽清单(槽基址: *const u64, 拥有型槽索引: &[usize]) {
    批量释放运行时值槽(槽基址, 拥有型槽索引)
}

// ════════════════════════════════════════════════════════════════════════════
// ⚠ **两引擎槽布局不同**（2026-09-22 取证纠正，勿合并为一套扫描）：
//   · 解释模式：`局部变量表: Vec<运行时值>` —— `运行时值` = **32 字节**
//     （`#[repr(C)]`：标签@+0 / 整数@+8 / 小数@+16 / **句柄@+24**；编译期断言 size==32）；
//   · 编译模式：影子块 —— **16 字节/槽**（标签@+0 / **句柄@+8**）。
//   ⇒ 用"通用 16 字节"扫描跨引擎复用会**读错偏移/步长 ⇒ 内存错乱**（务必勿合并）。
//   ⇒ 同源红线落在**释放语义**：两引擎最后都调用 `批量释放句柄列表`（唯一 −1 入口）。
// ════════════════════════════════════════════════════════════════════════════

/// ★单源释放★：对一批句柄逐个 `堆释放`（−1；归零即回收 + 级联）。**两引擎唯一释放入口**。
///   `堆释放` 幂等 ⇒ 批量语义"全部丢弃"与顺序无关。
pub fn 批量释放句柄列表(句柄列表: &[u64]) {
    for &句柄 in 句柄列表 { 堆释放(句柄); }
}

/// **解释模式**扫描（纯函数）：`运行时值` 数组（32 字节/槽，句柄@+24）⇒ 取「拥有型槽」的句柄。
///
/// 选取规则（与 `堆_释放引用` 同源）：`标签 == 标签_句柄` 且 `句柄 != 0`。
/// 拆为纯函数的原因：① **可确定性单测**（不触碰全局堆 ⇒ 不受 base 单测**并行执行**的计数竞争影响
///    —— 2026-09-22 实测：断言 `堆统计` 存活差值会随机失败）；② 便于"弹帧前只读预检"诊断。
///
/// # Safety
/// `槽基址` 须指向至少 `max(索引)+1` 个 `运行时值` 的有效内存。
pub unsafe fn 收集运行时值槽句柄(槽基址: *const u64, 拥有型槽索引: &[usize]) -> Vec<u64> {
    if 槽基址.is_null() || 拥有型槽索引.is_empty() { return Vec::new(); }
    let mut 结果: Vec<u64> = Vec::with_capacity(拥有型槽索引.len());
    for &槽 in 拥有型槽索引 {
        // `运行时值` = 4 个 u64（标签 / 整数 / 小数 / 句柄）⇒ 句柄在下标 `槽*4 + 3`
        let 标签 = *槽基址.add(槽 * 4);
        if 标签 != 标签_句柄 { continue; }
        let 句柄 = *槽基址.add(槽 * 4 + 3);
        if 句柄 != 0 { 结果.push(句柄); }
    }
    结果
}

/// **编译模式**扫描（纯函数）：影子块（16 字节/槽，句柄@+8）⇒ 取「拥有型槽」的句柄。
///
/// # Safety
/// `槽基址` 须指向至少 `max(索引)+1` 个 16 字节槽的有效内存。
pub unsafe fn 收集影子槽句柄(槽基址: *const u64, 拥有型槽索引: &[usize]) -> Vec<u64> {
    if 槽基址.is_null() || 拥有型槽索引.is_empty() { return Vec::new(); }
    let mut 结果: Vec<u64> = Vec::with_capacity(拥有型槽索引.len());
    for &槽 in 拥有型槽索引 {
        let 标签 = *槽基址.add(槽 * 2);
        if 标签 != 标签_句柄 { continue; }
        let 句柄 = *槽基址.add(槽 * 2 + 1);
        if 句柄 != 0 { 结果.push(句柄); }
    }
    结果
}

/// **解释模式**一步释放：`运行时值` 槽数组 + 拥有型槽清单。
///
/// # Safety
/// 同 `收集运行时值槽句柄`。
pub unsafe fn 批量释放运行时值槽(槽基址: *const u64, 拥有型槽索引: &[usize]) {
    if 槽基址.is_null() || 拥有型槽索引.is_empty() { return; }
    let 待释放 = 收集运行时值槽句柄(槽基址, 拥有型槽索引);
    批量释放句柄列表(&待释放);
}

/// **编译模式**一步释放：影子块槽数组 + 拥有型槽清单。
///
/// # Safety
/// 同 `收集影子槽句柄`。
pub unsafe fn 批量释放影子槽(槽基址: *const u64, 拥有型槽索引: &[usize]) {
    if 槽基址.is_null() || 拥有型槽索引.is_empty() { return; }
    let 待释放 = 收集影子槽句柄(槽基址, 拥有型槽索引);
    批量释放句柄列表(&待释放);
}

/// ★单源★ **帧槽扫描（纯函数）**：按「拥有型槽索引」选取**标签为句柄**的槽 ⇒ 返回待释放句柄列表。
///
/// 拆出为纯函数的两个理由：
///   ① **可确定性单测**（不触碰全局堆 ⇒ 不受 base 单测**并行执行**时的堆计数竞争影响
///      —— 2026-09-22 实测：直接断言 `堆统计` 存活差值会与其它测试并发而随机失败）；
///   ② 便于两引擎**只读预检**（如"弹帧前先看将释放什么"，用于诊断/断言）。
///
/// 选取规则（与 `堆_释放引用` 同源，**单一真相**）：`标签 == 标签_句柄` 且 `载荷 != 0` ⇒ 选中。
///   ⇒ 标量 / 空值 / 函数指针 / 局部引用 / 并发句柄 / 外部值 一律自动跳过。
///
// ════════════════════════════════════════════════════════════════════════════
// ⚡统一帧契约 v2（UFC-v2，阶段 3b 2026-09-23）：**帧消亡的唯一实现**⚡
//
//  动机（结构性，消灭一类缺陷）：`帧消亡` 的**释放 → 清零**顺序此前在**两引擎各写一遍**
//    （编译侧 `弹出编译帧` / 解释侧 `帧级批量释放` + `清当前帧槽`）⇒ 顺序知识**重复且易错**
//    （"先清零后释放"会把句柄读丢 ⇒ 系统性泄漏；本项目已两轮踩过"顺序"坑）。
//
//  设计：**一个实现、两相、一个组合入口** ——
//    · `帧消亡_释放`（相①）：按「拥有型槽清单」对**拥有型槽**逐槽 −1（读句柄 ⇒ **必须最先**）
//    · `帧消亡_清零`（相②）：**整块清零**该帧区间（消除借用型/临时槽的**陈旧句柄** ⇒ 根枚举
//      "全扫"不再把它当根 ⇒ 对账悬垂归零；并杜绝栈槽/表槽复用后**误读陈旧句柄**）
//    · `帧消亡` = ①→②（**顺序内化**；调用方无法写错 ⇒ 这是本次收敛的核心价值）
//
//  ⚠ **唯一被认可的例外（必须尊重的真实约束）**：**解释模式**的 `返回` 指令，其返回值操作数
//    **可能仍在本帧槽内**（`虚拟机核心.rs::清当前帧槽` 的注释有实测记录）⇒ 解释模式**必须**
//    拆成两相调用：`返回` 处先 **相①**，`读带标记操作数()` **之后**再 **相②**。
//    编译模式返回值走寄存器/sret ⇒ 直接用组合入口 `帧消亡` ✓
//  ⚠ 清零**不再设门控**：无论 `帧级释放启用()` 开关如何，帧区间在本帧死亡后**一律清零**
//    （与编译侧现有行为对齐；开关注销的是"逐槽释放 vs 批量释放"的选择，与"清陈旧句柄"无关）✓
//  ⚠ 安全性：本函数**不持堆锁**（`批量释放*` 自行取锁）⇒ 可在任意位置调用 ✓
// ════════════════════════════════════════════════════════════════════════════

/// 帧槽布局（**两引擎唯一的机制差异**，由它参数化）：
/// * `运行时值`：解释模式的 `局部变量表` 槽 = 4×u64（标签@+0 / 整数 / 小数 / **句柄@+24**）
/// * `影子对`：编译模式的影子块槽 = 2×u64（标签@+0 / **载荷@+8**）
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum 帧槽布局 {
    运行时值,
    影子对,
}

impl 帧槽布局 {
    /// 每槽占用的 u64 个数（偏移换算与"整块清零"的字节数都依赖它 ⇒ **单一真相**）。
    #[inline]
    pub fn 每槽u64(self) -> usize {
        match self {
            帧槽布局::运行时值 => 4,
            帧槽布局::影子对 => 2,
        }
    }
}

/// **相①**：按「拥有型槽清单」对被弹帧的**拥有型槽**逐槽 −1（幂等；悬垂/越界静默忽略）。
///
/// * `清单` 内的下标**相对 `块基址`**（解释模式调用方须先把"函数内绝对槽下标"加帧基址换算好）。
/// * 门控：`帧级释放启用()` 关闭 ⇒ 直接返回（此时由前端发射的**逐槽** `释放引用` 负责）。
pub fn 帧消亡_释放(布局: 帧槽布局, 块基址: usize, 清单指针: usize, 清单长度: usize) {
    if !帧级释放启用() || 块基址 == 0 || 清单指针 == 0 || 清单长度 == 0 {
        return;
    }
    let 清单 = unsafe { std::slice::from_raw_parts(清单指针 as *const usize, 清单长度) };
    match 布局 {
        帧槽布局::运行时值 => unsafe { 批量释放运行时值槽(块基址 as *const u64, 清单); },
        帧槽布局::影子对 => unsafe { 批量释放影子槽(块基址 as *const u64, 清单); },
    }
}

/// **相②**：**整块清零**帧区间（`槽数` 个槽 × 布局步长）。
///
/// ⚠ **必须在相①之后**（释放要读句柄）；解释模式下还必须在**读完返回值之后**（见上方例外说明）。
pub fn 帧消亡_清零(布局: 帧槽布局, 块基址: usize, 槽数: usize) {
    if 块基址 == 0 || 槽数 == 0 {
        return;
    }
    unsafe { std::ptr::write_bytes(块基址 as *mut u64, 0, 槽数 * 布局.每槽u64()); }
}

/// **组合入口**：`相① → 相②`（**顺序内化**，调用方无法写错顺序）。
///
/// 适用于"返回值不依赖本帧槽"的引擎（**编译模式** ✓）。解释模式须拆两相调用（见例外说明）。
pub fn 帧消亡(布局: 帧槽布局, 块基址: usize, 槽数: usize, 清单指针: usize, 清单长度: usize) {
    帧消亡_释放(布局, 块基址, 清单指针, 清单长度);
    帧消亡_清零(布局, 块基址, 槽数);
}

