    //    ⇒ 捕获到的句柄必须 +1；否则外层槽消亡/覆盖触发 −1 时会把「闭包仍在用」的对象回收（悬垂）。
    //    与 `收集子句柄`（级联释放对闭包环境捕获变量 −1）严格对称。
