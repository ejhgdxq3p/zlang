/// 增加引用计数（+1）—— **唯一真相入口**：凡「新产生一份对既有堆对象的引用」都必须经此，
/// 与 `堆释放`（−1）成对。当前调用点：接口型引用语义路径（前端在「接口实参 / 接口赋值」处
/// 发射 `操作码::增加引用`，见 语句转换.rs；解释与编译双模式共用本函数 ⇒ 由构造保证一致）。
///
/// ⚠ 只在"复制**既有**句柄"时 +1；新建对象内嵌新建子对象属**移动**，不 +1
///    （否则每层嵌套都会多出一份永不释放的计数 ⇒ 泄漏）。
pub fn 堆增加引用(id: u64) {
    let mut 堆 = 全局堆.write().unwrap();
    堆增加引用_已锁定(id, &mut *堆);
}

/// 写锁内联版（调用方**已持写锁**）：禁止在持锁上下文再调 堆增加引用（RwLock 不可重入 → 死锁）。
pub(crate) fn 堆增加引用_已锁定(id: u64, 堆: &mut 全局堆内部) {
    // 🔬 **内存诊断工具（长期保留）**：按句柄打印 **+1** 事件（与分配/−1 共同构成完整账本 ✓）
    if 释放探针目标() == Some(id) {
        let 前 = 解码句柄(堆, id).and_then(|i| 堆.槽位.get(i)).and_then(|s| s.as_ref()).map(|s| s.共享计数);
        eprintln!("[增加探针] 句柄={} 增加前计数={:?}", id, 前);
    }
    // 🔬 全量账本：+1 事件（`引用计数加一`（容器/字段存储）与接口 `增加引用` 均经此 ✓）
    if 账本全开() {
        let 前 = 解码句柄(堆, id).and_then(|i| 堆.槽位.get(i)).and_then(|s| s.as_ref()).map(|s| s.共享计数);
        eprintln!("[增加] 句柄={} 增加前计数={:?}", id, 前);
    }
    // 🆕 阶段 2：**代际校验**（陈旧句柄 ⇒ 幂等忽略；否则会给"复用后新对象"虚增计数 ⇒ 泄漏/错值）
    if let Some(i) = 解码句柄(堆, id) {
        if let Some(槽位) = 堆.槽位[i].as_mut() {
            槽位.共享计数 = 槽位.共享计数.saturating_add(1);
        }
    }
}

