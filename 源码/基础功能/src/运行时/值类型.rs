// ⚡统一帧契约（UFC）**释放侧元数据表**⚡（2026-09-22）
//
// 前端在降级完成后为**每个函数**登记其「拥有型槽索引」清单；两引擎**弹帧时按函数名查表**
// ⇒ 调用 `批量释放槽清单`。
//   · 解释模式：前端在同一进程内注册（降级完成后）⇒ VM 直接查表；
//   · 编译模式：编译产物在**独立进程** ⇒ 由编译器在 prologue 经 C ABI
//     `智语言_注册函数拥有型槽清单` 注册（与 base「外部结构体布局」同范式）。
// ⚠ 键 = 函数名（与 `底层表示函数.名称` 一致；匿名函数名由前端统一生成）。
// ════════════════════════════════════════════════════════════════════════════
static 函数拥有型槽清单表: once_cell::sync::Lazy<
    std::sync::Mutex<std::collections::HashMap<String, Vec<usize>>>,
> = once_cell::sync::Lazy::new(|| std::sync::Mutex::new(std::collections::HashMap::new()));

/// 登记某函数的「拥有型槽索引」清单（幂等：同键覆盖）。
pub fn 注册函数拥有型槽清单(函数名: String, 拥有型槽索引: Vec<usize>) {
    if 函数名.is_empty() { return; }
    函数拥有型槽清单表.lock().unwrap().insert(函数名, 拥有型槽索引);
}

/// 取某函数的「拥有型槽索引」清单；**未登记 ⇒ `None`**（调用方须保守不动，不得猜）。
pub fn 取函数拥有型槽清单(函数名: &str) -> Option<Vec<usize>> {
    函数拥有型槽清单表.lock().unwrap().get(函数名).cloned()
}

// ⚡**按顺序**登记（2026-09-22 实测必需）⚡：VM/编译产物的**函数表名是合成名**（实测 `f32/f33/…`），
//   与前端 HIR 函数名（`启动程序` / `检查` …）**不同命名空间** ⇒ 按名查找永不命中。
//   ⇒ 另按**登记顺序**（= 前端 `函数列表` 顺序 = 字节码/产物的函数表顺序）登记，并把
//     **局部变量表长度**一并存入作**对齐校验**：取值时校验长度一致才返回 ⇒ 一旦两侧顺序错位
//     （例如产物多出/重排函数）**必然校验失败** ⇒ 保守不释放（绝不误释放到别的函数的槽）。
static 函数拥有型槽序表: once_cell::sync::Lazy<
    std::sync::Mutex<Vec<(String, usize, Vec<usize>)>>,
> = once_cell::sync::Lazy::new(|| std::sync::Mutex::new(Vec::new()));

/// 按**前端函数列表顺序**登记（返回该函数的顺序下标）。`局部表长度` 用于取值时对齐校验。
pub fn 注册函数拥有型槽清单_按序(函数名: String, 局部表长度: usize, 拥有型槽索引: Vec<usize>) -> usize {
    let mut 表 = 函数拥有型槽序表.lock().unwrap();
    表.push((函数名, 局部表长度, 拥有型槽索引));
    表.len() - 1
}

/// 按**顺序下标**取清单；`局部表长度` 与登记值不一致 ⇒ 视为未登记（对齐校验失败 ⇒ 保守不动）。
pub fn 取函数拥有型槽清单_按序(索引: usize, 局部表长度: usize) -> Option<Vec<usize>> {
    let 表 = 函数拥有型槽序表.lock().unwrap();
    let (_, 记长, 清单) = 表.get(索引)?;
    if *记长 != 局部表长度 { return None; }
    Some(清单.clone())
}

/// 清空顺序表（**仅测试用**：进程内多次降级/多套件切换时避免残留错位）。
pub fn 清空函数拥有型槽序表() {
    函数拥有型槽序表.lock().unwrap().clear();
}

/// 是否启用**帧级批量释放**（默认 **开**；可用环境变量**逃生开关**退回旧行为）。
///
/// ⚠ 与前端「停发逐槽 `释放引用`」（`语句转换.rs::发射释放引用`）**共用同一开关**，必须同开同关：
///   · 只开引擎侧 ⇒ 逐槽 + 批量**双份 −1** ⇒ 提前回收（悬垂）；
///   · 只开前端侧 ⇒ 完全不释放 ⇒ 泄漏不降。
///
/// 默认开（2026-09-22 起，**两引擎均已验证**：解释/编译各 7+ 例，语义全绿、违例 0、悬垂 0）：
