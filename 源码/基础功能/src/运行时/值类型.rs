/// 把运行期值转换为映射键（**可失败**）。
///
/// 2026-10-12（规范 §2.4.2 键白名单）★ 此前非「整数/逻辑/文本」的值一律静默兜底为
/// `堆键::文本("")` ⇒ 数组/映射/结构体/接口/函数/小数等键**全部塌陷成同一个键**，
/// 互相覆盖并取回错值（静默数据损坏，双模一致）。现改为返回 `Err(诊断)`，由调用方
/// `值转键或抛异常` 抛**可捕获**异常。
///
/// 键白名单（与前端 `类型检查::检查映射键类型` 对齐）：
///   整数、小数、文本、逻辑、空值、枚举、可作键的结构体；
///   数组 / 映射 / 接口 / 函数 / `无效小数` ⇒ 不可作键。
pub fn 值转键(v: &运行时值) -> Result<堆键, String> {
    值转键_内部(v, 0, &mut Vec::new())
}

/// 键编码内部实现：带**深度上限 + 路径环检测**（结构体字段递归需要）。
///
/// 环从哪来：结构体可经 `空值` / `任意` 字段指向自身或成环（实测可造环，数组亦可自引用）
/// ⇒ 必须显式拒绝，否则编码会无限递归。
fn 值转键_内部(v: &运行时值, 深度: usize, 路径: &mut Vec<u64>) -> Result<堆键, String> {
    if 深度 > 64 {
        return Err("键的嵌套过深或含环，不能作为映射的键".to_string());
    }
    match v.标签 {
        标签_整数 => Ok(堆键::整数(v.整数)),
        标签_逻辑 => Ok(堆键::逻辑(v.整数 != 0)),
        标签_空值 => Ok(堆键::空值),
        标签_小数 => {
            let 数 = v.小数;
            if 数.is_nan() {
                return Err("无效小数不能作为映射的键".to_string());
            }
            // `-0.0 == 0.0`（实测为真）⇒ 必须归一到同一个键，否则违反「相等 当且仅当 同键」
            let 归一 = if 数 == 0.0 { 0.0 } else { 数 };
            // `1 == 1.0`（实测为真）⇒ 整数值的小数必须落回**整数键**
            const 下界: f64 = -9223372036854775808.0; // -2^63
            const 上界: f64 = 9223372036854775808.0; // 2^63（不含：避免 as 饱和踩到 i64::MAX 键）
            if 归一.fract() == 0.0 && 归一 >= 下界 && 归一 < 上界 {
                return Ok(堆键::整数(归一 as i64));
            }
            Ok(堆键::小数(归一.to_bits()))
        }
        标签_句柄 => {
            if let Some(s) = 堆读取文本字符串(v.句柄) {
                return Ok(堆键::文本(s));
            }
            match 堆读取(v.句柄) {
                Some(堆数据::结构体 { 类型索引, 字段值 }) => {
                    // 键资格：未自定义 `等于` 才可作键（前端注册；未注册 ⇒ 保守拒绝，绝不静默）
                    if !结构体可作键(类型索引) {
                        return Err(
                            "结构体不能作为映射的键（该类型自定义了 等于，或未注册键资格）".to_string(),
                        );
                    }
                    if 路径.contains(&v.句柄) {
                        return Err("键含环，不能作为映射的键".to_string());
                    }
                    路径.push(v.句柄);
                    let mut 字段键 = Vec::with_capacity(字段值.len());
                    for 字段 in &字段值 {
                        match 值转键_内部(字段, 深度 + 1, 路径) {
                            Ok(k) => 字段键.push(k),
                            Err(e) => {
                                路径.pop();
                                return Err(e);
                            }
                        }
                    }
                    路径.pop();
                    Ok(堆键::结构体 { 类型索引, 字段键 })
                }
                Some(堆数据::数组(arr)) => {
                    // 🆕 2026-10-12：**枚举载体** = `[成员标签, 数据…]`，首元素是含类型身份的
                    //   成员标签（前端 `枚举成员标签`）⇒ 命中**枚举标签注册表**即判定为枚举。
                    //   ⚠ 判定顺序：先看首元素是否整数、再查注册表；**未注册 ⇒ 仍按数组拒绝**
                    //     （保守：宁拒绝，不静默错；旧字节码/未声明场景行为不变）。
                    let 标签 = match arr.first() {
                        Some(首) if 首.标签 == 标签_整数 => 首.整数,
                        _ => return Err("数组不能作为映射的键".to_string()),
                    };
                    if 枚举标签名称(标签).is_none() {
                        return Err("数组不能作为映射的键".to_string());
                    }
                    if 路径.contains(&v.句柄) {
                        return Err("键含环，不能作为映射的键".to_string());
                    }
                    路径.push(v.句柄);
                    let mut 数据键 = Vec::with_capacity(arr.len().saturating_sub(1));
                    for 元素 in &arr[1..] {
                        match 值转键_内部(元素, 深度 + 1, 路径) {
                            Ok(k) => 数据键.push(k),
                            Err(e) => {
                                路径.pop();
                                return Err(e);
                            }
                        }
                    }
                    路径.pop();
                    Ok(堆键::枚举 { 标签, 数据键 })
                }
                Some(堆数据::映射(_)) => Err("映射不能作为映射的键".to_string()),
                Some(堆数据::闭包环境 { .. }) => Err("函数不能作为映射的键".to_string()),
                _ => Err("该值不能作为映射的键".to_string()),
            }
        }
        _ => Err("该值不能作为映射的键".to_string()),
    }
}

// ── 结构体「键资格」注册表（前端入口注入：该结构体类型未自定义 `等于` ⇒ 可作键）──

/// 全局结构体键资格表：类型索引 → 是否可作键（false = 自定义了 `等于`；未注册也按 false 处理）。
/// 与 `结构体字段名注册表` 同款「覆盖写」语义（支持单进程多程序 / REPL）。
static 结构体键资格表: Mutex<Vec<bool>> = Mutex::new(Vec::new());

/// 注册结构体键资格表（由前端在入口函数首块注入；解释/编译双模启动时统一调用）。
pub fn 注册结构体键资格(资格: Vec<bool>) {
    let mut 表 = 结构体键资格表.lock().unwrap();
    *表 = 资格;
}

/// 查询结构体是否可作键；**未注册 ⇒ false**（保守：宁拒绝，不静默错）。
pub fn 结构体可作键(类型索引: usize) -> bool {
    let 表 = 结构体键资格表.lock().unwrap();
    表.get(类型索引).copied().unwrap_or(false)
}

// ── 🆕 2026-10-12：枚举「成员标签」注册表（标签 → `枚举名.成员名`）──
/// 由前端在入口函数首块注入（158 载荷第三区）。标签 = `枚举成员标签`（含类型身份的 40 位散列）。
static 枚举标签表: Mutex<Vec<(i64, String)>> = Mutex::new(Vec::new());

/// 注册枚举标签表（双模启动时统一调用；空表 = 清空）。
pub fn 注册枚举标签表(表: Vec<(i64, String)>) {
    let mut 当前 = 枚举标签表.lock().unwrap();
    *当前 = 表;
}

/// 查询枚举成员标签的显示名；未注册 ⇒ None（保守：不猜、不静默）。
pub fn 枚举标签名称(标签: i64) -> Option<String> {
    let 表 = 枚举标签表.lock().unwrap();
    表.iter().find(|(t, _)| *t == 标签).map(|(_, n)| n.clone())
}

/// 判定并取出「枚举载体」的显示名：枚举值在运行期是数组 `[标签, 数据…]`，标签命中注册表即枚举。
fn 枚举载体显示名(v: &运行时值) -> Option<String> {
    if v.标签 != 标签_整数 { return None; }
    枚举标签名称(v.整数)
}

/// 键转换 + 失败即抛**可捕获**异常（异常类型「键类型无效」）。
///
/// 返回 `None` 表示已抛异常 ⇒ 调用方**必须立即返回**（不可继续执行后续逻辑，否则二次抛出会覆盖
/// 「键类型无效」的诊断）。语义对齐 Go（接口键运行期 panic）与 Python（unhashable 抛 TypeError）：
/// 不可作键的值在运行期**显式报错**，绝不静默塌陷。
pub fn 值转键或抛异常(v: &运行时值) -> Option<堆键> {
    match 值转键(v) {
        Ok(k) => Some(k),
        Err(描述) => {
            crate::异常运行时::智语言_抛出异常(
                "键类型无效".as_ptr(),
                "键类型无效".len() as i64,
                描述.as_ptr(),
                描述.len() as i64,
            );
            None
        }
    }
}

pub fn 键转值(k: &堆键) -> 运行时值 {
    match k {
        堆键::整数(i) => 运行时值::整数(*i),
        堆键::文本(s) => 分配文本(s.clone()),
        堆键::逻辑(b) => 运行时值::逻辑(*b),
        堆键::空值 => 运行时值::空值(),
        堆键::小数(位) => 运行时值::小数(f64::from_bits(*位)),
        // 结构体键 ⇒ 按「类型索引 + 字段值」重建实例（`.所有键()` / 外部值往返用）
        堆键::结构体 { 类型索引, 字段键 } => {
            分配结构体(*类型索引, 字段键.iter().map(键转值).collect())
        }
        // 枚举键 ⇒ 按「成员标签 + 数据」重建**载体数组** `[标签, 数据…]`（`.所有键()` / 外部值往返用）
        堆键::枚举 { 标签, 数据键 } => {
            let mut 元素: Vec<运行时值> = Vec::with_capacity(数据键.len() + 1);
            元素.push(运行时值::整数(*标签));
            元素.extend(数据键.iter().map(键转值));
            分配数组(元素)
        }
    }
}

/// 🔁 2026-09-24（**item 9：映射渲染临时泄漏修复**）★ —— 把**堆键**直接渲染为 `String`（**零分配** ✓）。
///
/// **为什么必须独立于 `键转值`**：渲染路径（`运行时值::转文本()` 的映射分支）只需键的**字符串**，
///   而 `键转值(k).转文本()` 对文本键会走 `分配文本(s.clone())` ⇒ 该新建对象**取完字符串即被丢弃、
///   无人 −1** ⇒ **每渲染一个文本键泄漏 1 个文本对象** ✗
///   实测（`日志/脚本/临时/soak/T_映射字面量作实参.智`）：`转文本({"甲":1,"乙":{"丙":1}})` 循环中
///   **文本 3/轮** = 三个键「甲/乙/丙」✓✓（`总网络模块` 里 `转文本(响应.响应头())` 同理，非循环 ⇒ 未显红）✓
///
/// ⚠ 为什么**不是**"分配后再释放"：本函数处于**热路径**（每次格式化映射/容器都会递归走到）
///   ⇒ **零分配**更优，且从构造上消除"忘记释放"的可能（无需配对 ✓）。
/// ⚠ 输出**逐字节等价**于 `键转值(k).转文本()`（整数 `i.to_string()`；文本 `s.clone()`；
///   逻辑 真/假 —— 与 `运行时值::转文本()` 的分支一致 ✓），**不改变任何可观测行为** ✓
pub fn 堆键转文本(k: &堆键) -> String {
    match k {
        堆键::整数(i) => i.to_string(),
        堆键::文本(s) => s.clone(),
        堆键::逻辑(b) => if *b { "真".to_string() } else { "假".to_string() },
        // 2026-10-12：与 `运行时值::转文本()` 一致（空值 ⇒ 空值；小数 ⇒ 同 格式化小数显示）
        堆键::空值 => "空值".to_string(),
        堆键::小数(位) => 运行时值::格式化小数显示(f64::from_bits(*位)),
        // 结构体键 ⇒ `类型名（字段键…）`
        堆键::结构体 { 类型索引, 字段键 } => {
            let 内部 = 字段键
                .iter()
                .map(堆键转文本)
                .collect::<Vec<_>>()
                .join(", ");
            format!("{}（{}）", 取结构体类型名称(*类型索引), 内部)
        }
        // 枚举键 ⇒ `枚举名.成员名`（有数据时 `枚举名.成员名(数据…)`）——与 `运行时值::转文本()`
        //   的**枚举专属渲染**同款（半角括号），保证「键渲染」与「重建后的值渲染」观感一致。
        //   未注册（理论上不会发生：编码前已查表）⇒ 退化为 `枚举#<标签>`，**不猜不静默**。
        堆键::枚举 { 标签, 数据键 } => {
            let 名称 = 枚举标签名称(*标签).unwrap_or_else(|| format!("枚举#{}", 标签));
            if 数据键.is_empty() { 名称 } else {
                format!("{}({})", 名称, 数据键.iter().map(堆键转文本).collect::<Vec<_>>().join(", "))
            }
        }
    }
}

