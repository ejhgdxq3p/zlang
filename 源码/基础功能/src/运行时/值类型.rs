pub const 标签_整数: u64 = 1;
pub const 标签_小数: u64 = 2;
pub const 标签_逻辑: u64 = 3;
pub const 标签_句柄: u64 = 4; // 引用全局堆中的复合对象
pub const 标签_异常: u64 = 5;
/// 🆕 统一架构: 函数指针（标签_句柄+句柄=堆闭包环境 以外，直接用整数载荷存储函数索引的快捷标记）
pub const 标签_函数指针: u64 = 6;
/// 🆕 统一架构: 传引用参数局部引用（整数载荷=变量槽位索引）
pub const 标签_局部引用: u64 = 7;
/// 🆕 统一架构: 并发资源句柄（通道/任务/终止器）
pub const 标签_并发句柄: u64 = 8;
/// 标签 9 已退役：原 GC 标记-清除标记位，随 WS-3 内存管理语义正名（引用计数 + 空闲表）删除。
/// 【勿复用 9】保留空位以免与既有字节码/产物中的历史值混淆。
/// 🆕 W4 FFI 导出块：跨 FFI 边界的「序列化堆对象」根标记（统一 FFI 编组层专用）。
/// 与 标签_函数指针(6) 等内部标记严格区分——它专用于 基础功能/src/运行时/外部调用注册.rs
/// 的「统一 FFI 编组层」，在 C ABI 边界把堆对象（文本/数组/映射/结构体）序列化为扁平缓冲后传递，
/// 彻底绕开全局堆跨 DLL 边界分裂的限制。旧 ad-hoc 标签 标签_外部文本=6 已废弃（与 标签_函数指针=6 撞车）。
pub const 标签_外部值: u64 = 10;

/// 对外 C ABI（智语言_二元算术 等）使用的「类型标志」魔数。
/// 与内部 标签_*（整数=1）不同：此套用于绕过 Cranelift 小整数常量损坏 bug。
