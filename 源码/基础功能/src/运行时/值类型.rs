/// 根提供者：把本引擎当前可见的根句柄逐个喂给回调。
/// `上下文` 由注册方给出（解释模式 = `*mut 虚拟机` 的 usize，与「回调桥守卫」同一模式）。
pub type 根提供者 = fn(上下文: usize, 回调: &mut dyn FnMut(u64));

// ⚠ **线程本地**（而非全局表）：根提供者会**读取本线程引擎的帧内存**，
//   若跨线程枚举别的线程的帧 ⇒ 与对方 mutator 并发读写 = **数据竞争** ⇒ 故按线程隔离。
//   跨线程完整性由「活跃提供者计数」判定：全局计数 > 本线程计数 ⇒ 结果**不完整**（禁止兜底清扫）。
thread_local! {
    static 本线程根提供者: std::cell::RefCell<Vec<(usize, usize, 根提供者)>> =
        const { std::cell::RefCell::new(Vec::new()) };
}
/// 全局活跃根提供者计数（登记/注销时增减；用于判定"对账结果是否覆盖全部线程"）。
static 活跃根提供者数: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
static 根提供者下一标识: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(1);

/// 注册根提供者（**注册到当前线程**，返回标识供注销）。解释器侧用 RAII 守卫包裹。
pub fn 注册根提供者(上下文: usize, 提供者: 根提供者) -> usize {
    let 标识 = 根提供者下一标识.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    本线程根提供者.with(|表| 表.borrow_mut().push((标识, 上下文, 提供者)));
    活跃根提供者数.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    标识
}

/// 注销根提供者（**本线程**，幂等）。
pub fn 注销根提供者(标识: usize) {
    // 🆕 **终局对账**：若这是**最后一个**根提供者（本线程仅剩它 且 全局仅此一个）⇒ 在**注销前**打印。
    //   ⚠ 必须"注销前"：注销后根集为空 ⇒ 可达恒 0、结论无意义（2026-09-22 实测踩过）。
    //   意义：小用例不达周期阈值也能被验证（引擎退出 = 解释模式 `执行()` 结束 / 编译模式最外层函数返回）。
    let 本线程数 = 本线程根提供者.with(|表| 表.borrow().len());
    if 本线程数 == 1
        && 活跃根提供者数.load(std::sync::atomic::Ordering::Relaxed) == 1
        && (std::env::var("智语言_内存对账").is_ok() || std::env::var("智语言_内存兜底清扫").is_ok())
    {
        打印对账("终局");
    }
    let 移除数 = 本线程根提供者.with(|表| {
        let 前 = 表.borrow().len();
        表.borrow_mut().retain(|(id, _, _)| *id != 标识);
        前.saturating_sub(表.borrow().len())
    });
    for _ in 0..移除数 { 活跃根提供者数.fetch_sub(1, std::sync::atomic::Ordering::Relaxed); }
}

