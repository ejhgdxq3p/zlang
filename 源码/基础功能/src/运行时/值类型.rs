/// 转义容器内引号（只处理 `\` 与 `"`，其余字符原样保留）。
fn 转义容器内引号(文本: &str) -> String {
    文本.replace('\\', "\\\\").replace('"', "\\\"")
}

/// 容器（数组/映射）内元素的文本渲染。
/// 规范 §4.1/§4.2 示例：`转文本([1, 2, 3])` ⇒ `"[1, 2, 3]"`、数组含文本 ⇒ `["苹果", "香蕉"]`、
/// 映射 ⇒ `{"键": "值"}` —— **容器内的文本元素必须带双引号**，否则
/// `[""].转文本()` 与 `[].转文本()` 同为 `"[]"`（长度 1 与 0 无法区分，语义歧义）。
/// 非文本元素沿用普通 `转文本()`（数值/逻辑/嵌套容器/空值都不加引号）。
pub fn 容器内值转文本(v: &运行时值) -> String {
    if v.标签 == 标签_句柄 {
        match 堆读取(v.句柄) {
            Some(堆数据::文本(s)) => return format!("\"{}\"", 转义容器内引号(&s)),
            Some(堆数据::文本_静态(p, n)) => {
                let 切片 = unsafe { std::slice::from_raw_parts(p as *const u8, n) };
                return format!("\"{}\"", 转义容器内引号(&String::from_utf8_lossy(切片)));
            }
            _ => {}
        }
    }
    v.转文本()
}

/// 映射键在容器内的渲染：文本键带双引号（与值一致），其它键沿用 `堆键转文本`。
pub fn 容器内键转文本(k: &堆键) -> String {
    match k {
        堆键::文本(s) => format!("\"{}\"", 转义容器内引号(s)),
        _ => 堆键转文本(k),
    }
}

