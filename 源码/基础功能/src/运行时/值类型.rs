/// 从精确小数结构体句柄读回 (缩放值 i128, 小数位数)。
pub(crate) fn 读精确小数(句柄: u64) -> Option<(i128, u32)> {
    if let Some(堆数据::结构体 { 字段值, .. }) = 堆读取(句柄) {
        if 字段值.len() >= 3 {
            let hi = 字段值[0].整数 as i128;
            let lo = (字段值[1].整数 as u64) as i128; // 低位按无符号解读，绝不能用 高位×2^64+低位 算术加法
            let v = (hi << 64) | lo;
            return Some((v, 字段值[2].整数 as u32));
        }
    }
    None
}

/// 把精确小数格式化为文本（严格保留构造时记录的小数位数 scale，不去尾零、精确补零）。
/// scale == 0 → 整数形式（无小数点）；scale > 0 → 整数部分.小数部分（小数部分严格补零到 scale 位）。
/// 与 Java BigDecimal / Python Decimal / C# decimal 默认行为一致：不去尾零，可区分 3 / 3.0 / 3.00。
/// 例：精确小数("3")→"3"、精确小数("3.0")→"3.0"、精确小数("3.50")→"3.50"、精确小数("3.00")→"3.00"、精确小数("-0.5")→"-0.5"、精确小数("0.00")→"0.00"。
pub(crate) fn 精确小数格式化(值: &运行时值) -> Option<String> {
    let (v, scale) = 读精确小数(值.句柄)?;
    let 绝对值 = v.unsigned_abs();
    let 因子 = 10u128.pow(scale as u32);
    let 整数部 = 绝对值 / 因子;
    let 小数部 = 绝对值 % 因子;
    let mut s = 整数部.to_string();
    if scale > 0 {
        let mut 小数 = 小数部.to_string();
        while 小数.len() < scale as usize { 小数.insert(0, '0'); }
        s.push('.');
        s.push_str(&小数);
    }
    if v < 0 { s.insert(0, '-'); }
    Some(s)
}

/// 精确小数数值相等（与 `==` 运算符语义一致：scale 不同仍判等）。
pub(crate) fn 精确小数相等(值a: &运行时值, 值b: &运行时值) -> Option<bool> {
    let (va, sa) = 读精确小数(值a.句柄)?;
    let (vb, sb) = 读精确小数(值b.句柄)?;
    // 交叉乘比较，避免放大到统一 scale 时溢出
    let lhs = va.checked_mul(10i128.pow(sb as u32))?;
    let rhs = vb.checked_mul(10i128.pow(sa as u32))?;
    Some(lhs == rhs)
}
