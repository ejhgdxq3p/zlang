/// 与解释器侧 `键值` 对齐
///
/// 🆕 2026-10-12（规范 §2.4.2 映射键「甲方案：清单为准」）：
///   `空值` 与 `小数` 提升为**独立键**，修复此前被静默折叠进 `文本("")` 的问题：
///   - `空值` 与 `文本("")` 实测 `空值 != ""` 为真，却塌陷成同一个键 ⇒ 违反不变量「a == b ⟺ 键(a) == 键(b)」；
///   - `小数` 此前无键变体 ⇒ 一律塌馅为空串键（不同小数互相覆盖）。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum 堆键 {
    整数(i64),
    文本(String),
    逻辑(bool),
    /// 空值键（独立变体，**不再**与 `文本("")` 合并）
    空值,
    /// 小数键：存 `f64::to_bits()` 位模式（调用方保证已归一：`-0.0` → `0.0`；`无效小数` 禁止作键）
    小数(u64),
    /// 结构体键：**类型索引 + 按声明顺序的字段键序列**。
    /// 与 `==` 一致（实测：结构体 `==` 跨类型为假、同类型逐字段递归）⇒ 编码必须含类型身份且按声明序。
    /// 前置条件：该结构体类型**未自定义 `等于`**（前端注册的键资格表）+ 所有字段都可就地编码。
    结构体 { 类型索引: usize, 字段键: Vec<堆键> },
    /// 🆕 2026-10-12：**枚举键** —— `成员标签 + 数据键序列`。
    /// 枚举值在运行期是数组 `[成员标签, 数据…]`；标签由前端 `枚举成员标签` 生成（含**类型身份**的
    /// 40 位散列 + 成员号）⇒ 同枚举同成员同数据 = 同键；跨枚举类型 / 异成员 / 异数据 = 不同键，
    /// 与 `==` 完全一致（实测：跨枚举为假、同枚举逐成员+数据比较）。
    /// 仅当首元素命中**枚举标签注册表**时才按枚举编码（普通数组仍抛「数组不能作为映射的键」）。
    枚举 { 标签: i64, 数据键: Vec<堆键> },
}

/// 全局堆中存储的复合数据类型（统一架构：包含解释器和编译器所有类型）
#[derive(Debug, Clone)]
pub enum 堆数据 {
    文本(String),
    /// 静态只读文本：指向 COFF 数据段 / 字节码常量池等进程级只读内存（零拷贝）。
    /// 仅在被修改时通过写时复制升级为 `文本(String)`（见 堆修改）。
    /// 用 usize 存地址（而非裸指针）以保持 堆数据 的 Send/Sync，使全局堆可跨线程访问。
    文本_静态(usize, usize),
    数组(Vec<运行时值>),
    映射(Vec<(堆键, 运行时值)>),
    结构体 { 类型索引: usize, 字段值: Vec<运行时值> },
    /// 🆕 统一架构: 闭包环境 — 合并解释器的闭包环境和编译器的闭包数组（堆数据::数组）
    /// 函数索引 0=无效；捕获变量为空列表=无环境捕获（静态函数引用降级为函数指针）
    闭包环境 { 函数索引: usize, 捕获变量: Vec<运行时值> },
}

/// 全局堆槽位：带引用计数的堆数据，支持 GC 标记
pub(crate) struct 堆槽位 {
    pub(crate) 数据: 堆数据,
    pub(crate) 共享计数: u32,
    /// 🆕 统一回收（2026-09-22）：**可达性标记位** —— 仅「可达性对账 / 兜底回收」使用，
    /// **不参与任何语义判定**（值语义隔离由降级层构造性深拷贝承担；生存期由 `共享计数` + 作用域批量释放承担）。
    pub(crate) 标记: bool,
}

/// 全局堆内部结构：Vec 槽位 + 空闲列表
/// 统一架构：全局堆是解释器/编译器的唯一堆，不再有私有堆。
pub(crate) struct 全局堆内部 {
    pub(crate) 槽位: Vec<Option<堆槽位>>,
    pub(crate) 空闲表: Vec<u32>,
    /// 🆕 阶段 2（2026-09-23）**代际表**（与 `槽位` **同长**，永不缩短）：
    ///   · 槽位**首次**分配 ⇒ 代际 0；**复用**（空闲表 pop）⇒ `wrapping_add(1)`；
    ///   · 槽位回收（`槽位[i] = None`）时 **保留代际** —— 这正是 ABA 防线。
    ///   配合「句柄 = `[代际32 | 索引32]`」⇒ **陈旧句柄静默失效**（读到 None / 幂等忽略），
    ///   不再有"读到复用后新对象"的**错值**风险（原先只靠"释放后写空值"尽力而为）。
    pub(crate) 代际表: Vec<u32>,
    /// 🆕 GC 集成: 回收统计
    pub(crate) 回收次数: u64,
    pub(crate) 累计回收字节: usize,
}

/// ⚠️ 重入死锁铁律（架构统一锁定规范）：
/// 全局堆使用 RwLock（**不可重入**）。在持有写锁的上下文（堆修改 / 堆写入 / 堆修改_内联 的闭包 f 内）
/// 禁止调用任何会再次获取全局堆锁的函数：堆读取 / 堆分配 / 堆_写入前复制 / 堆增加引用 / 堆减少引用 等。
/// 若需读堆数据或构造键（如 值转键 内部会 堆读取），必须在写锁【外】预计算，
/// 再在闭包内做纯内存操作。违反此约定 → RwLock 不可重入死锁（编译期查不出，运行时必卡死）。
/// 当前已知合规点：堆操作.rs 的 映射存储 / 映射删除 已把 值转键 移到写锁外（见 ⚡死锁修复 注释）。
static 全局堆: once_cell::sync::Lazy<RwLock<全局堆内部>> =
    once_cell::sync::Lazy::new(|| RwLock::new(全局堆内部 {
        // 🔁 2026-09-23（阶段 2/3a 暴露的**既有隐患修复**）：**保留 0 号槽**（永久 `None`）。
        //   原因：全库多处沿用"**句柄 != 0 才算有效**"的约定（`收集全部根`/`收集拥有型根` 的
        //   根过滤、帧槽扫描的 `载荷 != 0`、根枚举的 `载荷 != 0`）——若首个对象落在 0 号槽，
        //   其句柄恰为 `0` ⇒ **该对象永远无法成为根**：① `可达` 被误判为 0（J2 口径失真）；
        //   ② 开启 `智语言_内存兜底清扫` 时会**误收仍被引用的对象**（真实内存安全风险）✗
        //   ⇒ 保留 0 号槽（代价 = 16 字节占位）⇒ 真实句柄**恒 ≠ 0**，既有约定自动成立 ✓
        //   ⚠ 与解释器「局部变量表 0 号槽保留」的既有约定同构（两引擎一致的理解）。
        槽位: vec![None],
        空闲表: Vec::new(),
        代际表: vec![0],
        回收次数: 0,
        累计回收字节: 0,
    }));

/// 🆕 P1-2: GC 阈值控制 — 原子变量无锁读取优化（避免每次分配仅为了读两个标量而加堆锁）
/// ⚡性能⚡ B1: GC 降频（2026-08-03）— 审计确认 堆_执行回收 根集=全堆非空槽位→标记全真→清除阶段
/// 实际不回收对象（真正释放靠 堆释放 引用计数+空闲表）。因此调高阈值只减少 STW 全堆扫描频率，
/// 不增加内存占用（回收与否与阈值无关），双模（解释/编译）共同受益。
static 上次回收后分配字节: AtomicU64 = AtomicU64::new(0);
/// 回收阈值（字节）。**0 = 尚未初始化** ⇒ 首次访问由 `取回收阈值` 按是否「对账模式」确定初值。
/// （此前恒以 4MB 初始化 ⇒ **小用例永不触发回收/对账** ⇒ 门禁无法验证小用例。）
static 回收阈值字节: AtomicU64 = AtomicU64::new(0);

/// 取回收阈值（首次访问惰性初始化）。
/// **对账模式**（`智语言_内存对账` / `智语言_内存兜底清扫`）⇒ 初值 64KB，使**小用例也能触发对账**；
/// 否则 4MB（与原行为一致）。⚠ 仅环境变量门控 ⇒ 产品路径行为不变（首次多一次原子读）。
fn 取回收阈值() -> u64 {
    let 当前 = 回收阈值字节.load(Ordering::Relaxed);
    if 当前 != 0 { return 当前; }
    let 初值 = if std::env::var("智语言_内存对账").is_ok() || std::env::var("智语言_内存兜底清扫").is_ok() {
        8 * 1024
    } else {
        4 * 1024 * 1024
    };
    回收阈值字节.store(初值, Ordering::Relaxed);
    初值
}

/// 🆕 统一架构: 估算堆数据占用的字节数
pub fn 堆数据估算大小(数据: &堆数据) -> usize {
    match 数据 {
        堆数据::文本(s) => s.len() + std::mem::size_of::<String>(),
        堆数据::文本_静态(_, n) => *n + std::mem::size_of::<String>(),
        堆数据::数组(arr) => arr.len() * std::mem::size_of::<运行时值>() + std::mem::size_of::<Vec<运行时值>>(),
        堆数据::映射(m) => m.len() * (std::mem::size_of::<(堆键, 运行时值)>()) + std::mem::size_of::<Vec<(堆键, 运行时值)>>(),
        堆数据::结构体 { 字段值, .. } => 字段值.len() * std::mem::size_of::<运行时值>() + std::mem::size_of::<Vec<运行时值>>(),
        堆数据::闭包环境 { 捕获变量, .. } => 捕获变量.len() * std::mem::size_of::<运行时值>() + std::mem::size_of::<Vec<运行时值>>(),
    }
}

// ════════════════════════════════════════════════════════════════════════════
//  🆕 阶段 2（2026-09-23）**句柄代际**：句柄 = `[代际32 | 索引32]`（仍是 u64 ⇒ **零尺寸增长**）
//
//  背景（唯一有真实内存安全后果的缺口）：句柄此前只是**槽位索引** ⇒ 槽位被回收后**复用**，
//    仍持有旧句柄的地方会**静默读写到新对象**（ABA）——若新对象类型相同，连标签校验也救不了。
//    （原先仅靠"释放后写空值 / 清帧槽 / 影子块清零"尽力压制，属"尽力而为"，不可证明。）
//
//  机制：① 分配时把当前代际打包进句柄；② 槽位**复用**时 `代际 +1`；③ 回收时**保留代际**；
//        ④ 解码处**校验代际** ⇒ 不匹配 ⇒ 视为"陈旧句柄"：读 ⇒ None、释放/加引用 ⇒ 幂等忽略。
//
//  ⚠ 为什么**最优**（对比其它候选）：单调 id 表需额外哈希查找（每次访问多一跳）；
//     指针句柄需 pin（有对象移动问题）；延迟回收（quarantine）只是降低概率、且费内存。
//     代际打包是 **O(1) 且零额外内存** ⇒ 与 ECS/`slotmap`/`generational-arena` 工业做法一致。
//  ⚠ 索引上限 4G、代际回绕 4G 次复用（回绕后理论上可 ABA；概率可忽略，且方向仍是"最终会失效"）。
//  ⚠ 句柄 `0`（索引 0 + 代际 0）沿用既有"无效"约定（根枚举等处按 `!= 0` 过滤）—— 行为不变。
// ════════════════════════════════════════════════════════════════════════════

/// 打包句柄：低 32 位 = 槽位索引，高 32 位 = 代际。
#[inline]
pub(crate) fn 打包句柄(索引: u32, 代际: u32) -> u64 {
    (索引 as u64) | ((代际 as u64) << 32)
}

/// 取句柄的槽位索引（**不校验代际**；仅用于"句柄 → 索引"的机械换算，如内部遍历）。
#[inline]
pub(crate) fn 句柄索引(句柄: u64) -> usize {
    (句柄 & 0xFFFF_FFFF) as usize
}

/// 取句柄的代际。
#[inline]
pub(crate) fn 句柄代际(句柄: u64) -> u32 {
    (句柄 >> 32) as u32
}

/// **解码 + 代际校验**：有效 ⇒ `Some(槽位索引)`；陈旧/越界/空槽/0 ⇒ `None`。
/// 这是"陈旧句柄静默失效"的**唯一真相**（所有外部句柄入口都应经它）。
/// ⚠ 调用方必须**已持堆锁**（本函数不取锁 ⇒ 避免重入死锁）。
fn 解码句柄(堆: &全局堆内部, 句柄: u64) -> Option<usize> {
    // ⚠ **不得**把 `句柄 == 0` 当作"无效"哨兵：堆的**第 0 号槽**的句柄恰为 `0`（索引 0 + 代际 0）
    //   ⇒ 那样会把首个分配对象判成无效（2026-09-23 单测 `句柄代际` 当场抓到 ✗）。
    //   有效性**只由**「索引在界内 + 槽位非空 + 代际匹配」三者决定 ✓
    //   （其余地方沿用的 `句柄 != 0` 仍是**保守过滤**语义，与本次改动无关。）
    let i = 句柄索引(句柄);
    if i >= 堆.槽位.len() { return None; }
    if 堆.槽位[i].is_none() { return None; }
    if 堆.代际表.get(i).copied().unwrap_or(0) != 句柄代际(句柄) { return None; }
    Some(i)
}

/// 在全局堆中分配对象，返回句柄 id（u64；低32=索引，高32=代际）
/// 🆕 统一架构: 分配时累计字节数，达到阈值触发 GC
/// 🔬 **内存诊断工具（长期保留）**：`智语言_账本全部=1` ⇒ 逐事件打印 **分配 / `+1` / `−1`**
/// （含句柄与计数 ✓），用于在 **N=1 单轮**下读出"哪一次 `−1` 缺少持有" ✓
/// ⚠ 默认关闭、`OnceLock` 缓存（**热路径零开销** ✓）；带**条数上限**（2000）防爆量 ✓
/// 📌 2026-09-24 收尾裁定：**转为长期诊断** —— 本工具是 S 缺口"真根因"（实参被移动却仍被释放 ✗）
///   的唯一获取手段 ⇒ 保留 ✓（配套：`释放探针目标`（按句柄）+ `句柄共享计数` ✓）
pub(crate) fn 账本全开() -> bool {
    use std::sync::{OnceLock, atomic::{AtomicU64, Ordering}};
    static 缓存: OnceLock<bool> = OnceLock::new();
    static 已打印: AtomicU64 = AtomicU64::new(0);
    let 开 = *缓存.get_or_init(|| std::env::var("智语言_账本全部").is_ok());
    if !开 { return false; }
    已打印.fetch_add(1, Ordering::Relaxed) < 2000
}

pub fn 堆分配(数据: 堆数据) -> u64 {
    // 🔁 2026-09-25（**删除不可达兜底臂：`_ => "其它"`**）★
    //   编译器告警 `warning: unreachable pattern`（就本处）：该 `_` 臂**永不可达**
    //   ⇒ 说明 `堆数据` 的**全部变体已被上方各分支穷尽** ✓（本 match 仅用于**账本打印的分类标签**，
    //     不影响分配行为 ⇒ 删臂**零语义变化** ✓）
    //   **为何要删**：① 该告警是死代码审计清单里**唯一未定性**项 ⚠；
    //     ② 删后本 match **穷尽枚举** ⇒ 将来给 `堆数据` 增变体时**编译器会在此报错** ✓
    //        （若保留 `_`，新变体会被**静默**归入"其它"而无人察 ✗ —— 正是"绝不静默"要避免的情形 ✓）
    let 种类 = match &数据 {
        堆数据::文本(_) => "文本",
        堆数据::文本_静态(..) => "文本_静态",
        堆数据::数组(_) => "数组",
        堆数据::映射(_) => "映射",
        堆数据::结构体 { .. } => "结构体",
        堆数据::闭包环境 { .. } => "闭包环境",
    };
    let id = 堆分配_内部(数据, true);
    // 🔬 全量账本：分配事件（记录种类便于逐事件判读 ✓）
    //   兼支持**单句柄过滤**（`智语言_释放探针句柄=<id>` ⇒ 只打印该句柄的分配 ⇒ 便于取"种类" ✓✓）
    if 账本全开() || 释放探针目标() == Some(id) {
        eprintln!("[分配] 句柄={} 种类={} 计数=1", id, 种类);
    }
    id
}

fn 堆分配_内部(数据: 堆数据, 触发回收: bool) -> u64 {
    if 触发回收 {
        // 纯函数估算大小，无锁
        let 大小 = 堆数据估算大小(&数据);
        let 当前 = 上次回收后分配字节.load(Ordering::Relaxed);
        let 需要回收 = 当前.saturating_add(大小 as u64) >= 取回收阈值();
        if 需要回收 {
            // 内部加锁执行标记-清除并重置计数（GC 不频繁，此路径尚无论堆锁持有，不会死锁）
            crate::异常运行时::智语言_执行回收();
        }
        // 在（可能的）回收后累计本次分配字节，保证计数始终准确
        上次回收后分配字节.fetch_add(大小 as u64, Ordering::Relaxed);
    }

    let id = {
        let mut 堆 = 全局堆.write().unwrap();  // 只锁这一次
        if !触发回收 {
            let 大小 = 堆数据估算大小(&数据);
            上次回收后分配字节.fetch_add(大小 as u64, Ordering::Relaxed);
        }

        if let Some(空闲) = 堆.空闲表.pop() {
            let i = 空闲 as usize;
            // 🆕 阶段 2：**复用槽位 ⇒ 代际 +1**（陈旧句柄自此失效，ABA 被结构性消除）
            let 新代际 = 堆.代际表.get(i).copied().unwrap_or(0).wrapping_add(1);
            if i < 堆.代际表.len() { 堆.代际表[i] = 新代际; } else { 堆.代际表.push(新代际); }
            堆.槽位[i] = Some(堆槽位 { 数据, 共享计数: 1, 标记: false });
            打包句柄(空闲, 新代际)
        } else {
            let i = 堆.槽位.len();
            堆.槽位.push(Some(堆槽位 { 数据, 共享计数: 1, 标记: false }));
            堆.代际表.push(0);   // 首次分配：代际 0
            打包句柄(i as u32, 0)
        }
    };
    // 🆕 2026-09-22 L3 环收集预算触发（**必须在堆锁释放之后**调用 ⇒ 否则重入死锁）。
    //   与上面按字节触发的 mark-sweep（`智语言_执行回收`，需要根集齐备）不同：
    //   L3 是 **trial deletion（计数判据）** ⇒ **不依赖根枚举** ⇒ 多线程下同样安全、可用于产品路径。
    环收集_按预算();
    id
}

/// 从全局堆读取对象（克隆），返回 None 表示句柄无效
pub fn 堆读取(id: u64) -> Option<堆数据> {
    let 堆 = 全局堆.read().unwrap();
    // 🆕 阶段 2：**代际校验**（陈旧句柄 ⇒ None；不再可能读到"复用后的新对象"）
    let i = 解码句柄(&堆, id)?;
    Some(堆.槽位[i].as_ref()?.数据.clone())
}

/// 读锁内借用堆对象（不克隆整个数据），供热路径纯读操作使用。
/// ⚡性能⚡ 原 堆读取 每次整体深拷贝（数组/映射读 O(n)），借用后仅克隆命中的元素（O(1)）。
/// 闭包在写锁竞争窗口内执行，须保持轻量（不得再取堆锁，异常抛出走线程局部无锁，安全）。
pub fn 堆读取借用<R>(id: u64, f: impl FnOnce(&堆数据) -> R) -> Option<R> {
    let 堆 = 全局堆.read().unwrap();
    // 🆕 阶段 2：代际校验（陈旧 ⇒ None）
    let i = 解码句柄(&堆, id)?;
    Some(f(&堆.槽位[i].as_ref()?.数据))
}

/// 内部：写入前的句柄解析 —— **COW 已退役，恒等返回**（写入一律原地进行）。
///
/// ══════════════════════════════════════════════════════════════════════════════
/// 【2026-09-21 架构裁定】写时复制（COW）**退出「值语义隔离」职责**，本函数改为恒等。
///
/// **为什么淘汰 COW（三条实证/语义依据，缺一不可）**：
///
/// ① **规范字面即「存储即复制」**：《智语言编程规范》§4836-4844「赋值完整规则」明确
///    「结构体 → 复制数据」「数组 → 复制数据」「接口 → 复制标签」。即**隔离是构造性质**
///    （存入时就产生独立副本），不是"写入时才分离"的运行时性质。
///
/// ② **单一计数无法同时表达「标签」与「值副本」**（决定性反证，2026-09-21 实测）：
///    同一实例 O 可同时被「接口标签」与「容器槽位」持有：
///      `车丙 = 单车(0); 可移动 标签 = 车丙; 列表 = [车丙]`
///    此时要求 **槽位写入隔离**（`列表[1].移动(x)` ⇒ `车丙` 不变 = 值语义）
///    且 **标签写入共享**（`标签.移动(y)` ⇒ `车丙` 同步 = 引用语义）。
///    两者对"同一对象、同为 count>1"提出**相反**要求 ⇒ 以 `共享计数>1` 为唯一触发条件
///    的 COW **必然违反其中之一**。实测证据：接口来源的字段存储（`甲组.设备 = 甲车`）
///    合法产生 count=2（源变量槽 1 + 字段 1），随后 `可移动 甲标 = 甲组.设备; 甲标.移动(70)`
///    因 COW 分离而**连标签自身都读回 0**（预期 70）⇒ 规范「经接口方法修改作用于原实例」
///    （§4772 / §4834）被破坏。
///
/// ③ **写回覆盖面不可能"彻底"**：COW 要成立，每个"可能写入共享对象的落点"都必须能把
///    分离后的新句柄装回原位置。事实是落点分散在：变量赋值、字段/元素赋值、**嵌套左值链**
///    （`实例.内.字段 = x` 的基对象也会 COW）、**方法接收者**（`实例.内.方法()`，callee 的
///    COW 结果无法传回 caller）、**接口分派 thunk**（`__对象` 刻意传值）、闭包捕获、传引用别名……
///    每格都是一类"修改丢失"缺陷的温床（本项目历史上反复出现并逐个修补）。
///    改为"构造性隔离"后，这一类缺陷**从根上不存在**。
///
/// **替代方案（已落地）**：值语义隔离由 **降级层「存储即深拷贝」** 承担（赋值 / 字段存储 /
/// 索引存储 / 数组追加 / 数组插入 / 容器插入 / 复合字面量元素，对**非接口**复合值一律
/// `发射深拷贝` + RC 成对平衡）；接口 / `任意<接口>` / `传引用` 共享句柄（**不隔离、不 +1**，
/// 由「含接口用法的函数整体禁用释放发射」闸门防悬垂）。⇒ 「拷贝与否」即语义，**无歧义**。
///
/// **本函数保留的必要性**：`堆修改_内联`、base 各存储操作仍统一经此解析写入句柄，
/// 作为**单一真相的写入入口**；恒等实现确保「解析出的写入句柄 ≡ 传入句柄」，
/// 使"存储的 +1 / 覆盖的 −1"在正确的对象上成对发生。
/// ══════════════════════════════════════════════════════════════════════════════
fn 堆_写入前复制_已锁定(id: u64, _堆: &mut 全局堆内部) -> u64 {
    id
}

/// 内部：在单次写锁内完成 COW 分离 + 原地修改（消除 堆修改/堆写入 的双重锁）。
///
/// 🔒 重入防护：闭包 `f` 内**禁止**调用任何会再次获取全局堆锁的 `堆_X` 函数
/// （堆读取 / 堆分配 / 堆_写入前复制 / 堆增加引用 等）。所有需要读堆或构造键的操作
/// （如 `值转键`）必须在调用本函数**之前**于写锁外完成，闭包内只做纯内存写入。
/// 详见上方 `全局堆` 的铁律注释。
pub fn 堆修改_内联<R>(id: u64, f: impl FnOnce(&mut 堆数据) -> R) -> Option<R> {
    let mut 堆 = 全局堆.write().unwrap();
    // 🆕 阶段 2：**代际校验**（陈旧句柄 ⇒ None ⇒ 上层按"对象不存在"处理，**绝不写错对象**）
    let i0 = 解码句柄(&堆, id)?;
    let 真实id = 堆_写入前复制_已锁定(id, &mut *堆);
    let i = if 真实id == id { i0 } else { 解码句柄(&堆, 真实id)? };
    堆.槽位.get_mut(i)
        .and_then(|s| s.as_mut())
        .map(|s| f(&mut s.数据))
}

/// 写入句柄解析（对外入口）——**COW 已退役，恒等返回**。
/// 详见 `堆_写入前复制_已锁定` 的裁定说明（值语义隔离由降级层「存储即深拷贝」承担）。
pub fn 堆_写入前复制(id: u64) -> u64 {
    let mut 堆 = 全局堆.write().unwrap();
    堆_写入前复制_已锁定(id, &mut *堆)
}

/// 收集堆数据内嵌的句柄（引用计数**级联释放**用）。
/// 只有 `标签_句柄` 参与引用计数；标量/静态文本/外部值（JNI 式所有权）不参与。
fn 收集子句柄(数据: &堆数据) -> Vec<u64> {
    let mut 结果: Vec<u64> = Vec::new();
    let mut 收 = |v: &运行时值| {
        if v.标签 == 标签_句柄 {
            结果.push(v.句柄);
        }
    };
    match 数据 {
        堆数据::数组(元素列表) => {
            for v in 元素列表 { 收(v); }
        }
        堆数据::映射(条目列表) => {
            for (_, v) in 条目列表 { 收(v); }
        }
        堆数据::结构体 { 字段值, .. } => {
            for v in 字段值 { 收(v); }
        }
        堆数据::闭包环境 { 捕获变量, .. } => {
            for v in 捕获变量 { 收(v); }
        }
        堆数据::文本(_) | 堆数据::文本_静态(_, _) => {}
    }
    结果
}

/// 释放一个堆引用（**唯一回收入口**）：计数减 1；归零 ⇒ 回收槽位入空闲表 + **级联释放**子句柄。
///
/// 🔒 单锁内**迭代**（绝不递归）：全程只持一把写锁、只做纯内存操作，
///    不调用任何会再次获取全局堆锁的函数（重入 = RwLock 死锁，见上方铁律）。
/// ⚠ 不变量：堆对象内嵌的每个句柄各占一份引用计数，来源只有两种 ——
///    ① 由 base 存储类操作在「新产生一份对既有对象的引用」时 +1（见 堆增加引用）；
///    ② 创建者转移（新建对象内嵌**新建**子对象 = 移动，不额外 +1）。
///    级联释放据此逐个递减，环形成闭环 ⇒ 整棵对象树可回收。
///    **环形引用**（A↔B 互持、计数永不为 0）：由本文件的 **L3 环收集（trial deletion，
///    `环收集` / `环收集_按预算`）**专门回收 —— 产品路径默认开启（阈值 `智语言_环收集阈值`）。
///    ⚠ 本行原写「循环引用除外…属已知取舍」已**过期**（2026-09-25 校正），勿再按旧文推理。
/// 🔬 **内存诊断工具（长期保留）**：查询句柄当前**共享计数**（只读 ✓）。
/// ⚠ 必须在**未持堆锁**时调用（内部取读锁 ⇒ 与写锁死锁 ✗）。
/// 📌 2026-09-24 收尾裁定：**转为长期诊断**（不再"用后即删"）—— 它是本轮 S 缺口定位链的
///   关键工具，且**默认零开销**（仅被下两处 env 门控的探针调用）⇒ 保留可显著降低后续内存缺陷成本 ✓
pub fn 句柄共享计数(id: u64) -> Option<u32> {
    let 堆 = 全局堆.read().unwrap();
    let i = 解码句柄(&堆, id)?;
    堆.槽位.get(i)?.as_ref().map(|槽位| 槽位.共享计数)
}

