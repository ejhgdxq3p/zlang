// 文件: 核心库功能/基础辅助.rs
// 职责: 参数/值 提取辅助，供 系统调用() 各分支共用（与解释器侧语义一致）

use crate::值类型::*;

pub(crate) fn 取参数(参数: &[运行时值], idx: usize) -> 运行时值 {
    参数.get(idx).cloned().unwrap_or(运行时值::空值())
}

pub(crate) fn 取文本(参数: &[运行时值], idx: usize) -> String {
    参数.get(idx).map(|v| v.取文本()).unwrap_or_default()
}

pub(crate) fn 取整数(参数: &[运行时值], idx: usize) -> i64 {
    参数.get(idx).map(|v| v.取整数()).unwrap_or(0)
}

pub(crate) fn 取小数(参数: &[运行时值], idx: usize) -> f64 {
    参数.get(idx).map(|v| v.取小数()).unwrap_or(0.0)
}

/// 提取并发资源句柄 id（通道/任务/终止器）。
/// ⚡双模式⚡ 兼容两种表示：
///   - 标签_并发句柄(8)/标签_整数: 整数载荷直接是 id（编译模式，以及 终止器.信号通道 等路径）
///   - 标签_句柄(4)+通道结构体: 结构体第一个字段的整数值是 id（解释模式 `执行通道创建寄存器` 的表示）
pub(crate) fn 取并发句柄id(v: &运行时值) -> u64 {
    match v.标签 {
        标签_并发句柄 => v.整数 as u64,
        标签_整数 => v.整数 as u64,
        标签_句柄 => {
            if let Some(堆数据::结构体 { 字段值, .. }) = 堆读取(v.句柄) {
                if let Some(字段0) = 字段值.first() {
                    if 字段0.标签 == 标签_整数 {
                        return 字段0.整数 as u64;
                    }
                }
            }
            v.句柄 as u64 // 兜底：兼容直接以句柄承载 id 的路径
        }
        _ => 0,
    }
}

/// 任意运行时值 → 整数（与解释器 整数() 内置语义一致）
pub(crate) fn 值转整数(v: &运行时值) -> i64 {
    match v.标签 {
        标签_整数 => v.整数,
        标签_小数 => v.小数 as i64,
        标签_逻辑 => if v.整数 != 0 { 1 } else { 0 },
        标签_句柄 => {
            let s = v.取文本();
            match s.trim().parse::<i64>() {
                Ok(n) => n,
                Err(_) => {
                    // ⚡双模式⚡ A5: 非法文本转换应抛异常而非静默返 0。
                    // 系统函数无 VM 句柄，统一经线程局部异常标志（编译模式由代码生成注入检查捕获，解释模式由 VM 调用点桥接）。
                    let 消息 = format!("无法将文本“{}”转换为整数", s);
                    crate::异常运行时::智语言_抛出异常("类型转换错误".as_ptr(), "类型转换错误".len() as i64, 消息.as_ptr(), 消息.len() as i64);
                    0
                }
            }
        }
        _ => 0,
    }
}
