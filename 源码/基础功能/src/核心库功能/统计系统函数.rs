// 文件: 核心库功能/统计系统函数.rs
// 职责: 统计辅助函数（求和/平均/标准差/方差/中位数）
//
// ⚡类型守恒（规范 §5.1.4 求和 / §5.1.5 最大值列表·最小值列表）⚡
//   规范原文：`数学.求和(数组<整数|小数>)` 返回 `任意<整数|小数>`，
//   「整数数组返回整数，小数数组返回小数；混合数组按运行时元素类型提升，返回小数」
//   （示例 `[85,92,78,95,88]` 求和 = **438**，不是 438.0）。
//   base 侧只有**运行时值**、没有静态元素类型通道 ⇒ 判据取「运行时元素标签」：
//     全部元素 == 标签_整数 ⇒ 返回 整数（i64 精确，避免 f64 在 >2^53 时静默丢位）；
//     出现任一 标签_小数 ⇒ 返回 小数（即规范的"按运行时元素类型提升"）。
//   空数组无元素可判 ⇒ `求和` 保持 **小数 0.0**（与同族一致，且避免 `f64::sum()` 的 -0.0）。
//
// ⚡总体统计（规范 §5.1.7 示例口径）⚡
//   规范 §5.1.7 示例：数据 `[2,4,4,4,5,5,7,9]` ⇒ 标准差「约2.0」、方差「约4.0」，
//   且描述「`方差`：标准差的平方」。Σ(x-μ)² = 32，**总体**方差 = 32/8 = 4.0、σ = 2.0 ✓
//   （样本方差 32/7≈4.571、s≈2.138 与规范示例不符）。故 方差/标准差 一律按**总体**（÷n）计算。

use crate::值类型::*;

/// 取首参数的**数组元素**（保留标签，供「整数数组返回整数」的类型守恒判定）；非数组/非句柄 ⇒ None。
fn 取数组元素(参数: &[运行时值]) -> Option<Vec<运行时值>> {
    let v = 参数.get(0)?;
    if v.标签 != 标签_句柄 {
        return None;
    }
    match 堆读取(v.句柄) {
        Some(堆数据::数组(arr)) => Some(arr),
        _ => None,
    }
}

/// 统计函数只接受「整数/小数」元素（规范 §5.1.4/§5.1.7 形参 = 数组<整数|小数>）。
/// 供 数学系统函数::列表极值 复用（同为「数值数组收敛为一个数」的函数族）。
pub(crate) fn 是数值元素(v: &运行时值) -> bool {
    v.标签 == 标签_整数 || v.标签 == 标签_小数
}

/// 元素标签的类型名（仅用于错误描述）。
fn 元素类型名(v: &运行时值) -> &'static str {
    match v.标签 {
        标签_句柄 => "文本/容器/结构体",
        标签_逻辑 => "逻辑",
        标签_空值 => "空值",
        标签_函数指针 => "函数",
        _ => "非数值",
    }
}

/// 非数值元素 ⇒ 抛**可捕获**「类型错误」，绝不静默按 0 参与统计
/// （与 `堆操作::位运算类型错误` 同族做法：静默错值比报错更糟）。
pub(crate) fn 抛非数值元素错误(函数名: &str, 值: &运行时值) {
    let 描述 = format!(
        "数学.{} 只接受整数/小数元素组成的数组（实际含【{}】元素）",
        函数名,
        元素类型名(值)
    );
    crate::异常运行时::智语言_抛出异常(
        "类型错误".as_ptr(),
        "类型错误".len() as i64,
        描述.as_ptr(),
        描述.len() as i64,
    );
}

/// 数值化数组元素。非数组 ⇒ 空（保持既有宽容行为，交由上游静态检查拦截）；
/// 含非数值元素 ⇒ 抛异常并返回空。
pub(crate) fn 提取数值数组(参数: &[运行时值], 函数名: &str) -> Vec<f64> {
    let 元素 = match 取数组元素(参数) {
        Some(a) => a,
        None => return vec![],
    };
    let mut 数值 = Vec::with_capacity(元素.len());
    for e in &元素 {
        if !是数值元素(e) {
            抛非数值元素错误(函数名, e);
            return vec![];
        }
        数值.push(e.转为小数());
    }
    数值
}

pub(crate) fn 统计求和(参数: &[运行时值]) -> 运行时值 {
    let 元素 = match 取数组元素(参数) {
        Some(a) => a,
        None => return 运行时值::小数(0.0),
    };
    // 空数组：无元素可判元素类型 ⇒ 保持 `+0.0`（非 `-0.0`），与 平均值/方差/标准差/中位数 同族一致。
    // （根因备忘：Rust `f64::sum()` 以 `-0.0` 为加法单位元，曾使 `求和([])` 显示 `-0.0`。）
    if 元素.is_empty() {
        return 运行时值::小数(0.0);
    }
    for e in &元素 {
        if !是数值元素(e) {
            抛非数值元素错误("求和", e);
            return 运行时值::空值();
        }
    }
    // 整数数组 ⇒ 整数（规范 §5.1.4「整数数组返回整数」）。
    // 溢出语义与语言层 `整数 + 整数` 单源一致（堆操作::整数算术 = wrapping_add，两后端共用）；
    // 顺带避免走 f64 时 >2^53 的静默丢位。
    if 元素.iter().all(|e| e.标签 == 标签_整数) {
        let mut 和: i64 = 0;
        for e in &元素 {
            和 = 和.wrapping_add(e.整数);
        }
        return 运行时值::整数(和);
    }
    // 含小数（含混合数组）⇒ 小数。
    运行时值::小数(元素.iter().map(|e| e.转为小数()).sum())
}

pub(crate) fn 统计平均(参数: &[运行时值]) -> 运行时值 {
    let 数值 = 提取数值数组(参数, "平均值");
    if 数值.is_empty() { return 运行时值::小数(0.0); }
    运行时值::小数(数值.iter().sum::<f64>() / 数值.len() as f64)
}

/// 总体方差（÷n，规范 §5.1.7 示例口径）。空/单元素 ⇒ 0.0。
fn 总体方差(数值: &[f64]) -> Option<f64> {
    if 数值.is_empty() { return Some(0.0); }
    let 平均 = 数值.iter().sum::<f64>() / 数值.len() as f64;
    Some(数值.iter().map(|v| { let d = v - 平均; d * d }).sum::<f64>() / 数值.len() as f64)
}

pub(crate) fn 统计标准差(参数: &[运行时值]) -> 运行时值 {
    let 数值 = 提取数值数组(参数, "标准差");
    match 总体方差(&数值) {
        Some(方差) => 运行时值::小数(方差.sqrt()),
        None => 运行时值::小数(0.0),
    }
}

pub(crate) fn 统计方差(参数: &[运行时值]) -> 运行时值 {
    let 数值 = 提取数值数组(参数, "方差");
    match 总体方差(&数值) {
        Some(方差) => 运行时值::小数(方差),
        None => 运行时值::小数(0.0),
    }
}

pub(crate) fn 统计中位数(参数: &[运行时值]) -> 运行时值 {
    let mut 数值 = 提取数值数组(参数, "中位数");
    if 数值.is_empty() { return 运行时值::小数(0.0); }
    数值.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let 中位 = if 数值.len() % 2 == 1 {
        数值[数值.len() / 2]
    } else {
        (数值[数值.len() / 2 - 1] + 数值[数值.len() / 2]) / 2.0
    };
    运行时值::小数(中位)
}
