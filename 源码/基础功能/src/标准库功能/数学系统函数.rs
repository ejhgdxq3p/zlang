pub(crate) fn 处理数学(索引: usize, 参数: &[运行时值]) -> 运行时值 {
    match 索引 {
        标准库索引::数学_绝对值 => { // abs
            let v = 取参数(参数, 0);
            match v.标签 {
                标签_整数 => 运行时值::整数(v.整数.abs()),
                标签_小数 => 运行时值::小数(v.小数.abs()),
                _ => 运行时值::空值(),
            }
        }
        标准库索引::数学_最大值 => { // max
            let a = 取参数(参数, 0); let b = 取参数(参数, 1);
            // ⚡守恒对齐（2026-09-02，§5.1.1 数值甲族）：前端同名甲统一（整数→小数自动提升），
            // 含小数实参时甲=小数 → 结果须提升为小数返回，否则 最大值(3,2.5) 返回 3（整数标签）与小数槽冲突。
            if a.标签 == 标签_小数 || b.标签 == 标签_小数 {
                运行时值::小数(a.转为小数().max(b.转为小数()))
            } else if a.转为小数() > b.转为小数() { a } else { b }
        }
        标准库索引::数学_最小值 => { // min
            let a = 取参数(参数, 0); let b = 取参数(参数, 1);
            // ⚡守恒对齐（2026-09-02，§5.1.1 数值甲族）：同 最大值，含小数实参时提升为小数返回。
            if a.标签 == 标签_小数 || b.标签 == 标签_小数 {
                运行时值::小数(a.转为小数().min(b.转为小数()))
            } else if a.转为小数() < b.转为小数() { a } else { b }
        }
        标准库索引::数学_平方根 => { // sqrt
            match 取参数(参数, 0) {
                v if v.标签 == 标签_小数 => 运行时值::小数(v.小数.sqrt()),
                v if v.标签 == 标签_整数 => 运行时值::小数((v.整数 as f64).sqrt()),
                _ => 运行时值::空值(),
            }
        }
        标准库索引::数学_取整 => {
            // 规范 §5.1.2 任意<整数|小数>：整数实参直接返回自身（免 f64 精度损失）
            let v = 取参数(参数, 0);
            if v.标签 == 标签_整数 { v } else { 运行时值::整数(取小数(参数, 0) as i64) }
        }
        标准库索引::数学_向下取整 => {
            let v = 取参数(参数, 0);
            if v.标签 == 标签_整数 { v } else { 运行时值::整数(取小数(参数, 0).floor() as i64) }
        }
        标准库索引::数学_向上取整 => {
            let v = 取参数(参数, 0);
            if v.标签 == 标签_整数 { v } else { 运行时值::整数(取小数(参数, 0).ceil() as i64) }
        }
        标准库索引::数学_四舍五入取整 => {
            let v = 取参数(参数, 0);
            if v.标签 == 标签_整数 { v } else { 运行时值::整数(取小数(参数, 0).round() as i64) }
        }
        标准库索引::数学_保留小数 => 保留小数(参数),
        标准库索引::数学_科学计数法 => 科学计数法(参数),
        标准库索引::数学_正弦 => { let f = 取小数(参数, 0); 运行时值::小数(f.sin()) }
        标准库索引::数学_余弦 => { let f = 取小数(参数, 0); 运行时值::小数(f.cos()) }
        标准库索引::数学_正切 => { let f = 取小数(参数, 0); 运行时值::小数(f.tan()) }
        标准库索引::数学_幂 => {
            // 按操作数类型分派（§5.1.6 有名守恒，前端 类型推导.rs::数值甲统一返回类型 已按实参定返回槽）：
            // 全整且指数非负 → 整数幂（checked_pow，溢出抛「整数幂溢出」可捕获，对齐 无符号/字节 溢出抛）；
            // 全整且指数为负 → 整数域无定义，抛「整数幂负指数」（字面负指数已由前端编译期拦截，此处兜底变量/非常量）；
            // 含小数 → 小数幂（f64 powf，±inf 合法，支持负/分数指数 幂(2.0,-3)=0.125）。
            let 底 = 取参数(参数, 0);
            let 指数 = 取参数(参数, 1);
            if 底.标签 == 标签_整数 && 指数.标签 == 标签_整数 {
                // 整数幂域（返回整数槽，负指数在整数域无定义）→ 指数须非负
                if 指数.整数 < 0 {
                    let 描述 = format!(
                        "整数幂负指数：指数 {} 为负，整数幂无定义；请用小数指数（如 数学.幂(2.0, {})）",
                        指数.整数, 指数.整数
                    );
                    crate::异常运行时::智语言_抛出异常(
                        "整数幂负指数".as_ptr(), "整数幂负指数".len() as i64,
                        描述.as_ptr(), 描述.len() as i64,
                    );
                    return 运行时值::空值();
                }
                match 底.整数.checked_pow(指数.整数 as u32) {
                    Some(r) => 运行时值::整数(r),
                    None => {
                        let 描述 = format!("整数幂溢出：{} 的 {} 次方超出整数范围", 底.整数, 指数.整数);
                        crate::异常运行时::智语言_抛出异常(
                            "整数幂溢出".as_ptr(), "整数幂溢出".len() as i64,
                            描述.as_ptr(), 描述.len() as i64,
                        );
                        运行时值::空值()
                    }
                }
            } else {
                运行时值::小数(底.转为小数().powf(指数.转为小数()))
            }
        }
        标准库索引::数学_自然对数 => { let f = 取小数(参数, 0); 运行时值::小数(f.ln()) }
        标准库索引::数学_常用对数 => { let f = 取小数(参数, 0); 运行时值::小数(f.log10()) }
        标准库索引::数学_最大值列表 => 列表极值(参数, true),
        标准库索引::数学_最小值列表 => 列表极值(参数, false),
        205..=234 => 处理精确小数(索引, 参数),
        235..=258 => 处理短小数(索引, 参数),
        259..=280 => 处理无符号整数(索引, 参数),
        281..=303 => 处理字节(索引, 参数),
        304..=328 => 处理无限整数(索引, 参数),
        _ => 运行时值::空值(),
    }
}

/// 对数组做归约求极值（列表最大值/最小值）。空数组或非数组返回空值。
fn 列表极值(参数: &[运行时值], 取大: bool) -> 运行时值 {
    let 列表 = 取参数(参数, 0);
    if 列表.标签 != 标签_句柄 {
        return 运行时值::空值();
    }
    let 函数名 = if 取大 { "最大值列表" } else { "最小值列表" };
    if let Some(堆数据::数组(arr)) = 堆读取(列表.句柄) {
        if arr.is_empty() {
            return 运行时值::空值();
        }
        // ⚡类型守恒（规范 §5.1.5）⚡：返回类型是 `任意<整数|小数>` ——
        //   「整数数组返回整数，小数数组返回小数；混合数组按运行时元素类型提升，返回小数」。
        //   base 无静态元素类型通道 ⇒ 按**运行时元素标签**判定（与 数学.求和 同源口径）。
        for v in &arr {
            if !super::统计系统函数::是数值元素(v) {
                super::统计系统函数::抛非数值元素错误(函数名, v);
                return 运行时值::空值();
            }
        }
        if arr.iter().all(|v| v.标签 == 标签_整数) {
            let mut 极值 = arr[0].整数;
            for v in &arr[1..] {
                if (取大 && v.整数 > 极值) || (!取大 && v.整数 < 极值) {
                    极值 = v.整数;
                }
            }
            return 运行时值::整数(极值);
        }
        let mut 极值 = arr[0].转为小数();
        for v in &arr[1..] {
            let 当前 = v.转为小数();
            if (取大 && 当前 > 极值) || (!取大 && 当前 < 极值) {
                极值 = 当前;
            }
        }
        运行时值::小数(极值)
    } else {
        运行时值::空值()
    }
}

/// 保留指定小数位（四舍五入），返回小数。位数<0→空值，>15→按15。
/// 注意：返回小数类型，不补零（数值无补零概念）。
fn 保留小数(参数: &[运行时值]) -> 运行时值 {
    let v = 取小数(参数, 0);
    let 位数 = 取整数(参数, 1);
    if 位数 < 0 { return 运行时值::空值(); }
    let 位数 = if 位数 > 15 { 15 } else { 位数 };
    let factor = 10f64.powi(位数 as i32);
    运行时值::小数((v * factor).round() / factor)
}

/// 按有效数字转为科学计数法文本。有效位数 N → Rust e 格式小数位 = N-1（对齐 C %g / Python .Ng）。
/// 指数部分统一补 '+' 号（Rust 默认正指数无 '+'）。
fn 科学计数法(参数: &[运行时值]) -> 运行时值 {
    let v = 取小数(参数, 0);
    let 有效位数 = if 参数.len() >= 2 { 取整数(参数, 1) } else { 6 };
    let 有效位数 = if 有效位数 < 1 { 1 } else { 有效位数 };
    let 小数位 = (有效位数 - 1) as usize; // 有效数字 - 1 = 小数位
    let s = format!("{:.*e}", 小数位, v);
    let s = if s.contains("e-") { s } else { s.replacen('e', "e+", 1) };
    分配文本(s)
}

// ============================================================
//  数学.精确小数（§5.1.11）base 实现：用 i128 模拟 128 位缩放值
//  结构体字段: [0]=缩放值高位(i64,带符号) [1]=缩放值低位(i64,按无符号) [2]=小数位数(0~28)
//  所有运算委托本函数，解释/编译双模经同一 系统调用 单源（parity 由 base 保证）。
