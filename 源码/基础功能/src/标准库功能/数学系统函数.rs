/// 规整任意运行时值为精确小数 (缩放值, scale)；整数/文本自动转换，已是精确小数则直接读。
/// 注意：文本在运行时以 标签_句柄 存储（堆中 堆数据::文本 / 文本_静态），不存在 标签_文本。
/// 不支持 小数（浮点不精确）：运算前必须显式 精确小数(文本(3.14)) 转换。
fn 取或规整精确小数(v: &运行时值) -> Option<(i128, u32)> {
    match v.标签 {
        标签_句柄 => {
            match 堆读取(v.句柄) {
                Some(堆数据::结构体 { 类型索引, .. }) if 类型索引 == 精确小数类型索引 => return 读精确小数(v.句柄),
                Some(堆数据::文本(sb)) => return 解析文本小数(&sb),
                Some(堆数据::文本_静态(p, n)) => {
                    let 切片 = unsafe { std::slice::from_raw_parts(p as *const u8, n) };
                    return 解析文本小数(&String::from_utf8_lossy(切片));
                }
                _ => {}
            }
            None
        }
        标签_整数 => Some((v.整数 as i128, 0)),
        _ => None,
    }
}

/// 解析文本为 (缩放值 i128, 小数位数)；失败返回 None。
fn 解析文本小数(s: &str) -> Option<(i128, u32)> {
    let s = s.trim();
    if s.is_empty() { return None; }
    let 负 = s.starts_with('-');
    let s = if 负 { &s[1..] } else { s };
    let (整数部, 小数部) = if let Some(pos) = s.find('.') { (&s[..pos], &s[pos + 1..]) } else { (s, "") };
    if !整数部.chars().all(|c| c.is_ascii_digit()) || !小数部.chars().all(|c| c.is_ascii_digit()) { return None; }
    let scale = 小数部.len() as u32;
    if scale > 28 { return None; }
    let 拼接 = format!("{}{}", 整数部, 小数部).trim_start_matches('0').to_string();
    if 拼接.is_empty() { return Some((0, scale)); }
    let 数字 = 拼接.parse::<i128>().ok()?;
    Some((if 负 { -数字 } else { 数字 }, scale))
}

/// f64 → (缩放值 i128, 小数位数)：以最短唯一十进制表示解析（避免二进制直转误差，如 0.1→"0.1"）。
fn 小数到精确小数(f: f64) -> Option<(i128, u32)> {
    if !f.is_finite() { return None; }
    解析文本小数(&format!("{}", f))
}

/// 新建精确小数结构体（写入三个字段）。
fn 新建精确小数(v: i128, scale: u32) -> 运行时值 {
    let 句柄 = 堆分配(堆数据::结构体 {
        类型索引: 精确小数类型索引,
        字段值: vec![
            运行时值::整数((v >> 64) as i64),
            运行时值::整数((v as u64) as i64),
            运行时值::整数(scale as i64),
        ],
    });
    运行时值::句柄(句柄)
}

/// 抛精确小数异常（描述统一为「精确小数错误」）。
fn 抛精确小数异常(消息: &str) -> 运行时值 {
    let 描述 = "精确小数错误";
    crate::异常运行时::智语言_抛出异常(描述.as_ptr(), 描述.len() as i64, 消息.as_ptr(), 消息.len() as i64);
    运行时值::空值()
}

/// 对齐到统一 scale，返回 (a_scaled', b_scaled', 目标scale)。
fn 对齐(a: (i128, u32), b: (i128, u32)) -> Option<(i128, i128, u32)> {
    let 目标 = a.1.max(b.1);
    Some((a.0.checked_mul(10i128.pow(目标 - a.1))?, b.0.checked_mul(10i128.pow(目标 - b.1))?, 目标))
}

/// 四舍五入除法：返回 numerator/b 的四舍五入整数（half-up）。
fn 舍入除(numerator: i128, b: i128) -> Option<i128> {
    let 商 = numerator.div_euclid(b);
    let 余 = numerator.rem_euclid(b);
    let 阈值 = b.unsigned_abs();
    Some(if (余 as u128) * 2 >= 阈值 { 商 + 1 } else { 商 })
}

/// 精确小数整除核心：返回 floor(甲 / 乙) 的「缩放值整数」（scale=0 的 i128）。
/// 单一实现，供 `整除`（规范要求返回 **整数**）与 `整除赋值`（规范要求返回 **精确小数**）共用，
/// 避免两份除逻辑漂移。向下取整（向负无穷），除数为零/溢出均返回 Err（不静默）。
fn 精确小数整除值(a: (i128, u32), b: (i128, u32)) -> Result<i128, &'static str> {
    if b.0 == 0 {
        return Err("精确小数整除：除数不能为零");
    }
    let 指数 = b.1 as i32 - a.1 as i32;
    let 分子 = if 指数 >= 0 {
        a.0.checked_mul(10i128.pow(指数 as u32)).ok_or("精确小数整除溢出")?
    } else {
        // 指数为负：先按 10^|指数| 缩小被除数（对齐到较大 scale，精度受 i128 限制）
        a.0 / 10i128.pow((-指数) as u32)
    };
    分子.checked_div_euclid(b.0).ok_or("精确小数整除溢出")
}

/// 处理精确小数系统函数（索引 205..=222）。
fn 处理精确小数(索引: usize, 参数: &[运行时值]) -> 运行时值 {
    let 取两 = || -> Option<((i128, u32), (i128, u32))> {
        Some((取或规整精确小数(&取参数(参数, 0))?, 取或规整精确小数(&取参数(参数, 1))?))
    };
    match 索引 {
        标准库索引::数学精确小数创建 => {
            let 参数值 = 取参数(参数, 0);
            // 规范 §5.1.11 规则 1：「空文本构造失败返回空值」（不是异常）。
            // 此前空文本与非法文本同走 None ⇒ 一律抛异常，与规范不符。
            if 参数值.标签 == 标签_句柄 {
                if let Some(文本值) = 读堆文本(参数值.句柄) {
                    if 文本值.trim().is_empty() {
                        return 运行时值::空值();
                    }
                }
            }
            match 参数值.标签 {
                标签_小数 => match 小数到精确小数(取小数(参数, 0)) {
                    Some((s, sc)) => 新建精确小数(s, sc),
                    None => 抛精确小数异常("精确小数：浮点必须为有限值（非 无穷/无效）"),
                },
                _ => match 取或规整精确小数(&参数值) {
                    Some((s, sc)) => 新建精确小数(s, sc),
                    None => {
                        // 文本格式非法与类型不支持给出不同描述（原先统一说「仅支持整数/文本/小数」，
                        // 传入非法文本时描述**误导**：文本明明是支持的类型）。
                        let 是文本 = 参数值.标签 == 标签_句柄 && 读堆文本(参数值.句柄).is_some();
                        if 是文本 {
                            抛精确小数异常("精确小数：文本不是合法的十进制数字")
                        } else {
                            抛精确小数异常("精确小数：仅支持整数/文本/小数")
                        }
                    }
                },
            }
        }
        标准库索引::数学_精确小数_加法 => { // 加
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数加法：操作数类型错误") };
            if let Some((av, bv, t)) = 对齐(a, b) { if let Some(r) = av.checked_add(bv) { return 新建精确小数(r, t); } }
            抛精确小数异常("精确小数加法溢出")
        }
        标准库索引::数学_精确小数_减法 => { // 减
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数减法：操作数类型错误") };
            if let Some((av, bv, t)) = 对齐(a, b) { if let Some(r) = av.checked_sub(bv) { return 新建精确小数(r, t); } }
            抛精确小数异常("精确小数减法溢出")
        }
        标准库索引::数学_精确小数_乘法 => { // 乘（scale=clamp(sa+sb,28) 并舍入）
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数乘法：操作数类型错误") };
            let 原始scale = a.1 + b.1;
            if let Some(乘积) = a.0.checked_mul(b.0) {
                if 原始scale <= 28 { return 新建精确小数(乘积, 原始scale); }
                let 多余 = 原始scale - 28;
                let 因子 = 10u128.pow(多余 as u32);
                let 符号 = if 乘积 < 0 { -1 } else { 1 };
                let 绝对值 = 乘积.unsigned_abs();
                let 商 = 绝对值 / 因子;
                let 余 = 绝对值 % 因子;
                let 商 = if 余 * 2 >= 因子 { 商 + 1 } else { 商 };
                return 新建精确小数((商 as i128) * 符号, 28);
            }
            抛精确小数异常("精确小数乘法溢出")
        }
        标准库索引::数学_精确小数_除法 => { // 除（28 位四舍五入；除零抛异常）
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数除法：操作数类型错误") };
            if b.0 == 0 { return 抛精确小数异常("精确小数除法：除数不能为零"); }
            let 指数 = 28i32 + b.1 as i32 - a.1 as i32;
            let 分子 = if 指数 >= 0 {
                match a.0.checked_mul(10i128.pow(指数 as u32)) { Some(v) => v, None => return 抛精确小数异常("精确小数除法溢出") }
            } else { a.0 / 10i128.pow((-指数) as u32) };
            match 舍入除(分子, b.0) {
                Some(r) => 新建精确小数(r, 28),
                None => 抛精确小数异常("精确小数除法溢出"),
            }
        }
        标准库索引::数学_精确小数_整除 => { // 整除（floor）：规范 §5.1.11 返回类型 = **整数**
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数整除：操作数类型错误") };
            match 精确小数整除值(a, b) {
                Ok(r) => match i64::try_from(r) {
                    Ok(n) => 运行时值::整数(n),
                    Err(_) => 抛精确小数异常("精确小数整除：结果超出整数（i64）范围"),
                },
                Err(消息) => 抛精确小数异常(消息),
            }
        }
        标准库索引::数学_精确小数_整除赋值 => { // 原地整除：保持 精确小数（scale=0），供 `%%=` 写回
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数整除赋值：操作数类型错误") };
            match 精确小数整除值(a, b) {
                Ok(r) => 新建精确小数(r, 0),
                Err(消息) => 抛精确小数异常(消息),
            }
        }
        标准库索引::数学_精确小数_取余 => { // 取余（欧几里得非负，scale=max）
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数取余：操作数类型错误") };
            if b.0 == 0 { return 抛精确小数异常("精确小数取余：除数不能为零"); }
            if let Some((av, bv, t)) = 对齐(a, b) {
                return 新建精确小数(av.rem_euclid(bv), t);
            }
            抛精确小数异常("精确小数取余溢出")
        }
        标准库索引::数学_精确小数_等于 => { // 等于
            let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) };
            let (av, bv, _) = match 对齐(a, b) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(av == bv)
        }
        标准库索引::数学_精确小数_不等于 => { // 不等于
            let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) };
            let (av, bv, _) = match 对齐(a, b) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(av != bv)
        }
        标准库索引::数学_精确小数_大于 => { // 大于
            let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) };
            let (av, bv, _) = match 对齐(a, b) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(av > bv)
        }
        标准库索引::数学_精确小数_小于 => { // 小于
            let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) };
            let (av, bv, _) = match 对齐(a, b) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(av < bv)
        }
        标准库索引::数学_精确小数_大于等于 => { // 大于等于
            let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) };
            let (av, bv, _) = match 对齐(a, b) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(av >= bv)
        }
        标准库索引::数学_精确小数_小于等于 => { // 小于等于
            let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) };
            let (av, bv, _) = match 对齐(a, b) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(av <= bv)
        }
        标准库索引::数学_精确小数_取负 => { // 取负
            let (v, sc) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛精确小数异常("精确小数取负：类型错误") };
            match v.checked_neg() { Some(r) => 新建精确小数(r, sc), None => 抛精确小数异常("精确小数取负溢出") }
        }
        标准库索引::数学_精确小数_转文本 => { // 转文本
            match 精确小数格式化(&取参数(参数, 0)) {
                Some(s) => 分配文本(s),
                None => 抛精确小数异常("精确小数转文本：类型错误"),
            }
        }
        标准库索引::数学_精确小数_转小数 => { // 转小数（近似，f64 仅 15-17 位精度）
            let (v, scale) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::小数(0.0) };
            运行时值::小数(v as f64 / 10f64.powi(scale as i32))
        }
        标准库索引::数学_精确小数_转整数 => { // 转整数（截断向零）
            let (v, scale) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::整数(0) };
            运行时值::整数((v / 10i128.pow(scale)) as i64)
        }
        标准库索引::数学_精确小数_是否为零 => { // 是否为零
            let (v, _) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(v == 0)
        }
        标准库索引::数学_精确小数_幂 => 精确小数幂(参数),                                    // 幂（整数指数）
        标准库索引::数学_精确小数_绝对值 => { // 绝对值
            let (v, sc) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛精确小数异常("精确小数绝对值：类型错误") };
            match v.checked_abs() { Some(r) => 新建精确小数(r, sc), None => 抛精确小数异常("精确小数绝对值溢出") }
        }
        标准库索引::数学_精确小数_平方根 => 精确小数平方根(参数),                                // 平方根
        标准库索引::数学_精确小数_保留小数 => 精确小数保留小数(参数),                              // 保留小数
        标准库索引::数学_精确小数_是否正数 => { // 是否正数
            let (v, _) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(v > 0)
        }
        标准库索引::数学_精确小数_是否负数 => { // 是否负数
            let (v, _) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(v < 0)
        }
        标准库索引::数学_精确小数_是否为整数 => { // 是否为整数（小数位数为零）
            let (_, sc) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) };
            运行时值::逻辑(sc == 0)
        }
        标准库索引::数学_精确小数_符号值 => { // 符号值
            let (v, _) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::整数(0) };
            运行时值::整数(if v > 0 { 1 } else if v < 0 { -1 } else { 0 })
        }
        标准库索引::数学_精确小数_最大值 => { // 最大值
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数最大值：操作数类型错误") };
            let (av, bv, t) = match 对齐(a, b) { Some(x) => x, None => return 抛精确小数异常("精确小数最大值溢出") };
            if av >= bv { 新建精确小数(av, t) } else { 新建精确小数(bv, t) }
        }
        标准库索引::数学_精确小数_最小值 => { // 最小值
            let (a, b) = match 取两() { Some(x) => x, None => return 抛精确小数异常("精确小数最小值：操作数类型错误") };
            let (av, bv, t) = match 对齐(a, b) { Some(x) => x, None => return 抛精确小数异常("精确小数最小值溢出") };
            if av <= bv { 新建精确小数(av, t) } else { 新建精确小数(bv, t) }
        }
        标准库索引::数学_精确小数_科学计数法 => 精确小数科学计数法(参数),                            // 科学计数法
        _ => 运行时值::空值(),
    }
}

/// 整数指数幂：正数重复乘法；负数取倒数；溢出抛异常。结果 scale = base.scale × |exp|（超出 28 位四舍五入）。
fn 精确小数幂(参数: &[运行时值]) -> 运行时值 {
    let (v, scale) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛精确小数异常("精确小数幂：底数类型错误") };
    let exp = 取整数(参数, 1);
    if exp == 0 { return 新建精确小数(1, 0); }
    let 正指数 = exp.unsigned_abs() as u32;
    let 幂值 = match v.checked_pow(正指数) { Some(x) => x, None => return 抛精确小数异常("精确小数幂溢出") };
    let 目标scale = scale as u64 * 正指数 as u64;
    let (最终值, 最终scale) = if 目标scale <= 28 {
        (幂值, 目标scale as u32)
    } else {
        let 多余 = (目标scale - 28) as u32;
        if 多余 > 38 { return 抛精确小数异常("精确小数幂溢出"); }
        let 因子 = match 10i128.checked_pow(多余) { Some(x) => x, None => return 抛精确小数异常("精确小数幂溢出") };
        let 商 = 幂值.div_euclid(因子);
        let 余 = 幂值.rem_euclid(因子);
        let 阈值 = 因子.unsigned_abs();
        let 商 = if (余 as u128) * 2 >= 阈值 { 商 + 1 } else { 商 };
        (商, 28)
    };
    if exp < 0 {
        if 最终值 == 0 { return 抛精确小数异常("精确小数幂：除数不能为零"); }
        let 指数 = 最终scale as i32 + 28;
        if 指数 > 38 { return 抛精确小数异常("精确小数幂溢出"); }
        let 分子 = match 10i128.checked_pow(指数 as u32) { Some(x) => x, None => return 抛精确小数异常("精确小数幂溢出") };
        return match 舍入除(分子, 最终值) {
            Some(r) => 新建精确小数(r, 28),
            None => 抛精确小数异常("精确小数幂溢出"),
        };
    }
    新建精确小数(最终值, 最终scale)
}

/// 平方根：i128 可行精度（约 18 位有效数字），结果按 28 位小数存储（不足位补零）。
fn 精确小数平方根(参数: &[运行时值]) -> 运行时值 {
    let (v, scale) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛精确小数异常("精确小数平方根：类型错误") };
    if v < 0 { return 抛精确小数异常("精确小数平方根：负数无实数平方根"); }
    if v == 0 { return 新建精确小数(0, 0); }
    let 位数 = if v == 0 { 0 } else { (v.unsigned_abs() as f64).log10().floor() as i32 + 1 };
    let 目标e = 56 - scale as i32;                 // 期望指数（使结果达 28 位小数）
    let e_max = 38 - 位数;                          // v·10^e 不溢出 i128 的最大指数
    let mut e = if 目标e <= e_max { 目标e } else { e_max };
    if (e % 2) != (目标e % 2) && e > 0 { e -= 1; } // 对齐奇偶，保证结果 scale 为整数
    let 因子 = match 10i128.checked_pow(e as u32) { Some(x) => x, None => return 抛精确小数异常("精确小数平方根溢出") };
    let n = match v.checked_mul(因子) { Some(x) => x, None => return 抛精确小数异常("精确小数平方根溢出") };
    let r = n.isqrt();
    let k = (e / 2) as u32;                         // 当前可得小数位数
    if k >= 28 {
        新建精确小数(r, k)
    } else {
        match r.checked_mul(10i128.pow(28 - k)) {
            Some(rv) => 新建精确小数(rv, 28),
            None => 新建精确小数(r, k),
        }
    }
}

/// 保留小数：四舍五入到指定位数（n >= 当前小数位则补零，n < 当前则舍入）。
fn 精确小数保留小数(参数: &[运行时值]) -> 运行时值 {
    let (v, scale) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛精确小数异常("精确小数保留小数：类型错误") };
    let n = 取整数(参数, 1);
    let n = if n < 0 { 0 } else { n as u32 };
    if n >= scale {
        let 补 = n - scale;
        match v.checked_mul(10i128.pow(补)) {
            Some(rv) => 新建精确小数(rv, n),
            None => 抛精确小数异常("精确小数保留小数溢出"),
        }
    } else {
        let 降 = scale - n;
        let 因子 = 10i128.pow(降);
        let 商 = v.div_euclid(因子);
        let 余 = v.rem_euclid(因子);
        let 阈值 = 因子.unsigned_abs();
        let 商 = if (余 as u128) * 2 >= 阈值 { 商 + 1 } else { 商 };
        新建精确小数(商, n)
    }
}

/// 科学计数法：保留 有效位数 位有效数字，返回形如 "m.mmm...e±E" 的文本。
fn 精确小数科学计数法(参数: &[运行时值]) -> 运行时值 {
    let (v, scale) = match 取或规整精确小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛精确小数异常("精确小数科学计数法：类型错误") };
    // ⚡双模式⚡ 兜底默认 6 位有效数字（规范 §5.1.11 科学计数法(整数 有效位数 = 6)），
    //   与模块级 数学.科学计数法（标准库索引::数学_科学计数法）的 `else { 6 }` 对称。
    //   解释模式不经降级默认填充，base 必须自持默认，否则缺参取到 0 → 钳位为 1 位有效数字。
    let 有效 = if 参数.len() >= 2 { 取整数(参数, 1) } else { 6 };
    let 有效 = if 有效 < 1 { 1 } else { 有效 as usize };
    if v == 0 { return 分配文本("0".to_string()); }
    let 符号 = if v < 0 { "-" } else { "" };
    let a = v.unsigned_abs();
    let 数字串 = a.to_string();
    let d = 数字串.len() as i32;
    let mut 指数 = d - 1 - scale as i32;
    let 需取 = 有效;
    let 尾数串 = if 数字串.len() >= 需取 {
        let 主体 = &数字串[..需取];
        let 下一位 = 数字串.as_bytes().get(需取).map(|&b| b - b'0').unwrap_or(0);
        let mut 主体值: u128 = 主体.parse().unwrap();
        if 下一位 >= 5 { 主体值 += 1; }
        主体值.to_string()
    } else {
        let mut s = 数字串.clone();
        for _ in 0..(需取 - 数字串.len()) { s.push('0'); }
        s
    };
    if 尾数串.len() as i32 > 需取 as i32 { 指数 += 1; } // 四舍五入进位增加位数
    let 整数部分 = &尾数串[0..1];
    let 小数部分 = if 尾数串.len() > 1 { &尾数串[1..] } else { "" };
    let 结果 = if 小数部分.is_empty() {
        format!("{}{}e{:+}", 符号, 整数部分, 指数)
    } else {
        format!("{}{}.{}e{:+}", 符号, 整数部分, 小数部分, 指数)
    };
    分配文本(结果)
}

/// 从堆句柄读文本内容（文本以 标签_句柄 存储，统一处理 堆数据::文本 / 文本_静态）。
fn 读堆文本(句柄: u64) -> Option<String> {
    match 堆读取(句柄) {
        Some(堆数据::文本(sb)) => Some(sb.clone()),
        Some(堆数据::文本_静态(p, n)) => {
            let 切片 = unsafe { std::slice::from_raw_parts(p as *const u8, n) };
            Some(String::from_utf8_lossy(切片).to_string())
        }
        _ => None,
    }
}

// ============================================================
//  数学.短小数（§5.1.12）base 实现：f32 位模式存于 整数 字段
//  存储用 Rust f32（位模式），运算用真·f32，显示用 小数/文本
// ============================================================
fn 取或规整短小数(v: &运行时值) -> Option<f32> {
    match v.标签 {
        标签_句柄 => {
            if let Some(堆数据::结构体 { 类型索引, 字段值, .. }) = 堆读取(v.句柄) {
                if 类型索引 == 短小数类型索引 && !字段值.is_empty() {
                    return Some(f32::from_bits(字段值[0].整数 as u32));
                }
            }
            读堆文本(v.句柄).and_then(|s| s.trim().parse::<f32>().ok())
        }
        标签_整数 => Some(v.整数 as f32),
        标签_小数 => Some(v.小数 as f32),
        _ => None,
    }
}
/// 运算用严格规整：规范 §5.1.12 规则 4 —— **不支持与普通 `小数` 直接混合运算**。
/// 构造允许小数（`短小数(3.14)` ✓ 见创建方式表），运算不允许（`短小数(1) + 1.5` 必须报错）。
/// 此前 `取或规整短小数` 直接接受 `标签_小数` ⇒ 混合运算被静默接受 ✗（约束形同虚设）。
fn 取或规整短小数_运算(v: &运行时值) -> Option<f32> {
    if v.标签 == 标签_小数 {
        return None;
    }
    取或规整短小数(v)
}
fn 新建短小数(f: f32) -> 运行时值 {
    let 句柄 = 堆分配(堆数据::结构体 {
        类型索引: 短小数类型索引,
        字段值: vec![运行时值::整数(f32::to_bits(f) as i64)],
    });
    运行时值::句柄(句柄)
}
fn 抛短小数异常(消息: &str) -> 运行时值 {
    let 描述 = "短小数错误";
    crate::异常运行时::智语言_抛出异常(描述.as_ptr(), 描述.len() as i64, 消息.as_ptr(), 消息.len() as i64);
    运行时值::空值()
}
fn 处理短小数(索引: usize, 参数: &[运行时值]) -> 运行时值 {
    // 二元运算一律走「严格规整」：拒绝普通小数（§5.1.12 规则 4）；
    // 构造（数学短小数创建）单独使用宽容版，允许 `短小数(3.14)`。
    let 取两 = || -> Option<(f32, f32)> {
        Some((取或规整短小数_运算(&取参数(参数, 0))?, 取或规整短小数_运算(&取参数(参数, 1))?))
    };
    match 索引 {
        标准库索引::数学短小数创建 => match 取或规整短小数(&取参数(参数, 0)) {
            Some(f) => 新建短小数(f),
            None => 抛短小数异常("短小数构造：仅支持整数/小数/文本/短小数"),
        },
        标准库索引::数学_短小数_加法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛短小数异常("短小数加法：操作数类型错误") }; 新建短小数(a + b) }
        标准库索引::数学_短小数_减法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛短小数异常("短小数减法：操作数类型错误") }; 新建短小数(a - b) }
        标准库索引::数学_短小数_乘法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛短小数异常("短小数乘法：操作数类型错误") }; 新建短小数(a * b) }
        标准库索引::数学_短小数_除法 => {
            let (a, b) = match 取两() { Some(x) => x, None => return 抛短小数异常("短小数除法：操作数类型错误") };
            if b == 0.0 { return 抛短小数异常("短小数除法：除数不能为零"); }
            新建短小数(a / b)
        }
        标准库索引::数学_短小数_幂 => {
            let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛短小数异常("短小数幂：底数类型错误") };
            let b = match 取或规整短小数_运算(&取参数(参数, 1)) { Some(x) => x, None => return 抛短小数异常("短小数幂：指数类型错误（不支持普通小数）") };
            新建短小数(a.powf(b))
        }
        标准库索引::数学_短小数_取负 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛短小数异常("短小数取负：类型错误") }; 新建短小数(-a) }
        标准库索引::数学_短小数_绝对值 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛短小数异常("短小数绝对值：类型错误") }; 新建短小数(a.abs()) }
        标准库索引::数学_短小数_平方根 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛短小数异常("短小数平方根：类型错误") }; 新建短小数(a.sqrt()) }
        标准库索引::数学_短小数_保留小数 => {
            let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛短小数异常("短小数保留小数：类型错误") };
            let n = if 取整数(参数, 1) < 0 { 0 } else { 取整数(参数, 1) } as i32;
            let 因子 = 10f32.powi(n);
            新建短小数((a * 因子).round() / 因子)
        }
        标准库索引::数学_短小数_是否为零 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a == 0.0) }
        标准库索引::数学_短小数_是否为正数 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a > 0.0) }
        标准库索引::数学_短小数_是否为负数 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a < 0.0) }
        标准库索引::数学_短小数_等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a == b) }
        标准库索引::数学_短小数_不等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a != b) }
        标准库索引::数学_短小数_大于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a > b) }
        标准库索引::数学_短小数_小于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a < b) }
        标准库索引::数学_短小数_大于等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a >= b) }
        标准库索引::数学_短小数_小于等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a <= b) }
        标准库索引::数学_短小数_最大值 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛短小数异常("短小数最大值：操作数类型错误") }; 新建短小数(if a >= b { a } else { b }) }
        标准库索引::数学_短小数_最小值 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛短小数异常("短小数最小值：操作数类型错误") }; 新建短小数(if a <= b { a } else { b }) }
        标准库索引::数学_短小数_转文本 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 抛短小数异常("短小数转文本：类型错误") }; 分配文本(format!("{}", a)) }
        标准库索引::数学_短小数_转小数 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::小数(0.0) }; 运行时值::小数(a as f64) }
        标准库索引::数学_短小数_转整数 => { let a = match 取或规整短小数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::整数(0) }; 运行时值::整数(a as i64) }
        _ => 运行时值::空值(),
    }
}

// ============================================================
//  数学.无符号整数（§5.1.14）base 实现：u64 位模式存于 整数 字段
//  支持无符号算术与位运算；算术溢出抛异常不回绕
// ============================================================
fn 取或规整无符号整数(v: &运行时值) -> Option<u64> {
    match v.标签 {
        标签_句柄 => {
            if let Some(堆数据::结构体 { 类型索引, 字段值, .. }) = 堆读取(v.句柄) {
                if 类型索引 == 无符号整数类型索引 && !字段值.is_empty() {
                    return Some(字段值[0].整数 as u64);
                }
            }
            读堆文本(v.句柄).and_then(|s| s.trim().parse::<u64>().ok())
        }
        // ⚠ 规范 §5.1.14 规则 5：与普通整数混合要求整数**非负**；规则 2：构造值须在无符号范围内。
        //   此前直接 `as u64` 会把 -1 静默变成 18446744073709551615（既不报错也不提示）✗。
        //   现负数 ⇒ None（本函数为类型规整的单一真相，防御性拒绝），
        //   调用方入口（处理无符号整数）另给出精确异常消息。
        标签_整数 => if v.整数 < 0 { None } else { Some(v.整数 as u64) },
        _ => None,
    }
}
fn 新建无符号整数(u: u64) -> 运行时值 {
    let 句柄 = 堆分配(堆数据::结构体 {
        类型索引: 无符号整数类型索引,
        字段值: vec![运行时值::整数(u as i64)],
    });
    运行时值::句柄(句柄)
}
fn 抛无符号整数异常(消息: &str) -> 运行时值 {
    let 描述 = "无符号整数错误";
    crate::异常运行时::智语言_抛出异常(描述.as_ptr(), 描述.len() as i64, 消息.as_ptr(), 消息.len() as i64);
    运行时值::空值()
}
fn 处理无符号整数(索引: usize, 参数: &[运行时值]) -> 运行时值 {
    // 规范 §5.1.14 规则 2/5：负整数既不能构造，也不能参与无符号运算（均为非法输入，须抛异常不静默）。
    // 单独前置检查以给出**可定位**的异常描述（否则会退化成本文件通用的「操作数类型错误」）。
    for 位 in 0..2usize {
        let 参 = 取参数(参数, 位);
        if 参.标签 == 标签_整数 && 参.整数 < 0 {
            return 抛无符号整数异常(if 索引 == 标准库索引::数学无符号整数创建 {
                "无符号整数构造：输入必须在 0~18446744073709551615 范围内（负整数非法）"
            } else {
                "无符号整数运算：普通整数操作数不能为负"
            });
        }
    }
    let 取两 = || -> Option<(u64, u64)> {
        Some((取或规整无符号整数(&取参数(参数, 0))?, 取或规整无符号整数(&取参数(参数, 1))?))
    };
    match 索引 {
        标准库索引::数学无符号整数创建 => match 取或规整无符号整数(&取参数(参数, 0)) {
            Some(u) => 新建无符号整数(u),
            None => 抛无符号整数异常("无符号整数构造：仅支持整数/文本/无符号整数"),
        },
        标准库索引::数学_无符号整数_加法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数加法：操作数类型错误") }; match a.checked_add(b) { Some(r) => 新建无符号整数(r), None => return 抛无符号整数异常("无符号整数加法溢出") } }
        标准库索引::数学_无符号整数_减法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数减法：操作数类型错误") }; match a.checked_sub(b) { Some(r) => 新建无符号整数(r), None => return 抛无符号整数异常("无符号整数减法溢出（结果不能为负）") } }
        标准库索引::数学_无符号整数_乘法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数乘法：操作数类型错误") }; match a.checked_mul(b) { Some(r) => 新建无符号整数(r), None => return 抛无符号整数异常("无符号整数乘法溢出") } }
        标准库索引::数学_无符号整数_除法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数除法：操作数类型错误") }; if b == 0 { return 抛无符号整数异常("无符号整数除法：除数不能为零"); } 新建无符号整数(a / b) }
        标准库索引::数学_无符号整数_整除 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数整除：操作数类型错误") }; if b == 0 { return 抛无符号整数异常("无符号整数整除：除数不能为零"); } 新建无符号整数(a / b) }
        标准库索引::数学_无符号整数_取余 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数取余：操作数类型错误") }; if b == 0 { return 抛无符号整数异常("无符号整数取余：除数不能为零"); } 新建无符号整数(a % b) }
        标准库索引::数学_无符号整数_位与 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数位与：操作数类型错误") }; 新建无符号整数(a & b) }
        标准库索引::数学_无符号整数_位或 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数位或：操作数类型错误") }; 新建无符号整数(a | b) }
        标准库索引::数学_无符号整数_异或 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无符号整数异常("无符号整数异或：操作数类型错误") }; 新建无符号整数(a ^ b) }
        标准库索引::数学_无符号整数_位非 => { let a = match 取或规整无符号整数(&取参数(参数, 0)) { Some(x) => x, None => return 抛无符号整数异常("无符号整数位非：类型错误") }; 新建无符号整数(!a) }
        标准库索引::数学_无符号整数_左移 => { let a = match 取或规整无符号整数(&取参数(参数, 0)) { Some(x) => x, None => return 抛无符号整数异常("无符号整数左移：类型错误") }; match a.checked_shl(取整数(参数, 1) as u32) { Some(r) => 新建无符号整数(r), None => return 抛无符号整数异常("无符号整数左移：移位量必须 0~63") } }
        标准库索引::数学_无符号整数_右移 => { let a = match 取或规整无符号整数(&取参数(参数, 0)) { Some(x) => x, None => return 抛无符号整数异常("无符号整数右移：类型错误") }; match a.checked_shr(取整数(参数, 1) as u32) { Some(r) => 新建无符号整数(r), None => return 抛无符号整数异常("无符号整数右移：移位量必须 0~63") } }
        标准库索引::数学_无符号整数_是否为零 => { let a = match 取或规整无符号整数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a == 0) }
        标准库索引::数学_无符号整数_等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a == b) }
        标准库索引::数学_无符号整数_不等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a != b) }
        标准库索引::数学_无符号整数_大于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a > b) }
        标准库索引::数学_无符号整数_小于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a < b) }
        标准库索引::数学_无符号整数_大于等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a >= b) }
        标准库索引::数学_无符号整数_小于等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a <= b) }
        标准库索引::数学_无符号整数_转文本 => { let a = match 取或规整无符号整数(&取参数(参数, 0)) { Some(x) => x, None => return 抛无符号整数异常("无符号整数转文本：类型错误") }; 分配文本(a.to_string()) }
        标准库索引::数学_无符号整数_转整数 => { let a = match 取或规整无符号整数(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::整数(0) }; 运行时值::整数(a as i64) }
        _ => 运行时值::空值(),
    }
}

// ============================================================
//  数学.字节（§5.1.15）base 实现：u8 存于 整数 字段（0~255）
//  提供字节语义与范围校验；算术溢出抛异常不回绕
// ============================================================
fn 读字节(句柄: u64) -> Option<u8> {
    if let Some(堆数据::结构体 { 类型索引, 字段值, .. }) = 堆读取(句柄) {
        if 类型索引 == 字节类型索引 && !字段值.is_empty() {
            return Some(字段值[0].整数 as u8);
        }
    }
    None
}
fn 取或规整字节(v: &运行时值) -> Option<u8> {
    match v.标签 {
        标签_句柄 => 读字节(v.句柄),
        // ⚠ 规范 §5.1.15 规则 5：与普通 `整数` 混合运算要求整数在 0~255 范围内；
        //   此前直接 `as u8` 会把 300 静默截断为 44 ✗（既不报错也不提示，属静默数字错误）。
        标签_整数 => if !(0..=255).contains(&v.整数) { None } else { Some(v.整数 as u8) },
        _ => None,
    }
}
fn 新建字节(u: u8) -> 运行时值 {
    let 句柄 = 堆分配(堆数据::结构体 {
        类型索引: 字节类型索引,
        字段值: vec![运行时值::整数(u as i64)],
    });
    运行时值::句柄(句柄)
}
fn 抛字节异常(消息: &str) -> 运行时值 {
    let 描述 = "字节错误";
    crate::异常运行时::智语言_抛出异常(描述.as_ptr(), 描述.len() as i64, 消息.as_ptr(), 消息.len() as i64);
    运行时值::空值()
}
fn 处理字节(索引: usize, 参数: &[运行时值]) -> 运行时值 {
    // 规范 §5.1.15 规则 5：普通整数操作数必须在 0~255 内（构造与运算同等要求）。
    // 前置检查只为给出可定位的异常描述，否则会退化为通用「字节运算：操作数类型错误」。
    for 位 in 0..2usize {
        let 参 = 取参数(参数, 位);
        if 参.标签 == 标签_整数 && !(0..=255).contains(&参.整数) {
            return 抛字节异常(if 索引 == 标准库索引::数学字节创建 {
                "字节构造：输入整数必须在 0~255 范围内"
            } else {
                "字节运算：普通整数操作数必须在 0~255 范围内"
            });
        }
    }
    let 取两 = || -> Option<(u8, u8)> {
        Some((取或规整字节(&取参数(参数, 0))?, 取或规整字节(&取参数(参数, 1))?))
    };
    match 索引 {
        标准库索引::数学字节创建 => {
            let p = 取参数(参数, 0);
            let v: u8 = match p.标签 {
                标签_整数 => {
                    let n = p.整数;
                    if n < 0 || n > 255 { return 抛字节异常("字节必须在 0~255 范围内"); }
                    n as u8
                }
                标签_句柄 => {
                    if let Some(x) = 读字节(p.句柄) { x }
                    else if let Some(s) = 读堆文本(p.句柄) {
                        let s = s.trim();
                        if let Some(n) = s.parse::<i64>().ok() {
                            if n >= 0 && n <= 255 { n as u8 }
                            else { return 抛字节异常("字节构造：数值超出 0~255 范围"); }
                        } else if s.chars().count() == 1 {
                            // 单字符文本：取其 Unicode 码点作为字节值（码点须 0~255，与 转字符 互逆）
                            let 码点 = s.chars().next().unwrap() as u32;
                            if 码点 <= 255 { 码点 as u8 }
                            else { return 抛字节异常("字节构造：字符码点超出 0~255"); }
                        } else { return 抛字节异常("字节构造：须为 0~255 数字或单字符文本"); }
                    } else { return 抛字节异常("字节构造：类型错误") }
                }
                _ => return 抛字节异常("字节构造：仅支持整数/文本/字节"),
            };
            新建字节(v)
        }
        标准库索引::数学_字节_加法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节加法：操作数类型错误") }; match a.checked_add(b) { Some(r) => 新建字节(r), None => return 抛字节异常("字节加法溢出（超过 255）") } }
        标准库索引::数学_字节_减法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节减法：操作数类型错误") }; match a.checked_sub(b) { Some(r) => 新建字节(r), None => return 抛字节异常("字节减法溢出（结果不能为负）") } }
        标准库索引::数学_字节_乘法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节乘法：操作数类型错误") }; match a.checked_mul(b) { Some(r) => 新建字节(r), None => return 抛字节异常("字节乘法溢出（超过 255）") } }
        标准库索引::数学_字节_除法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节除法：操作数类型错误") }; if b == 0 { return 抛字节异常("字节除法：除数不能为零"); } 新建字节(a / b) }
        标准库索引::数学_字节_整除 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节整除：操作数类型错误") }; if b == 0 { return 抛字节异常("字节整除：除数不能为零"); } 新建字节(a / b) }
        标准库索引::数学_字节_取余 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节取余：操作数类型错误") }; if b == 0 { return 抛字节异常("字节取余：除数不能为零"); } 新建字节(a % b) }
        标准库索引::数学_字节_位与 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节位与：操作数类型错误") }; 新建字节(a & b) }
        标准库索引::数学_字节_位或 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节位或：操作数类型错误") }; 新建字节(a | b) }
        标准库索引::数学_字节_异或 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛字节异常("字节异或：操作数类型错误") }; 新建字节(a ^ b) }
        标准库索引::数学_字节_位非 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 抛字节异常("字节位非：类型错误") }; 新建字节(!a) }
        标准库索引::数学_字节_左移 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 抛字节异常("字节左移：类型错误") }; match a.checked_shl(取整数(参数, 1) as u32) { Some(r) => 新建字节(r), None => return 抛字节异常("字节左移：移位量必须 0~7") } }
        标准库索引::数学_字节_右移 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 抛字节异常("字节右移：类型错误") }; match a.checked_shr(取整数(参数, 1) as u32) { Some(r) => 新建字节(r), None => return 抛字节异常("字节右移：移位量必须 0~7") } }
        标准库索引::数学_字节_是否为零 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a == 0) }
        标准库索引::数学_字节_等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a == b) }
        标准库索引::数学_字节_不等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a != b) }
        标准库索引::数学_字节_大于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a > b) }
        标准库索引::数学_字节_小于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a < b) }
        标准库索引::数学_字节_大于等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a >= b) }
        标准库索引::数学_字节_小于等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a <= b) }
        标准库索引::数学_字节_转文本 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 抛字节异常("字节转文本：类型错误") }; 分配文本(a.to_string()) }
        标准库索引::数学_字节_转整数 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 抛字节异常("字节转整数：类型错误") }; 运行时值::整数(a as i64) }
        标准库索引::数学_字节_转字符 => { let a = match 取或规整字节(&取参数(参数, 0)) { Some(x) => x, None => return 抛字节异常("字节转字符：类型错误") }; let c = char::from_u32(a as u32).unwrap_or('\u{FFFD}'); 分配文本(c.to_string()) }
        _ => 运行时值::空值(),
    }
}

// ============================================================
//  数学.无限整数（§5.1.13）base 实现：Vec<u64> 块（低位在前）存于 数组<整数> 字段
//  数值块[0] = 符号块（0 正 / 1 负），数值块[1..] = 幅值（base 2^64 小端）
// ============================================================
struct 大整数 { 负: bool, 块: Vec<u64> }

fn 规整块(mut 块: Vec<u64>) -> Vec<u64> {
    while 块.len() > 1 && *块.last().unwrap() == 0 { 块.pop(); }
    if 块.is_empty() { 块 = vec![0]; }
    块
}
fn 取或规整无限整数(v: &运行时值) -> Option<大整数> {
    match v.标签 {
        标签_句柄 => {
            if let Some(堆数据::结构体 { 类型索引, 字段值, .. }) = 堆读取(v.句柄) {
                if 类型索引 == 无限整数类型索引 {
                    if 字段值.is_empty() { return Some(大整数 { 负: false, 块: vec![0] }); }
                    let 负 = 字段值[0].整数 != 0;
                    let 块: Vec<u64> = 字段值[1..].iter().map(|v2| v2.整数 as u64).collect();
                    let 块 = if 块.is_empty() { vec![0] } else { 规整块(块) };
                    return Some(大整数 { 负, 块 });
                }
            }
            读堆文本(v.句柄).and_then(|s| 十进制转大整数(&s))
        }
        标签_整数 => {
            let n = v.整数;
            let 负 = n < 0;
            let 块 = if n == i64::MIN { vec![1u64 << 63] } else { vec![(n.unsigned_abs()) as u64] };
            Some(大整数 { 负, 块: 规整块(块) })
        }
        _ => None,
    }
}
fn 新建无限整数(bi: &大整数) -> 运行时值 {
    let mut 块 = vec![运行时值::整数(if bi.负 { 1 } else { 0 })];
    for b in &bi.块 { 块.push(运行时值::整数(*b as i64)); }
    let 句柄 = 堆分配(堆数据::结构体 { 类型索引: 无限整数类型索引, 字段值: 块 });
    运行时值::句柄(句柄)
}
fn 抛无限整数异常(消息: &str) -> 运行时值 {
    let 描述 = "无限整数错误";
    crate::异常运行时::智语言_抛出异常(描述.as_ptr(), 描述.len() as i64, 消息.as_ptr(), 消息.len() as i64);
    运行时值::空值()
}

/// 十进制文本 → 大整数（幅值逐位乘 10 累加）。
fn 十进制转大整数(s: &str) -> Option<大整数> {
    let s = s.trim();
    if s.is_empty() { return None; }
    let 负 = s.starts_with('-');
    let s = if 负 { &s[1..] } else { s };
    if s.is_empty() || !s.chars().all(|c| c.is_ascii_digit()) { return None; }
    let mut 块 = vec![0u64];
    for c in s.chars() {
        let d = (c as u8 - b'0') as u64;
        块 = 加幅值(&乘幅值(&块, &[10]), &[d]);
    }
    Some(大整数 { 负, 块: 规整块(块) })
}

// ——— 幅值运算（只处理非负幅值，符号由调用方处理）———
fn 比较幅值(a: &[u64], b: &[u64]) -> std::cmp::Ordering {
    let a = 规整块(a.to_vec());
    let b = 规整块(b.to_vec());
    if a.len() != b.len() { return a.len().cmp(&b.len()); }
    for i in (0..a.len()).rev() {
        if a[i] != b[i] { return a[i].cmp(&b[i]); }
    }
    std::cmp::Ordering::Equal
}
fn 加幅值(a: &[u64], b: &[u64]) -> Vec<u64> {
    let n = a.len().max(b.len());
    let mut r = vec![0u64; n + 1];
    let mut carry: u128 = 0;
    for i in 0..n {
        let av = *a.get(i).unwrap_or(&0) as u128;
        let bv = *b.get(i).unwrap_or(&0) as u128;
        let s = av + bv + carry;
        r[i] = s as u64;
        carry = s >> 64;
    }
    r[n] = carry as u64;
    规整块(r)
}
fn 减幅值(a: &[u64], b: &[u64]) -> Vec<u64> {
    // 前置：a 幅值 >= b 幅值
    let n = a.len().max(b.len());
    let mut r = vec![0u64; n];
    let mut borrow: i128 = 0;
    for i in 0..n {
        let av = *a.get(i).unwrap_or(&0) as i128;
        let bv = *b.get(i).unwrap_or(&0) as i128;
        let mut s = av - bv - borrow;
        if s < 0 { s += 1i128 << 64; borrow = 1; } else { borrow = 0; }
        r[i] = s as u64;
    }
    规整块(r)
}
fn 乘幅值(a: &[u64], b: &[u64]) -> Vec<u64> {
    if a.iter().all(|&x| x == 0) || b.iter().all(|&x| x == 0) { return vec![0]; }
    let mut r = vec![0u128; a.len() + b.len()];
    for i in 0..a.len() {
        let mut carry: u128 = 0;
        let av = a[i] as u128;
        for j in 0..b.len() {
            let cur = r[i + j] + av * (b[j] as u128) + carry;
            r[i + j] = cur & 0xFFFFFFFFFFFFFFFF;
            carry = cur >> 64;
        }
        let mut k = i + b.len();
        while carry > 0 {
            let cur = r[k] + carry;
            r[k] = cur & 0xFFFFFFFFFFFFFFFF;
            carry = cur >> 64;
            k += 1;
        }
    }
    let 块: Vec<u64> = r.into_iter().map(|x| x as u64).collect();
    规整块(块)
}
fn 位长(块: &[u64]) -> usize {
    let 块 = 规整块(块.to_vec());
    if 块.len() == 1 && 块[0] == 0 { return 0; }
    let top = 块[块.len() - 1];
    let leading = top.leading_zeros() as usize;
    块.len() * 64 - leading
}
fn 取位(块: &[u64], bit: usize) -> u64 {
    let idx = bit / 64;
    let off = bit % 64;
    块.get(idx).map_or(0, |&b| (b >> off) & 1)
}
fn 左移进位(块: &mut Vec<u64>, bit_in: u64) {
    let mut carry: u64 = bit_in & 1;
    for b in 块.iter_mut() {
        let next = *b >> 63;
        *b = (*b << 1) | carry;
        carry = next;
    }
    if carry != 0 { 块.push(carry); }
}
fn 置位(块: &mut Vec<u64>, bit: usize) {
    let idx = bit / 64;
    let off = bit % 64;
    while 块.len() <= idx { 块.push(0); }
    块[idx] |= 1u64 << off;
}
fn 除幅值(a: &[u64], b: &[u64]) -> (Vec<u64>, Vec<u64>) {
    // |a| = 商 * |b| + 余数，0 <= 余数 < |b|；前置 b != 0
    match 比较幅值(a, b) {
        std::cmp::Ordering::Less => return (vec![0], 规整块(a.to_vec())),
        std::cmp::Ordering::Equal => return (vec![1], vec![0]),
        _ => {}
    }
    let mut 余数 = vec![0u64; a.len() + 1];
    let mut 商 = vec![0u64; a.len()];
    let bits = 位长(a);
    for bit in (0..bits).rev() {
        左移进位(&mut 余数, 取位(a, bit));
        if 比较幅值(&余数, b) != std::cmp::Ordering::Less {
            余数 = 减幅值(&余数, b);
            置位(&mut 商, bit);
        }
    }
    (规整块(商), 规整块(余数))
}
fn 除以小整数(块: &[u64], d: u64) -> (Vec<u64>, u64) {
    let mut 商 = vec![0u64; 块.len()];
    let mut 余数: u128 = 0;
    for i in (0..块.len()).rev() {
        let cur = (余数 << 64) | (块[i] as u128);
        let q = (cur / (d as u128)) as u64;
        let r = (cur % (d as u128)) as u64;
        商[i] = q;
        余数 = r as u128;
    }
    (规整块(商), 余数 as u64)
}
fn 幅值转十进制(块: &[u64]) -> String {
    if 块.iter().all(|&x| x == 0) { return "0".to_string(); }
    let mut 数值 = 规整块(块.to_vec());
    let mut digits = Vec::new();
    while 数值.iter().any(|&x| x != 0) {
        let (q, r) = 除以小整数(&数值, 10);
        数值 = q;
        digits.push((b'0' + r as u8) as char);
    }
    digits.reverse();
    digits.iter().collect()
}
fn 幅值平方根(n: &[u64]) -> Vec<u64> {
    // 牛顿法求 floor(sqrt(幅值))，逐次检验 floor 条件避免振荡
    if n.iter().all(|&x| x == 0) { return vec![0]; }
    let mut x = vec![1u64];
    loop {
        let (q, _) = 除幅值(n, &x);
        let 半 = 除幅值(&加幅值(&x, &q), &[2]).0;
        if 比较幅值(&半, &x) == std::cmp::Ordering::Equal { x = 半; break; }
        x = 半;
        let x2 = 乘幅值(&x, &x);
        if 比较幅值(&x2, n) != std::cmp::Ordering::Greater {
            let xp1 = 加幅值(&x, &[1]);
            if 比较幅值(&乘幅值(&xp1, &xp1), n) == std::cmp::Ordering::Greater { break; }
        }
    }
    规整块(x)
}

// ——— 带符号运算 ———
fn 取负无限(b: &大整数) -> 大整数 {
    大整数 { 负: if b.块.iter().all(|&x| x == 0) { false } else { !b.负 }, 块: b.块.clone() }
}
fn 加无限整数(a: &大整数, b: &大整数) -> 大整数 {
    if !a.负 && !b.负 { return 大整数 { 负: false, 块: 加幅值(&a.块, &b.块) }; }
    if a.负 && b.负 { return 大整数 { 负: true, 块: 加幅值(&a.块, &b.块) }; }
    let cmp = 比较幅值(&a.块, &b.块);
    match cmp {
        std::cmp::Ordering::Equal => 大整数 { 负: false, 块: vec![0] },
        std::cmp::Ordering::Greater => 大整数 { 负: a.负, 块: 减幅值(&a.块, &b.块) },
        std::cmp::Ordering::Less => 大整数 { 负: b.负, 块: 减幅值(&b.块, &a.块) },
    }
}
fn 乘无限整数(a: &大整数, b: &大整数) -> 大整数 {
    大整数 { 负: a.负 != b.负, 块: 乘幅值(&a.块, &b.块) }
}
/// 返回 (商, 余数)：商 = floor(a/b)（向负无穷），余数 = 欧几里得非负（0 <= r < |b|）。
/// 无限整数「向下取整除法」：返回 (floor 商, 截断余数)。
/// 商 = floor(甲/乙)（向负无穷，与普通整数 `%%` 一致）；余数按**截断语义**（与被除数同号）。
/// ⚠ 语言层 `%`（取余）**不使用**本余数 —— 项目定稿（§5.1.11 同款）要求 `%` 为**欧几里得非负余数**，
///   见 `无限整数取余值`（本文件 2026-10-25 F57 修复）。
fn 无限整数除余(a: &大整数, b: &大整数) -> Option<(大整数, 大整数)> {
    if b.块.iter().all(|&x| x == 0) { return None; }
    let (qm, rm) = 除幅值(&a.块, &b.块);
    let 同号 = a.负 == b.负;
    let (q, r) = if 同号 {
        (大整数 { 负: false, 块: qm }, 大整数 { 负: a.负, 块: rm })
    } else if rm.iter().all(|&x| x == 0) {
        (大整数 { 负: true, 块: qm }, 大整数 { 负: false, 块: vec![0] })
    } else {
        let qm1 = 加幅值(&qm, &[1]);
        let rmag = 减幅值(&b.块, &rm);
        (大整数 { 负: true, 块: qm1 }, 大整数 { 负: a.负, 块: rmag })
    };
    Some((q, r))
}

/// 无限整数「取余」（欧几里得非负）：0 ≤ r < |乙|，**与两操作数符号都无关**。
/// 依据：项目取余语义定稿（`%` = 数学非负余数，与普通整数 `-11%3=1`、`10%-3=1` 一致）。
/// 修复前余数符号取「除数符号」⇒ `7 % -3` 得 **-2** ✗（应 1），与普通整数语义分叉。
fn 无限整数取余值(a: &大整数, b: &大整数) -> Option<大整数> {
    if b.块.iter().all(|&x| x == 0) { return None; }
    let (_, rm) = 除幅值(&a.块, &b.块);
    if rm.iter().all(|&x| x == 0) {
        return Some(大整数 { 负: false, 块: vec![0] });
    }
    let 值 = if a.负 { 减幅值(&b.块, &rm) } else { rm };
    Some(大整数 { 负: false, 块: 值 })
}
fn 比较无限整数(a: &大整数, b: &大整数) -> std::cmp::Ordering {
    if a.负 && !b.负 { return std::cmp::Ordering::Less; }
    if !a.负 && b.负 { return std::cmp::Ordering::Greater; }
    let cmp = 比较幅值(&a.块, &b.块);
    if a.负 { return cmp.reverse(); }
    cmp
}
fn 无限整数幂(a: &大整数, exp: &大整数) -> Option<大整数> {
    if exp.负 { return None; } // 负指数不支持
    if exp.块.iter().all(|&x| x == 0) { return Some(大整数 { 负: false, 块: vec![1] }); }
    let 符号负 = a.负 && (exp.块[0] & 1 == 1);
    let mut 结果 = 大整数 { 负: false, 块: vec![1] };
    let mut 底 = a.块.clone();
    let mut e = exp.块.clone();
    loop {
        if e[0] & 1 == 1 { 结果 = 大整数 { 负: false, 块: 乘幅值(&结果.块, &底) }; }
        底 = 乘幅值(&底, &底);
        // e >>= 1
        let mut carry = 0u64;
        for x in e.iter_mut() {
            let next = *x & 1;
            *x = (*x >> 1) | (carry << 63);
            carry = next;
        }
        e = 规整块(e);
        if e.iter().all(|&x| x == 0) { break; }
    }
    Some(大整数 { 负: 符号负, 块: 结果.块 })
}

fn 处理无限整数(索引: usize, 参数: &[运行时值]) -> 运行时值 {
    let 取两 = || -> Option<(大整数, 大整数)> {
        Some((取或规整无限整数(&取参数(参数, 0))?, 取或规整无限整数(&取参数(参数, 1))?))
    };
    let 取a = || -> Option<大整数> { 取或规整无限整数(&取参数(参数, 0)) };
    match 索引 {
        标准库索引::数学无限整数创建 => match 取a() { Some(bi) => 新建无限整数(&bi), None => 抛无限整数异常("无限整数构造：仅支持整数/文本/无限整数") },
        标准库索引::数学_无限整数_加法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数加法：操作数类型错误") }; 新建无限整数(&加无限整数(&a, &b)) }
        标准库索引::数学_无限整数_减法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数减法：操作数类型错误") }; 新建无限整数(&加无限整数(&a, &取负无限(&b))) }
        标准库索引::数学_无限整数_乘法 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数乘法：操作数类型错误") }; 新建无限整数(&乘无限整数(&a, &b)) }
        标准库索引::数学_无限整数_除法 => {
            let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数除法：操作数类型错误") };
            match 无限整数除余(&a, &b) { Some((q, _)) => 新建无限整数(&q), None => return 抛无限整数异常("无限整数除法：除数不能为零") }
        }
        标准库索引::数学_无限整数_整除 => {
            let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数整除：操作数类型错误") };
            match 无限整数除余(&a, &b) { Some((q, _)) => 新建无限整数(&q), None => return 抛无限整数异常("无限整数整除：除数不能为零") }
        }
        标准库索引::数学_无限整数_取余 => {
            let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数取余：操作数类型错误") };
            match 无限整数取余值(&a, &b) { Some(r) => 新建无限整数(&r), None => return 抛无限整数异常("无限整数取余：除数不能为零") }
        }
        标准库索引::数学_无限整数_幂 => {
            let a = match 取a() { Some(x) => x, None => return 抛无限整数异常("无限整数幂：底数类型错误") };
            let b = match 取或规整无限整数(&取参数(参数, 1)) { Some(x) => x, None => return 抛无限整数异常("无限整数幂：指数类型错误") };
            match 无限整数幂(&a, &b) { Some(r) => 新建无限整数(&r), None => return 抛无限整数异常("无限整数幂：指数必须为非负整数") }
        }
        标准库索引::数学_无限整数_取负 => { let a = match 取a() { Some(x) => x, None => return 抛无限整数异常("无限整数取负：类型错误") }; 新建无限整数(&取负无限(&a)) }
        标准库索引::数学_无限整数_绝对值 => { let a = match 取a() { Some(x) => x, None => return 抛无限整数异常("无限整数绝对值：类型错误") }; 新建无限整数(&大整数 { 负: false, 块: a.块 }) }
        标准库索引::数学_无限整数_平方根 => {
            let a = match 取a() { Some(x) => x, None => return 抛无限整数异常("无限整数平方根：类型错误") };
            if a.负 { return 抛无限整数异常("无限整数平方根：负数无实数平方根"); }
            新建无限整数(&大整数 { 负: false, 块: 幅值平方根(&a.块) })
        }
        标准库索引::数学_无限整数_是否为零 => { let a = match 取a() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a.块.iter().all(|&x| x == 0)) }
        标准库索引::数学_无限整数_是否为正数 => { let a = match 取a() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(!a.负 && !a.块.iter().all(|&x| x == 0)) }
        标准库索引::数学_无限整数_是否为负数 => { let a = match 取a() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(a.负) }
        标准库索引::数学_无限整数_符号值 => { let a = match 取a() { Some(x) => x, None => return 运行时值::整数(0) }; 运行时值::整数(if a.块.iter().all(|&x| x == 0) { 0 } else if a.负 { -1 } else { 1 }) }
        标准库索引::数学_无限整数_等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(比较无限整数(&a, &b) == std::cmp::Ordering::Equal) }
        标准库索引::数学_无限整数_不等于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(比较无限整数(&a, &b) != std::cmp::Ordering::Equal) }
        标准库索引::数学_无限整数_大于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(比较无限整数(&a, &b) == std::cmp::Ordering::Greater) }
        标准库索引::数学_无限整数_小于 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(比较无限整数(&a, &b) == std::cmp::Ordering::Less) }
        323 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(比较无限整数(&a, &b) != std::cmp::Ordering::Less) }
        324 => { let (a, b) = match 取两() { Some(x) => x, None => return 运行时值::逻辑(false) }; 运行时值::逻辑(比较无限整数(&a, &b) != std::cmp::Ordering::Greater) }
        325 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数最大值：操作数类型错误") }; if 比较无限整数(&a, &b) != std::cmp::Ordering::Less { 新建无限整数(&a) } else { 新建无限整数(&b) } }
        326 => { let (a, b) = match 取两() { Some(x) => x, None => return 抛无限整数异常("无限整数最小值：操作数类型错误") }; if 比较无限整数(&a, &b) != std::cmp::Ordering::Greater { 新建无限整数(&a) } else { 新建无限整数(&b) } }
        327 => {
            let a = match 取a() { Some(x) => x, None => return 抛无限整数异常("无限整数转文本：类型错误") };
            let mut s = 幅值转十进制(&a.块);
            if a.负 && !a.块.iter().all(|&x| x == 0) { s.insert(0, '-'); }
            分配文本(s)
        }
        328 => {
            let a = match 取a() { Some(x) => x, None => return 运行时值::整数(0) };
            if a.块.len() > 1 { return 抛无限整数异常("无限整数转整数：超出 i64 范围"); }
            let mag = a.块[0];
            let v = if !a.负 {
                if mag > i64::MAX as u64 { return 抛无限整数异常("无限整数转整数：超出 i64 范围"); }
                mag as i64
            } else if mag == 0x8000_0000_0000_0000 {
                i64::MIN
            } else {
                if mag > 0x8000_0000_0000_0000 { return 抛无限整数异常("无限整数转整数：超出 i64 范围"); }
                -(mag as i64)
            };
            运行时值::整数(v)
        }
        _ => 运行时值::空值(),
    }
}
