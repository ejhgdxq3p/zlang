//! 阶段 2（2026-09-23）回归：**句柄代际** —— 陈旧句柄在「槽位复用」后必须**失效**（ABA 防线）。
//!
//! 背景：句柄此前只是"槽位索引" ⇒ 槽位被回收后复用，仍持有旧句柄的地方会**静默读写到新对象**。
//! 现在句柄 = `[代际32 | 索引32]`：槽位**复用**时代际 +1，解码处校验 ⇒ 陈旧句柄读到 `None`、
//! 释放/加引用**幂等忽略**（不得影响复用后的新对象）。
//!
//! 运行：`cargo test -p base --offline --test 句柄代际`

use base::值类型::{堆分配, 堆读取, 堆释放, 堆数据};

/// 取句柄的槽位索引（低 32 位）—— 与运行时同一定义，测试内自算（不依赖 crate 内部函数）。
fn 索引(h: u64) -> usize {
    (h & 0xFFFF_FFFF) as usize
}

#[test]
fn 陈旧句柄在槽位复用后失效() {
    // ① 分配 A ⇒ 句柄有效
    let a = 堆分配(堆数据::文本("A".to_string()));
    assert!(堆读取(a).is_some(), "新分配句柄应可读");

    // ② 释放 A ⇒ 槽位进空闲表（**代际保留**）
    堆释放(a);
    assert!(堆读取(a).is_none(), "释放后句柄应失效");

    // ③ 再分配 B ⇒ 极可能**复用同一槽位**（空闲表后进先出）⇒ 该槽代际 +1
    let b = 堆分配(堆数据::文本("B".to_string()));
    assert!(堆读取(b).is_some(), "新分配句柄应可读");

    // ④ ★核心断言★：陈旧句柄 A **即使槽位已被复用，也必须仍然失效**
    //    （旧实现下这里会读到 B 的内容 → 错值；代际防线使其静默失效）
    assert!(
        堆读取(a).is_none(),
        "槽位复用后**陈旧句柄必须失效**（代际防线；索引={} 是否复用={}）",
        索引(a),
        索引(a) == 索引(b)
    );

    // ⑤ 陈旧句柄的 −1 必须**幂等**：不得把复用后的新对象提前回收
    堆释放(a);
    堆释放(a);
    assert!(堆读取(b).is_some(), "陈旧句柄的重复释放不得影响复用后的新对象");

    // ⑥ 正常的 B 仍可回收（防线不误伤活句柄）
    堆释放(b);
    assert!(堆读取(b).is_none(), "活句柄释放后应失效");
}
