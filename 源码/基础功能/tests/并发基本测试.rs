// 文件: 基础功能/tests/并发基本测试.rs
// 职责: 并发引擎（原 并发服务 crate）合并进 基础功能 后的集成冒烟测试。
//   仅使用高层 Rust API（通道 / 任务句柄 / 终止器 / 拥有值），
//   验证合并后模块路径 `base::公共服务::*` 可正常访问与运行。

use base::公共服务::{任务句柄, 通道, 终止器, 拥有值};

#[test]
fn 基本通道收发() {
    let 测试通道 = 通道::新建(1);
    测试通道.发送(拥有值::整数(42)).expect("发送应成功");
    let 收到 = 测试通道.接收().expect("应收到值");
    assert_eq!(收到, 拥有值::整数(42));
}

#[test]
fn 基本任务执行与等待() {
    let 句柄 = 任务句柄::启动(|| 拥有值::整数(7));
    let 结果 = 句柄.等待结果();
    assert_eq!(结果, 拥有值::整数(7));
}

#[test]
fn 基本终止器触发() {
    let 测试终止器 = 终止器::新建();
    测试终止器.触发终止();
    assert!(测试终止器.是否终止());
}
