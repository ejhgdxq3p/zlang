/// 检查命令：只做前端分析（词法→语法→语义），不生成任何产物
pub fn 执行检查(参数: &[String]) {
    let 通过 = 执行检查并返回(参数);
    if 参数解析::有标志(参数, "--结构化") {
        crate::输出格式::打印结构化(&[
            ("命令".to_string(), "检查".to_string()),
            ("通过".to_string(), if 通过 { "true" } else { "false" }.to_string()),
        ]);
        if !通过 {
            std::process::exit(1);
        }
    } else if 通过 {
        eprintln!("[智语言] 检查通过");
    } else {
        std::process::exit(1);
    }
}

/// 执行检查并返回是否通过（供 发布 等命令在内部复用，不触发进程退出）
pub fn 执行检查并返回(参数: &[String]) -> bool {
    let 文件路径 = 参数解析::提取文件路径(参数);

    // 无文件参数时，扫描当前目录所有 .智 文件
    if 文件路径.is_none() {
        let 全部文件 = 扫描智文件();
        if 全部文件.is_empty() {
            eprintln!("[智语言] 错误：未找到 .智 源文件。用法: 智语言 检查 <文件.智>");
            return false;
        }
        let mut 总错误 = 0usize;
        for 文件 in &全部文件 {
            // ★ 2026-10-25 修复（P1）：批量检查时**不能把每个源文件都当程序入口**，
            //   否则库项目（无 `启动程序`）恒报「入口程序【启动程序】未定义」⇒ `库 发布` 永远中止。
            //   只有项目入口文件（`启动程序.智`，规范 §6.2.1 布局）才要求定义 `启动程序`。
            let 视为入口 = std::path::Path::new(文件)
                .file_stem()
                .and_then(|s| s.to_str())
                .map_or(false, |名| 名 == "启动程序");
            if let Err(错误数) = 检查单个文件(文件, 视为入口) {
                总错误 += 错误数;
            }
        }
        if 总错误 > 0 {
            eprintln!("[智语言] 检查完成，发现 {} 个错误", 总错误);
            return false;
        }
        return true;
    }

    let 路径 = 文件路径.unwrap();
    // ★规范 §3.7.4「单文件路径」前置校验（路径级中文命名强制检查）
    if !crate::命名校验::校验源文件路径(&路径) {
        return false;
    }
    match 检查单个文件(&路径, true) {
        Ok(()) => true,
        Err(错误数) => {
            eprintln!("[智语言] 检查完成，发现 {} 个错误", 错误数);
            false
        }
    }
}

/// 检查单个文件，返回错误数量
/// `视为入口`：显式单文件检查=true（保持既有语义：用户 `检查 脚本.智` 会校验入口）；
///             项目批量检查=仅 `启动程序.智` 为 true（库/模块文件不要求有 `启动程序`）。
fn 检查单个文件(文件路径: &str, 视为入口: bool) -> Result<(), usize> {
    let 源码 = fs::read_to_string(文件路径)
        .map_err(|e| {
            eprintln!("无法读取文件 '{}': {}", 文件路径, e);
            1usize
        })?;

    let mut 诊断 = 诊断收集器::新建();
    frontend::诊断全局::设置诊断模式_自CLI(&mut 诊断);
    // 注册源文件以支持代码上下文显示
    诊断.注册源文件(文件路径, &源码);

    // 词法分析
    let 词条列表 = 词法分析器::新建(&源码, 文件路径.to_string(), &mut 诊断).扫描所有词条();
    if 诊断.有错误() {
        let count = 诊断.错误计数();
        输出诊断(&诊断);
        return Err(count);
    }

    // 语法分析
    let mut 程序 = 语法分析器::新建(&词条列表, &mut 诊断).解析程序();
    if 诊断.有错误() {
        let count = 诊断.错误计数();
        输出诊断(&诊断);
        return Err(count);
    }

    // 语义分析
    // ⚠ 必须给出「入口文件路径」（与 运行/构建 同源，规范 §2.7.5 三层分派）：
    //   语义分析器靠它 `检测项目根` → `构建模块解析方案` ⇒ 才能按 `导入 库名/模块路径`
    //   定位第三方库源码根。缺它 ⇒ 方案为空 ⇒ 项目内引用已装库必报
    //   「无法找到模块【库名.模块名】」（实测 `检查 源码/启动程序.智` 假红，
    //   而同一文件 `运行` 正常 —— 属观测口径不一致的真缺陷）。
    let mut 分析器 = 语义分析器::新建(&mut 诊断);
    分析器.设置入口文件路径(文件路径).设置是否为入口文件(视为入口);
    match 分析器.分析程序(&mut 程序) {
        Ok(_) => Ok(()),
        Err(_) => {
            let count = 诊断.错误计数();
            输出诊断(&诊断);
            Err(count)
        }
    }
}

/// 格式化命令：使用前端格式化器自动格式化代码
pub fn 执行格式化(参数: &[String]) {
    let 文件路径 = match 参数解析::提取文件路径(参数) {
        Some(f) => f,
        None => {
            eprintln!("[智语言] 错误：用法: 智语言 格式化 <文件.智>");
            return;
        }
    };

    let 源码 = match fs::read_to_string(&文件路径) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[智语言] 错误：无法读取文件 '{}': {}", 文件路径, e);
            return;
        }
    };

    let mut 诊断 = 诊断收集器::新建();
    frontend::诊断全局::设置诊断模式_自CLI(&mut 诊断);
    let mut 格式化器 = 代码格式化器::新建(&mut 诊断);

    let 绝对路径 = std::fs::canonicalize(&文件路径).unwrap_or_else(|_| PathBuf::from(&文件路径));

    match 格式化器.格式化(&源码, &文件路径) {
        Ok(格式化后源码) => {
            if let Err(e) = fs::write(&文件路径, &格式化后源码) {
                eprintln!("[智语言] 错误：无法写入格式化结果到 '{}': {}", 文件路径, e);
            } else {
                eprintln!("[智语言] 格式化完成：{}", 绝对路径.display());
            }
        }
        Err(_) => {
            输出诊断(&诊断);
            eprintln!("[智语言] 格式化失败：源代码包含语法错误，请先修复");
        }
    }
}

/// 扫描待检查的 .智 文件。
///
/// ★ 2026-10-25 修复（P1，双模无关、纯工具链）：此前只扫「cwd 根」+「cwd/测试」，
///   **不含标准项目布局的 `源码/`**（规范 §6.2.1）=>
///     · `智语言 检查`（项目内无参数）恒报「未找到 .智 源文件」；
///     · `库 发布`（默认先跑检查+测试，规范 §6.3.6）**必然中止**，用户只能永远 `--跳过检查`
///       ⇒ 发布前质量门形同虚设（由用例 `智语言客户端_发布前检查与封装选项测试.js` 复现）。
///   现在：项目内 ⇒ 递归扫 `源码/` + `测试/`；项目外 ⇒ 保持旧行为（cwd 根 + cwd/测试，不越界）。
fn 扫描智文件() -> Vec<String> {
    use pm::项目检测;
    let mut 文件列表 = Vec::new();
    match 项目检测::检测当前目录项目归属() {
        项目检测::项目归属::项目内(根) => {
            for 子目录 in ["源码", "测试"] {
                递归收集智文件(&根.join(子目录), &mut 文件列表, usize::MAX);
            }
        }
        项目检测::项目归属::项目外 => {
            // 项目外：当前目录 + 一层子目录（等效旧行为「cwd 根 + cwd/测试」）
            递归收集智文件(&PathBuf::from("."), &mut 文件列表, 2);
        }
    }
    文件列表
}

/// 递归收集 `.智` 文件（跳过产出/依赖等非源码目录；`剩余层数` 限制递归深度，`usize::MAX` = 不限）
fn 递归收集智文件(目录: &std::path::Path, 输出: &mut Vec<String>, 剩余层数: usize) {
    const 跳过目录: [&str; 6] = ["产出", "库", "外部语言", ".智语言", "配置", "node_modules"];
    if let Some(名) = 目录.file_name().and_then(|n| n.to_str()) {
        if 跳过目录.contains(&名) {
            return;
        }
    }
    if let Ok(条目) = std::fs::read_dir(目录) {
        for 条目 in 条目.flatten() {
            let 路径 = 条目.path();
            if 路径.is_dir() {
                if 剩余层数 > 1 {
                    递归收集智文件(&路径, 输出, 剩余层数 - 1);
                }
            } else if 路径.extension().map_or(false, |e| e == "智") {
                if let Some(名称) = 路径.to_str() {
                    输出.push(名称.to_string());
                }
            }
        }
    }
}
