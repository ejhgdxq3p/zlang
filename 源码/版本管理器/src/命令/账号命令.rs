// 文件: 版本管理器/src/命令/账号命令.rs
// 职责: `智语言 账号 注册/登录/登出/状态` —— 库镜像源的账号与本地会话凭据管理
//
// 背景（此前是缺口）：
//   《库镜像源服务端系统设计》§8 列出了 `智语言 账号 注册/登录/登出`，但 CLI **没有这三个入口**
//   （实测报「未知命令: 账号」）；客户端的 登录/注册 函数虽已实现却只在 库 发布 内部自动调用，
//   且**从不保存令牌** ⇒ 每次发布都重新登录（§4.2 要求的 `凭据.配置` 此前完全不存在）。
//   本文件把三者接到 CLI，并把登录得到的会话令牌落盘到 `<全局目录>/配置/凭据.配置`。
//
// 安全约定：
//   · **不保存密码**，只保存服务端签发的会话令牌；POSIX 下文件权限 600。
//   · 令牌来源优先级（见 镜像源客户端::获取发布令牌）：`智语言_库令牌` > `智语言_库用户名/密码(+邮箱)`
//     > 本地凭据文件 ⇒ 设置了环境变量时**完全忽略**本地文件（CI/自动化可控）。
//   · **没有任何凭据时直接拒绝发布**：客户端不再内置默认发布账号（2026-11-16 安全修复，见
//     镜像源客户端::获取发布令牌 的注释）。
//   · 建议用环境变量 `智语言_库密码` 传密码，避免密码留在命令历史里。
use libmgr::{凭据, 镜像源客户端};

pub fn 执行(参数: &[String]) {
    let 子命令 = 参数.first().map(|s| s.as_str()).unwrap_or("");
    match 子命令 {
        "注册" => 执行注册(&参数[1..]),
        "登录" => 执行登录(&参数[1..]),
        "登出" => 执行登出(),
        "状态" => 执行状态(),
        "" | "-h" | "--help" | "帮助" => 打印帮助(),
        其他 => eprintln!("[智语言] 错误：未知账号子命令: {}。可用: 注册, 登录, 登出, 状态", 其他),
    }
}

/// 取位置参数或 `--键=值` 形式的长选项
fn 取参数(参数: &[String], 位置序号: usize, 长名: &str) -> Option<String> {
    let 前缀 = format!("--{}", 长名);
    for 项 in 参数 {
        if let Some(值) = 项.strip_prefix(&format!("{}=", 前缀)) {
            return Some(值.to_string());
        }
    }
    参数.get(位置序号).cloned()
}

fn 执行注册(参数: &[String]) {
    let 用户名 = 取参数(参数, 0, "用户名");
    let 密码 = 取参数(参数, 1, "密码").or_else(|| std::env::var("智语言_库密码").ok());
    let 邮箱 = 取参数(参数, 2, "邮箱");
    let (用户名, 密码, 邮箱) = match (用户名, 密码, 邮箱) {
        (Some(u), Some(p), Some(e)) if !u.trim().is_empty() => (u, p, e),
        _ => {
            eprintln!("用法: 智语言 账号 注册 <用户名> <密码> <邮箱>");
            eprintln!("  也可写成: 智语言 账号 注册 --用户名=X --密码=Y --邮箱=Z");
            eprintln!("  密码建议用环境变量 智语言_库密码 传入，避免留在命令历史里");
            return;
        }
    };
    eprintln!("[智语言] 正在向镜像源注册 {} …", 用户名);
    match 镜像源客户端::注册(&用户名, &密码, &邮箱) {
        Ok(()) => {
            eprintln!("[智语言] 注册成功并已自动激活");
            eprintln!("[智语言] 下一步: 智语言 账号 登录 {}  <密码>", 用户名);
        }
        Err(e) => eprintln!("[智语言] 注册失败: {}", e),
    }
}

fn 执行登录(参数: &[String]) {
    let 用户名 = 取参数(参数, 0, "用户名");
    let 密码 = 取参数(参数, 1, "密码").or_else(|| std::env::var("智语言_库密码").ok());
    let (用户名, 密码) = match (用户名, 密码) {
        (Some(u), Some(p)) if !u.trim().is_empty() => (u, p),
        _ => {
            eprintln!("用法: 智语言 账号 登录 <用户名> <密码>");
            eprintln!("  密码建议用环境变量 智语言_库密码 传入，避免留在命令历史里");
            return;
        }
    };
    match 镜像源客户端::登录(&用户名, &密码) {
        Ok(结果) => {
            match 凭据::保存(&用户名, &结果.令牌, 结果.过期时间) {
                Ok(()) => {
                    eprintln!("[智语言] 登录成功: {}", 用户名);
                    if 结果.过期时间 > 0 {
                        eprintln!("[智语言] 令牌有效期至: {}（Unix 秒）", 结果.过期时间);
                    }
                    eprintln!("[智语言] 凭据已保存: {}", 凭据::凭据路径().display());
                }
                Err(e) => eprintln!("[智语言] 登录成功，但保存凭据失败: {}", e),
            }
        }
        Err(e) => eprintln!("[智语言] 登录失败: {}", e),
    }
}

fn 执行登出() {
    match 镜像源客户端::登出当前() {
        Ok(账号) => {
            eprintln!("[智语言] 已登出: {}", 账号);
            eprintln!("[智语言] 本地凭据已删除: {}", 凭据::凭据路径().display());
        }
        Err(e) => eprintln!("[智语言] 登出失败: {}", e),
    }
}

fn 执行状态() {
    println!("凭据文件: {}", 凭据::凭据路径().display());
    match 镜像源客户端::当前凭据状态() {
        Some((用户名, 过期时间, 有效)) => {
            println!("已保存账号: {}", if 用户名.is_empty() { "(未记录)" } else { &用户名 });
            println!("令牌过期时间: {}（Unix 秒）", 过期时间);
            println!("状态: {}", if 有效 { "有效" } else { "已过期，请重新登录" });
        }
        None => println!("状态: 本地没有已保存的登录凭据（发布前请先 `智语言 账号 登录` 或设置 智语言_库令牌；不会自动登录）"),
    }
}

