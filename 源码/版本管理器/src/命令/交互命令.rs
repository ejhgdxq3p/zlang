/// 一次编译的结果
enum 编译结果 {
    成功(Vec<u8>),
    /// 输入还没写完（块未闭合），应继续读下一行
    未完,
    /// 真正的错误；诊断文本留待调用方决定是否打印
    出错(Vec<String>),
}

/// 把一段完整源码编译成字节码（词法 → 语法 → 语义 → 降级 → 字节码）。
fn 编译(源码: &str, 文件路径: &str) -> 编译结果 {
    let mut 诊断 = 诊断收集器::新建();
    frontend::诊断全局::设置诊断模式_自CLI(&mut 诊断);
    let 词条列表 = 词法分析器::新建(源码, 文件路径.to_string(), &mut 诊断).扫描所有词条();
    if 诊断.有错误() { return 编译结果::出错(诊断.输出所有诊断()); }
    let mut 程序 = 语法分析器::新建(&词条列表, &mut 诊断).解析程序();
    if 诊断.有错误() {
        let 文本 = 诊断.输出所有诊断();
        // 语法分析器在块未闭合时报「实际得到【文件结束】」：据此判断是否需要续行
        if 文本.iter().any(|行| 行.contains("文件结束")) { return 编译结果::未完; }
        return 编译结果::出错(文本);
    }
    let 高层表示模块 = match 语义分析器::新建(&mut 诊断).分析程序(&mut 程序) {
        Ok(m) => m,
        Err(_) => return 编译结果::出错(诊断.输出所有诊断()),
    };
    if 诊断.有错误() { return 编译结果::出错(诊断.输出所有诊断()); }
    let 底层表示模块 = 公共降级::降级转换(&高层表示模块);
    match 字节码生成器::新建().生成(&底层表示模块) {
        Ok(b) => 编译结果::成功(b),
        Err(e) => 编译结果::出错(vec![format!("[智语言] 字节码生成失败: {}", e)]),
    }
}

/// 在**全新的虚拟机**里执行一段字节码。
/// 旧实现把每行的字节码追加加载进同一个虚拟机：常量池/函数表只增不清，而上一行的字节码缓冲
/// 已被释放 ⇒ 第二行起执行的是上一行的代码，文本常量指向已释放内存。
fn 运行(字节码: &[u8]) {
    let mut 虚拟机 = 虚拟机::新建();
    虚拟机.最大步数 = u64::MAX;
    虚拟机.加载字节码(字节码);
    // 上一次输入若以未捕获异常结束，清掉残留标志，不让它影响这一次
    base::异常运行时::顶层未捕获异常_清();
    虚拟机.执行();
    let _ = base::异常运行时::顶层未捕获异常_取并清();
    let _ = io::stdout().flush();
}

fn 打印(诊断文本: &[String]) {
    for 行 in 诊断文本 { eprintln!("{}", 行); }
}

/// 交互模式的工作方式：
///   · **定义**（函数、结构体、导入、模块级变量……凡是能单独作为顶层代码的输入）记入「定义区」，
///     之后每次执行都带上它们；
///   · **语句**（如 `输出("甲")`）包进一个临时的 `启动程序` 里，连同定义区一起编译并执行一次；
///   · 输入完整的 `启动程序(): … 结束` 则连同定义区执行一次，不记入定义区；
///   · 块没写完（缺 `结束`）时自动续行，续行时输入空行放弃本次输入。
/// 每次执行都从头开始：模块级变量每次按初值重新计算，语句里对它们的修改不带到下一次输入。
pub fn 执行(_参数: &[String]) {
    eprintln!("智语言 交互模式（输入 .退出 结束，.帮助 查看说明）");

    let mut 定义区 = String::new();
    let mut 序号 = 1u64;
    // 交互模式临时缓存目录（退出时自动清理）
    let 临时缓存 = 目录::全局字节码目录().join("交互");

    'outer: loop {
        print!("> ");
        if io::stdout().flush().is_err() { break; }
        let mut 行 = String::new();
        match io::stdin().read_line(&mut 行) {
            Ok(0) | Err(_) => break,
            Ok(_) => {}
        }
        let 首行 = 行.trim().to_string();
        if 首行.is_empty() { continue; }

        if 首行.starts_with('.') {
            match 首行.as_str() {
                ".退出" | ".quit" | ".q" => break,
                ".帮助" | ".help" | ".h" => {
                    eprintln!("直接输入语句立即执行；输入函数/结构体/导入/模块级变量等定义会被记住。");
                    eprintln!("块没写完时自动续行（续行中输入空行放弃）。访问模块级变量请写 本模块.名称。");
                    eprintln!("特殊命令:");
                    eprintln!("  .退出, .quit, .q    退出交互控制台");
                    eprintln!("  .帮助, .help, .h    显示此帮助");
                    eprintln!("  .定义, .defs        查看已记住的定义");
                    eprintln!("  .清空, .clear       清空已记住的定义");
                }
                ".定义" | ".defs" => {
                    if 定义区.is_empty() { eprintln!("（尚无定义）"); } else { eprint!("{}", 定义区); }
                }
                ".清空" | ".clear" => {
                    定义区.clear();
                    eprintln!("状态已清空");
                }
                _ => eprintln!("未知命令: {}。输入 '.帮助' 查看可用命令。", 首行),
            }
            continue;
        }

        let 文件路径 = format!("<交互#{}>", 序号);
        序号 += 1;
        let mut 输入 = 行.trim_end().to_string();

        loop {
            // ① 当作顶层定义
            let 作定义 = format!("{}{}\n", 定义区, 输入);
            let 定义结果 = 编译(&作定义, &文件路径);
            if let 编译结果::成功(字节码) = &定义结果 {
                if 输入.trim_start().starts_with("启动程序(") {
                    运行(字节码);
                } else {
                    定义区 = 作定义;
                }
                continue 'outer;
            }
            // ② 当作语句：包进临时入口
            let 作语句 = format!("{}启动程序():\n{}\n结束\n", 定义区, 输入);
            let 语句结果 = 编译(&作语句, &文件路径);
            if let 编译结果::成功(字节码) = &语句结果 {
                运行(字节码);
                continue 'outer;
            }
            // ③ 两种读法都不成立：未写完则续行，否则报错
            // 顶层读法的「未完」只在首行以冒号开块时才可信：`输出(某名)` 这类语句按顶层去读
            // 同样会报到文件结束，但它其实是一条完整（只是有错）的语句，不该等续行。
            let 首行开块 = 输入.lines().next().map(|首| 首.trim_end().ends_with(':') || 首.trim_end().ends_with('：')).unwrap_or(false);
            let 需续行 = matches!(语句结果, 编译结果::未完)
                || (matches!(定义结果, 编译结果::未完) && 首行开块);
            if !需续行 {
                // 输入本身像顶层定义（能通过语法）时报定义的错，否则报语句的错
                match (&定义结果, &语句结果) {
                    (_, 编译结果::出错(文本)) if 输入.trim_end().ends_with(')') || !matches!(定义结果, 编译结果::出错(_)) => 打印(文本),
                    (编译结果::出错(文本), _) => 打印(文本),
                    (_, 编译结果::出错(文本)) => 打印(文本),
                    _ => {}
                }
                continue 'outer;
            }
            print!("… ");
            if io::stdout().flush().is_err() { break 'outer; }
            let mut 续 = String::new();
            match io::stdin().read_line(&mut 续) {
                Ok(0) | Err(_) => break 'outer,
                Ok(_) => {}
            }
            if 续.trim().is_empty() {
                eprintln!("（已放弃本次输入）");
                continue 'outer;
            }
            输入.push('\n');
            输入.push_str(续.trim_end());
        }
    }

    // 退出前自动清理临时缓存
    if 临时缓存.exists() {
        let _ = std::fs::remove_dir_all(&临时缓存);
    }
    eprintln!("[智语言] 已退出");
}
