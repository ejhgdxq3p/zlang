// 文件: 版本管理器/src/命令/清理命令.rs
// 职责: 薄 CLI 壳 — 解析参数 → 检测项目 → 调用 pm::清理 → 执行 I/O 删除 + 打印

use crate::参数解析;
use pm::{目录, 项目检测, 项目检测::项目归属, 清理};
use std::fs;
use std::path::PathBuf;

/// 解析清理参数，返回要清理的子目录列表（CLI flag → 子目录名映射）
fn 解析清理目标(参数: &[String]) -> Vec<&'static str> {
    if 参数.is_empty() || 参数.iter().all(|p| p == "--预览") {
        return vec![]; // 空 = 清理全部
    }
    let mut 目标 = Vec::new();
    for p in 参数 {
        match p.as_str() {
            "--字节码文件" => 目标.push("字节码文件"),
            "--编译文件" => 目标.push("编译文件"),
            "--执行文件" => 目标.push("执行文件"),
            "--库中间文件" => 目标.push("库中间文件"),
            "--留库中间文件" => {
                目标.push("字节码文件");
                目标.push("编译文件");
                目标.push("执行文件");
            }
            "--外部语言文件" => 目标.push("外部语言文件"),
            "--留外部语言文件" => {
                目标.push("字节码文件");
                目标.push("编译文件");
                目标.push("执行文件");
                目标.push("库中间文件");
            }
            "--导出文件" => 目标.push("导出文件"),
            "--留导出文件" => {
                目标.push("字节码文件");
                目标.push("编译文件");
                目标.push("执行文件");
                目标.push("库中间文件");
                目标.push("外部语言文件");
            }
            "--封装文件" => 目标.push("封装文件"),
            "--留封装文件" => {
                目标.push("字节码文件");
                目标.push("编译文件");
                目标.push("执行文件");
                目标.push("库中间文件");
                目标.push("外部语言文件");
                目标.push("导出文件");
            }
            _ => {}
        }
    }
    目标
}

/// 清理项目：删除项目根目录下的 产出/ 子目录（需在项目内）
pub fn 执行清理项目(参数: &[String]) {
    let 是否预览 = 参数解析::有标志(参数, "--预览");
    let 目标子目录 = 解析清理目标(参数);

    match 项目检测::检测当前目录项目归属() {
        项目归属::项目内(根目录) => {
            let 产出目录 = 根目录.join("产出");
            let 绝对路径 = 根目录.canonicalize().unwrap_or(根目录.clone());

            if !产出目录.exists() {
                eprintln!("[智语言] 无需清理：项目根目录没有产出/目录");
                return;
            }

            let 路径列表 = 清理::要清理的路径(&产出目录, &目标子目录);
            for 路径 in &路径列表 {
                清理单路径(路径, &绝对路径, "产出/", 是否预览);
            }
        }
        项目归属::项目外 => {
            eprintln!("[智语言] 错误：当前目录不是项目根目录，无法执行清理项目");
        }
    }
}

/// 清理全局：删除全局缓存目录下的 产出/ 子目录
pub fn 执行清理全局(参数: &[String]) {
    let 是否预览 = 参数解析::有标志(参数, "--预览");
    let 目标子目录 = 解析清理目标(参数);
    let 全局缓存 = 目录::全局目录();
    let 产出目录 = 全局缓存.join("产出");

    if !产出目录.exists() {
        eprintln!("[智语言] 无需清理：全局缓存没有产出/目录");
        return;
    }

    let 路径列表 = 清理::要清理的路径(&产出目录, &目标子目录);
    for 路径 in &路径列表 {
        清理单路径(路径, &全局缓存, "产出/", 是否预览);
    }
}

// 私有辅助：执行 I/O 删除 + 打印（留在 CLI 层，非工程管理决策）
fn 清理单路径(目标: &PathBuf, _基准: &PathBuf, _标签: &str, 是否预览: bool) {
    if !目标.exists() {
        eprintln!("[智语言] 无需清理：{}", 目标.display());
        return;
    }

    if 是否预览 {
        let (文件数, 总大小) = 清理::统计目录(目标);
        eprintln!("[智语言] 将清理 {}（{}，{} 文件）",
            目标.display(), 清理::格式化大小(总大小), 文件数);
    } else {
        match fs::remove_dir_all(目标) {
            Ok(()) => eprintln!("[智语言] 已清理：{}", 目标.display()),
            Err(e) => {
                eprintln!("[智语言] 已清理：{}", 目标.display());
                eprintln!("[智语言] 部分文件清理失败: {}", e);
            }
        }
    }
}
