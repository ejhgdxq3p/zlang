// 文件: 版本管理器/src/命令/命名校验.rs
// 职责: 规范 §3.7.4「单文件路径：文件加载前置校验」——校验命令行给出的源文件路径命名。
//
// 双模式说明：纯静态前置检查，发生在「读取/分析源码之前」，解释模式与编译模式走同一条命令入口，
//   判定完全一致（不产生任何后端差异）。

use std::path::Path;

/// 校验命令行给出的源文件路径（§3.7.2 字符集：中文简繁汉字 + 半角数字 + 下划线 + 点）。
///
/// 返回 `true` = 通过；`false` = 已输出诊断，调用方应**直接返回**（不继续读取/分析）。
///
/// 口径：文件属于某项目 ⇒ 校验相对项目根的每一段；项目外（用户环境路径）⇒ 只校验文件名本身。
/// 详见 `pm::命名规范::检查入口文件路径`。
pub fn 校验源文件路径(文件路径: &str) -> bool {
    let 违规列表 = pm::命名规范::检查入口文件路径(Path::new(文件路径));
    if 违规列表.is_empty() {
        return true;
    }
    for 违规 in &违规列表 {
        // 输出格式对齐规范 §3.7.4 错误输出示例
        eprintln!("[智语言] 错误：{}", 违规.描述());
        eprintln!("帮助：{}", 违规.帮助());
    }
    false
}
