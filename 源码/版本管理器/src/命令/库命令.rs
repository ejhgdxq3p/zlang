/// 卸载库，支持 --全局 选项
fn 执行卸载(安装器实例: &库安装器::安装器, 子参数: &[String]) {
    let 模式 = 提取操作模式(子参数);
    let 有效参数 = 过滤选项(子参数);

    let 库名 = match 有效参数.get(0) {
        Some(n) => n.as_str(),
        None => {
            eprintln!("[智语言] 错误：请指定要卸载的库名");
            return;
        }
    };

    match 模式 {
        操作模式::全局级 => {
            if let Err(e) = 安装器实例.卸载_全局(库名) {
                eprintln!("[智语言] 全局卸载失败: {}", e);
            } else {
                eprintln!("[智语言] 已卸载全局库：{}", 库名);
            }
        }
        操作模式::项目级 => {
            if let Err(e) = 安装器实例.卸载(库名) {
                eprintln!("[智语言] 卸载失败: {}", e);
            } else {
                eprintln!("[智语言] 已卸载：{}", 库名);
            }
        }
        操作模式::按锁文件 => {
            // 按锁文件路径卸载
            if let Some((_版本, 路径)) = 安装器实例.读取锁条目和路径(库名) {
                if 路径.starts_with(".智语言/") {
                    执行卸载(安装器实例, &[库名.to_string(), "--全局".to_string()]);
                } else {
                    执行卸载(安装器实例, &[库名.to_string(), "--项目".to_string()]);
                }
            } else {
                eprintln!("[智语言] 错误：库 '{}' 不在锁文件中。请使用 --项目 或 --全局 指定位置", 库名);
            }
        }
    }
}

