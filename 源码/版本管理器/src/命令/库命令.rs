/// 列出当前项目已安装的库（从 项目依赖.配置 读取）
fn 执行已安装(项目目录: &PathBuf) {
    let 锁路径 = 项目目录.join("配置/项目依赖.配置");
    if !锁路径.exists() {
        eprintln!("[智语言] 暂无已安装的依赖库");
        return;
    }
    let 内容 = match std::fs::read_to_string(&锁路径) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("[智语言] 读取依赖锁文件失败: {}", e);
            return;
        }
    };
    let 文档 = 配置读取器::解析配置(&内容);
    if 文档.段.is_empty() {
        eprintln!("[智语言] 暂无已安装的依赖库");
        return;
    }
    eprintln!("[智语言] 已安装的库：");
    for 段 in &文档.段 {
        let 版本 = 配置读取器::取文本(段, "版本").unwrap_or_else(|| "?".into());
        let 路径 = 配置读取器::取文本(段, "路径").unwrap_or_default();
        let 类型标记 = if 路径.starts_with(".智语言/") { "[全局]" } else { "[项目]" };
        eprintln!("  {} {}    {}", 段.段名, 版本, 类型标记);
    }
}

/// 列出全局已安装的库（扫描 全局目录/库/）
fn 执行全局已安装() {
    let 全局库根 = pm::目录::全局库根();
    if !全局库根.exists() {
        eprintln!("[智语言] 暂无全局安装的库");
        return;
    }
    let 条目 = match std::fs::read_dir(&全局库根) {
        Ok(e) => e,
        Err(_) => {
            eprintln!("[智语言] 暂无全局安装的库");
            return;
        }
    };
    let mut 库列表: Vec<String> = Vec::new();
    for 条目 in 条目.flatten() {
        let 路径 = 条目.path();
        if 路径.is_dir() {
            if let Some(目录名) = 路径.file_name().and_then(|n| n.to_str()) {
                库列表.push(目录名.to_string());
            }
        }
    }
    if 库列表.is_empty() {
        eprintln!("[智语言] 暂无全局安装的库");
    } else {
        eprintln!("[智语言] 全局已安装的库：");
        for 库 in &库列表 {
            eprintln!("  {}", 库);
        }
    }
}

/// 以树形结构展示依赖关系
fn 执行查看依赖(项目目录: &PathBuf) {
    let 锁路径 = 项目目录.join("配置/项目依赖.配置");
    let 项目名 = 项目目录
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("项目");
    println!("{}", 项目名);
    if !锁路径.exists() {
        println!("  (无依赖)");
        return;
    }
    let 内容 = match std::fs::read_to_string(&锁路径) {
        Ok(c) => c,
        Err(_) => {
            println!("  (无依赖)");
            return;
        }
    };
    let 文档 = 配置读取器::解析配置(&内容);
    if 文档.段.is_empty() {
        println!("  (无依赖)");
        return;
    }
    let 条目数 = 文档.段.len();
    for (i, 段) in 文档.段.iter().enumerate() {
        let 版本 = 配置读取器::取文本(段, "版本").unwrap_or_else(|| "?".into());
        let 前缀 = if i + 1 == 条目数 { "└──" } else { "├──" };
        println!("{} {} {}", 前缀, 段.段名, 版本);
    }
}

/// 解析库名与可选版本：支持「库名@版本」与「库名 + 显式版本」两种形式
fn 解析库版本约束(原始: String, 显式: Option<String>) -> (String, Option<String>) {
    if let Some(位置) = 原始.find('@') {
        let 名 = 原始[..位置].to_string();
        let 版本 = Some(原始[位置 + 1..].to_string());
        (名, 版本)
    } else {
        (原始, 显式)
    }
}
