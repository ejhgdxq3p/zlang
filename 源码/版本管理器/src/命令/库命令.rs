/// 更新库，支持 --全局 选项
/// 更新决策只读 项目.配置：查 管理方式/版本约束 → 判断能不能更新、去哪更新
fn 执行更新(安装器实例: &库安装器::安装器, 子参数: &[String]) {
    let 模式 = 提取操作模式(子参数);
    let 有效参数 = 过滤选项(子参数);

    if let Some(库名) = 有效参数.get(0) {
        let (请求名, 显式版本) = 解析库版本约束(库名.to_string(), 有效参数.get(1).map(|s| s.to_string()));
        // 代号 → 原始名（从 项目.配置 声明解析；全局模式或未声明时用原名）
        let 原始名 = 读取项目依赖()
            .ok()
            .and_then(|列表| 列表.into_iter().find(|e| e.代号 == 请求名).map(|e| e.原始名))
            .unwrap_or_else(|| 请求名.clone());
        let 解析名 = 原始名;

        // 更新决策（仅按锁文件/项目级模式需要）：只读 项目.配置 判断能否自动更新（规范 6.2.3）
        // 锁文件只记录安装结果，不参与决策——手动管理判断完全由 项目.配置 声明驱动。
        if 模式 != 操作模式::全局级 {
            if 显式版本.is_none() {
                if let Ok(列表) = 读取项目依赖() {
                    if let Some(条目) = 列表.iter().find(|e| e.原始名 == 解析名 || e.代号 == 请求名) {
                        if 条目.管理方式 == "手动" || 条目.类型 == 依赖类型::外部语言 {
                            eprintln!("[智语言] 跳过 {}：手动管理依赖。如需升级请更新 项目.配置 中路径后重新安装", 解析名);
                            return;
                        }
                    }
                }
            }
        }

        let 版本 = 显式版本.as_deref();
        match 模式 {
            操作模式::全局级 => {
                if let Err(e) = 安装器实例.更新_全局(&解析名, 版本) {
                    eprintln!("[智语言] 全局更新失败: {}", e);
                } else {
                    eprintln!("[智语言] 已更新全局库：{}", 解析名);
                }
            }
            操作模式::项目级 | 操作模式::按锁文件 => {
                if let Err(e) = 安装器实例.更新(&解析名, 版本) {
                    eprintln!("[智语言] 更新失败: {}", e);
                } else {
                    eprintln!("[智语言] 已更新：{}", 解析名);
                }
            }
        }
    } else {
        // 无参数：更新全部依赖
        match 尝试更新全部依赖(安装器实例) {
            Ok(已更新数) => {
                if 已更新数 == 0 {
                    eprintln!("[智语言] 没有找到需要更新的依赖。");
                } else {
                    eprintln!("[智语言] 全部依赖更新完成 ({} 个)", 已更新数);
                }
            }
            Err(e) => eprintln!("[智语言] 错误：{}", e),
        }
    }
}

