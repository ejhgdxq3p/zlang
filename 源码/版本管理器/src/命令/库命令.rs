/// 安装库，支持 --项目/--全局 选项
/// 无参数：批量安装项目依赖
/// 有参数：安装指定库
fn 执行安装(安装器实例: &库安装器::安装器, 子参数: &[String]) {
    let 模式 = 提取操作模式(子参数);
    let 有效参数 = 过滤选项(子参数);

    if 有效参数.is_empty() {
        // 无参数：尝试安装全部依赖
        match 尝试安装全部依赖(安装器实例) {
            Ok(已安装数) => {
                if 已安装数 == 0 {
                    eprintln!("[智语言] 没有找到需要安装的依赖。");
                } else {
                    eprintln!("[智语言] 全部依赖安装完成 ({} 个)", 已安装数);
                }
            }
            Err(e) => eprintln!("[智语言] 错误：{}", e),
        }
        return;
    }

    let 库标识 = 有效参数[0];
    let 尾部版本 = 有效参数.get(1).map(|s| s.as_str());
    按模式安装(安装器实例, 库标识, 尾部版本, 模式);
}

/// 按模式安装库
fn 按模式安装(安装器实例: &库安装器::安装器, 库标识: &str, 尾部版本: Option<&str>, 模式: 操作模式) {
    // 支持「库名@版本号」格式
    let (库名, 版本号) = if let Some(at位置) = 库标识.find('@') {
        (库标识[..at位置].to_string(), Some(库标识[at位置 + 1..].to_string()))
    } else {
        (库标识.to_string(), 尾部版本.map(|s| s.to_string()))
    };
    // 代号 → 原始名 + 声明的版本约束（从 项目.配置 读取；未声明时用原名 / 无约束）
    let 声明 = 读取项目依赖()
        .ok()
        .and_then(|列表| 列表.into_iter().find(|e| e.代号 == 库名 || e.原始名 == 库名));
    let 原始名 = 声明.as_ref().map(|e| e.原始名.clone()).unwrap_or_else(|| 库名.clone());
    // ⚠ 2026-10-03 修复（规范 §6.3.3 表：「智语言 库 安装 <库名>」= **读取 项目.配置 中该库的声明，
    //   安装指定库的最新**兼容**版本）：
    //   原先未显式给版本时直接传 None ⇒ 下层 `安装(名, None)` 回退约束 ">= 0.0.0" ⇒ 选**全局最新**，
    //   **越过** 项目.配置 声明的约束（实测：声明 `>= 1.0.0, < 2.0.0`，`库 安装 <名>` 却装到 2.0.0）✗。
    //   ⇒ 未显式给版本时改用声明的版本约束（与无参 `库 安装` / `库 更新` 口径一致）。
    let 版本 = 版本号.clone().or_else(|| 声明.as_ref().and_then(|e| e.版本约束.clone()));
    let 版本 = 版本.as_deref();

    match 模式 {
        操作模式::项目级 => {
            if let Err(e) = 安装器实例.安装(&原始名, 版本) {
                eprintln!("[智语言] 安装失败: {}", e);
            } else if let Some(v) = 版本号.as_deref() {
                eprintln!("[智语言] 已安装：{} {}", 库名, v);
            } else {
                eprintln!("[智语言] 已安装：{}", 库名);
            }
        }
        操作模式::全局级 => {
            if let Err(e) = 安装器实例.安装_全局(&原始名, 版本) {
                eprintln!("[智语言] 全局安装失败: {}", e);
            } else {
                eprintln!("[智语言] 已安装全局库：{}", 库名);
            }
        }
        操作模式::按锁文件 => {
            // 查锁文件：若有路径则按路径执行，否则默认项目级
            if let Some((_版本, 路径)) = 安装器实例.读取锁条目和路径(&原始名) {
                if 路径.starts_with(".智语言/") {
                    // 原为全局级 → 继续全局
                    按模式安装(安装器实例, &库名, 尾部版本, 操作模式::全局级)
                } else {
                    按模式安装(安装器实例, &库名, 尾部版本, 操作模式::项目级)
                }
            } else {
                // 库不在锁文件中 → 默认项目级
                按模式安装(安装器实例, &库名, 尾部版本, 操作模式::项目级)
            }
        }
    }
}

