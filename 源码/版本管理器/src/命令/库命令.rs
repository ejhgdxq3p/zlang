/// 安装/卸载/更新 模式：不加选项则按锁文件路径，显式指定则强制对应位置
#[derive(Clone, Copy, PartialEq)]
enum 操作模式 {
    按锁文件,
    项目级,  // --项目
    全局级,  // --全局
}

pub fn 执行(参数: &[String]) {
    if 参数.is_empty() {
        eprintln!("[智语言] 错误：用法: 智语言 库 <子命令> [参数]");
        eprintln!("子命令: 安装, 卸载, 更新, 搜索, 信息, 封装, 发布, 弃用, 初始化, 已安装, 查看依赖");
        eprintln!("选项: --项目 (强制项目级), --全局 (强制全局级)");
        return;
    }

    let 子命令 = &参数[0];
    let 子参数 = &参数[1..];

    // 检测项目根（向上查找 配置/项目.配置），全局命令（搜索/信息）也兼容项目外
    let 项目目录 = match 项目检测::检测当前目录项目归属() {
        项目检测::项目归属::项目内(根) => 根,
        项目检测::项目归属::项目外 => {
            let 回退 = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
            回退
        }
    };
    let 安装器实例 = 库安装器::安装器::新建(项目目录.clone());

    match 子命令.as_str() {
        "安装" => 执行安装(&安装器实例, 子参数),
        "卸载" => 执行卸载(&安装器实例, 子参数),
        "更新" => 执行更新(&安装器实例, 子参数),
        "搜索" => {
            if let Some(关键词) = 子参数.get(0) {
                // 如实区分「查询失败（网络/服务端）」与「无匹配结果」（此前网络失败被吞成"未找到"✗）
                match 镜像源客户端::搜索(关键词) {
                    Ok(结果) => {
                        if 结果.is_empty() {
                            eprintln!("[智语言] 未找到匹配的库");
                        } else {
                            println!("找到 {} 个相关库：", 结果.len());
                            for 项 in &结果 {
                                println!("{} {} {} {}", 项.名称, 项.版本, 项.许可证, 项.描述);
                            }
                        }
                    }
                    Err(e) => eprintln!("[智语言] 搜索失败: {}", e),
                }
            } else {
                eprintln!("[智语言] 错误：请指定搜索关键词");
            }
        }
        "信息" => {
            if let Some(库名) = 子参数.get(0) {
                match 镜像源客户端::查询库信息(库名) {
                    Ok(信息) => {
                        println!("{} 可用版本:", 库名);
                        if !信息.版本.is_empty() {
                            for 版本 in &信息.版本 {
                                println!("  - {}", 版本);
                            }
                        }
                        if !信息.描述.is_empty() {
                            println!("描述: {}", 信息.描述);
                        }
                        if !信息.许可证.is_empty() {
                            println!("许可证: {}", 信息.许可证);
                        }
                        // 弃用状态：库作者标记弃用的版本要明确提示，避免新用户误装
                        for d in &信息.弃用 {
                            if d.是否弃用 {
                                eprintln!("[智语言] 警告：版本 {} 已弃用", d.版本号);
                                if !d.替代库.is_empty() {
                                    eprintln!("[智语言]   替代库：{}", d.替代库);
                                }
                                if !d.弃用提示.is_empty() {
                                    eprintln!("[智语言]   弃用提示：{}", d.弃用提示);
                                }
                            }
                        }
                    }
                    Err(e) => eprintln!("[智语言] 错误：{}", e),
                }
                if let Some((名称, 类型, 版本)) = 安装器实例.查询库元数据(库名) {
                    println!("已安装元数据：");
                    println!("  名称: {}", 名称);
                    if !版本.is_empty() {
                        println!("  版本: {}", 版本);
                    }
                    if !类型.is_empty() {
                        println!("  类型: {}", 类型);
                    }
                }
            } else {
                eprintln!("[智语言] 错误：请指定库名");
            }
        }
        "封装" => {
            let 命令行含库 = 子参数.iter().any(|p| p == "--包含库");
            let 命令行含外部语言 = 子参数.iter().any(|p| p == "--包含外部语言");
            match 安装器实例.封装(&项目目录, 命令行含库, 命令行含外部语言) {
                Ok(库文件) => {
                    let 绝对路径 = 库文件.canonicalize().unwrap_or(库文件.clone());
                    eprintln!("[智语言] 封装完成：{}", 绝对路径.display());
                }
                Err(e) => eprintln!("[智语言] 封装失败: {}", e),
            }
        }
        "发布" => {
            let 跳过检查 = 子参数.iter().any(|p| p == "--跳过检查");
            if !跳过检查 {
                eprintln!("[智语言] 发布前执行检查与测试...");
                if !crate::质量命令::执行检查并返回(子参数) {
                    eprintln!("[智语言] 检查未通过，已中止发布");
                    std::process::exit(1);
                }
                let (_通过, 失败) = crate::测试命令::执行并返回(子参数);
                if 失败 > 0 {
                    eprintln!("[智语言] 发布前测试未通过（失败 {} 项），已中止发布", 失败);
                    std::process::exit(1);
                }
            }
            match 安装器实例.发布(&项目目录, 跳过检查) {
                Ok(()) => eprintln!("[智语言] 已发布"),
                // ⚠ 2026-11-16：发布失败必须**非零退出**，否则 CI/脚本会把"被拒绝发布"当成成功。
                //   （实测：无凭据时此前仍返回 0，脚本无从判定。）
                Err(e) => {
                    eprintln!("[智语言] 发布失败: {}", e);
                    std::process::exit(1);
                }
            }
        }
        "初始化" => {
            if let Some(库名) = 子参数.get(0) {
                执行初始化(库名);
            } else {
                eprintln!("[智语言] 错误：请指定要创建的库名。用法: 智语言 库 初始化 <库名>");
            }
        }
        "弃用" => {
            // 库作者标记已发布版本为弃用（服务端 POST /库/:名/:版本/弃用，需作者身份）
            // ⚠ 客户端函数 镜像源客户端::弃用版本 早已实现，此前**没有 CLI 入口** ⇒ 报「未知子命令: 弃用」
            let 长选项 = |名: &str| -> String {
                子参数.iter()
                    .find_map(|p| p.strip_prefix(&format!("--{}=", 名)))
                    .unwrap_or("")
                    .to_string()
            };
            match (子参数.get(0), 子参数.get(1)) {
                (Some(库名), Some(版本号)) => {
                    match 镜像源客户端::弃用版本(库名, 版本号, &长选项("替代库"), &长选项("提示信息")) {
                        Ok(()) => eprintln!("[智语言] 已标记弃用: {} {}", 库名, 版本号),
                        Err(e) => eprintln!("[智语言] 弃用失败: {}", e),
                    }
                }
                _ => eprintln!("用法: 智语言 库 弃用 <库名> <版本> [--替代库=名称] [--提示信息=文本]"),
            }
        }
        "已安装" => {
            let 查看全局 = 子参数.iter().any(|p| p == "--全局");
            if 查看全局 {
                执行全局已安装()
            } else {
                执行已安装(&项目目录)
            }
        }
        "查看依赖" => 执行查看依赖(&项目目录),
        _ => eprintln!("[智语言] 错误：未知子命令: {}。可用: 安装, 卸载, 更新, 搜索, 信息, 封装, 发布, 弃用, 初始化, 已安装, 查看依赖", 子命令),
    }
}

/// 从参数中提取 --项目/--全局 操作模式
fn 提取操作模式(参数: &[String]) -> 操作模式 {
    if 参数.iter().any(|p| p == "--全局") { 操作模式::全局级 }
    else if 参数.iter().any(|p| p == "--项目") { 操作模式::项目级 }
    else { 操作模式::按锁文件 }
}

/// 过滤掉 --项目/--全局 选项参数，保留库名等有效参数
fn 过滤选项(参数: &[String]) -> Vec<&String> {
    参数.iter().filter(|p| p.as_str() != "--项目" && p.as_str() != "--全局").collect()
}

