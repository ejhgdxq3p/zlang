/// 尝试安装项目的全部依赖（从 项目.配置 [运行/开发/构建依赖] 读取声明）
/// 按类型分流：智语言库 → 镜像源安装；远程 → 镜像源下载；外部语言（手动）→ 提示手动放置
fn 尝试安装全部依赖(安装器实例: &库安装器::安装器) -> Result<usize, String> {
    let 依赖列表 = 读取项目依赖()?;
    if 依赖列表.is_empty() {
        return Ok(0);
    }
    let mut 已安装 = 0usize;
    let 并发上限 = (pm::全局配置::读取配置().网络.并发下载数.max(1)) as usize;
    for 批次 in 依赖列表.chunks(并发上限) {
        for 条目 in 批次 {
            match 条目.类型 {
                依赖类型::外部语言 => {
                    // 外部语言（手动）：工具链不自动下载，提示手动放置
                    print!("  检查外部语言 {} ... ", 条目.代号);
                    // 路径是否已存在由 构建/运行 时校验，此处仅提示
                    println!("⏭️  手动管理（路径由 项目依赖.配置 或 外部语言/ 指定）");
                    已安装 += 1;
                }
                依赖类型::远程 | 依赖类型::智语言库 => {
                    print!("  安装 {} ... ", 条目.代号);
                    match 安装器实例.安装(&条目.原始名, 条目.版本约束.as_deref()) {
                        Ok(()) => {
                            println!("✅");
                            已安装 += 1;
                        }
                        Err(e) => {
                            println!("❌ {}", e);
                        }
                    }
                }
            }
        }
    }
    Ok(已安装)
}

/// 尝试更新项目的全部依赖
/// 更新决策只读 项目.配置：手动管理方式跳过；自动管理按约束更新
fn 尝试更新全部依赖(安装器实例: &库安装器::安装器) -> Result<usize, String> {
    let 依赖列表 = 读取项目依赖()?;
    if 依赖列表.is_empty() {
        return Ok(0);
    }
    let mut 已更新 = 0usize;
    for 条目 in &依赖列表 {
        // 更新决策：只读 项目.配置（管理方式）——锁文件只记录安装结果，不参与决策（规范 6.2.3）
        if 条目.管理方式 == "手动" || 条目.类型 == 依赖类型::外部语言 {
            println!("⏭️  已跳过 {}（手动管理）", 条目.代号);
            continue;
        }
        print!("  更新 {} ... ", 条目.代号);
        match 安装器实例.更新(&条目.原始名, 条目.版本约束.as_deref()) {
            Ok(()) => {
                println!("✅");
                已更新 += 1;
            }
            Err(e) => {
                println!("❌ {}", e);
            }
        }
    }
    Ok(已更新)
}

/// 依赖条目（从 项目.配置 声明解析出的统一结构）
struct 依赖条目 {
    /// 代号（代码中 `导入` 用的名字）
    代号: String,
    /// 原始名（镜像源真实库名）
    原始名: String,
    /// 版本约束
    版本约束: Option<String>,
    /// 管理方式："自动"/"手动"
    管理方式: String,
    /// 类型：智语言库/外部语言/远程
    类型: 依赖类型,
}

#[derive(Clone, Copy, PartialEq)]
enum 依赖类型 {
    智语言库,
    外部语言,
    远程,
}

/// 从 项目.配置 中读取依赖列表（扫描 [运行依赖]、[开发依赖]、[构建依赖] 三个段）
/// 支持规范 6.2.2 对象形式：`代号 = { 类型 = "...", 原始名 = "...", 版本 = "...", 管理方式 = "..." }`
/// 兼容旧形式：`库名 = "版本约束"`
fn 读取项目依赖() -> Result<Vec<依赖条目>, String> {
    let 配置路径 = match 项目检测::检测当前目录项目归属() {
        项目检测::项目归属::项目内(根) => 根.join("配置/项目.配置"),
        项目检测::项目归属::项目外 => PathBuf::from("配置/项目.配置"),
    };
    if !配置路径.exists() {
        return Ok(Vec::new());
    }
    let 文档 = 配置读取器::解析文件(&配置路径)?;
    let mut 依赖列表 = Vec::new();

    for 段名 in &["运行依赖", "开发依赖", "构建依赖"] {
        if let Some(段) = 配置读取器::取段(&文档, 段名) {
            for (键, 值) in &段.键值 {
                match 值 {
                    配置读取器::配置值::表(条目) => {
                        let 类型 = match 配置读取器::表取文本(条目, "类型").as_deref() {
                            Some("外部语言") => 依赖类型::外部语言,
                            Some("远程") => 依赖类型::远程,
                            _ => 依赖类型::智语言库,
                        };
                        let 原始名 = 配置读取器::表取文本(条目, "原始名").unwrap_or_else(|| 键.clone());
                        let 版本约束 = 配置读取器::表取文本(条目, "版本")
                            .filter(|v| !v.is_empty() && v != "*");
                        let 管理方式 = 配置读取器::表取文本(条目, "管理方式")
                            .unwrap_or_else(|| "自动".into());
                        依赖列表.push(依赖条目 {
                            代号: 键.clone(),
                            原始名,
                            版本约束,
                            管理方式,
                            类型,
                        });
                    }
                    配置读取器::配置值::文本(v) => {
                        // 旧形式：`库名 = "版本约束"`
                        let 版本约束 = if v.is_empty() || v == "*" { None } else { Some(v.clone()) };
                        依赖列表.push(依赖条目 {
                            代号: 键.clone(),
                            原始名: 键.clone(),
                            版本约束,
                            管理方式: "自动".into(),
                            类型: 依赖类型::智语言库,
                        });
                    }
                    _ => {}
                }
            }
        }
    }
    Ok(依赖列表)
}

