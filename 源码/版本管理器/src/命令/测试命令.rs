pub fn 执行(参数: &[String]) {
    let (通过, 失败) = 执行并返回(参数);
    let _ = (通过, 失败);
}

/// 运行测试并返回 (通过数, 失败数)；失败详情单独打印「失败 函数名 - 原因」
pub fn 执行并返回(参数: &[String]) -> (usize, usize) {
    let 文件路径 = 参数解析::提取文件路径(参数);
    let 过滤关键词 = 参数解析::获取标志值(参数, "--过滤");
    let 超时秒数 = 参数解析::获取标志值(参数, "--超时")
        .and_then(|s| s.parse::<u64>().ok())
        .unwrap_or(60);
    // T1：是否走编译模式（默认解释）
    let 是否编译 = 参数解析::有标志(参数, "--编译模式");

    if let Some(路径) = 文件路径 {
        // ★规范 §3.7.4「单文件路径」前置校验（路径级中文命名强制检查）
        //   必须打印汇总行并 exit(1)：路径非法绝不能被当作"零测试、零失败"放行
        //   （否则 `库 发布` 的发布前测试会把非法路径当成通过；门禁也会因缺 `通过：` 标记而误判）。
        if !crate::命名校验::校验源文件路径(&路径) {
            println!("通过：0 失败：1");
            std::process::exit(1);
        }
        let (通过, 失败, 记录) = 运行测试文件(&路径, 过滤关键词, 超时秒数, 是否编译);
        for (函数名, 原因) in &记录 {
            eprintln!("  失败  {} - {}", 函数名, 原因);
        }
        // 汇总行（含全角冒号），供门禁/CI 以「通过：」判定通过
        println!("通过：{} 失败：{}", 通过, 失败);
        if 参数解析::有标志(参数, "--结构化") {
            输出格式::打印结构化(&[
                ("命令".to_string(), "测试".to_string()),
                ("通过".to_string(), 通过.to_string()),
                ("失败".to_string(), 失败.to_string()),
            ]);
        }
        return (通过, 失败);
    }

    // 无文件参数：必须在项目内
    match 项目检测::检测当前目录项目归属() {
        项目归属::项目内(_根目录) => {
            let 测试文件列表 = 扫描测试文件();
            if 测试文件列表.is_empty() {
                eprintln!("[智语言] 错误：未找到 .智 测试文件");
                return (0, 0);
            }
            let mut 总通过 = 0usize;
            let mut 总失败 = 0usize;
            for 文件 in &测试文件列表 {
                let (通过, 失败, 记录) = 运行测试文件(文件, 过滤关键词.clone(), 超时秒数, 是否编译);
                总通过 += 通过;
                总失败 += 失败;
                for (函数名, 原因) in &记录 {
                    eprintln!("  失败  {} - {}", 函数名, 原因);
                }
            }
            println!("[智语言] 通过 {}，失败 {}", 总通过, 总失败);
            if 参数解析::有标志(参数, "--结构化") {
                输出格式::打印结构化(&[
                    ("命令".to_string(), "测试".to_string()),
                    ("通过".to_string(), 总通过.to_string()),
                    ("失败".to_string(), 总失败.to_string()),
                ]);
            }
            (总通过, 总失败)
        }
        项目归属::项目外 => {
            eprintln!("[智语言] 错误：未找到 配置/项目.配置，测试命令需要在项目目录下执行");
            (0, 0)
        }
    }
}

/// 从测试输出文本解析出 (通过数, 失败数, 失败记录[(来源, 原因)])
/// 解释模式传 VM.输出缓冲拼接文本；编译模式传 exe stdout+stderr 拼接文本。
/// 行中含「通过：」计为通过；**行首**（去空白后）以「失败：」或「失败 」开头才计失败。
/// 判定必须锚定行首：用例常把异常描述原样打印在通过行里（如「通过：文件复制 失败抛异常（文件复制失败：不存在的源.txt）」），
/// 若沿用 contains 会把这类通过行误判为失败行，造成「通过：5 失败：1」的假阴性。
fn 解析测试输出(文本: &str) -> (usize, usize, Vec<(String, String)>) {
    let 行: Vec<&str> = 文本.lines().collect();
    let 通过数 = 行.iter().filter(|l| l.contains("通过：")).count();
    let 失败记录: Vec<(String, String)> = 行.iter()
        .filter(|l| {
            let 去空白 = l.trim_start();
            去空白.starts_with("失败：") || 去空白.starts_with("失败 ")
        })
        .map(|l| {
            let 原因 = l
                .trim_start()
                .trim_start_matches("失败：")
                .trim_start_matches("失败 ")
                .to_string();
            ("启动程序/夹具".to_string(), 原因)
        })
        .collect();
    (通过数, 失败记录.len(), 失败记录)
}

/// 运行单个测试文件，返回 (通过数, 失败数, 失败记录[(测试函数名, 原因)])
fn 运行测试文件(文件路径: &str, 过滤: Option<String>, 超时秒数: u64, 是否编译: bool) -> (usize, usize, Vec<(String, String)>) {
    let 源码 = match fs::read_to_string(文件路径) {
        Ok(s) => s,
        Err(e) => { eprintln!("[智语言] 错误：无法读取文件: {}", e); return (0, 0, Vec::new()); }
    };

    let mut 诊断 = 诊断收集器::新建();
    frontend::诊断全局::设置诊断模式_自CLI(&mut 诊断);
    // 注册源文件以支持代码上下文显示
    诊断.注册源文件(文件路径, &源码);

    let 词条列表 = 词法分析器::新建(&源码, 文件路径.to_string(), &mut 诊断).扫描所有词条();
    if 诊断.有错误() { 输出诊断(&诊断); return (0, 0, Vec::new()); }

    let mut 程序 = 语法分析器::新建(&词条列表, &mut 诊断).解析程序();
    if 诊断.有错误() { 输出诊断(&诊断); return (0, 0, Vec::new()); }

    let mut 测试函数列表 = Vec::new();
    // 启动程序 由解析器单独存入 程序.入口（不在 顶层定义列表 中）
    let 含启动程序 = 程序.入口.is_some();
    for 定义 in &程序.顶层定义列表 {
        if let 顶层定义::函数定义(函数) = 定义 {
            if 函数.名称.starts_with("测试") {
                if let Some(ref 过滤词) = 过滤 {
                    if !函数.名称.contains(过滤词.as_str()) { continue; }
                }
                测试函数列表.push(函数.名称.clone());
            }
        }
    }

    // 语义分析（解释/编译双模式统一预检）：
    // 编译模式经 构建运行 复用同一前端，但此处提前运行语义分析，使 @预期错误 用例在编译模式
    // 也能暴露语义错误并被门禁正确判定（此前编译模式未运行语义分析预检，靠「失败：0」汇总行被误判通过）。
    let mut 语义器 = 语义分析器::新建(&mut 诊断);
    // 🆕 设置入口文件路径：模块加载器依赖它推导 入口目录/项目根，解析项目内绝对路径与相对路径
    语义器.设置入口文件路径(文件路径);
    let 高层表示模块 = match 语义器.分析程序(&mut 程序) {
        Ok(m) => m, Err(_) => { 输出诊断(&诊断); return (0, 0, Vec::new()); }
    };

    // T1：编译模式 —— 合成/复用 启动程序 夹具，编译成 exe 跑一次后解析 stdout
    if 是否编译 {
        return 运行测试文件_编译(文件路径, &源码, &测试函数列表, 含启动程序);
    }

    // 生成字节码（启动程序 形态与 测试X 形态都需要，复用上面已分析得到的 高层表示模块）
    let 底层表示模块 = 公共降级::降级转换(&高层表示模块);

    // FFI：与 `运行` 命令同源注册外部函数（双模式统一真相）。
    // 缺少这一步时，含外部块的项目在 `测试` 命令下报「[调试FFI] 调用 索引=401 未注册」，
    // 而同一文件用 `运行` 命令却正常 —— 命令间行为不一致的缺陷。
    let 项目归属 = pm::项目检测::查找项目根目录(文件路径);
    let 默认项目根 = std::path::Path::new(".");
    super::运行命令::注册外部函数(&底层表示模块, 项目归属.as_deref().unwrap_or(默认项目根));
    let 字节码 = match 字节码生成器::新建().生成(&底层表示模块) {
        Ok(b) => b,
        Err(e) => { eprintln!("[智语言] 字节码生成失败: {}", e); return (0, 0, Vec::new()); }
    };

    let 名称到索引: HashMap<String, usize> = 底层表示模块.函数列表
        .iter()
        .enumerate()
        .map(|(i, f)| (f.名称.clone(), i))
        .collect();

    // —— 解释模式：优先逐函数（与既有语义一致）——
    if !测试函数列表.is_empty() {
        let mut 通过 = 0;
        let mut 失败 = 0;
        let mut 失败记录: Vec<(String, String)> = Vec::new();

        for 函数名 in &测试函数列表 {
            let mut 虚拟机 = 虚拟机::新建();
            虚拟机.加载字节码(&字节码);
            虚拟机.抑制异常打印 = true;
            虚拟机.超时秒数 = 超时秒数;
            虚拟机.最大步数 = if 超时秒数 == 0 { u64::MAX } else { 超时秒数 * 1_000_000 };

            let 索引 = match 名称到索引.get(函数名) {
                Some(&i) => i,
                None => {
                    失败 += 1;
                    失败记录.push((函数名.clone(), "函数未找到".to_string()));
                    continue;
                }
            };
            // ★§2.4.7（2026-09-19）：**先执行「模块初始化」**（顶层变量/常量初始化）。
            //   解释模式逐函数直接调用 `测试X`，不经过入口函数 ⇒ 若不先初始化，`本模块.X` 读到空值，
            //   与编译模式（合成启动程序夹具，初始化随其注入）产生**双模分歧**。
            //   放在下方异常标志重置**之前**：初始化自身的异常不污染该测试用例的判定。
            if let Some(&初始化索引) = 名称到索引.get("__模块初始化") {
                虚拟机.运行函数(初始化索引, vec![]);
            }
            虚拟机.异常激活 = false;
            虚拟机.异常信息类型 = String::new();
            虚拟机.异常信息描述 = String::new();
            虚拟机.断定失败标志 = false;
            虚拟机.运行函数(索引, vec![]);

            if 虚拟机.异常激活 {
                let 原因 = if 虚拟机.异常信息描述.is_empty() {
                    虚拟机.异常信息类型.clone()
                } else {
                    format!("{}: {}", 虚拟机.异常信息类型, 虚拟机.异常信息描述)
                };
                失败 += 1;
                失败记录.push((函数名.clone(), 原因));
            } else if 虚拟机.断定失败标志 {
                失败 += 1;
                失败记录.push((函数名.clone(), "断定失败".to_string()));
            } else {
                通过 += 1;
            }
        }
        return (通过, 失败, 失败记录);
    }

    // —— 解释模式：T0 启动程序 形态（无 测试X 函数时）——
    if 含启动程序 {
        let 启动索引 = match 名称到索引.get("启动程序") {
            Some(&i) => i,
            None => { eprintln!("[智语言] 警告：未找到 启动程序 入口"); return (0, 0, Vec::new()); }
        };
        let mut 虚拟机 = 虚拟机::新建();
        虚拟机.加载字节码(&字节码);
        虚拟机.抑制异常打印 = true;
        虚拟机.捕获输出 = true;
        虚拟机.超时秒数 = 超时秒数;
        虚拟机.最大步数 = if 超时秒数 == 0 { u64::MAX } else { 超时秒数 * 1_000_000 };
        虚拟机.运行函数(启动索引, vec![]);

        let 缓冲文本 = 虚拟机.输出缓冲.join("\n");
        // 回打 stdout，保持与 `运行 --直接执行` 一致的可观测性
        for 行 in &虚拟机.输出缓冲 { println!("{}", 行); }

        let (通过, 失败, 记录) = 解析测试输出(&缓冲文本);
        if 虚拟机.异常激活 && 失败 == 0 {
            // 启动程序 本身抛了未捕获异常且未输出失败行
            let 原因 = format!("{}: {}", 虚拟机.异常信息类型, 虚拟机.异常信息描述);
            eprintln!("  失败  启动程序 - {}", 原因);
            return (通过, 1, vec![("启动程序".to_string(), 原因)]);
        }
        return (通过, 失败, 记录);
    }

    // 既无 测试X 也无 启动程序
    eprintln!("[智语言] 警告：未找到 测试X 函数或 启动程序 入口");
    (0, 0, Vec::new())
}

/// 编译模式：为测试文件合成/复用 启动程序 夹具，编译成原生 exe 并运行一次，解析 stdout。
fn 运行测试文件_编译(文件路径: &str, 源码: &str, 测试函数列表: &[String], 含启动程序: bool) -> (usize, usize, Vec<(String, String)>) {
    let 合成源码 = 测试辅助::合成测试启动程序(测试函数列表, 含启动程序, 源码);
    let 临时路径 = 测试辅助::写出临时夹具(文件路径, &合成源码);
    let (文本, 退出码) = 测试辅助::编译并执行(&临时路径);
    测试辅助::清理临时夹具(&临时路径);

    let (通过, 失败, 记录) = 解析测试输出(&文本);
    // ⚠️ 双模统一（2026-10-22 修）：编译模式 exe 的**程序输出必须始终回打**，
    //   与解释模式（`for 行 in &虚拟机.输出缓冲 { println!(...) }` 无条件回打）对齐。
    //   此前仅在「退出码非 0 或含未捕获异常」时回打 ⇒ 用例断言失败（打印 ❌ / 失败：N）
    //   但进程 rc=0 时输出被**静默丢弃**，门禁只看到汇总行 `通过：1 失败：0`，
    //   无法区分「断言全过」与「断言失败」⇒ 编译模式门禁存在假通过风险。
    if 退出码 != 0 || 文本.contains("未捕获异常") {
        eprintln!("{}", 文本.trim());
    } else {
        // 只回打**程序自身输出**：编译阶段的 `[智语言] ...` 日志行必须滤掉，
        // 否则双模输出一致性判据会出现「编译模式多两行」的假分歧。
        let 程序输出: Vec<&str> = 文本
            .lines()
            .filter(|l| !l.trim_start().starts_with("[智语言]"))
            .collect();
        println!("{}", 程序输出.join("\n").trim());
    }
    (通过, 失败, 记录)
}

/// 扫描当前目录及测试子目录下的 .智 文件
fn 扫描测试文件() -> Vec<String> {
    let mut 文件列表 = Vec::new();
    for 目录 in &[".".to_string(), "测试".to_string()] {
        if let Ok(条目) = std::fs::read_dir(目录) {
            for 条目 in 条目.flatten() {
                let 路径 = 条目.path();
                if 路径.extension().map_or(false, |e| e == "智") {
                    if let Some(名称) = 路径.to_str() {
                        文件列表.push(名称.to_string());
                    }
                }
            }
        }
    }
    文件列表
}
