// 文件: 版本管理器/src/构建签名.rs
// 职责: 统一暴露「共享层内容指纹」，供 运行命令（解释模式）/编译命令（编译模式）/
//       链接器（base.lib 新鲜度）共用同一来源。避免各处各自拼写 env! 导致未来漂移。
//
// 指纹由 版本管理器/build.rs 在构建期烧入二进制（env! 在编译期解析）。
// 语义: 改任一前端共享层源码 → 重建 智语言开发套件.exe → 指纹随之变化 →
//       所有依赖该指纹的增量缓存（字节码 / .编译 / 用户 exe / base.lib）必然失效。

/// 前端层指纹（源码/前端/src）：解释模式与编译模式共用的降级/语义层
/// 解释器层指纹（源码/后端/解释器/src）：仅解释模式加载并执行 .字节码 的运行时。
/// 方案C2 补充：此前缺此源树，改字节码格式/生成器后 .字节码 缓存不失效（S2 曾误判「修复无效」）。
/// 仅并入【解释模式】签名，不并入编译模式签名（保持细粒度：改解释器不该让编译产物失效）。
pub fn 解释器指纹() -> &'static str {
    env!("解释器指纹")
}

pub fn 前端指纹() -> &'static str {
    env!("前端指纹")
}

/// 编译器层指纹（源码/后端/编译器/src）：仅编译模式经 Cranelift 后端
pub fn 编译器指纹() -> &'static str {
    env!("编译器指纹")
}

/// 基础功能指纹（源码/基础功能/src）：解释模式/编译模式/base.lib 共用真相源
///
/// 与 base（运行时静态库）**逐字同构**的构建标识文本：`ZHI-BASE-FP:<16 位十六进制>\0`。
/// 打包闸门把「工具 exe 里的这个字符串」与「base.lib 里的那个字符串」对读，
/// 因此两边的前缀、长度、编码必须完全一致（base 侧见 基础功能/src/运行时/构建标识.rs）。
/// 未在本文件内直接使用也无妨：`基础指纹()` 由它派生 ⇒ 字面量一定被使用
/// ⇒ 一定落进 exe 的只读数据段 ⇒ 打包器才扫得到。
pub const 构建标识文本: &str = concat!("ZHI-BASE-FP:", env!("基础指纹"), "\0");

pub fn 基础指纹() -> &'static str {
    // 由标识文本派生而不是再写一遍 env!：既保证字面量被使用，也保证两处永远同源。
    构建标识文本
        .strip_prefix("ZHI-BASE-FP:")
        .and_then(|余| 余.strip_suffix('\0'))
        .unwrap_or_else(|| env!("基础指纹"))
}
