use std::env;

/// 开发套件版本号（读 Cargo.toml 的 version，唯一真相源）
const 开发套件版本号: &str = env!("CARGO_PKG_VERSION");

fn main() {
    // 防递归：被引导程序转发时 env 已置位，直接执行业务命令
    // 否则为单二进制软实现（开发期直接运行本体）
    let _已引导 = env::var("智语言_已引导").is_ok();
    let 参数列表: Vec<String> = env::args().collect();
    if 参数列表.len() < 2 {
        打印帮助(None);
        return;
    }
    let 命令 = &参数列表[1];
    let 参数 = &参数列表[2..];

    match 命令.as_str() {
        "运行" => 运行命令::执行(参数),
        "构建" => 编译命令::执行(参数),
        "构建运行" => 编译命令::执行编译运行(参数),
        "测试" => 测试命令::执行(参数),
        "检查" => 质量命令::执行检查(参数),
        "格式化" => 质量命令::执行格式化(参数),
        "清理项目" => 清理命令::执行清理项目(参数),
        "清理全局" => 清理命令::执行清理全局(参数),
        "交互" => 交互命令::执行(参数),
        "文档" => 文档命令::执行(参数),
        "基准" => 基准命令::执行(参数),
        "创建" => 创建命令::执行(参数),
        "版本" | "--version" | "-v" => 打印版本(),
        "库" => 库命令::执行(参数),
        "账号" => 账号命令::执行(参数),
        "生成关联" => 生成关联::执行(参数),
        "生成门面" => 生成门面::执行(参数),
        "帮助" | "--help" | "-h" => {
            let 子命令 = 参数.first().map(|s| s.as_str());
            打印帮助(子命令);
        }
        _ => {
            eprintln!("[智语言] 错误：未知命令: {}。使用 '智语言 帮助' 查看可用命令。", 命令);
            std::process::exit(1);
        }
    }
}

fn 打印版本() {
    println!("智语言开发套件 v{}", 开发套件版本号);
}

