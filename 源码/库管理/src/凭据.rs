// 文件: 库管理/src/凭据.rs
// 职责: 客户端**会话凭据的本地持久化**（库镜像源服务端系统设计 §4.2）
//
// 为什么需要（此前是缺口）：
//   §4.2 要求把登录得到的会话令牌存到 `<全局目录>/配置/凭据.配置`，使 `库 发布`/`库 弃用`
//   不必每次都重新登录；此前客户端**完全不写这个文件** ⇒ 每次发布都重新登录（甚至自动注册），
//   既慢又把"密码"留在环境变量/默认值里。
//
// 三条安全/行为约定：
//   ① **只保存显式登录得到的令牌**：`账号 登录` 才落盘；`库 发布` 内部自动登录**不落盘**
//      （否则 CI/测试用环境变量凭据会把测试令牌写进用户真实凭据文件 ✗）。
//   ② **环境变量优先于文件**：`智语言_库用户名/库密码/库邮箱/库令牌` 仍是最强覆盖手段
//      （测试与自动化靠它），有它们时完全忽略文件。
//   ③ 文件权限：POSIX 下 600（仅本人可读）；Windows 依赖用户目录 ACL。
//      令牌有效期由服务端签发（默认 7 天），本地按 `过期时间` 判定，**留 60 秒余量**。
use std::path::PathBuf;

/// 凭据文件路径：`<全局目录>/配置/凭据.配置`
pub fn 凭据路径() -> PathBuf {
    pm::目录::全局配置目录().join("凭据.配置")
}

pub struct 凭据 {
    pub 用户名: String,
    pub 令牌: String,
    pub 过期时间: i64,
}

fn 当前时间秒() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

/// 保存凭据（写 `<全局目录>/配置/凭据.配置`）
pub fn 保存(用户名: &str, 令牌: &str, 过期时间: i64) -> Result<(), String> {
    let 路径 = 凭据路径();
    if let Some(父) = 路径.parent() {
        std::fs::create_dir_all(父).map_err(|e| format!("创建配置目录失败 {}: {}", 父.display(), e))?;
    }
    let 内容 = format!(
        "// 此文件由工具链自动生成，请勿手动编辑\n// 会话凭据：仅保存令牌，不保存密码\n\n[凭据]\n用户名 = \"{}\"\n令牌 = \"{}\"\n过期时间 = {}\n",
        用户名, 令牌, 过期时间
    );
    std::fs::write(&路径, 内容).map_err(|e| format!("写入凭据失败 {}: {}", 路径.display(), e))?;
    收紧权限(&路径);
    Ok(())
}

/// 收紧文件权限：POSIX 600（仅本人可读）；Windows/其它平台不做处理（依赖目录 ACL）
fn 收紧权限(路径: &PathBuf) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(路径, std::fs::Permissions::from_mode(0o600));
    }
    #[cfg(not(unix))]
    let _ = 路径;
}

/// 读取凭据；文件不存在 / 格式不对 / **已过期** ⇒ `None`（过期令牌不得使用）
pub fn 读取() -> Option<凭据> {
    读取原始().filter(|c| c.过期时间 - 60 > 当前时间秒())
}

/// 读取凭据但**不做过期判定**（供 `账号 状态` 展示"上次登录"用）
pub fn 读取原始() -> Option<凭据> {
    let 路径 = 凭据路径();
    let 内容 = std::fs::read_to_string(&路径).ok()?;
    let 文档 = pm::配置读取器::解析配置(&内容);
    let 段 = pm::配置读取器::取段(&文档, "凭据")?;
    let 用户名 = pm::配置读取器::取文本(段, "用户名").unwrap_or_default();
    let 令牌 = pm::配置读取器::取文本(段, "令牌").unwrap_or_default();
    if 令牌.is_empty() {
        return None;
    }
    // ⚠ 必须用 取整数（不是 取文本）：凭据文件里 过期时间 是**无引号整数**，
    //   配置读取器会把无引号数值解析成 `配置值::整数`；而 取文本 只认 `文本` 变体、
    //   对整数返回 None ⇒ 过期时间恒为 0 ⇒ 凭据被误判"已过期" ⇒ 发布/弃用回退到默认账号、
    //   登出报"无凭据"。这是 2026-10-02 实测暴露的真实缺陷。
    let 过期时间 = pm::配置读取器::取整数(段, "过期时间").unwrap_or(0);
    Some(凭据 { 用户名, 令牌, 过期时间 })
}

/// 删除本地凭据（登出后调用；文件不存在不算失败）
pub fn 删除() {
    let _ = std::fs::remove_file(凭据路径());
}
